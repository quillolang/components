const hs = $$(".ui-heading");
if (hs.length !== 8) return `expected 8 headings, found ${hs.length}`;
const tags = hs.map((h) => h.tagName).join();
if (tags !== "H1,H2,H3,H4,H5,H6,H3,H2") return `the elements are ${tags}`;
if (!$("#heading-demo-h1").classList.contains("ui-heading-1")) return "id or level class does not reach the h1";
const size = (el) => parseFloat(getComputedStyle(el).fontSize);
for (let i = 1; i < 6; i++) if (!(size(hs[i]) < size(hs[i - 1]))) return `level ${i + 1} is not smaller than level ${i}`;
const billing = $("#heading-demo-billing");
if (billing.parentElement.tagName !== "HGROUP") return "a heading with a subtitle is not in an hgroup";
const sub = billing.parentElement.querySelector(".ui-heading-sub");
if (!sub || !sub.textContent.startsWith("Cards, invoices")) return "the subtitle is missing";
if (sub.getBoundingClientRect().top < billing.getBoundingClientRect().bottom - 1) return "the subtitle is not under the heading";
const a = billing.querySelector("a.ui-heading-anchor");
if (!a || a.getAttribute("href") !== "#heading-demo-billing" || !a.getAttribute("aria-label")) return "the anchor link is missing or unnamed";
if (getComputedStyle(a).opacity !== "0") return "the anchor shows before hover";
const rules = [...document.styleSheets].flatMap((s) => { try { return [...s.cssRules]; } catch { return []; } });
if (!rules.some((r) => r.selectorText?.includes(".ui-heading-anchor:focus") && r.style.opacity === "1")) return "no rule shows the anchor when it is focused";
if (!rules.some((r) => r.selectorText?.includes(".ui-heading:hover .ui-heading-anchor") && r.style.opacity === "1")) return "no rule shows the anchor when the heading is hovered";
if (hs[2].querySelector("a")) return "a heading without anchor={true} has a link";
const small = $("#heading-demo-small");
if (small.tagName !== "H3" || !small.classList.contains("ui-heading-5") || size(small) !== size(hs[4])) return `size={5} does not give a level-3 heading the level-5 look: ${small.tagName} ${small.className} ${size(small)} vs ${size(hs[4])}`;
const center = $("#heading-demo-center");
if (getComputedStyle(center).textAlign !== "center") return "align=center is not applied";
if (getComputedStyle(center).color !== getComputedStyle($(".ui-heading-sub")).color) return "tone=muted is not the muted colour";
