const sel = $("#language-picker-demo-all");
if (!sel || sel.tagName !== "SELECT" || sel.name !== "lang") return "the picker is not a named select";
if (sel.labels.length !== 1 || !sel.labels[0].textContent.includes("Language")) return "the label is not tied to the select";
if (sel.value !== "pt") return `value did not choose Portuguese: ${sel.value}`;
const groups = [...sel.querySelectorAll("optgroup")].map((g) => g.label);
if (groups.join() !== "Common,All languages") return `favourites are not grouped first: ${groups}`;
const common = [...sel.querySelector("optgroup[label=Common]").querySelectorAll("option")].map((o) => o.value);
if (common.join() !== "en,pt") return `the favourites: ${common}`;
if (sel.options.length < 70) return `expected the built-in list, found ${sel.options.length}`;
const de = sel.querySelector("option[value=de]");
if (de.textContent.trim() !== "Deutsch" || de.getAttribute("lang") !== "de") return `German is not "Deutsch" with lang=de: ${de.textContent}`;
if (sel.querySelector("option[value=ja]").textContent.trim() !== "日本語") return "Japanese is not in its own script";
if (sel.getAttribute("autocomplete") !== "language") return "the select does not ask for language autofill";
if (!document.getElementById(sel.getAttribute("aria-describedby"))?.textContent.includes("itself")) return "the hint is not tied to the select";
if (!sel.required) return "required did not reach the select";
const en = $("#language-picker-demo-english");
if (en.options[0].value !== "" || !en.options[0].disabled || !en.options[0].selected) return "the placeholder is not a disabled first option";
if (en.options.length !== 5 || en.querySelector("optgroup")) return `only={...} should give those four, ungrouped: ${en.options.length}`;
if (en.querySelector("option[value=de]").textContent.trim() !== "Deutsch (German)") return `english={true}: ${en.querySelector("option[value=de]").textContent}`;
if (en.querySelector("option[value=en]").textContent.trim() !== "English") return "English should not repeat its name";
const live = $("#language-picker-demo-live");
if (live.value !== "ja") return `the live picker starts on ${live.value}`;
live.value = "ar"; live.dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (!$(".demo-note").textContent.includes("العربية (ar)")) return `on_change did not update the note: ${$(".demo-note").textContent}`;
if (!$("select[name=locked]").disabled) return "disabled did not reach the select";
