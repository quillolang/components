const opts = $("#collapsible-demo-options"), log = $("#collapsible-demo-log"), live = $("#collapsible-demo-live"), a = $("#collapsible-demo-a"), b = $("#collapsible-demo-b");
if (!opts || opts.tagName !== "DETAILS" || !opts.querySelector("summary")) return "it is not a <details> with a <summary>";
if (opts.open || !log.open) return "open={...} is not respected";
if (!opts.querySelector("summary").textContent.includes("Advanced options") || opts.querySelector(".ui-collapsible-hint")?.textContent !== "3 settings") return "the title or hint is missing";
const sw = opts.querySelector(".ui-switch");
if (sw.checkVisibility()) return "closed, the body still shows";
opts.querySelector("summary").click(); await wait(300);
if (!opts.open || !sw.checkVisibility()) return "clicking the summary did not open it";
opts.querySelector("summary").click(); await wait(300);
if (opts.open || sw.checkVisibility()) return "clicking again did not close it";
if (!log.classList.contains("ui-collapsible-box") || getComputedStyle(log).borderTopWidth !== "1px") return "variant=\"box\" draws no box";
if (!live.classList.contains("ui-collapsible-button") || getComputedStyle(live.querySelector("summary")).borderTopWidth !== "1px") return "variant=\"button\" does not look like a button";
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
live.querySelector("summary").click(); await wait(300);
if (!live.open || note() !== "The details are open.") return `on_toggle: ${note()}`;
live.querySelector("summary").click(); await wait(300);
if (note() !== "The details are closed.") return `on_toggle on closing: ${note()}`;
if (a.name !== "collapsible-demo-group" || b.name !== "collapsible-demo-group") return "group does not set the details' name";
a.querySelector("summary").click(); await wait(100); b.querySelector("summary").click(); await wait(300);
if (!b.open || a.open) return "opening the second of a group did not close the first";
b.querySelector("summary").click(); await wait(100);
