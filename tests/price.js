const prices = $$(".ui-price");
if (prices.length !== 9) return `expected 9 prices, found ${prices.length}`;
const now = (p) => p.querySelector(".ui-price-now").textContent.replace(/\s/g, " ");
if (now(prices[0]) !== "$19.99") return `19.99 USD reads "${now(prices[0])}"`;
const sale = prices[1];
if (now(sale) !== "$29.99") return `the sale price reads "${now(sale)}"`;
const old = sale.querySelector("s.ui-price-old");
if (!old || !old.textContent.includes("$39.99") || !old.textContent.includes("was")) return `the old price: "${old?.textContent}"`;
if (getComputedStyle(old).textDecorationLine !== "line-through") return "the old price is not struck through";
if (sale.querySelector(".ui-price-off")?.textContent.replace(/\s/g, "") !== ",−25%off") return `the discount reads "${sale.querySelector(".ui-price-off")?.textContent}"`;
if (now(prices[2]) !== "1.234,50 €") return `de-DE EUR reads "${now(prices[2])}"`;
if (!/^(￥|¥)1,250$/.test(now(prices[3]))) return `JPY reads "${now(prices[3])}"`;
if (now(prices[4]) !== "Free") return `0 reads "${now(prices[4])}"`;
if (now(prices[5]) !== "£12.50" || !prices[5].querySelector(".ui-price-old").textContent.includes("£20.00")) return "text amounts are not shown as they are";
if (prices[5].querySelector(".ui-price-off")) return "text amounts should give no discount";
if (!prices[6].classList.contains("ui-price-lg") || !prices[6].classList.contains("ui-price-danger")) return "size and tone classes are missing";
if (getComputedStyle(prices[6].querySelector(".ui-price-now")).color === getComputedStyle(prices[0].querySelector(".ui-price-now")).color) return "tone danger does not colour the price";
if (prices[6].querySelector(".ui-price-off").textContent.replace(/\s/g, "") !== ",−38%off") return `49 from 79: "${prices[6].querySelector(".ui-price-off").textContent}"`;
if (parseFloat(getComputedStyle(prices[7]).fontSize) <= parseFloat(getComputedStyle(prices[6]).fontSize)) return "xl is not larger than lg";
if (prices[8].querySelector(".ui-price-off")) return "discount={false} still shows the percentage";
