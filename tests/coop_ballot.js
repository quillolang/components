const f = $(".ui-coop-ballot");
if (!f || f.tagName !== "FORM" || f.method !== "post" || !f.getAttribute("action").endsWith("#coop-ballot")) return "not a post form";
const box = (n) => $(`#coop-ballot-demo-c-10${n}`);
const count = () => f.querySelector(".ui-coop-ballot-count").textContent;
const submit = f.querySelector("button[type=submit]");
if (f.querySelectorAll(".ui-coop-ballot-card").length !== 5) return "the candidates";
if (count() !== "0 of 3 chosen" || !submit.disabled) return `start: ${count()}, submit disabled ${submit.disabled}`;
if (f.querySelector(".ui-coop-ballot-text").textContent !== "Choose up to 3.") return "the instruction";
if (box(1).closest("label").querySelector(".ui-coop-ballot-initials").textContent !== "LV") return "initials";
const st = $(`#${box(1).getAttribute("aria-describedby")}`);
if (!st || !st.textContent.startsWith("Twelve years")) return "the statement is not tied to the checkbox";
box(1).click(); box(3).click(); await wait();
if (count() !== "2 of 3 chosen" || submit.disabled || !box(1).closest("label").classList.contains("ui-coop-ballot-on")) return `two: ${count()}`;
box(4).click(); await wait();
if (count() !== "3 of 3 chosen" || !box(2).disabled || !box(5).disabled || box(1).disabled) return "at three the others are not stopped";
if (!box(2).closest("label").classList.contains("ui-coop-ballot-off") || !f.querySelector(".ui-coop-ballot-full")) return "the full state is not shown";
box(5).click(); await wait();
if (box(5).checked || count() !== "3 of 3 chosen") return "a fourth got ticked";
const sent = new FormData(f);
if (sent.getAll("candidates").join(",") !== "c-101,c-103,c-104" || sent.get("election") !== "board-2026") return `the form sends ${[...sent.entries()]}`;
box(3).click(); await wait();
if (count() !== "2 of 3 chosen" || box(2).disabled || f.querySelector(".ui-coop-ballot-full")) return "unticking does not free the others";
box(5).click(); await wait();
if (!box(5).checked || new FormData(f).getAll("candidates").join(",") !== "c-101,c-104,c-105") return "a new choice after unticking";
box(1).click(); box(4).click(); box(5).click(); await wait();
if (count() !== "0 of 3 chosen" || !submit.disabled) return "back to none";
