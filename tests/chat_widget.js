const host = $(".ui-chat-widget"), bubble = $(".ui-chat-widget-bubble"), panel = $(".ui-chat-widget-panel");
const msgs = () => [...panel.querySelectorAll(".ui-chat-widget-msg:not(:has(.ui-chat-widget-typing))")], last = () => msgs().at(-1);
if (!host || !bubble || bubble.getAttribute("aria-expanded") !== "false" || bubble.getAttribute("aria-label") !== "Support" || !panel.hidden) return "it does not start as a closed, named bubble";
const box = host.closest("[style*=relative]").getBoundingClientRect(), b = bubble.getBoundingClientRect();
if (Math.abs(box.right - b.right - 16) > 1 || Math.abs(box.bottom - b.bottom - 16) > 1) return "inline does not put it in its box's bottom right corner";
bubble.click(); await wait();
const input = panel.querySelector("textarea");
if (panel.hidden || bubble.getAttribute("aria-expanded") !== "true" || document.activeElement !== input) return "the bubble does not open the panel with the box focused";
if (panel.getAttribute("role") !== "dialog" || panel.getAttribute("aria-label") !== "Support" || !panel.textContent.includes("We reply in a few minutes")) return "the panel is not named, with its status";
if (panel.querySelector("[role=log]")?.getAttribute("aria-live") !== "polite") return "the messages are not a log";
if (msgs().length !== 1 || !msgs()[0].textContent.includes("Hi! How can we help?") || msgs()[0].querySelector(".ui-chat-widget-from").textContent !== "Mia") return "the first message is not shown with its sender";
const send = panel.querySelector(".ui-chat-widget-send");
if (!send.disabled) return "Send is enabled with nothing written";
type(input, "What is the price?"); await wait(50);
key(input, "Enter"); await wait(100);
if (!last().classList.contains("ui-chat-widget-mine") || !last().textContent.includes("What is the price?") || input.value !== "") return "Enter does not send the message and empty the box";
if (!panel.querySelector(".ui-chat-widget-typing")) return "no typing while the answer comes";
await wait(600);
if (last().classList.contains("ui-chat-widget-mine") || !last().textContent.includes("€9 a month") || panel.querySelector(".ui-chat-widget-typing")) return `the reply did not come: ${last().textContent}`;
const lg = panel.querySelector(".ui-chat-widget-log");
if (Math.abs(lg.scrollTop) > 2) return "the log is not at the newest message";
const shift = new KeyboardEvent("keydown", { key: "Enter", shiftKey: true, bubbles: true, cancelable: true });
type(input, "two"); input.dispatchEvent(shift); await wait();
if (shift.defaultPrevented || msgs().length !== 3) return "Shift+Enter sent the message";
type(input, "Hello"); panel.querySelector("form").requestSubmit(); await wait(50);
key(input, "Escape"); await wait();
if (!panel.hidden || document.activeElement !== bubble) return "Escape does not close the panel and focus the bubble";
await wait(600);
if (bubble.querySelector(".ui-chat-widget-count")?.textContent !== "1" || bubble.getAttribute("aria-label") !== "Support, 1 new") return "a reply while closed does not put a count on the bubble";
bubble.click(); await wait();
if (bubble.querySelector(".ui-chat-widget-count") || !last().textContent.includes("You said: “Hello”")) return "opening does not clear the count and show the reply";
bubble.click(); await wait();
