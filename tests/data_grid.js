const g = $("#data-grid-demo-orders");
const th = (name) => [...g.querySelectorAll("th")].find((t) => t.textContent.trim() === name);
const col = (i) => [...g.querySelectorAll("tbody tr")].map((r) => r.children[i]?.textContent.trim());
const foot = () => g.querySelector(".ui-datagrid-foot span").textContent.trim();
const btn = (t) => [...g.querySelectorAll(".ui-datagrid-pages button")].find((b) => b.textContent === t);
const boxes = () => [...g.querySelectorAll("tbody input[type=checkbox]")];
const note = () => g.closest(".demo-stack").querySelector(".demo-note").textContent;
if (g.querySelector("table").getAttribute("aria-label") !== "Orders") return "the table is not named";
if (th("Placed").getAttribute("aria-sort") !== "descending") return "order_by + descending do not set aria-sort";
if (col(0).length !== 10 || foot() !== "1–10 of 32") return `the first page: ${col(0).length} rows, "${foot()}"`;
const dates = col(4);
if (dates[0] < dates[1] && dates[0] !== "Sep 30, 2026") return `not newest first: ${dates.slice(0, 3)}`;
th("Total").querySelector("button").click(); await wait();
if (th("Total").getAttribute("aria-sort") !== "ascending" || th("Placed").hasAttribute("aria-sort")) return "sorting by Total";
const money = col(5).map((s) => Number(s.replace(/[$,]/g, "")));
if (money.some((m, i) => i && m < money[i - 1])) return `not ascending: ${money}`;
if (!/^\$\d{1,3}(,\d{3})*\.\d\d$/.test(col(5)[0])) return `money is not formatted: ${col(5)[0]}`;
btn("Next").click(); await wait();
if (foot() !== "11–20 of 32") return `Next: "${foot()}"`;
const filters = [...g.querySelectorAll(".ui-datagrid-filter")];
if (filters.length !== 2 || filters[0].getAttribute("aria-label") !== "Filter by customer") return "the filter selects are missing";
if ([...filters[1].options].map((o) => o.value).join() !== ",Draft,Open,Overdue,Paid") return `status options: ${[...filters[1].options].map((o) => o.value)}`;
filters[1].value = "Open"; filters[1].dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (col(3).some((s) => s !== "Open")) return `the filter kept other statuses: ${col(3)}`;
if (!foot().startsWith("1–")) return `the filter did not go back to the first page: "${foot()}"`;
if (!filters[1].classList.contains("ui-datagrid-on")) return "an active filter is not marked";
const open_total = Number(foot().split("of ")[1]);
type(g.querySelector(".ui-datagrid-search"), "initech"); await wait();
if (col(2).some((c) => c !== "Initech") || col(3).some((s) => s !== "Open")) return `search and filter together: ${col(2)} / ${col(3)}`;
const both = Number(foot().split("of ")[1]);
if (!(both < open_total)) return "searching did not narrow the filtered rows";
type(g.querySelector(".ui-datagrid-search"), "zzz"); await wait();
if (g.querySelector(".ui-datagrid-empty")?.textContent.trim() !== "Nothing to show." || foot() !== "No rows") return "no match does not say so";
if (g.querySelectorAll("tbody tr").length !== 1) return `old rows stay beside the empty row: ${g.querySelectorAll("tbody tr").length}`;
g.querySelector(".ui-datagrid-clear").click(); await wait();
if (foot() !== "1–10 of 32" || g.querySelector(".ui-datagrid-search").value !== "" || filters[1].value !== "") return `Clear: "${foot()}"`;
// selection
const head = g.querySelector("thead input[type=checkbox]");
boxes()[0].click(); await wait();
const first = g.querySelector("tbody tr").dataset.id;
if (!boxes()[0].checked || g.querySelector("tbody tr").getAttribute("aria-selected") !== "true") return "a row did not check";
if (g.querySelector(".ui-datagrid-picked")?.textContent !== "1 selected" || note() !== `on_select: ${first}`) return `one selected: ${note()}`;
if (!head.indeterminate) return "the header is not half-checked";
head.click(); await wait();
if (boxes().some((b) => !b.checked) || g.querySelector(".ui-datagrid-picked").textContent !== "10 selected") return "the header did not check the page";
if ([...g.querySelectorAll("input[type=hidden][name=order]")].length !== 10) return "hidden inputs do not follow the selection";
btn("Next").click(); await wait();
if (boxes().some((b) => b.checked) || head.checked) return "the next page shows the first page's checks";
if (g.querySelector(".ui-datagrid-picked").textContent !== "10 selected") return "paging lost the selection";
btn("Previous").click(); await wait();
head.click(); await wait();
if (boxes().some((b) => b.checked) || g.querySelector(".ui-datagrid-picked")) return "the header did not uncheck the page";
const size = g.querySelector(".ui-datagrid-size");
size.value = "25"; size.dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (col(0).length !== 25 || foot() !== "1–25 of 32") return `25 per page: ${col(0).length}, "${foot()}"`;
// a plain grid
const s = $("#data-grid-demo-small");
if (s.querySelector(".ui-datagrid-bar") || s.querySelector(".ui-datagrid-pages") || s.querySelector("input[type=checkbox]")) return "the plain grid has controls it was not given";
if (!/^\d+ rows$/.test(s.querySelector(".ui-datagrid-foot span").textContent.trim())) return "the plain grid does not count its rows";
