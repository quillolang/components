const groups = $$(".ui-plan-toggle");
if (groups.length !== 3) return `expected 3, found ${groups.length}`;
const [live, free, small] = groups;
const radios = (g) => [...g.querySelectorAll("input[type=radio]")];
if (live.getAttribute("role") !== "radiogroup" || live.getAttribute("aria-label") !== "Billing period") return "no radio group with a name";
const lr = radios(live);
if (lr.length !== 2 || lr.map((r) => r.value).join() !== "monthly,yearly" || !lr[0].checked) return "it does not start on monthly";
if (live.querySelector(".ui-plan-toggle-save")?.textContent !== "Save 20%" || !lr[1].closest("label").contains(live.querySelector(".ui-plan-toggle-save"))) return "the saving is not on the yearly side";
lr[1].closest("label").click(); await wait();
if (!lr[1].checked || !$(".demo-note").textContent.includes("a year")) return `clicking yearly: ${$(".demo-note").textContent}`;
const bg = (r) => getComputedStyle(r.nextElementSibling).backgroundColor;
if (bg(lr[1]) === bg(lr[0])) return "the chosen side does not look chosen";
lr[0].closest("label").click(); await wait();
if (!lr[0].checked || !$(".demo-note").textContent.includes("a month")) return "clicking monthly does not go back";
const f = document.createElement("form"); live.parentElement.insertBefore(f, live); f.appendChild(live);
const sent = new FormData(f).get("plan-toggle-demo-live"); f.parentElement.insertBefore(live, f); f.remove();
if (sent !== "monthly") return `a form would send ${sent}`;
if (!radios(free)[1].checked || free.querySelector(".ui-plan-toggle-save")?.textContent !== "2 months free") return "value=yearly or text saving is wrong";
if (radios(small).map((r) => r.value).join() !== "m,y" || [...small.querySelectorAll(".ui-plan-toggle-text")].map((t) => t.textContent.trim()).join("|") !== "Pay monthly|Pay yearly" || small.querySelector(".ui-plan-toggle-save")) return "labels and values are not used";
if (parseFloat(getComputedStyle(small.querySelector(".ui-plan-toggle-text")).height) >= parseFloat(getComputedStyle(live.querySelector(".ui-plan-toggle-text")).height)) return "sm is not smaller";
