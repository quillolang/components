const box = $("#markdown-editor-md-demo-post");
const host = box.closest(".ui-markdown-editor");
const tool = (name) => host.querySelector(`button[aria-label^="${name}"]`);
if (box.tagName !== "TEXTAREA" || box.name !== "md-demo-post" || !box.value.startsWith("# Release notes")) return "the box is not a named textarea with the value";
if (host.querySelectorAll(".ui-markdown-editor-tool").length !== 8) return "the toolbar does not have every tool";
const tabs = host.querySelectorAll("[role=tab]");
if (tabs.length !== 2 || tabs[0].getAttribute("aria-selected") !== "true") return "Write is not the selected tab";
const set = (v, a, b) => { box.value = v; box.dispatchEvent(new Event("input", { bubbles: true })); box.setSelectionRange(a, b); };
set("make this bold", 10, 14); await wait();
tool("Bold").click(); await wait();
if (box.value !== "make this **bold**" || box.selectionStart !== 12 || box.selectionEnd !== 16) return `bold: "${box.value}" ${box.selectionStart}-${box.selectionEnd}`;
set("x", 1, 1); await wait();
tool("Italic").click(); await wait();
if (box.value !== "x_italic text_") return `italic with nothing selected: "${box.value}"`;
set("one\ntwo", 0, 7); await wait();
tool("Numbered").click(); await wait();
if (box.value !== "1. one\n2. two") return `numbered: "${box.value}"`;
set("see docs", 4, 8); await wait();
tool("Link").click(); await wait();
if (box.value !== "see [docs](https://)" || box.value.slice(box.selectionStart, box.selectionEnd) !== "https://") return `link: "${box.value}"`;
set("a\nb", 2, 2); await wait();
tool("Quote").click(); await wait();
if (box.value !== "a\n> b") return `quote on the caret's line: "${box.value}"`;
set("hot key", 0, 3); await wait();
box.dispatchEvent(new KeyboardEvent("keydown", { key: "b", ctrlKey: true, bubbles: true, cancelable: true })); await wait();
if (box.value !== "**hot** key") return `Ctrl+B: "${box.value}"`;
set("# Title\n\nSome *em* and [a link](https://x.org)", 0, 0); await wait();
tabs[1].click(); await wait(600);
const pv = host.querySelector(".ui-markdown-editor-preview");
if (pv.hidden || tabs[1].getAttribute("aria-selected") !== "true") return "the Preview tab does not show the preview";
if (pv.querySelector("h1")?.textContent !== "Title" || pv.querySelector("em")?.textContent !== "em" || pv.querySelector("a")?.getAttribute("href") !== "https://x.org") return `the preview shows: ${pv.innerHTML}`;
if (!box.closest("[role=tabpanel]").hidden || !tool("Bold").disabled) return "the box and the tools are not put away while previewing";
tabs[0].click(); await wait();
if (box.closest("[role=tabpanel]").hidden) return "Write does not come back";
const note = $("#markdown-editor-md-demo-note");
const nh = note.closest(".ui-markdown-editor");
if (nh.querySelectorAll(".ui-markdown-editor-tool").length !== 4) return "tools={[...]} is not kept";
note.setSelectionRange(0, 4); nh.querySelector('button[aria-label^="Code"]').click(); await wait();
if (note.closest(".demo-stack").querySelector(".demo-note").textContent !== `${note.value.length} characters of Markdown.` || !note.value.startsWith("`Some`")) return `on_change: ${note.value}`;
