const live = $("#reply-box-demo-live");
const form = live.closest("form");
const actions = form.querySelector(".ui-reply-box-actions");
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
if (live.tagName !== "TEXTAREA" || live.name !== "reply") return "the box is not a textarea named reply";
if (!form.querySelector(`label[for="${live.id}"]`)) return "the box has no label";
if (form.querySelector(".ui-reply-box-avatar").textContent.trim() !== "AS") return "the avatar does not show your initials";
if (!actions.hidden || form.classList.contains("ui-reply-box-open") || live.getAttribute("aria-expanded") !== "false") return "it starts open";
live.dispatchEvent(new FocusEvent("focus")); await wait();
if (actions.hidden || !form.classList.contains("ui-reply-box-open") || live.getAttribute("aria-expanded") !== "true") return "focus did not open it";
const post = form.querySelector("button[type=submit]");
if (!post.disabled) return "Post is enabled with nothing written";
type(live, "  Looks good to me  "); await wait();
if (post.disabled) return "Post stayed disabled after typing";
post.click(); await wait();
if (note() !== "Posted: Looks good to me.") return `on_post did not reach the note: ${note()}`;
if (live.value !== "" || !actions.hidden) return "posting did not empty and fold the box";
live.dispatchEvent(new FocusEvent("focus")); type(live, "Second");
live.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", ctrlKey: true, bubbles: true, cancelable: true })); await wait();
if (!note().startsWith("Posted: Looks good to me · Second.")) return `Ctrl+Enter did not post: ${note()}`;
live.dispatchEvent(new FocusEvent("focus")); type(live, "never mind"); key(live, "Escape"); await wait();
if (live.value !== "" || !actions.hidden || !note().includes("Cancelled 1")) return `Escape did not cancel: value "${live.value}", hidden ${actions.hidden}, ${note()}`;
live.dispatchEvent(new FocusEvent("focus")); type(live, "x"); await wait();
form.querySelector(".ui-reply-box-cancel").click(); await wait();
if (!note().includes("Cancelled 2") || live.value !== "") return "the Cancel button did not cancel";
// In a page: Post submits the form, with the children in it.
const pbox = $("#reply-box-demo-form");
const pform = pbox.closest("form");
if (pform.getAttribute("method") !== "get" || !pform.getAttribute("action").endsWith("#reply_box")) return "the page's form has the wrong method or action";
if (!pform.querySelector(".ui-reply-box-avatar img")) return "an avatar image is not shown";
let sent = null;
const stop = (e) => { e.preventDefault(); sent = new FormData(pform); };
pform.addEventListener("submit", stop);
pbox.dispatchEvent(new FocusEvent("focus")); type(pbox, "Here it is");
pbox.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", metaKey: true, bubbles: true, cancelable: true })); await wait();
pform.removeEventListener("submit", stop);
if (!sent || sent.get("text") !== "Here it is" || sent.get("post") !== "42") return `the page's form sent ${sent && [...sent].join(";")}`;
type(pbox, "");
