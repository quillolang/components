const list = $("[role=tablist]");
if (!list || list.getAttribute("aria-orientation") !== "vertical" || list.getAttribute("aria-label") !== "Settings") return "it is not a vertical, labelled tablist";
const tabs = [...list.querySelectorAll("[role=tab]")];
if (tabs.length !== 5 || tabs[0].getAttribute("aria-selected") !== "true" || tabs[1].tabIndex !== -1) return "it does not start on the first tab";
const [a, b] = tabs.map((t) => t.getBoundingClientRect());
if (b.top <= a.bottom - 1) return "the tabs are not one under another";
const panel = $("[role=tabpanel]");
const pr = panel.getBoundingClientRect();
if (pr.left <= a.right || panel.getAttribute("aria-labelledby") !== tabs[0].id) return "the panel is not at the right, named by the tab";
if (!tabs[0].querySelector(".ui-vtabs-icon svg") || tabs[0].querySelector(".ui-vtabs-hint")?.textContent !== "Name, photo, bio") return "the icon or the hint is missing";
if (tabs[1].querySelector(".ui-vtabs-badge")?.textContent !== "2" || !tabs[4].disabled) return "the badge or disabled is missing";
tabs[2].click(); await wait();
if (tabs[2].getAttribute("aria-selected") !== "true" || !panel.textContent.includes("Password")) return `clicking Security did not show its panel: ${panel.textContent}`;
if (getComputedStyle(tabs[2]).backgroundColor === getComputedStyle(tabs[1]).backgroundColor) return "the selected tab does not look it";
key(tabs[2], "ArrowDown"); await wait();
if (tabs[3].getAttribute("aria-selected") !== "true" || document.activeElement !== tabs[3] || !panel.textContent.includes("Plan")) return "ArrowDown did not select and focus Billing";
key(tabs[3], "ArrowDown"); await wait();
if (tabs[0].getAttribute("aria-selected") !== "true") return "ArrowDown from the last live tab did not wrap to the first, skipping the disabled one";
key(tabs[0], "ArrowUp"); await wait();
if (tabs[3].getAttribute("aria-selected") !== "true") return "ArrowUp from the first did not wrap to the last live tab";
key(tabs[3], "Home"); await wait();
if (tabs[0].getAttribute("aria-selected") !== "true" || panel.getAttribute("aria-labelledby") !== tabs[0].id) return "Home did not go to the first tab";
