const [live, small] = $$(".ui-variant");
if (!live || !small) return "expected 2 pickers";
const groups = (p) => [...p.querySelectorAll("[role=radiogroup]")];
const radios = (g) => [...g.querySelectorAll("[role=radio]")];
const [colour, size] = groups(live);
if (document.getElementById(colour.getAttribute("aria-labelledby"))?.textContent !== "Colour:Black") return `the colour group's label: "${document.getElementById(colour.getAttribute("aria-labelledby"))?.textContent}"`;
const cr = radios(colour);
if (cr.length !== 4 || !cr.every((r) => r.classList.contains("ui-variant-swatch"))) return "colours are not swatches";
if (cr[0].getAttribute("aria-checked") !== "true" || cr[0].getAttribute("aria-label") !== "Black") return "chosen does not check black, or it is unnamed";
if (getComputedStyle(cr[1].querySelector("span")).backgroundColor !== "rgb(216, 199, 160)") return "the swatch does not show its colour";
if (cr[3].getAttribute("aria-disabled") !== "true" || !cr[3].getAttribute("aria-label").includes("sold out")) return "a sold-out colour is not said";
const hidden = (n) => live.querySelector(`input[type=hidden][name=${n}]`).value;
if (hidden("colour") !== "black" || hidden("size") !== "M") return `hidden inputs: ${hidden("colour")}, ${hidden("size")}`;
cr[1].click(); await wait();
if (cr[1].getAttribute("aria-checked") !== "true" || cr[0].getAttribute("aria-checked") !== "false" || hidden("colour") !== "sand") return "clicking a swatch does not choose it";
if (!$(".demo-note").textContent.includes("colour=sand, size=M")) return `on_change: ${$(".demo-note").textContent}`;
cr[3].click(); await wait();
if (hidden("colour") !== "sand") return "a sold-out swatch can be chosen";
const sr = radios(size);
if (sr.map((r) => r.textContent).join() !== "XS,S,M,L,XL" || sr[2].getAttribute("aria-checked") !== "true") return "sizes are not buttons starting on M";
if (sr[2].tabIndex !== 0 || sr[1].tabIndex !== -1) return "only the chosen size should be in the tab order";
key(sr[2], "ArrowRight"); await wait();
if (hidden("size") !== "L" || document.activeElement !== sr[3]) return "ArrowRight does not move to L";
if (!document.getElementById(size.getAttribute("aria-labelledby")).textContent.includes("Fits large")) return "the hint is not shown when chosen";
key(sr[3], "ArrowRight"); await wait();
if (hidden("size") !== "XS") return `ArrowRight from L skips sold-out XL and wraps: got ${hidden("size")}`;
key(sr[0], "End"); await wait();
if (hidden("size") !== "L") return "End does not go to the last available";
const [width] = groups(small);
if (!small.querySelector(".ui-variant-need") || small.querySelector(".ui-variant-need").textContent !== "Choose width") return "required with nothing chosen does not say so";
if (width.getAttribute("aria-required") !== "true") return "aria-required is missing";
if (radios(width)[0].tabIndex !== 0) return "with nothing chosen the first option is not focusable";
if (!small.classList.contains("ui-variant-sm")) return "size=sm is missing";
