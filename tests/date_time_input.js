const d = $("#date-time-input-dti-demo-starts-date");
const t = $("#date-time-input-dti-demo-starts-time");
const hidden = $("input[type=hidden][name=dti-demo-starts]");
if (d.type !== "date" || t.type !== "time") return "the fields are not the browser's date and time";
if (d.getAttribute("aria-label") !== "Date" || t.getAttribute("aria-label") !== "Time") return "the fields are not named";
if (!d.closest("fieldset").querySelector("legend")?.textContent.includes("Starts")) return "no legend";
if (d.value !== "2026-11-02" || t.value !== "09:00" || hidden.value !== "2026-11-02T09:00") return `the value starts as ${d.value} ${t.value} / ${hidden.value}`;
if (d.min !== "2026-11-01" || d.max !== "2027-12-31") return "earliest and latest are not the date's limits";
type(d, "2026-12-24"); type(t, "18:45"); await wait();
if (hidden.value !== "2026-12-24T18:45") return `a local value: ${hidden.value}`;
type(t, ""); await wait();
if (hidden.value !== "") return "without a time the value is not empty";
const cd = $("#date-time-input-dti-demo-call-date"), ct = $("#date-time-input-dti-demo-call-time");
const note = () => cd.closest(".demo-stack").querySelector(".demo-note").textContent;
if (ct.step !== "900") return `step={15} is ${ct.step}s`;
type(cd, "2026-07-02"); await wait();
if (note() !== "Pick a date and a time.") return "a date alone was sent";
type(ct, "14:30"); await wait();
if (note() !== "The form sends 2026-07-02T14:30:00+01:00.") return `summer in Lisbon: ${note()}`;
type(cd, "2026-12-02"); await wait();
if (note() !== "The form sends 2026-12-02T14:30:00Z.") return `winter in Lisbon: ${note()}`;
const zone = $("#date-time-input-dti-demo-call-zone");
if (!zone.textContent.includes("Europe/Lisbon") || !cd.closest("fieldset").getAttribute("aria-describedby").includes(zone.id)) return "the zone is not said";
const ud = $("#date-time-input-dti-demo-utc-date"), ut = $("#date-time-input-dti-demo-utc-time");
if (ud.value !== "2026-11-02" || ut.value !== "13:30" || $("input[name=dti-demo-utc]").value !== "2026-11-02T13:30:00Z") return `an offset value in UTC: ${ud.value} ${ut.value}`;
if (!ud.required || ud.getAttribute("aria-invalid") !== "true") return "required and error are not on the fields";
