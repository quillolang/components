const box = $("#masked-input-mi-demo-phone");
const hidden = $("input[type=hidden][name=mi-demo-phone]");
if (box.name) return "the visible box itself would be sent";
if (box.placeholder !== "(___) ___-____") return `the placeholder is "${box.placeholder}"`;
if (box.inputMode !== "numeric" || box.maxLength !== 14) return "a digits-only mask does not bring a number pad and a length";
if (!box.labels[0]?.textContent.includes("Phone")) return "the label is not tied to the box";
type(box, "555"); await wait();
if (box.value !== "(555" || hidden.value !== "555") return `"555" shows "${box.value}", sends "${hidden.value}"`;
type(box, "5551234567"); await wait();
if (box.value !== "(555) 123-4567" || hidden.value !== "5551234567") return `pasting digits shows "${box.value}", sends "${hidden.value}"`;
if (!box.closest(".ui-masked-input").classList.contains("ui-masked-input-done")) return "a full mask is not marked done";
type(box, "55a5-1x2"); await wait();
if (box.value !== "(555) 12") return `letters got in: "${box.value}"`;
type(box, "555123456789"); await wait();
if (box.value !== "(555) 123-4567") return `too many digits: "${box.value}"`;
const plate = $("#masked-input-mi-demo-plate");
const note = () => plate.closest(".demo-stack").querySelector(".demo-note").textContent;
type(plate, "ab12"); await wait();
if (plate.value !== "AB-12" || note() !== "So far: AB-12") return `plate: "${plate.value}", note: ${note()}`;
type(plate, "ab12cd"); await wait();
if (note() !== "Plate AB-12-CD is complete." || $("input[name=mi-demo-plate]").value !== "AB-12-CD") return `on_change complete: ${note()}`;
type(plate, "1ab"); await wait();
if (plate.value !== "AB") return `a digit in a letter slot got in: "${plate.value}"`;
const code = $("#masked-input-mi-demo-code");
if (code.value !== "ABC-1234" || $("input[name=mi-demo-code]").value !== "ABC-1234") return `value is not shaped: "${code.value}"`;
const exp = $("#masked-input-mi-demo-exp");
if (exp.placeholder !== "MM/YY" || exp.getAttribute("aria-invalid") !== "true" || !exp.closest(".ui-masked-input").querySelector("[role=alert]")) return "placeholder or error is not passed through";
