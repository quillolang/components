const c = $("#record-card-demo-customer");
if (!c || c.tagName !== "ARTICLE") return "the card is not an <article>";
const h = c.querySelector("h3.ui-recordcard-title");
if (!h || h.textContent !== "Northwind Traders" || h.querySelector("a")?.getAttribute("href") !== "#northwind") return "the title and its link";
if (c.querySelector(".ui-recordcard-pic").textContent.trim() !== "NT") return "initials";
const st = c.querySelector(".ui-recordcard-status");
if (st.textContent !== "Active" || !st.classList.contains("ui-recordcard-success")) return "status";
if (c.querySelector(".ui-recordcard-sub").textContent !== "Customer since 2019") return "subtitle";
const dts = [...c.querySelectorAll("dt")].map((d) => d.textContent);
const dds = [...c.querySelectorAll("dd")].map((d) => d.textContent.trim());
if (dts.length !== 7) return `expected 7 fields, found ${dts.length}`;
const val = (l) => dds[dts.indexOf(l)];
if (val("Balance") !== "$1,240.50" || val("Renews") !== "Jan 31, 2027" || val("Tax exempt") !== "No" || val("Phone") !== "—") return `values: ${dds}`;
const dd = (l) => c.querySelectorAll("dd")[dts.indexOf(l)];
if (dd("Email").querySelector("a")?.getAttribute("href") !== "mailto:buy@northwind.example") return "href makes a link";
if (!dd("Customer id").classList.contains("ui-recordcard-mono") || !dd("Phone").classList.contains("ui-recordcard-none")) return "mono and none";
if (getComputedStyle(c.querySelector(".ui-recordcard-fields")).gridTemplateColumns.split(" ").length !== 2) return "two columns";
if (!dd("Notes").parentElement.classList.contains("ui-recordcard-wide") || getComputedStyle(dd("Notes").parentElement).gridColumnStart !== "1") return "wide";
const foot = c.querySelector("footer.ui-recordcard-foot");
if (!foot || foot.querySelectorAll("a.ui-btn").length !== 2) return "the actions footer";
const d = $("#record-card-demo-device");
if (!d.querySelector("h4.ui-recordcard-title")) return "level={4}";
if (d.querySelector(".ui-recordcard-pic") || d.querySelector("footer")) return "a card without avatar or children has them";
if (getComputedStyle(d.querySelector(".ui-recordcard-fields")).gridTemplateColumns.split(" ").length !== 1) return "columns={1}";
const ddv = [...d.querySelectorAll("dd")].map((x) => x.textContent.trim());
if (ddv.join("|") !== "PHB8K21734|18%|48,210") return `formats: ${ddv}`;
