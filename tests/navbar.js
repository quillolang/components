const [wide, narrow] = $$(".ui-navbar");
if (!wide || !narrow) return "expected two navbars";
const shown = (el) => el && getComputedStyle(el).display !== "none";
const wn = wide.querySelector(".ui-navbar-nav");
if (!shown(wn) || shown(wide.querySelector(".ui-navbar-menu"))) return "when wide, the links show and the menu button does not";
if (wn.getAttribute("aria-label") !== "Main" || wn.querySelectorAll("a").length !== 4) return "the nav has no label or not 4 links";
const cur = wn.querySelectorAll('[aria-current="page"]');
if (cur.length !== 1 || cur[0].textContent !== "Docs") return "the link to `current` is not marked aria-current=page";
if (wide.querySelector(".ui-navbar-brand").getAttribute("href") !== "/") return "the brand does not link home";
if (wide.querySelectorAll(".ui-navbar-end .ui-btn").length !== 2) return "the children are not at the end";
if (shown(narrow.querySelector(".ui-navbar-nav"))) return "when narrow, the links still show in the bar";
const menu = narrow.querySelector("details.ui-navbar-menu");
if (!shown(menu) || menu.open) return "when narrow, there is no closed menu button";
menu.querySelector("summary").click(); await wait();
if (!menu.open) return "the menu button does not open the menu";
const a = menu.querySelector('nav a[aria-current="page"]');
if (!a || a.getBoundingClientRect().height === 0) return "the opened menu does not show the links";
menu.querySelector("summary").click(); await wait();
if (menu.open) return "the menu button does not close the menu";
