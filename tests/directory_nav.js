const nav = $("#directory-nav-demo");
if (!nav || nav.tagName !== "NAV" || nav.getAttribute("aria-label") !== "Directory") return "it is not a labelled <nav>";
const heads = [...nav.querySelectorAll(".ui-dirnav-head")].map((h) => h.textContent);
if (heads.join("") !== "ABDEFGHJKLMNRTY#") return `the groups are ${heads.join("")}`;
const a = nav.querySelector("#directory-nav-demo-A");
if (!a || a.tagName !== "H3" || a.closest("section").getAttribute("aria-labelledby") !== "directory-nav-demo-A") return "a group is not a section named by its header";
const names = [...a.closest("section").querySelectorAll(".ui-dirnav-name")].map((n) => n.textContent);
if (names.join() !== "Ada Lovelace,Alan Turing") return `the A group, sorted, is ${names}`;
const other = nav.querySelector("#directory-nav-demo-other");
if (!other || !other.closest("section").textContent.includes("3Blue1Brown")) return "a name starting with a digit is not under #";
const bar = nav.querySelector(".ui-dirnav-bar");
const letters = [...bar.querySelectorAll("li > *")];
if (letters.length !== 27 || letters[0].getAttribute("href") !== "#directory-nav-demo-A") return "the letter row does not link to the headers";
if (letters[2].tagName !== "SPAN" || letters[2].getAttribute("aria-disabled") !== "true") return "a letter with no names is not disabled";
if (letters[26].getAttribute("href") !== "#directory-nav-demo-other") return "# does not link to the other group";
const cur = nav.querySelectorAll("[aria-current=page]");
if (cur.length !== 1 || !cur[0].textContent.includes("Ada")) return "the current item is not marked once";
if (cur[0].querySelector(".ui-dirnav-meta")?.textContent !== "Engineering") return "meta is missing";
if (getComputedStyle(bar).position !== "sticky" || getComputedStyle(a).position !== "sticky") return "the letter row and the headers are not sticky";
const box = nav.getBoundingClientRect();
nav.scrollTop = 500; await wait(100);
const stuck = [...nav.querySelectorAll(".ui-dirnav-head")].filter((h) => { const r = h.getBoundingClientRect(); return r.top >= box.top && r.top < box.top + 60; });
if (stuck.length === 0) return "scrolled, no letter header is stuck at the top";
if (bar.getBoundingClientRect().top - box.top > 2) return "scrolled, the letter row is not at the top";
nav.scrollTop = 0;
