const radios = $$("input[name=color]");
if (radios.length !== 6 || radios.some((r) => r.type !== "radio")) return "the swatches are not 6 radios";
if (radios.find((r) => r.checked)?.value !== "#18794e") return "value did not check the green swatch";
const fs = radios[0].closest("fieldset");
if (fs.getAttribute("role") !== "radiogroup" || !fs.querySelector("legend")?.textContent.includes("Label colour")) return "the group has no legend or role";
if (!document.getElementById(fs.getAttribute("aria-describedby"))?.textContent.includes("arrow")) return "the hint is not tied to the group";
if (radios.some((r) => r.labels.length !== 1)) return "every swatch needs its own label";
const chip = radios[0].parentElement.querySelector(".ui-color-swatches-chip");
if (getComputedStyle(chip).backgroundColor !== "rgb(91, 75, 219)") return `the swatch is not painted its colour: ${getComputedStyle(chip).backgroundColor}`;
if (radios[0].labels[0].querySelector(".ui-sr")?.textContent.trim() !== "#5b4bdb") return "a hex swatch has no name for screen readers";
const themes = $$("input[name=theme]");
if (themes.length !== 5 || themes.find((r) => r.checked)?.value !== "ocean") return "the live group does not start on ocean";
if (!themes[4].disabled) return "a disabled swatch is not disabled";
const names = themes.map((r) => r.labels[0].querySelector(".ui-color-swatches-name")?.textContent.trim());
if (names.join() !== "Ocean,Forest,Plum,Ember,Sand") return `names={true} does not write the names: ${names}`;
themes[2].labels[0].click(); await wait();
if (!themes[2].checked || !$(".demo-note").textContent.includes("plum")) return `on_change did not update: ${$(".demo-note").textContent}`;
const tiny = $$("input[name=tiny]");
if (!tiny[0].required) return "required is not on the radios";
const tfs = tiny[0].closest("fieldset");
if (tfs.getAttribute("aria-invalid") !== "true" || !tfs.querySelector("[role=alert]")?.textContent.includes("Pick")) return "an error does not mark the group";
