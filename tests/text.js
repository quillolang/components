const all = $$(".ui-text");
if (all.length < 18) return `expected at least 18 texts, found ${all.length}`;
const plain = $("#text-demo-plain"), muted = $("#text-demo-muted");
if (plain.tagName !== "P" || muted.tagName !== "P") return "the default element is not a <p>";
const probe = document.createElement("span"); probe.style.color = "var(--ui-muted)"; plain.parentElement.append(probe);
const mutedColor = getComputedStyle(probe).color; probe.remove();
if (getComputedStyle(muted).color !== mutedColor) return "tone=muted is not the muted colour";
if (getComputedStyle(muted).color === getComputedStyle(plain).color) return "the muted tone looks like plain text";
if (muted.getBoundingClientRect().top < plain.getBoundingClientRect().bottom) return "two paragraphs are not stacked";
const size = (el) => parseFloat(getComputedStyle(el).fontSize);
const sizes = $$("span.ui-text").slice(0, 5);
if (sizes.some((s) => s.tagName !== "SPAN")) return "tag=span does not write a span";
for (let i = 1; i < 5; i++) if (!(size(sizes[i]) > size(sizes[i - 1]))) return `size ${i} is not larger than the one before`;
if (getComputedStyle($("#text-demo-bold")).fontWeight !== "700") return "weight=bold is not bold";
if (!/mono|Menlo|Consolas/i.test(getComputedStyle($("#text-demo-mono")).fontFamily)) return "mono is not in the monospace font";
const center = $("#text-demo-center");
if (getComputedStyle(center).textAlign !== "center") return "align=center is not applied";
const danger = $$("span.ui-text").find((s) => s.textContent === "3 failed");
if (!danger || getComputedStyle(danger).color === getComputedStyle(plain).color || getComputedStyle(danger).fontWeight !== "600") return "a danger, semibold span is not coloured and weighted";
