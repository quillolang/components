const [live, form, none] = $$(".ui-tokens");
if (!live || !form || !none) return "the three lists are missing";
const table = live.querySelector("table");
if (!table || table.getAttribute("aria-label") !== "API tokens") return "the table is not named";
const rows = () => [...live.querySelectorAll("tbody tr")];
if (rows().length !== 3) return `3 tokens, found ${rows().length}`;
const [ci, laptop, old] = rows();
if (ci.querySelector(".ui-tokens-name")?.textContent !== "CI deploy" || ci.querySelector(".ui-tokens-prefix")?.textContent !== "qt_live_8f3a…") return "name and prefix are wrong";
if (!ci.children[1].textContent.includes("Sep 14, 2026") || !ci.children[2].textContent.includes("Oct 27, 2026")) return `dates: ${ci.children[1].textContent} / ${ci.children[2].textContent}`;
if (laptop.querySelector(".ui-tokens-never")?.textContent !== "Never") return "a null last_used is not Never";
if (!laptop.children[1].textContent.includes("Expires Dec 31, 2027")) return "an expiry to come is not shown";
if (old.querySelector(".ui-tokens-expired")?.textContent.trim() !== "· Expired") return "a past expiry does not say Expired";
if ([...ci.querySelectorAll(".ui-tokens-scope")].map((s) => s.textContent).join() !== "read,deploy" || old.querySelector(".ui-tokens-scope")) return "scopes are wrong";
const btn = laptop.querySelector("button.ui-confirm-btn");
if (!btn || btn.textContent.trim() !== "Revoke" || btn.getAttribute("aria-haspopup") !== "dialog") return "the Revoke button does not ask";
btn.click(); await wait();
let dlg = [...document.querySelectorAll(".q-dialog")].pop();
if (!dlg || !dlg.textContent.includes("Revoke this token?") || !dlg.textContent.includes('"Laptop"')) return "the dialog does not name the token";
dlg.querySelector(".q-cancel").click(); await wait(300);
if (rows().length !== 3) return "Cancel still revoked";
btn.click(); await wait();
dlg = [...document.querySelectorAll(".q-dialog")].pop();
dlg.querySelector(".q-ok").click(); await wait(300);
if (rows().length !== 2 || rows().some((r) => r.textContent.includes("Laptop"))) return "confirming did not remove the row";
if (!live.closest(".demo-stack").querySelector(".demo-note").textContent.includes("Revoked: Laptop.")) return "on_revoke did not reach the note";
if (form.tagName !== "FORM" || form.getAttribute("method") !== "post" || form.getAttribute("action") !== "#token_list") return "revoke_action does not make a form";
const fb = form.querySelector("button.ui-confirm-btn");
if (fb.type !== "submit" || fb.name !== "revoke" || fb.value !== "7") return "in a form Revoke is a submit button with the id";
if (none.querySelector(".ui-tokens-empty")?.textContent !== "No tokens yet." || none.querySelector("table")) return "no tokens does not say so";
