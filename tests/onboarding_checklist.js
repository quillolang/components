const [live, billing] = $$("section.ui-onboard");
if (!live || !billing) return "the two checklists are missing";
if (live.getAttribute("aria-label") !== "Get started" || live.querySelector("h3.ui-onboard-title")?.textContent !== "Get started") return "the default title is wrong";
const count = live.querySelector(".ui-onboard-count"), bar = live.querySelector("[role=progressbar]");
if (count.textContent.trim() !== "1 of 3 done" || bar.getAttribute("aria-valuenow") !== "1" || bar.getAttribute("aria-valuemax") !== "3") return `the count: ${count.textContent} / ${bar.outerHTML}`;
if (live.querySelector(".ui-onboard-fill").style.width !== "33%") return "the bar is not a third";
const steps = live.querySelectorAll("ol.ui-onboard-steps > li.ui-onboard-step");
if (steps.length !== 3) return `3 steps, found ${steps.length}`;
const [profile, team, deploy] = steps;
const box = (s) => s.querySelector("input[type=checkbox]");
if (!box(profile).checked || !profile.classList.contains("ui-onboard-done") || box(team).checked) return "done does not tick the first alone";
if (box(team).name !== "done" || box(team).value !== "team" || box(team).getAttribute("aria-label") !== "Done: Invite your team") return "the checkbox is not named";
const link = team.querySelector("a.ui-onboard-link");
if (!link || link.getAttribute("href") !== "#onboarding_checklist" || link.textContent !== "Invite →" || deploy.querySelector("a").textContent !== "Set up →") return "the links are wrong";
if (team.querySelector(".ui-onboard-text")?.textContent !== "Three seats are free on this plan.") return "the text is missing";
if (live.querySelector(".ui-onboard-all")) return "it says all done with two to go";
const noteEl = live.closest(".demo-stack").querySelector(".demo-note");
const note = () => noteEl.textContent;
box(team).click(); await wait();
if (!box(team).checked || !team.classList.contains("ui-onboard-done") || count.textContent.trim() !== "2 of 3 done" || note() !== "team done") return `ticking: ${count.textContent} / ${note()}`;
box(team).click(); await wait();
if (box(team).checked || count.textContent.trim() !== "1 of 3 done" || note() !== "team undone") return "unticking does not go back";
box(team).click(); box(deploy).click(); await wait();
const all = live.querySelector(".ui-onboard-all");
if (!all || !all.textContent.includes("All done") || live.querySelector(".ui-onboard-fill").style.width !== "100%") return "all done is not said";
if (!billing.querySelector(".ui-onboard-all") || billing.querySelector(".ui-onboard-hide")) return "dismissable={false} still offers Hide";
const hide = all.querySelector("button.ui-onboard-hide");
if (!hide) return "no Hide button";
hide.click(); await wait();
if (live.isConnected && live.offsetParent) return "Hide did not hide it";
if (!note().includes("on_dismiss was called")) return "on_dismiss did not reach the note";
