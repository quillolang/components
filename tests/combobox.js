const cb = $("#cb-country");
const hidden = $("input[type=hidden][name=country]");
const pop = cb.parentElement.querySelector(".ui-combobox-pop");
const opts = () => [...$("#cb-country-list").querySelectorAll("[role=option]")];
if (cb.getAttribute("role") !== "combobox" || cb.getAttribute("aria-controls") !== "cb-country-list") return "the input is not a combobox for its list";
if (cb.value !== "Portugal" || hidden.value !== "PT") return `it starts with "${cb.value}" / ${hidden.value}`;
if (!pop.hidden || cb.getAttribute("aria-expanded") !== "false") return "the list starts open";
type(cb, "land"); await wait();
if (pop.hidden || cb.getAttribute("aria-expanded") !== "true") return "typing did not open the list";
const names = opts().map((o) => o.textContent.trim());
if (names.join() !== "Finland,Iceland,Ireland,Netherlands,New Zealand,Switzerland") return `"land" shows: ${names}`;
if (cb.getAttribute("aria-activedescendant") !== opts()[0].id) return "the first option is not active";
key(cb, "ArrowDown"); await wait();
if (cb.getAttribute("aria-activedescendant") !== opts()[1].id || opts()[1].getAttribute("aria-selected") !== "true") return "ArrowDown did not move to the second";
key(cb, "ArrowUp"); key(cb, "ArrowUp"); await wait();
if (cb.getAttribute("aria-activedescendant") !== opts()[5].id) return "ArrowUp from the first did not wrap to the last";
key(cb, "Enter"); await wait();
if (cb.value !== "Switzerland" || hidden.value !== "CH" || !pop.hidden) return `Enter picked "${cb.value}" / ${hidden.value}, open: ${!pop.hidden}`;
type(cb, "zzz"); await wait();
if (opts().length !== 0 || !pop.textContent.includes("No matches")) return "no matches does not say so";
key(cb, "Escape"); await wait();
if (!pop.hidden) return "Escape did not close the list";
key(cb, "Escape"); await wait();
if (cb.value !== "" || hidden.value !== "") return "Escape on a closed list did not clear it";
type(cb, "nor"); await wait();
opts()[0].click(); await wait();
if (cb.value !== "Norway" || hidden.value !== "NO" || !pop.hidden) return `clicking picked "${cb.value}" / ${hidden.value}`;
type(cb, "xx"); cb.blur(); cb.dispatchEvent(new FocusEvent("blur")); await wait();
if (cb.value !== "Norway" || hidden.value !== "NO") return `leaving with unknown text did not go back: "${cb.value}"`;
type(cb, "spain"); cb.blur(); cb.dispatchEvent(new FocusEvent("blur")); await wait();
if (hidden.value !== "ES" || cb.value !== "Spain") return "leaving with an option's name did not pick it";
const lang = $("#cb-lang");
lang.focus(); key(lang, "ArrowDown"); await wait();
const all = [...$("#cb-lang-list").querySelectorAll("[role=option]")];
if (all.length !== 10 || lang.getAttribute("aria-expanded") !== "true") return "ArrowDown on a closed box did not open the whole list";
key(lang, "ArrowDown"); key(lang, "Enter"); await wait();
const note = lang.closest(".demo-stack").querySelector(".demo-note").textContent;
if (note !== "Picked Elixir.") return `on_change did not update the note: ${note}`;
lang.blur(); lang.dispatchEvent(new FocusEvent("blur"));
// Options found as one types, from the server.
const city = $("#cb-city");
const cpop = city.parentElement.querySelector(".ui-combobox-pop");
const copts = () => [...$("#cb-city-list").querySelectorAll("[role=option]")].map((o) => o.textContent.trim());
const cnote = () => city.closest(".demo-stack").querySelector(".demo-note").textContent;
type(city, "l"); await wait(500);
if (!cpop.hidden) return "one letter opened the list, with min_chars={2}";
type(city, "li"); await wait(80);
if (!cpop.textContent.includes("Searching…") || city.getAttribute("aria-busy") !== "true") return `no "Searching…" while asking: ${cpop.textContent}`;
await wait(600);
if (copts().join() !== "Lisbon" || cpop.textContent.includes("Searching")) return `"li" found: ${copts()}`;
key(city, "Enter"); await wait();
if (city.value !== "Lisbon" || cnote() !== "Going to Lisbon.") return `Enter picked "${city.value}": ${cnote()}`;
type(city, "p"); type(city, "po"); type(city, "pr"); await wait(900);
if (copts().join() !== "Prague") return `an older answer won: ${copts()}`;
city.blur(); city.dispatchEvent(new FocusEvent("blur")); await wait();
if (city.value !== "Lisbon" || $("input[type=hidden][name=city]").value !== "Lisbon") return `leaving did not go back to the city picked: "${city.value}"`;
type(city, "zz"); await wait(700);
if (!cpop.textContent.includes("No matches")) return "no matches does not say so";
