const items = $$(".ui-cart-item");
if (items.length !== 3) return `expected 3 items, found ${items.length}`;
const [live, beanie, bottle] = items;
const total = (it) => it.querySelector(".ui-cart-item-total .ui-price-now").textContent.replace(/\s/g, " ");
const qty = (it) => it.querySelector("input[type=number]");
if (live.querySelector(".ui-cart-item-name a")?.textContent !== "Trail runner") return "the name is not a link";
if ([...live.querySelectorAll(".ui-cart-item-opts li")].map((l) => l.textContent).join("|") !== "Size: 42|Black") return "options are not listed";
if (qty(live).value !== "2" || total(live) !== "$178.00" || live.querySelector(".ui-cart-item-each")?.textContent !== "$89.00 each") return `it starts at ${qty(live).value}, ${total(live)}`;
if (qty(live).getAttribute("aria-label") !== "Quantity of Trail runner") return "the quantity input is not named";
const [m1, p1] = [...live.querySelectorAll(".ui-cart-item-qty button")];
p1.click(); await wait();
if (qty(live).value !== "3" || total(live) !== "$267.00") return `+ gives ${qty(live).value}, ${total(live)}`;
if (!$(".demo-note").textContent.includes("Quantity 3")) return `on_change did not reach the note: ${$(".demo-note").textContent}`;
p1.click(); p1.click(); p1.click(); await wait();
if (qty(live).value !== "5" || !p1.disabled) return `limit={5} is not held: ${qty(live).value}`;
type(qty(live), "0"); await wait();
if (qty(live).value !== "1" || !m1.disabled || total(live) !== "$89.00" || live.querySelector(".ui-cart-item-each")) return `typing 0 gives ${qty(live).value}`;
live.querySelector(".ui-cart-item-remove").click(); await wait();
if (!$(".demo-note").textContent.includes("Removed") || $$(".ui-cart-item").length !== 2) return "on_remove was not called";
const form = beanie.closest("form");
const data = new FormData(form);
if (data.get("qty[beanie]") !== "1" || data.get("qty[bottle]") !== "3") return `the form sends ${[...data.entries()]}`;
const rm = beanie.querySelector(".ui-cart-item-remove");
if (rm.type !== "submit" || rm.name !== "remove" || rm.value !== "beanie") return "remove_field does not make a named submit button";
if (total(beanie) !== "24,00 €") return `de-DE reads ${total(beanie)}`;
if (beanie.querySelector(".ui-cart-item-stock")?.textContent !== "Only a few left" || bottle.querySelector(".ui-cart-item-stock")?.textContent !== "Out of stock") return "stock is not said";
if (total(bottle) !== "$97.50" || !bottle.classList.contains("ui-cart-item-sm")) return `3 × 32.5 reads ${total(bottle)}`;
