const half = $("#upload-progress-demo-half");
const bar = half.querySelector("[role=progressbar]");
if (!bar || bar.getAttribute("aria-label") !== "quarterly-report-final-v3-really-final.pdf") return "the progressbar is not named after the file";
if (bar.getAttribute("aria-valuenow") !== "37" || bar.getAttribute("aria-valuetext") !== "37%") return `37% of 4.2 MB: ${bar.getAttribute("aria-valuenow")}`;
if (half.querySelector(".ui-upprog-fill").style.width !== "37%") return "the fill is not 37% wide";
if (half.querySelector(".ui-upprog-meta").textContent !== "1.5 MB of 4 MB · 605.5 KB/s · 5 s left") return `the meta line: ${half.querySelector(".ui-upprog-meta").textContent}`;
if (half.querySelector(".ui-upprog-btn")) return "a Cancel button without on_cancel";
if (half.querySelector(".ui-upprog-pct")?.textContent !== "37%") return "no percent";
const name = half.querySelector(".ui-upprog-name");
if (name.scrollWidth > name.clientWidth + 1 && getComputedStyle(name).textOverflow !== "ellipsis") return "a long name is not cut with an ellipsis";
const done = $("#upload-progress-demo-done");
if (done.querySelector("[role=progressbar]").getAttribute("aria-valuenow") !== "100" || done.querySelector(".ui-upprog-meta").textContent !== "18 KB · Done") return `done: ${done.querySelector(".ui-upprog-meta").textContent}`;
const err = $("#upload-progress-demo-error");
if (err.querySelector(".ui-upprog-meta").getAttribute("role") !== "alert" || err.querySelector(".ui-upprog-meta").textContent !== "The connection dropped") return "the error is not an alert";
if (!$$(".ui-upprog").some((u) => u.classList.contains("ui-upprog-paused") && u.textContent.includes("Paused"))) return "paused";
const live = $("#upload-progress-demo-live");
$("#upload-progress-demo-restart").click(); await wait();
const cancel = live.querySelector(".ui-upprog-btn");
if (!cancel || cancel.textContent !== "Cancel" || !cancel.getAttribute("aria-label").startsWith("Cancel ")) return "the live one has no Cancel";
const n0 = Number(live.querySelector("[role=progressbar]").getAttribute("aria-valuenow"));
await wait(900);
const n1 = Number(live.querySelector("[role=progressbar]").getAttribute("aria-valuenow"));
if (!(n1 > n0) && n0 < 100) return "it does not move";
cancel.click(); await wait();
if (!live.classList.contains("ui-upprog-paused") || !live.textContent.includes("Paused")) return "on_cancel did not pause it";
const n2 = Number(live.querySelector("[role=progressbar]").getAttribute("aria-valuenow"));
await wait(900);
if (Number(live.querySelector("[role=progressbar]").getAttribute("aria-valuenow")) !== n2) return "paused, it still moves";
