const box = $("#post-composer-demo-live");
const form = box.closest("form");
const count = form.querySelector(".ui-post-composer-count");
const post = form.querySelector("button[type=submit]");
const note = () => form.closest(".demo-stack").querySelector(".demo-note").textContent;
if (box.tagName !== "TEXTAREA" || box.name !== "text" || !form.querySelector(`label[for="${box.id}"]`)) return "the box is not a labelled textarea named text";
if (form.getAttribute("enctype") !== "multipart/form-data") return "the form does not send files";
if (count.textContent.trim() !== "120 characters left0 / 120" && !count.textContent.includes("0 / 120")) return `the count starts at ${count.textContent}`;
if (!post.disabled) return "Post is on with nothing written";
type(box, "Hello"); await wait();
if (!count.textContent.includes("5 / 120") || !count.querySelector(".ui-sr").textContent.includes("115 characters left")) return `after typing, the count says ${count.textContent}`;
if (post.disabled) return "Post stayed off after typing";
type(box, "x".repeat(112)); await wait();
if (!count.classList.contains("ui-post-composer-near")) return "the count is not marked near the limit";
type(box, "x".repeat(125)); await wait();
if (!count.classList.contains("ui-post-composer-over") || !post.disabled || !count.querySelector(".ui-sr").textContent.includes("5 characters over")) return `over the limit: ${count.className}, disabled ${post.disabled}`;
// Attach two files, remove one.
const picker = form.querySelector("input[type=file]");
if (!picker || picker.name !== "files" || !picker.multiple) return "no multiple file input named files";
const dt = new DataTransfer();
dt.items.add(new File(["a".repeat(2048)], "photo.png", { type: "image/png" }));
dt.items.add(new File(["b"], "notes.txt", { type: "text/plain" }));
picker.files = dt.files; picker.dispatchEvent(new Event("change", { bubbles: true })); await wait();
const chips = () => [...form.querySelectorAll(".ui-post-composer-file")];
if (chips().length !== 2 || chips()[0].querySelector("span").textContent !== "photo.png" || chips()[0].querySelector("small").textContent !== "2 KB") return `attached: ${chips().map((c) => c.textContent)}`;
chips()[1].querySelector("button").click(); await wait();
if (chips().length !== 1) return "removing a file did not remove its chip";
type(box, "Shipped the new tables today."); await wait();
post.click(); await wait();
if (note() !== `"Shipped the new tables today." with 1 file`) return `on_post did not reach the note: ${note()}`;
if (box.value !== "" || chips().length !== 0 || !post.disabled) return "posting did not empty the box and the files";
type(box, "Again"); box.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", ctrlKey: true, bubbles: true, cancelable: true })); await wait();
if (!note().endsWith(`"Again" with 0 files`)) return `Ctrl+Enter did not post: ${note()}`;
// In a page: Post submits the form with the children in it.
const pbox = $("#post-composer-demo-form");
const pform = pbox.closest("form");
if (pform.querySelector("input[type=file]")) return "attach={false} still shows the file input";
if (!pform.querySelector(".ui-post-composer-avatar img")) return "an avatar image is not shown";
if (pform.querySelector("button[type=submit]").textContent !== "Share") return "post_label is not the button's text";
let sent = null;
const stop = (e) => { e.preventDefault(); sent = new FormData(pform); };
pform.addEventListener("submit", stop);
type(pbox, "Update"); await wait(); pform.querySelector("button[type=submit]").click(); await wait();
pform.removeEventListener("submit", stop);
if (!sent || sent.get("text") !== "Update" || sent.get("channel") !== "general") return `the page's form sent ${sent && [...sent].join(";")}`;
type(pbox, "");
