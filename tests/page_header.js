const [orders, ada] = $$("header.ui-pagehead");
if (!orders || !ada) return "expected two page headers";
const h1 = orders.querySelector("h1.ui-pagehead-title");
if (!h1 || h1.textContent !== "Orders") return "the title is not an <h1>";
const crumb = orders.querySelector(".ui-breadcrumbs");
if (!crumb || crumb.getBoundingClientRect().bottom > h1.getBoundingClientRect().top) return "the breadcrumb is not above the title";
if (!orders.querySelector(".ui-pagehead-desc")?.textContent.startsWith("Everything")) return "the description is missing";
const acts = orders.querySelector(".ui-pagehead-actions");
if (!acts || acts.querySelectorAll(".ui-btn").length !== 2) return "the two actions are missing";
const ar = acts.getBoundingClientRect(), hr = orders.getBoundingClientRect();
if (hr.right - ar.right > 2 || ar.left < h1.getBoundingClientRect().right) return "the actions are not at the right of the title row";
if (!orders.querySelector(".ui-pagehead-below .ui-tabs")) return "the children (tabs) are not below the row";
if (getComputedStyle(orders).borderBottomWidth !== "1px") return "the divider line is missing";
if (ada.querySelector(".ui-pagehead-eyebrow")?.textContent !== "Customer") return "the eyebrow is missing";
const back = ada.querySelector("a.ui-pagehead-back");
if (!back || !back.textContent.includes("All customers") || back.getAttribute("href") !== "#page_header") return "the back link is missing";
if (!ada.querySelector(".ui-pagehead-avatar .ui-avatar")) return "the avatar slot is missing";
if (!ada.querySelector(".ui-pagehead-meta .ui-badge") || !ada.querySelector(".ui-pagehead-meta").textContent.includes("12 orders")) return "the meta slot is missing";
if (getComputedStyle(ada).borderBottomWidth !== "0px") return "divider={false} still draws a line";
if (ada.querySelector(".ui-pagehead-below").offsetHeight !== 0) return "an empty below slot takes room";
