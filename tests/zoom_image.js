const [main, square] = $$(".ui-zoom-image");
if (!main || !square) return "expected two zoom images";
if (main.getAttribute("role") !== "img" || main.getAttribute("aria-label") !== "Linen fabric with a small label" || main.tabIndex !== 0) return "the frame is not a focusable, named image";
const img = main.querySelector("img");
const scale = (el) => new DOMMatrix(getComputedStyle(el.querySelector("img")).transform).a;
if (scale(main) !== 1) return "it starts zoomed";
const r = main.getBoundingClientRect();
const pe = (t, fx, fy) => main.dispatchEvent(new PointerEvent(t, { bubbles: true, pointerType: "mouse", clientX: r.left + r.width * fx, clientY: r.top + r.height * fy }));
pe("pointerenter", 0.25, 0.75); await wait(350);
if (Math.abs(scale(main) - 2.5) > 0.01) return `hovering zooms to ${scale(main)}`;
if (main.style.getPropertyValue("--x").trim() !== "25%" || main.style.getPropertyValue("--y").trim() !== "75%") return `the zoom is centred at ${main.style.getPropertyValue("--x")} ${main.style.getPropertyValue("--y")}`;
pe("pointermove", 0.8, 0.1); await wait();
if (main.style.getPropertyValue("--x").trim() !== "80%" || main.style.getPropertyValue("--y").trim() !== "10%") return "moving the pointer does not move the zoom";
pe("pointerleave", 0.8, 0.1); await wait(350);
if (scale(main) !== 1) return "leaving does not zoom out";
main.focus(); key(main, "Enter"); await wait(350);
if (Math.abs(scale(main) - 2.5) > 0.01 || !main.getAttribute("aria-description").startsWith("Zoomed")) return "Enter does not zoom";
key(main, "ArrowRight"); key(main, "ArrowUp"); await wait();
if (main.style.getPropertyValue("--x").trim() !== "60%" || main.style.getPropertyValue("--y").trim() !== "40%") return `the arrows move the zoom to ${main.style.getPropertyValue("--x")} ${main.style.getPropertyValue("--y")}`;
key(main, "Escape"); await wait(350);
if (scale(main) !== 1) return "Escape does not zoom out";
main.dispatchEvent(new MouseEvent("click", { bubbles: true, clientX: r.left + r.width / 2, clientY: r.top + r.height / 2 })); await wait(350);
if (scale(main) === 1) return "a click does not hold the zoom on";
pe("pointerleave", 0.5, 0.5); await wait(350);
if (scale(main) === 1) return "a held zoom ends when the pointer leaves";
main.dispatchEvent(new MouseEvent("click", { bubbles: true })); await wait(350);
if (scale(main) !== 1) return "a second click does not zoom out";
if (main.querySelector(".ui-zoom-image-hint")?.textContent.trim() !== "Hover to zoom") return "the hint is missing";
const simg = square.querySelector("img");
if (!simg.src.startsWith("data:")) return "the large picture loads before it is wanted";
square.focus(); key(square, "Enter"); await wait(350);
if (!simg.src.startsWith("https://picsum.photos/seed/weave/")) return "zooming does not switch to the large picture";
if (Math.abs(scale(square) - 4) > 0.01) return "zoom={4} is not applied";
key(square, "Escape");
const sq = square.getBoundingClientRect();
if (Math.abs(sq.width - sq.height) > 1) return "ratio 1 is not square";
