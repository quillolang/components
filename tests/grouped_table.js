const t = $("#grouped-table-demo-expenses table");
if (!t || t.getAttribute("aria-label") !== "Expenses by team") return "the table is not named";
const bodies = [...t.querySelectorAll("tbody")];
if (bodies.length !== 3) return `expected 3 groups, found ${bodies.length}`;
const heads = bodies.map((b) => b.querySelector(".ui-grouped-group th"));
if (heads.map((h) => h.querySelector(".ui-grouped-name").textContent).join() !== "Design,Engineering,Sales") return "groups are not in the order of their first rows";
if (heads[0].getAttribute("scope") !== "rowgroup" || heads[0].getAttribute("colspan") !== "4") return "the group heading does not span the row";
if (heads[1].querySelector(".ui-grouped-count").textContent !== "3 rows") return `show_count: ${heads[1].querySelector(".ui-grouped-count").textContent}`;
const sub = (i) => [...bodies[i].querySelector(".ui-grouped-sub").children].map((c) => c.textContent.trim());
if (sub(0).join("|") !== "Subtotal||14%|$629.50") return `the Design subtotal row is ${sub(0)}`;
if (sub(1)[3] !== "$3,900.40") return `the Engineering subtotal is ${sub(1)[3]}`;
if (sub(2).join("|") !== "Subtotal||0%|$0.00") return `a group of nulls sums to ${sub(2)}`;
const total = [...t.querySelector("tfoot .ui-grouped-total").children].map((c) => c.textContent.trim());
if (total.join("|") !== "Total||100%|$4,529.90") return `the grand total row is ${total}`;
if (t.querySelector("tfoot th").getAttribute("scope") !== "row") return "the total label is not a row header";
const cells = [...bodies[0].querySelectorAll("tr:not(.ui-grouped-group):not(.ui-grouped-sub) td")].map((c) => c.textContent.trim());
if (cells.join("|") !== "Figma seats|Mar 2, 2026|12%|$540.00|Stock photos|Mar 14, 2026|2%|$89.50") return `the Design rows are ${cells}`;
if (!bodies[2].querySelector("td.ui-grouped-right")?.textContent.includes("—")) return "a null is not a dash";
if (!t.querySelector("thead th.ui-grouped-right")) return "number columns are not right-aligned";
const s = $("#grouped-table-demo-scores table");
const names = [...s.querySelectorAll(".ui-grouped-name")].map((n) => n.textContent);
if (names.join() !== "Round 1,Round 2") return `order="asc" gives ${names}`;
if (s.querySelector("tfoot")) return "grand={false} still shows a grand total";
const r1 = [...s.querySelector("tbody .ui-grouped-sub").children].map((c) => c.textContent.trim());
if (r1.join("|") !== "Round total|142") return `the round total is ${r1}`;
