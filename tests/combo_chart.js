if (document.documentElement.scrollWidth > innerWidth) return "widens the page";
const charts = $$("figure.ui-comboc");
if (charts.length !== 3) return `expected 3 combo charts, found ${charts.length}`;
if (/NaN|Infinity|undefined/.test(charts.map((c) => c.innerHTML).join(""))) return "a chart has NaN, Infinity or undefined in it";
const [rev, visits, weather] = charts;
const left = [...rev.querySelectorAll(".ui-comboc-left span")].map((s) => s.textContent);
const right = [...rev.querySelectorAll(".ui-comboc-right span")].map((s) => s.textContent);
if (left.join() !== "$0,$20k,$40k,$60k,$80k") return `the left axis: ${left}`;
if (right.join() !== "0%,10%,20%,30%") return `the right axis: ${right}`;
const plot = rev.querySelector(".ui-comboc-plot").getBoundingClientRect();
const l = rev.querySelector(".ui-comboc-left").getBoundingClientRect(), r = rev.querySelector(".ui-comboc-right").getBoundingClientRect();
if (!(l.right <= plot.left && r.left >= plot.right)) return "the axes are not on either side of the plot";
const bars = [...rev.querySelectorAll(".ui-comboc-bar")];
if (bars.length !== 8) return `8 values made ${bars.length} bars`;
if (Math.abs(bars[7].getBoundingClientRect().height - 240 * 64900 / 80000) > 1) return "a bar is not as tall as its value on the left axis";
const pts = [...rev.querySelectorAll(".ui-comboc-pt")];
if (pts.length !== 8) return "the line has no dot per value";
const p7 = pts[7].getBoundingClientRect();
if (Math.abs((p7.top + p7.bottom) / 2 - (plot.bottom - 240 * 27.3 / 30)) > 1) return "a line's dot is not at its value on the right axis";
const b7 = bars[7].getBoundingClientRect();
if (Math.abs((p7.left + p7.right) / 2 - (b7.left + b7.right) / 2) > 1) return "the line's dot is not above its label's bar";
if (getComputedStyle(pts[0]).backgroundColor === getComputedStyle(bars[0]).backgroundColor) return "the line has the bars' colour";
const tip = rev.querySelectorAll(".ui-comboc-col")[2].querySelector(".ui-comboc-tip");
if (getComputedStyle(tip).display !== "none") return "the tooltip shows before hover";
if (tip.textContent !== "MarRevenue$51,200Margin22.1%") return `tooltip: ${tip.textContent}`;
if ([...rev.querySelectorAll(".ui-comboc-axis")].map((a) => a.textContent).join() !== "Revenue,Margin") return "the axes are not named";
if (rev.querySelectorAll("thead th").length !== 3) return "the table has no column per series";

if (visits.querySelectorAll(".ui-comboc-col")[0].querySelectorAll(".ui-comboc-bar").length !== 2) return "two bar series are not side by side";
if (visits.querySelector(".ui-comboc-right span").textContent !== "2.4%") return "line_zero={false} still starts at 0";
const vline = visits.querySelector(".ui-comboc-line").getAttribute("d");
if ((vline.match(/M/g) || []).length !== 2) return `a null does not break the line: ${vline}`;
if ([...visits.querySelectorAll(".ui-comboc-axis")].map((a) => a.textContent).join() !== "Visits,Conversion") return "bar_axis and line_axis";
if (!visits.querySelectorAll(".ui-comboc-col")[3].querySelector(".ui-comboc-tip").textContent.endsWith("Conversion—")) return "the missing value is not a dash";

if (weather.querySelectorAll(".ui-comboc-line").length !== 2) return "two lines are not drawn";
if (weather.querySelectorAll(".ui-comboc-legend li").length !== 3) return "the legend does not list bars and lines";
if (!weather.querySelector(".ui-comboc-right").textContent.includes("-10°")) return "the right axis does not reach below zero";
if (weather.querySelectorAll(".ui-comboc-axis")[1].textContent !== "High, Low") return "the lines' axis is not named after them";
