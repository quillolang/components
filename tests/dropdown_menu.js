const [project] = $$(".ui-dropdown-btn");
const menu = document.getElementById(project.getAttribute("popovertarget"));
if (!menu || !menu.hasAttribute("popover")) return "the button does not target a popover";
project.scrollIntoView({ block: "center" });
project.click(); await wait();
if (!menu.matches(":popover-open")) return "clicking the button does not open the menu";
if (project.getAttribute("aria-expanded") !== null && project.ariaExpanded === "false") return "aria-expanded is false while open";
const b = project.getBoundingClientRect(), m = menu.getBoundingClientRect();
if (CSS.supports("position-area: bottom") && (m.top < b.bottom - 1 || Math.abs(m.left - b.left) > 1)) return `the menu is not under the button: ${m.top},${m.left} vs ${b.bottom},${b.left}`;
if (menu.querySelectorAll("a.ui-dropdown-item[href]").length !== 3) return "expected 3 link items";
if (!menu.querySelector("button.ui-dropdown-item").disabled) return "disabled: true does not disable the item";
if (!menu.querySelector('[role="separator"]')) return "divider: true does not make a separator";
if (!menu.querySelector("a.ui-dropdown-danger")?.textContent.includes("Delete")) return "tone: danger is missing";
project.click(); await wait();
if (menu.matches(":popover-open")) return "clicking the button again does not close it";
const sort = $$(".ui-dropdown-btn")[2];
sort.click(); await wait();
const sm = document.getElementById(sort.getAttribute("popovertarget"));
const oldest = [...sm.querySelectorAll("button")].find((x) => x.textContent === "Oldest");
oldest.click(); await wait();
if (sm.matches(":popover-open")) return "choosing an item does not close the menu";
if (!$(".demo-note").textContent.includes("Oldest")) return `on_select was not called: ${$(".demo-note").textContent}`;
