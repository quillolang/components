const [live, page] = $$("section.ui-chat");
const log = live.querySelector("[role=log]");
if (!log || log.getAttribute("aria-label") !== "Messages") return "the messages are not a labelled log";
const rows = () => [...live.querySelectorAll(".ui-chat-list > li")];
if (rows().length !== 8) return `expected 8 messages, found ${rows().length}`;
const days = [...live.querySelectorAll(".ui-chat-day")].map((d) => d.textContent);
if (days.join() !== "Yesterday,Today") return `the day lines are ${days}`;
const r = rows();
if (!r[1].classList.contains("ui-chat-mine") || !r[0].classList.contains("ui-chat-theirs")) return "mine and theirs are not told apart";
const side = (li) => li.querySelector(".ui-chat-bubble").getBoundingClientRect();
if (side(r[1]).right <= side(r[0]).right) return "my messages are not on the right";
// Ana's two in a row today: one group, the name on the first, the avatar and time on the last.
if (!r[3].classList.contains("ui-chat-first") || r[4].classList.contains("ui-chat-first")) return "consecutive messages are not grouped";
if (r[3].querySelector(".ui-chat-name")?.textContent !== "Ana Silva" || r[4].querySelector(".ui-chat-name")) return "the name is not on the group's first message only";
if (r[4].querySelector(".ui-sr")?.textContent !== "Ana Silva:") return "a grouped message does not name its sender for screen readers";
if (!r[3].querySelector(".ui-chat-avatar").classList.contains("ui-chat-avatar-off") || !r[4].querySelector(".ui-chat-avatar:not(.ui-chat-avatar-off)")) return "the avatar is not on the group's last message";
if (r[4].querySelector(".ui-chat-avatar").textContent.trim() !== "AS") return "the avatar does not show the initials";
if (!r[2].classList.contains("ui-chat-first")) return "a new day does not start a new group";
if (r[3].querySelector("time").className !== "ui-sr" || r[4].querySelector("time").className !== "ui-chat-time") return "the time shows on the wrong message";
if (getComputedStyle(r[4].querySelector(".ui-chat-bubble")).whiteSpace !== "pre-wrap") return "line breaks in a message are lost";
const atBottom = () => { const l = log.getBoundingClientRect(), last = rows().at(-1).getBoundingClientRect(); return last.bottom <= l.bottom + 1 && last.bottom > l.bottom - 60; };
if (log.scrollHeight <= log.clientHeight) return "the demo's messages do not overflow, so scrolling is not tested";
if (!atBottom()) return "it does not open at the newest message";
const box = live.querySelector("textarea");
if (!box || live.querySelector(`label[for="${box.id}"]`) === null) return "the text box has no label";
type(box, "Line one"); await wait(50);
key(box, "Enter"); await wait();
if (rows().length !== 9 || rows().at(-1).querySelector(".ui-chat-bubble").textContent !== "Line one") return "Enter did not send";
if (box.value !== "") return "sending did not empty the box";
if (!atBottom()) return `after sending, it is not at the bottom: ${log.scrollTop} ${log.scrollHeight} ${log.clientHeight} ${rows().at(-1).getBoundingClientRect().bottom} ${log.getBoundingClientRect().bottom}`;
const typing = live.querySelector(".ui-chat-typing");
if (typing.getAttribute("role") !== "status" || !typing.textContent.includes("Ana Silva is typing")) return `the typing line says "${typing.textContent}"`;
await wait(1800);
if (rows().length !== 10 || typing.textContent.trim() !== "") return "the reply did not come, or the typing line stayed";
if (!atBottom()) return "a new message did not keep it at the bottom";
// Shift+Enter is a new line, and an empty box sends nothing.
type(box, "a");
box.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", shiftKey: true, bubbles: true, cancelable: true }));
await wait(50);
if (rows().length !== 10) return "Shift+Enter sent";
type(box, "   "); key(box, "Enter"); await wait();
if (rows().length !== 10) return "an empty message was sent";
type(box, "");
// Sending from higher up goes back down; a message from someone else, while scrolled up, keeps your place.
log.scrollTo({ top: -100000 }); await wait(100);
type(box, "Second"); key(box, "Enter"); await wait();
if (!atBottom()) return "sending from higher up did not go back down";
log.scrollTo({ top: -150 }); await wait(150);
const mark = rows()[6].getBoundingClientRect().top;
await wait(1800);
if (rows().length !== 12) return "the second reply did not come";
if (Math.abs(rows()[6].getBoundingClientRect().top - mark) > 2) return `scrolled up, a new message moved what you were reading by ${rows()[6].getBoundingClientRect().top - mark}px`;
// In a page: Enter submits the form, with the children in it.
const form = page.querySelector("form");
if (form.getAttribute("method") !== "get" || !form.getAttribute("action").endsWith("#chat_thread")) return "the page's form has the wrong method or action";
let sent = null;
const stop = (e) => { e.preventDefault(); sent = new FormData(form); };
form.addEventListener("submit", stop);
const pbox = page.querySelector("textarea");
type(pbox, "Here it is"); key(pbox, "Enter"); await wait();
form.removeEventListener("submit", stop);
if (!sent || sent.get("message") !== "Here it is" || sent.get("ticket") !== "77") return `Enter in a page sent ${sent && [...sent].join(";")}`;
if (page.querySelector("[role=log]").getAttribute("aria-label") !== "Support ticket") return "label is not the log's name";
type(pbox, "");
