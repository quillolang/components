const avatars = $$("input[name=ip-demo-avatar]");
if (avatars.length !== 4 || avatars.some((r) => r.type !== "radio")) return "the avatars are not 4 radios";
if (avatars.find((r) => r.checked)?.value !== "owl") return "value did not choose the owl";
if (avatars[3].disabled !== true) return "a disabled option is not disabled";
if (avatars.map((r) => r.getAttribute("aria-label")).join() !== "Fox,Owl,Bear,Cat") return "the radios are not named after their pictures";
const fs = avatars[0].closest("fieldset");
if (fs.getAttribute("role") !== "radiogroup" || !fs.querySelector("legend")?.textContent.includes("Avatar")) return "no radiogroup with a legend";
if (!fs.classList.contains("ui-image-picker-circle")) return "shape=circle is not marked";
const frame = avatars[1].closest("label").querySelector(".ui-image-picker-frame");
const img = frame.querySelector("img");
if (!img || !img.src.startsWith("data:image/svg+xml") || img.alt !== "") return "the picture is not shown as a decorative image";
if (getComputedStyle(frame).borderTopLeftRadius !== "50%" && !getComputedStyle(frame).borderTopLeftRadius.endsWith("px")) return "a circle is not round";
const r = frame.getBoundingClientRect();
if (Math.abs(r.width - 96) > 2 || Math.abs(r.height - 96) > 2) return `the picture is ${r.width}x${r.height}, not 96x96`;
const chosenShadow = getComputedStyle(frame).boxShadow;
const foxFrame = avatars[0].closest("label").querySelector(".ui-image-picker-frame");
if (chosenShadow === getComputedStyle(foxFrame).boxShadow) return "the chosen picture does not stand out";
if (getComputedStyle(frame.querySelector(".ui-image-picker-check")).opacity !== "1" || getComputedStyle(foxFrame.querySelector(".ui-image-picker-check")).opacity !== "0") return "the check shows on the wrong picture";
if (avatars[0].closest("label").querySelector(".ui-image-picker-caption")?.textContent !== "Fox") return "captions are not shown";
foxFrame.click(); await wait();
if (!avatars[0].checked || getComputedStyle(foxFrame.querySelector(".ui-image-picker-check")).opacity !== "1") return "clicking a picture does not choose it";
const themes = $$("input[name=ip-demo-theme]");
const note = () => themes[0].closest(".demo-stack").querySelector(".demo-note").textContent;
const wide = themes[0].closest("label").querySelector(".ui-image-picker-frame").getBoundingClientRect();
if (Math.abs(wide.width - 140) > 2 || Math.abs(wide.width / wide.height - 16 / 9) > 0.1) return `a wide picture is ${wide.width}x${wide.height}`;
themes[2].closest("label").click(); await wait();
if (note() !== "The night theme is on.") return `on_change did not update the note: ${note()}`;
const covers = $$("input[name=ip-demo-cover]");
const cfs = covers[0].closest("fieldset");
if (!covers[0].required || cfs.getAttribute("aria-invalid") !== "true") return "required and error are not on the group";
if (cfs.querySelector(".ui-image-picker-caption")) return "captions={false} still shows captions";
if (getComputedStyle(cfs.querySelector(".ui-image-picker-list")).gridTemplateColumns.split(" ").length !== 3) return "columns={3} does not make three columns";
if (!document.getElementById(cfs.getAttribute("aria-describedby"))?.textContent.includes("Choose a cover")) return "the error is not tied to the group";
