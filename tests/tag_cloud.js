const c = $("#tag-cloud-demo-topics");
if (!c || c.tagName !== "UL" || c.getAttribute("aria-label") !== "Topics") return "the cloud is not a named <ul>";
const tags = [...c.querySelectorAll(".ui-tagcloud-tag")];
const names = tags.map((t) => t.firstChild.textContent);
if (names.join() !== [...names].sort((a, b) => a.localeCompare(b)).join()) return `not in name order: ${names}`;
const tag = (n) => tags.find((t) => t.firstChild.textContent === n);
if (tag("quillo").parentElement.dataset.size !== "5" || tag("http").parentElement.dataset.size !== "1") return "the largest and smallest sizes";
if (tag("forms").parentElement.dataset.size !== "3") return `forms (30 of 2..64) is size ${tag("forms").parentElement.dataset.size}`;
if (parseFloat(getComputedStyle(tag("quillo")).fontSize) <= parseFloat(getComputedStyle(tag("css")).fontSize)) return "a heavier tag is not larger";
if (tag("css").tagName !== "A" || tag("css").getAttribute("href") !== "#css") return "href makes a link";
if (tag("forms").getAttribute("aria-current") !== "true" || tag("css").hasAttribute("aria-current")) return "selected";
if (tag("css").querySelector(".ui-sr").textContent !== ", 21") return "the count is not said";
if (tag("css").querySelector(".ui-tagcloud-n")) return "counts are shown without counts={true}";
const s = $("#tag-cloud-demo-skills");
const st = [...s.querySelectorAll(".ui-tagcloud-tag")];
if (st.map((t) => t.firstChild.textContent).join() !== "SQL,Python,TypeScript,Go,Elixir") return "order weight";
if (st[0].tagName !== "SPAN" || st[0].querySelector(".ui-tagcloud-n").textContent !== "340") return "plain tags with counts";
if (st.map((t) => t.parentElement.dataset.size).join() !== "5,5,4,3,1") return `the log scale: ${st.map((t) => t.parentElement.dataset.size)}`;
if (!s.classList.contains("ui-tagcloud-neutral")) return "tone";
