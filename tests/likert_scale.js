const docs = $$("input[name=docs]");
if (docs.length !== 5 || docs.some((r) => r.type !== "radio")) return "the scale is not 5 radios";
if (docs.map((r) => r.value).join() !== "1,2,3,4,5") return `the values are not 1 to 5: ${docs.map((r) => r.value)}`;
if (docs.find((r) => r.checked)?.value !== "4") return "value did not check the fourth point";
const fs = docs[0].closest("fieldset");
if (fs.getAttribute("role") !== "radiogroup" || !fs.querySelector("legend")?.textContent.includes("easy to follow")) return "the statement is not the legend";
if (!document.getElementById(fs.getAttribute("aria-describedby"))?.textContent.includes("strongly")) return "the hint is not tied to the group";
const ends = [...fs.querySelectorAll(".ui-likert-scale-end")].map((e) => e.textContent.trim());
if (ends.join("|") !== "Strongly disagree|Strongly agree") return `the end words: ${ends}`;
if (docs[0].getAttribute("aria-label") !== "1 of 5, Strongly disagree" || docs[2].getAttribute("aria-label") !== "3 of 5") return `the points' names: ${docs.map((r) => r.getAttribute("aria-label"))}`;
if (!docs[0].required) return "required is not on the radios";
const rec = $$("input[name=recommend]");
if (rec.length !== 7 || rec.some((r) => r.checked)) return "points={7} should give 7 unchecked radios";
rec[5].labels[0].click(); await wait();
if (!rec[5].checked || !$(".demo-note").textContent.includes("6 of 7")) return `on_change did not update: ${$(".demo-note").textContent}`;
const often = $$("input[name=often]");
const words = [...often[0].closest("fieldset").querySelectorAll(".ui-likert-scale-word")].map((w) => w.textContent.trim());
if (words.join() !== "Never,Monthly,Weekly,Daily,Hourly") return `a list of points does not write their words: ${words}`;
if (often[1].getAttribute("aria-label") !== "Monthly" || often[1].value !== "2") return "a worded point is not named by its word with a numbered value";
const ofs = often[0].closest("fieldset");
if (ofs.querySelector(".ui-likert-scale-end")) return "low={null} high={null} still shows end words";
if (ofs.getAttribute("aria-invalid") !== "true" || !ofs.querySelector("[role=alert]")?.textContent.includes("Pick")) return "an error does not mark the group";
