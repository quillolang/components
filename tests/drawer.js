const [filters, bottom, fromState] = $$("button.ui-btn");
const dialogs = $$("dialog.ui-drawer");
if (dialogs.length !== 3) return `expected 3 drawers, found ${dialogs.length}`;
filters.click(); await wait(350);
const d = dialogs[0];
if (!d.open) return "the trigger did not open the drawer";
let r = d.getBoundingClientRect();
if (Math.abs(r.right - innerWidth) > 1 || r.top !== 0 || Math.abs(r.height - innerHeight) > 1) return `side="right" is not along the right edge: ${JSON.stringify(r)}`;
d.querySelector(".ui-drawer-x").click(); await wait();
if (d.open) return "the close button did not close it";
bottom.click(); await wait(350);
r = dialogs[1].getBoundingClientRect();
if (!dialogs[1].open || Math.abs(r.bottom - innerHeight) > 1 || r.left !== 0) return `side="bottom" is not along the bottom: ${JSON.stringify(r)}`;
dialogs[1].close(); await wait();
fromState.click(); await wait(350);
const s = dialogs[2];
if (!s.open) return "open={state} did not open it";
// On a busy page the slide may still be running: measure where it ends.
await Promise.all(s.getAnimations({ subtree: true }).map((a) => a.finished.catch(() => null)));
r = s.getBoundingClientRect();
if (r.left !== 0 || r.width > 321) return `side="left" size="sm" is not along the left: ${JSON.stringify(r)}`;
s.close(); await wait();
fromState.click(); await wait();
if (!s.open) return "on_close did not set the state back, so it cannot open again";
s.close();
