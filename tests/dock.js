const phone = $("#dock-demo-phone"), main = $("#dock-demo-main"), side = $("#dock-demo-side"), tools = $("#dock-demo-tools");
if (!main || main.tagName !== "NAV" || main.getAttribute("aria-label") !== "Dock") return "the dock is not a labelled <nav>";
if (getComputedStyle(main).position !== "fixed") return "the dock is not fixed";
const pr = phone.getBoundingClientRect(), mr = main.getBoundingClientRect();
if (Math.abs(pr.bottom - mr.bottom - 12) > 1) return `the dock is not 12px above the bottom edge: ${pr.bottom - mr.bottom}`;
if (Math.abs((mr.left + mr.width / 2) - (pr.left + pr.width / 2)) > 1) return "the dock is not centred";
const items = [...main.querySelectorAll(".ui-dock-item")];
if (items.length !== 4 || items.some((i) => i.tagName !== "A")) return "items with an href are not four links";
if (items[0].getAttribute("aria-current") !== "page" || items[1].hasAttribute("aria-current")) return "current does not mark the matching item";
if (items[0].querySelector(".ui-dock-label")?.textContent !== "Home" || !items[0].querySelector(".ui-dock-icon svg path")) return "a label or an SVG icon is missing";
if (items[2].querySelector(".ui-dock-badge")?.textContent !== "3") return "the badge is missing";
if (new Set(items.map((i) => Math.round(i.getBoundingClientRect().top))).size !== 1) return "the bottom dock's items are not in a row";
const sr = side.getBoundingClientRect();
if (Math.abs(sr.left - pr.left - 12) > 1 || Math.abs((sr.top + sr.height / 2) - (pr.top + pr.height / 2)) > 1) return "side=\"left\" is not at the left middle";
const si = [...side.querySelectorAll(".ui-dock-item")];
if (si[1].getBoundingClientRect().top <= si[0].getBoundingClientRect().bottom - 1) return "a side dock's items are not in a column";
if (si[0].getAttribute("aria-label") !== "New" || si[0].title !== "New" || si[0].querySelector(".ui-dock-label")) return "labels={false} does not name the items for screen readers and tooltips";
if (getComputedStyle(tools).position !== "relative") return "fixed={false} is still fixed";
const tb = [...tools.querySelectorAll("button.ui-dock-item")];
if (tb.length !== 4 || !tb[3].disabled) return "the tool items are not buttons, with the last disabled";
if (tb[0].getAttribute("aria-current") !== "page") return "the current tool is not marked";
tb[1].click(); await wait();
const note = tools.closest(".demo-stack").querySelector(".demo-note").textContent;
if (!note.startsWith("Tool: eraser") || tb[1].getAttribute("aria-current") !== "page" || tb[0].hasAttribute("aria-current")) return `on_select: ${note}`;
tb[0].click(); await wait();
