const input = $("input[name=fd-docs]");
const zone = input.closest(".ui-file-drop-zone");
if (input.type !== "file" || !input.multiple || input.accept !== ".pdf,.docx,.txt") return "the input is not a multiple file input with accept";
const zr = zone.getBoundingClientRect(), ir = input.getBoundingClientRect();
if (Math.abs(zr.width - ir.width) > 4 || Math.abs(zr.height - ir.height) > 4) return "the input does not cover the zone, so a drop would miss it";
input.dispatchEvent(new DragEvent("dragenter", { bubbles: true })); await wait();
if (!zone.classList.contains("ui-file-drop-over")) return "dragging over does not mark the zone";
input.dispatchEvent(new DragEvent("dragleave", { bubbles: true })); await wait();
if (zone.classList.contains("ui-file-drop-over")) return "leaving does not unmark the zone";
const dt = new DataTransfer();
dt.items.add(new File(["x".repeat(2048)], "report.pdf", { type: "application/pdf" }));
dt.items.add(new File(["hello"], "notes.txt", { type: "text/plain" }));
input.files = dt.files;
input.dispatchEvent(new Event("change", { bubbles: true })); await wait();
const rows = [...input.closest(".ui-file-drop").querySelectorAll(".ui-file-drop-list li")].map((li) => [...li.querySelectorAll("span")].map((s) => s.textContent).join(" "));
if (rows.join(" | ") !== "report.pdf 2 KB | notes.txt 5 B") return `the list shows: ${rows.join(" | ")}`;
const note = input.closest(".demo-stack").querySelector(".demo-note").textContent;
if (!note.includes("2 KB in all")) return `on_change did not report the files: ${note}`;
const form = document.createElement("form");
const host = input.closest(".ui-file-drop"); host.parentElement.insertBefore(form, host); form.appendChild(host);
const sent = new FormData(form).getAll("fd-docs").map((f) => f.name);
form.parentElement.insertBefore(host, form); form.remove();
if (sent.join() !== "report.pdf,notes.txt") return `a form would send: ${sent}`;
if (!$("input[name=fd-off]").disabled) return "disabled is not applied";
if (!$("input[name=fd-photos]").required) return "required is not applied";
