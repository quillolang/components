const grid = $("#tree-table-demo-accounts table");
if (!grid || grid.getAttribute("role") !== "treegrid" || grid.getAttribute("aria-label") !== "Chart of accounts") return "the table is not a named treegrid";
const rows = () => [...grid.querySelectorAll("tbody tr")];
const names = () => rows().map((r) => r.querySelector(".ui-treetable-first span:last-child").textContent);
const row = (n) => rows().find((r) => r.querySelector(".ui-treetable-first span:last-child").textContent === n);
if (names().join() !== "Assets,Cash,Accounts receivable,Equipment,Liabilities,Equity") return `at first: ${names()}`;
if (row("Assets").getAttribute("aria-expanded") !== "true" || row("Liabilities").getAttribute("aria-expanded") !== "false") return "aria-expanded is wrong";
if (row("Equity").hasAttribute("aria-expanded")) return "a leaf has aria-expanded";
if (row("Cash").getAttribute("aria-level") !== "2" || row("Cash").getAttribute("aria-posinset") !== "1" || row("Cash").getAttribute("aria-setsize") !== "3") return "level/posinset/setsize are wrong";
if (rows().filter((r) => r.tabIndex === 0).length !== 1) return "more than one Tab stop";
if (row("Assets").querySelector(".ui-treetable-right").textContent.trim() !== "$184,250.75") return `money: ${row("Assets").querySelector(".ui-treetable-right").textContent}`;
if (row("Liabilities").querySelector(".ui-treetable-right").textContent.trim() !== "-$56,400.00") return "a negative amount";
const arrow = row("Liabilities").querySelector(".ui-treetable-arrow");
if (arrow.getAttribute("aria-label") !== "Open Liabilities") return `the arrow is named ${arrow.getAttribute("aria-label")}`;
arrow.click(); await wait();
if (!names().includes("Bank loan") || row("Liabilities").getAttribute("aria-expanded") !== "true") return "clicking the arrow did not open";
if (arrow.getAttribute("aria-label") !== "Close Liabilities") return "the open arrow is not named Close";
if (row("Bank loan").getAttribute("aria-level") !== "2") return "a child's level";
row("Assets").focus(); await wait();
key(row("Assets"), "ArrowDown"); await wait();
if (document.activeElement !== row("Cash")) return "ArrowDown did not move the focus";
key(row("Cash"), "ArrowRight"); await wait();
if (row("Cash").getAttribute("aria-expanded") !== "true" || !names().includes("Checking")) return "ArrowRight did not open";
key(row("Cash"), "ArrowRight"); await wait();
if (document.activeElement !== row("Checking")) return "ArrowRight on an open row did not go into it";
if (getComputedStyle(row("Checking").querySelector(".ui-treetable-first")).paddingLeft !== "40px") return `the indent is ${getComputedStyle(row("Checking").querySelector(".ui-treetable-first")).paddingLeft}`;
key(row("Checking"), "ArrowLeft"); await wait();
if (document.activeElement !== row("Cash")) return "ArrowLeft on a leaf did not go to the parent";
key(row("Cash"), "ArrowLeft"); await wait();
if (names().includes("Checking")) return "ArrowLeft did not close";
key(row("Cash"), "End"); await wait();
if (document.activeElement !== row("Equity")) return "End";
key(row("Equity"), "Home"); await wait();
if (document.activeElement !== row("Assets")) return "Home";
key(row("Assets"), "Enter"); await wait();
if (names().includes("Cash")) return "Enter did not close the row";
key(row("Assets"), " "); await wait();
if (!names().includes("Cash")) return "Space did not open the row";
// open_all and on_toggle
const parts = $("#tree-table-demo-parts table");
const pnames = () => [...parts.querySelectorAll("tbody tr .ui-treetable-first span:last-child")].map((s) => s.textContent);
if (pnames().length !== 9) return `open_all shows ${pnames().length} rows`;
const wheel = [...parts.querySelectorAll("tbody tr")].find((r) => r.textContent.includes("Wheel"));
wheel.querySelector(".ui-treetable-arrow").click(); await wait();
if (pnames().length !== 6) return `closing Wheel leaves ${pnames().length} rows`;
const note = parts.closest(".demo-stack").querySelector(".demo-note").textContent;
if (note !== "Last toggle: closed 0-1.") return `on_toggle: ${note}`;
