const form = $("#loading-overlay-demo-form");
if (!form || form.classList.contains("ui-lo-busy") || form.getAttribute("aria-busy")) return "the form starts busy";
if (form.querySelector(".ui-lo-cover")) return "a cover shows while not busy";
const content = form.querySelector(".ui-lo-content");
if (content.hasAttribute("inert")) return "the content is inert while not busy";
$("#loading-overlay-demo-save").click(); await wait();
if (!form.classList.contains("ui-lo-busy") || form.getAttribute("aria-busy") !== "true") return "busy did not set aria-busy";
const cover = form.querySelector(".ui-lo-cover");
if (!cover || cover.getAttribute("role") !== "status" || !cover.textContent.includes("Saving your changes")) return "the cover does not say what is happening";
if (!content.hasAttribute("inert")) return "the content is not inert while busy";
const fr = form.getBoundingClientRect(), cr = cover.getBoundingClientRect();
if (Math.abs(fr.width - cr.width) > 1 || Math.abs(fr.height - cr.height) > 1) return "the cover does not fill the box";
if (!cover.querySelector(".ui-lo-spin") || getComputedStyle(cover.querySelector(".ui-lo-spin")).animationName !== "ui-lo-turn") return "no turning spinner";
$("#loading-overlay-demo-done").click(); await wait();
if (form.querySelector(".ui-lo-cover") || form.getAttribute("aria-busy")) return "done did not lift the cover";
if (!$(".demo-note").textContent.includes("Saved 1 time")) return "the note did not update";
const empty = $("#loading-overlay-demo-empty");
if (empty.offsetHeight < 140) return `min_height gave ${empty.offsetHeight}px`;
if (empty.querySelector(".ui-lo-cover")?.textContent.trim() !== "Loading invoices") return "the label is not shown";
const quiet = $("#loading-overlay-demo-quiet");
const sr = quiet.querySelector(".ui-lo-cover .ui-sr");
if (!sr || sr.textContent !== "Loading the chart" || quiet.querySelector(".ui-lo-label")) return "show_label={false} does not keep the label for screen readers only";
if (quiet.classList.contains("ui-lo-blur")) return "blur={false} still blurs";
