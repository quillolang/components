const grids = $$("section.ui-feature-grid");
if (grids.length !== 2) return `expected 2 grids, found ${grids.length}`;
const [list, cards] = grids;
if (list.id !== "feature-grid-demo") return "the id does not reach the section";
if (list.querySelector("h2.ui-feature-grid-title")?.textContent !== "Everything in one file") return "the heading is missing";
const items = list.querySelectorAll(".ui-feature");
if (items.length !== 6) return `6 features from the list, found ${items.length}`;
if (items[0].querySelector("h3.ui-feature-title")?.textContent !== "No build step") return "a feature's title is not an h3";
if (items[0].querySelector(".ui-feature-icon")?.textContent !== "⚡") return "the icon is missing";
const link = items[2].querySelector(".ui-feature-title a");
if (!link || link.getAttribute("href") !== "#feature_grid") return "href does not make the title a link";
if (items[3].querySelector(".ui-feature-title a")) return "a feature without href is a link";
const rows = new Set([...items].map((i) => Math.round(i.getBoundingClientRect().top)));
if (rows.size !== 2) return `6 features at 260px wide should make 2 rows in 1000px, found ${rows.size}`;
if (!cards.classList.contains("ui-feature-grid-cards") || !cards.classList.contains("ui-feature-grid-cols")) return "cards and columns classes are missing";
const hand = cards.querySelectorAll(".ui-feature");
if (hand.length !== 3 || !hand[0].querySelector(".ui-feature-icon svg")) return "hand-written Features with an SVG icon are missing";
if (!hand[0].querySelector(".ui-feature-text").textContent.includes("under a millisecond")) return "children are not the feature's text";
if (getComputedStyle(hand[0]).borderStyle !== "solid") return "cards are not bordered";
if (new Set([...hand].map((i) => Math.round(i.getBoundingClientRect().top))).size !== 1) return "columns={3} does not put three in a row";
if (getComputedStyle(hand[0]).textAlign !== "center") return "align=center does not centre the text";
