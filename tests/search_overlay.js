const dlg = $("dialog.ui-search-overlay"), input = document.getElementById("search-demo-input"), note = () => $(".demo-note").textContent;
const opts = () => [...dlg.querySelectorAll("[role=option]")], titles = () => opts().map((o) => o.querySelector(".ui-search-overlay-title").textContent);
const trig = $$(".ui-search-overlay-trigger")[0];
if (!dlg || dlg.open || dlg.getAttribute("aria-label") !== "Search") return "not a closed, named dialog";
if (trig.getAttribute("aria-keyshortcuts") !== "/" || trig.querySelector("span").textContent !== "Search the docs" || trig.querySelector("kbd")?.textContent !== "/") return `the trigger: "${trig.textContent}"`;
document.body.dispatchEvent(new KeyboardEvent("keydown", { key: "/", bubbles: true, cancelable: true })); await wait();
if (!dlg.open || document.activeElement !== input) return "/ does not open it with the box focused";
const r = dlg.getBoundingClientRect();
if (Math.abs(r.width - innerWidth) > 1 || Math.abs(r.height - innerHeight) > 1) return "it does not take the whole screen";
if (input.getAttribute("role") !== "combobox" || input.getAttribute("aria-controls") !== "search-demo-list") return "the box is not a combobox for its list";
if (!dlg.textContent.includes("Type to search.")) return "with nothing typed it does not say to type";
type(input, "comp"); await wait(80);
if (input.getAttribute("aria-busy") !== "true" || !dlg.textContent.includes("Searching…")) return "no Searching… while the server answers";
await wait(400);
if (titles().join() !== "Components,Grace Hopper") return `"comp" found: ${titles()}`;
const groups = [...dlg.querySelectorAll("[role=group]")].map((g) => g.getAttribute("aria-label"));
if (groups.join() !== "Guides,People") return `groups: ${groups}`;
if (opts()[0].querySelector("mark")?.textContent !== "Comp") return "the words typed are not marked";
if (dlg.querySelector("[role=status]").textContent !== "2 results") return `the count says "${dlg.querySelector("[role=status]").textContent}"`;
if (input.getAttribute("aria-activedescendant") !== opts()[0].id || opts()[0].getAttribute("aria-selected") !== "true") return "the first result is not active";
key(input, "ArrowDown"); await wait();
if (input.getAttribute("aria-activedescendant") !== opts()[1].id || opts()[1].getAttribute("aria-selected") !== "true") return "ArrowDown does not move";
key(input, "ArrowDown"); await wait();
if (input.getAttribute("aria-activedescendant") !== opts()[0].id) return "ArrowDown from the last does not wrap";
key(input, "ArrowUp"); await wait();
if (input.getAttribute("aria-activedescendant") !== opts()[1].id) return "ArrowUp from the first does not wrap";
type(input, "zzz"); await wait(400);
if (opts().length || !dlg.textContent.includes("No results for “zzz”.")) return "no match does not say so";
type(input, "l"); type(input, "li"); type(input, "liv"); await wait(500);
if (titles().join() !== "Live data") return `an older answer won: ${titles()}`;
key(input, "Enter"); await wait();
if (dlg.open || note() !== "Opened Live data.") return `Enter does not open the result: ${note()}`;
trig.click(); await wait();
if (!dlg.open || input.value !== "") return "the trigger does not open it afresh";
type(input, "getting"); await wait(400);
opts()[0].click(); await wait();
if (location.hash !== "#search_overlay" || note() !== "Opened Getting started.") return `a click does not follow the href: ${location.hash}`;
history.replaceState(null, "", location.pathname + location.search);
const local = $$("dialog.ui-search-overlay")[1], li = document.getElementById("search-demo-local-input");
$$(".ui-search-overlay-trigger")[1].click(); await wait();
type(li, "london"); await wait();
const lt = [...local.querySelectorAll("[role=option] .ui-search-overlay-title")].map((t) => t.textContent);
if (lt.join() !== "Ada Lovelace") return `items are not searched by their text: ${lt}`;
local.close(); await wait();
document.body.dispatchEvent(new KeyboardEvent("keydown", { key: "/", bubbles: true, cancelable: true })); await wait();
if (local.open) return "shortcut={false} still opens with /";
dlg.close();
