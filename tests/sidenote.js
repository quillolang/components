const wide = $("#sidenote-demo-wide");
if (!wide?.classList.contains("ui-bsnote-text")) return "the SidenoteText with its id is missing";
const flow = wide.querySelector(".ui-bsnote-flow"), p = flow.querySelector("p");
const n1 = document.getElementById("sidenote-demo-1"), n2 = document.getElementById("sidenote-demo-2"), m = document.getElementById("sidenote-demo-margin");
if (!n1 || n1.getAttribute("role") !== "note" || !n1.textContent.includes("Every route, every time")) return "the first note";
if ([n1, n2, m].some((n) => !n.checkVisibility())) return "on a wide page a note is hidden";
const text = p.getBoundingClientRect(), r1 = n1.getBoundingClientRect();
if (!(r1.left >= text.right + 20)) return `the note is not in the margin: note at ${r1.left}, text ends at ${text.right}`;
if (Math.abs(r1.width - 210) > 1) return `the column is ${r1.width}px, not 210`;
const ref = p.querySelector("label.ui-bsnote-ref");
if (ref.textContent !== "1" || ref.getAttribute("for") !== "sidenote-demo-1-toggle") return "the mark";
if (Math.abs(r1.top - ref.getBoundingClientRect().top) > 30) return "the note is not beside its line";
if (n1.querySelector(".ui-bsnote-n")?.textContent !== "1") return "the note does not start with its number";
if (getComputedStyle(document.getElementById("sidenote-demo-1-toggle")).display !== "none") return "on a wide page the toggle can be reached";
if (!(m.getBoundingClientRect().top >= n2.getBoundingClientRect().bottom)) return "the notes overlap";
if (m.querySelector(".ui-bsnote-n") || m.parentElement.querySelector(".ui-bsnote-mark").checkVisibility()) return "a margin note shows a number or its ⊕";
if (n2.querySelector("a")?.getAttribute("href") !== "#sidenote") return "a link in a note";
const narrow = $("#sidenote-demo-narrow"), note = document.getElementById("sidenote-demo-n1"), box = document.getElementById("sidenote-demo-n1-toggle");
if (note.checkVisibility()) return "on a narrow page the note is not folded";
if (box.getAttribute("aria-label") !== "Note 1" || box.getAttribute("aria-controls") !== "sidenote-demo-n1" || box.type !== "checkbox") return "the toggle's name";
narrow.querySelector("label.ui-bsnote-ref").click(); await wait(50);
if (!box.checked || !note.checkVisibility()) return "the number does not open the note";
const nr = note.getBoundingClientRect(), np = narrow.querySelector("p").getBoundingClientRect();
if (!(nr.left >= np.left - 1 && nr.right <= np.right + 1)) return "the opened note is not under its line";
box.focus(); box.click(); await wait(50);
if (note.checkVisibility()) return "pressing again does not fold it";
if (document.activeElement !== box) return "the toggle cannot take the focus";
