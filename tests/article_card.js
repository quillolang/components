const first = $("#article-card-demo-first");
if (first.tagName !== "ARTICLE") return "not an article";
const img = first.querySelector(".ui-article-card-img img");
if (!img || img.getAttribute("alt") !== "Rocks in a calm sea") return "the image or its alt";
const cat = first.querySelector(".ui-article-card-cat");
if (cat.tagName !== "A" || cat.getAttribute("href") !== "#article_card" || cat.textContent !== "Engineering") return "category_href does not link the category";
const title = first.querySelector("h3.ui-article-card-title a");
if (!title || title.getAttribute("href") !== "#article_card" || title.textContent !== "Islands, resumed") return "the title is not a link";
if (!first.querySelector(".ui-article-card-excerpt").textContent.startsWith("How a page")) return "the excerpt";
if ([...first.querySelectorAll(".ui-article-card-tags li")].map((t) => t.textContent).join() !== "components,runtime") return "the tags";
if (first.querySelector(".ui-article-card-author").textContent !== "Ada Lovelace" || first.querySelector(".ui-avatar span").textContent !== "AL") return "the author";
if (first.querySelector(".ui-avatar").getBoundingClientRect().width !== 26) return "the author picture is not 26px";
const when = first.querySelector("time");
if (when.getAttribute("datetime") !== "2026-10-12" || when.textContent !== "Oct 12, 2026") return `date: ${when.textContent}`;
if (!first.querySelector(".ui-article-card-when").textContent.includes("4 min read")) return "the read time";
const second = $$(".ui-article-card")[1];
if (second.querySelector(".ui-article-card-cat").tagName !== "SPAN") return "a category without a link is plain";
if (second.querySelector(".ui-avatar img")?.getAttribute("src") !== "https://i.pravatar.cc/64?img=47") return "author_src";
const bare = $("#article-card-demo-bare");
if (bare.querySelector(".ui-article-card-img") || bare.querySelector(".ui-article-card-cat") || bare.querySelector(".ui-avatar")) return "parts left out still show";
if (bare.querySelector("time").textContent !== "Oct 1, 2026") return "a bare card's date";
const wide = $("#article-card-demo-wide");
if (!wide.classList.contains("ui-article-card-horizontal") || getComputedStyle(wide).flexDirection !== "row") return "horizontal is not a row";
