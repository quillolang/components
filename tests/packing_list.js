const txt = (el) => el?.textContent.replace(/\s+/g, " ").trim();
const p = $("#packing-list-demo");
const item = (l) => p.querySelector(`[data-item="${l}"]`);
const box = (l) => item(l)?.querySelector("input[type=checkbox]");
const count = () => txt(p.querySelector(".ui-packlist-count"));
const group = (g) => p.querySelector(`[data-group="${g}"]`);
const tally = (g) => txt(group(g).querySelector(".ui-packlist-tally"));
const note = () => $("#packing-list-demo-note").textContent;
if (p.getAttribute("aria-labelledby") !== "packing-list-packed-title" || txt($("#packing-list-packed-title")) !== "Lisbon, 4 nights") return "the heading";
if (count() !== "4 of 12 packed") return `count: ${count()}`;
const bar = p.querySelector(".ui-packlist-bar");
if (bar.getAttribute("role") !== "progressbar" || bar.getAttribute("aria-valuenow") !== "4" || bar.getAttribute("aria-valuemax") !== "12" || bar.querySelector("span").style.width !== "33%") return "the bar";
if (tally("Documents") !== "1/4" || tally("Tech") !== "All packed (2)" || !group("Tech").classList.contains("ui-packlist-full")) return `tallies: ${tally("Documents")}, ${tally("Tech")}`;
if (group("Clothes").tagName !== "FIELDSET" || txt(group("Clothes").querySelector("legend")).split(" ")[0] !== "Clothes0/4") return `group legend: ${txt(group("Clothes").querySelector("legend"))}`;
if (txt(item("Socks").querySelector(".ui-packlist-qty")) !== ", ×5" || item("Passport").querySelector(".ui-packlist-qty")) return "quantities";
if (!box("Euros").checked || !item("Euros").classList.contains("ui-packlist-packed") || box("Passport").checked) return "packed to start";
if (box("Passport").labels.length !== 1 || !box("Passport").labels[0].textContent.includes("Passport")) return "a checkbox without its label";
if (getComputedStyle(item("Euros").querySelector(".ui-packlist-label")).textDecorationLine !== "line-through") return "packed things are not struck through";
box("Passport").click(); await wait();
if (count() !== "5 of 12 packed" || tally("Documents") !== "2/4" || !item("Passport").classList.contains("ui-packlist-packed")) return `ticking: ${count()}`;
if (note() !== "on_change: 5 of 12 packed.") return `on_change: ${note()}`;
// Adding: a new thing, then the same again adds one.
const add = p.querySelector(".ui-packlist-add");
const input = add.querySelector("input"), sel = add.querySelector("select");
sel.value = "Toiletries"; sel.dispatchEvent(new Event("change", { bubbles: true })); await wait();
type(input, "Toothpaste"); key(input, "Enter"); await wait();
if (!item("Toothpaste") || item("Toothpaste").closest("[data-group]").dataset.group !== "Toiletries" || input.value !== "") return "Enter does not add to the group chosen";
if (count() !== "5 of 13 packed" || txt(p.querySelector(".ui-sr[aria-live]")) !== "Added Toothpaste to Toiletries") return `after adding: ${count()}, ${txt(p.querySelector(".ui-sr[aria-live]"))}`;
type(input, "sunscreen"); add.querySelector("button").click(); await wait();
if (txt(item("Sunscreen").querySelector(".ui-packlist-qty")) !== ", ×2" || box("Sunscreen").checked || count() !== "4 of 13 packed") return "the same thing again does not add one to it";
type(input, "   "); add.querySelector("button").click(); await wait();
if (count() !== "4 of 13 packed") return "blank text was added";
// Taking off, hiding, unpacking.
item("Light jacket").querySelector(".ui-packlist-remove").click(); await wait();
if (item("Light jacket") || count() !== "4 of 12 packed" || txt(p.querySelector(".ui-sr[aria-live]")) !== "Took Light jacket off the list") return "taking a thing off";
if (item("Socks").querySelector(".ui-packlist-remove").getAttribute("aria-label") !== "Take Socks off the list") return "the remove button is not named";
const hide = p.querySelector(".ui-packlist-hide input");
hide.click(); await wait();
if (item("Euros") || item("Phone charger") || !item("Socks")) return "Hide packed";
if (txt(group("Tech").querySelector(".ui-packlist-empty")) !== "All packed.") return "a group all packed and hidden";
hide.click(); await wait();
const form = document.createElement("form"); p.parentElement.insertBefore(form, p); form.appendChild(p);
const sent = new FormData(form).getAll("packed"); form.parentElement.insertBefore(p, form); form.remove();
if (sent.join("|") !== "Passport|Euros|Phone charger|Plug adapter (type F)") return `a form would send ${sent}`;
p.querySelector(".ui-packlist-reset").click(); await wait();
if (count() !== "0 of 12 packed" || !p.querySelector(".ui-packlist-reset").disabled || box("Euros").checked) return "Unpack all";
for (const b of p.querySelectorAll(".ui-packlist-item input")) { b.click(); await wait(20); }
await wait();
if (!p.classList.contains("ui-packlist-done") || count() !== "12 of 12 packed") return "all packed is not marked";
const d = $("#packing-list-demo-day");
if (d.querySelector(".ui-packlist-add") || txt(d.querySelector('[data-group="Extras"] .ui-packlist-empty')) !== "Nothing here yet." || txt(d.querySelector(".ui-packlist-count")) !== "0 of 3 packed") return "the plain list";
