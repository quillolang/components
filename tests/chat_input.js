const box = $("#chat-input-demo-live");
const form = box.closest("form");
const send = form.querySelector("button[type=submit]");
const note = () => form.closest(".demo-stack").querySelector(".demo-note").textContent;
if (box.tagName !== "TEXTAREA" || box.name !== "message" || !form.querySelector(`label[for="${box.id}"]`)) return "the box is not a labelled textarea named message";
if (send.getAttribute("aria-label") !== "Send" || !send.disabled) return "Send is not named, or is on while empty";
if (!form.querySelector(".ui-chat-composer-before [aria-label=Attach]")) return "the before slot is not shown";
const h0 = box.getBoundingClientRect().height;
type(box, "Line one\nLine two\nLine three"); await wait();
if (box.getBoundingClientRect().height <= h0) return "the box does not grow with its lines";
if (send.disabled) return "Send stayed off after typing";
type(box, "x\n".repeat(12)); await wait();
if (box.scrollHeight <= box.clientHeight + 2) return "past the rows it does not scroll";
type(box, "Hello there  "); key(box, "Enter"); await wait();
if (note() !== `Sent: "Hello there". Typing told 4 times.` && !note().startsWith(`Sent: "Hello there".`)) return `Enter did not send: ${note()}`;
if (box.value !== "" || !send.disabled || document.activeElement !== box) return "sending did not empty the box, turn Send off and keep the focus";
type(box, "a");
box.dispatchEvent(new KeyboardEvent("keydown", { key: "Enter", shiftKey: true, bubbles: true, cancelable: true })); await wait();
if (!note().startsWith(`Sent: "Hello there".`) || note().includes(`"a"`)) return "Shift+Enter sent";
type(box, "   "); key(box, "Enter"); await wait();
if (note().includes(`""`)) return "an empty message was sent";
type(box, "Second"); await wait(); send.click(); await wait();
if (!note().includes(`"Hello there", "Second"`)) return `the Send button did not send: ${note()}`;
if (!/Typing told \d+ times/.test(note())) return `on_typing was not told: ${note()}`;
// In a page: Enter submits the form, with the children in it.
const pbox = $("#chat-input-demo-form");
const pform = pbox.closest("form");
if (pform.getAttribute("method") !== "get" || !pform.getAttribute("action").endsWith("#chat_input")) return "the page's form has the wrong method or action";
if (pform.querySelector("button[type=submit]").getAttribute("aria-label") !== "Send to support") return "send_label is not the button's name";
let sent = null;
const stop = (e) => { e.preventDefault(); sent = new FormData(pform); };
pform.addEventListener("submit", stop);
type(pbox, "Here it is"); key(pbox, "Enter"); await wait();
pform.removeEventListener("submit", stop);
if (!sent || sent.get("message") !== "Here it is" || sent.get("ticket") !== "77") return `the page's form sent ${sent && [...sent].join(";")}`;
type(pbox, "");
