const live = $("#typing-indicator-demo-live .ui-typing-indicator");
const text = () => live.textContent.trim();
if (!live || live.getAttribute("role") !== "status" || live.getAttribute("aria-live") !== "polite") return "the indicator is not a live status";
if (text() !== "Ana is typing…" || live.querySelectorAll(".ui-typing-indicator-dots i").length !== 3) return `it starts as "${text()}"`;
const boxes = $$("input[type=checkbox]");
boxes[1].click(); await wait();
if (text() !== "Ana and Ben are typing…") return `two: "${text()}"`;
boxes[2].click(); await wait();
if (text() !== "Ana, Ben and Lee are typing…") return `three: "${text()}"`;
boxes[3].click(); await wait();
if (text() !== "Ana, Ben and 2 others are typing…") return `four: "${text()}"`;
for (const b of boxes) b.click();
await wait();
if (text() !== "" || live.children.length !== 0 || live.getBoundingClientRect().height > 2) return `nobody typing still shows "${text()}" at ${live.getBoundingClientRect().height}px`;
boxes[2].click(); await wait();
if (text() !== "Lee is typing…") return `one again: "${text()}"`;
const plain = $("#typing-indicator-demo-plain .ui-typing-indicator");
if (plain.textContent.trim() !== "Ana Silva, Ben Okafor and Lee Chen are typing…") return `full names: "${plain.textContent.trim()}"`;
const inline = $("#typing-indicator-demo-inline .ui-typing-indicator");
if (inline.querySelector(".ui-typing-indicator-dots") || inline.textContent.trim() !== "Sam is looking into it…" || getComputedStyle(inline).display !== "inline-flex") return "dots={false} with a text is not inline";
if (getComputedStyle(live.querySelector(".ui-typing-indicator-dots i")).animationName !== "ui-typing-indicator-dot") return "the dots do not animate";
