const box = $("#faq-demo");
if (!box || box.type !== "search" || box.getAttribute("aria-label") !== "Search questions" || box.getAttribute("aria-controls") !== "faq-demo-list") return "the search box is not labelled and tied to the list";
const items = () => [...$("#faq-demo-list").querySelectorAll("details.ui-faq-item")];
const count = () => box.closest(".ui-faq").querySelector(".ui-faq-count");
if (items().length !== 6) return `6 questions to start, found ${items().length}`;
if (!items()[0].open || items()[1].open) return "open: true does not open the first alone";
if (items()[0].querySelector("summary .ui-faq-q")?.textContent !== "What does it cost?") return "the question is not the summary";
if (count().textContent.trim() !== "6 questions" || count().getAttribute("role") !== "status") return `the count: "${count().textContent}"`;
type(box, "invoice"); await wait();
if (items().length !== 1 || !items()[0].textContent.includes("invoices")) return `"invoice" shows ${items().length}`;
if (count().textContent.trim() !== "1 of 6") return `the count after a search: "${count().textContent}"`;
type(box, "CANCEL"); await wait();
if (items().length !== 1 || !items()[0].querySelector(".ui-faq-q").textContent.includes("cancel")) return "the search is not case-insensitive";
type(box, "zzz"); await wait();
if (items().length !== 0 || !box.closest(".ui-faq").querySelector(".ui-faq-empty")) return "no matches does not say so";
type(box, ""); await wait();
if (items().length !== 6 || box.closest(".ui-faq").querySelector(".ui-faq-empty")) return "clearing does not bring them back";
const short = $$(".ui-faq")[1];
if (short.querySelector(".ui-faq-input")) return "search={false} still has a box";
const [a, b] = short.querySelectorAll("details");
if (a.getAttribute("name") !== "faq-demo-short-group") return "exclusive does not group the details";
b.querySelector("summary").click(); await wait();
if (!b.open || a.open) return "opening one of an exclusive group did not close the other";
