const col = (i) => trs().map((r) => r.children[i].textContent.trim());
const count = () => vt.querySelector(".ui-vt-count").textContent.trim();
const th = (t) => [...grid.querySelectorAll("th")].find((h) => h.textContent.trim() === t);
if (grid.getAttribute("role") !== "grid" || grid.getAttribute("aria-rowcount") !== "10001") return `grid / rowcount: ${grid.getAttribute("aria-rowcount")}`;
if (count() !== "10,000 rows") return `count: ${count()}`;
const n = grid.querySelectorAll("tr").length;
if (n > 40) return `${n} <tr>s on the page; only the visible ones should be`;
if (col(0)[0] !== "ORD-10001") return `first row: ${col(0)[0]}`;
const rh = trs()[0].getBoundingClientRect().height;
if (rh !== 36) return `a row is ${rh}px high, not 36`;
if (box.scrollHeight < 36 * 10001 - 2 || box.scrollHeight > 36 * 10001 + 2) return `the scroll height is ${box.scrollHeight}, not 10,001 rows`;
