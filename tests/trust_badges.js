const lists = $$("ul.ui-trust");
if (lists.length !== 3) return `expected 3 lists, found ${lists.length}`;
const [row, grid, list] = lists;
const titles = (l) => [...l.querySelectorAll(".ui-trust-title")].map((t) => t.textContent);
if (titles(row).join() !== "Secure payment,Free returns,Money-back guarantee") return `the defaults: ${titles(row)}`;
if (row.getAttribute("aria-label") !== "Why shop with us") return "the list has no name";
if (row.querySelectorAll(".ui-trust-icon svg path").length !== 3) return "built-in icons are not drawn";
if (row.querySelector(".ui-trust-note").textContent !== "Encrypted checkout") return "the built-in text is missing";
const items = [...row.querySelectorAll(".ui-trust-item")];
if (items[0].getBoundingClientRect().top !== items[2].getBoundingClientRect().top) return "a row does not lay them out side by side";
if (titles(grid).join() !== "Free shipping,Here to help,Plants a tree,2-year warranty") return `the grid's titles: ${titles(grid)}`;
const gi = [...grid.querySelectorAll(".ui-trust-item")];
if (gi[2].querySelector(".ui-trust-icon").textContent.trim() !== "🌱" || gi[2].querySelector("svg")) return "an emoji icon is not shown as text";
if (gi[1].querySelector(".ui-trust-note").textContent !== "Chat with us, 9 to 6") return "a map item's text is missing";
if (getComputedStyle(gi[0]).borderTopWidth === "0px") return "bordered does not draw a box";
if (getComputedStyle(grid).display !== "grid") return "layout=grid is not a grid";
const li = [...list.querySelectorAll(".ui-trust-item")];
if (li[0].getBoundingClientRect().top === li[1].getBoundingClientRect().top) return "layout=list does not stack";
if (parseFloat(getComputedStyle(li[0].querySelector(".ui-trust-icon")).width) >= parseFloat(getComputedStyle(items[0].querySelector(".ui-trust-icon")).width)) return "sm icons are not smaller";
