const nav = $("#mega-menu-demo");
if (!nav || nav.tagName !== "NAV" || nav.getAttribute("aria-label") !== "Main") return "it is not a labelled <nav>";
if (nav.querySelector(".ui-megamenu-brand")?.getAttribute("href") !== "/") return "the brand does not link home";
const items = [...nav.querySelectorAll(".ui-megamenu-item")];
if (items.length !== 4) return `expected 4 items, found ${items.length}`;
const [products, resources, pricing] = items;
const btn = products.querySelector("button.ui-megamenu-trigger"), panel = products.querySelector(".ui-megamenu-panel");
if (!btn || !panel || btn.getAttribute("aria-controls") !== panel.id || btn.getAttribute("aria-haspopup") !== "true") return "an item with columns is not a button controlling its panel";
if (pricing.querySelector("a.ui-megamenu-trigger")?.getAttribute("href") !== "#pricing" || pricing.querySelector(".ui-megamenu-panel")) return "an item with only an href is not a plain link";
if (btn.getAttribute("aria-current") !== "page") return "the item holding the current page is not marked";
const shown = (el) => getComputedStyle(el).display !== "none";
if (shown(panel)) return "the panel starts open";
btn.focus(); await wait(200);
if (document.activeElement !== btn || !shown(panel)) return "focusing the item does not open its panel";
const cols = [...panel.querySelectorAll(".ui-megamenu-col")];
if (cols.length !== 2 || cols[0].querySelector(".ui-megamenu-title")?.textContent !== "Build" || cols[0].querySelectorAll("a").length !== 3) return "the columns or their links are wrong";
const lefts = cols.map((c) => Math.round(c.getBoundingClientRect().left));
if (new Set(lefts).size !== 2 || Math.abs(cols[0].getBoundingClientRect().top - cols[1].getBoundingClientRect().top) > 1) return "the columns are not side by side";
const pr = panel.getBoundingClientRect(), nr = nav.getBoundingClientRect();
if (Math.abs(pr.left - nr.left) > 1 || Math.abs(pr.right - nr.right) > 1 || pr.top < nr.bottom - 2) return "the panel does not span the bar's width under it";
const comp = [...panel.querySelectorAll("a")].find((a) => a.textContent.includes("Components"));
if (comp.getAttribute("aria-current") !== "page" || !comp.querySelector(".ui-megamenu-desc")?.textContent.includes("kit") || !comp.querySelector(".ui-megamenu-icon svg")) return "a link's current mark, description or icon is missing";
comp.focus(); await wait(100);
if (!shown(panel)) return "the panel closes when focus moves to a link in it";
if (panel.querySelector(".ui-megamenu-featured")?.getAttribute("href") !== "#new" || !panel.querySelector(".ui-megamenu-cta")?.textContent.includes("Read the notes")) return "the featured box is missing";
comp.blur(); await wait(200);
if (shown(panel)) return "the panel stays open after focus leaves";
if (!nav.querySelector(".ui-megamenu-end .ui-btn")) return "children are not at the end";
