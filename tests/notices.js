const btn = (t) => $$("button").find((b) => b.textContent.trim() === t);
const host = () => document.getElementById("q-notices");
btn("Success").click(); await wait(400);
const toast = host()?.querySelector(".q-toast.q-success");
if (!toast) return "notify() made no success toast";
if (host().querySelector(".q-toasts").getAttribute("aria-live") !== "polite") return "the toasts are not a polite live region";
const cs = getComputedStyle(toast);
if (cs.position === "static" && getComputedStyle(toast.parentElement).position !== "fixed") return "the toasts are not laid out (not fixed)";
if (cs.opacity !== "1") return `the toast did not finish showing: opacity ${cs.opacity}`;
const probe = document.createElement("span"); probe.style.color = "var(--ui-success)"; toast.appendChild(probe);
if (cs.borderLeftColor !== getComputedStyle(probe).color) return "the success toast does not use the success colour";
probe.remove();
const r = toast.getBoundingClientRect();
if (r.top > 40 || innerWidth - r.right > 40) return `the toast is not at the top right: ${r.top},${r.right}`;
toast.querySelector(".q-close").click(); await wait(300);
if (toast.isConnected) return "the close button did not remove the toast";
btn("Ask").click(); await wait(300);
const dlg = host().querySelector(".q-dialog");
if (!dlg || dlg.getAttribute("role") !== "alertdialog") return "ask() made no dialog";
const back = dlg.parentElement;
if (getComputedStyle(back).position !== "fixed" || getComputedStyle(back).opacity !== "1") return "the dialog backdrop is not fixed and shown";
const d = dlg.getBoundingClientRect();
if (Math.abs((d.left + d.right) / 2 - innerWidth / 2) > 4) return "the dialog is not centred";
if (document.activeElement !== dlg.querySelector(".q-ok")) return "OK is not focused";
dlg.querySelector(".q-ok").click(); await wait(300);
if (!$(".demo-note").textContent.includes("You said publish")) return `ask() did not give true: ${$(".demo-note").textContent}`;
btn("Ask (danger)").click(); await wait(300);
const dd = host().querySelector(".q-dialog.q-danger");
if (!dd || document.activeElement !== dd.querySelector(".q-cancel")) return "a danger question does not start on Cancel";
const red = document.createElement("span"); red.style.color = "var(--ui-danger)"; dd.appendChild(red);
if (getComputedStyle(dd.querySelector(".q-ok")).backgroundColor !== getComputedStyle(red).color) return "a danger question's OK is not red";
red.remove();
dd.querySelector(".q-cancel").click(); await wait(300);
if (!$(".demo-note").textContent.includes("Kept")) return `cancel did not give false: ${$(".demo-note").textContent}`;
