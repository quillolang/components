const doc = $("#markdown-view-demo-doc");
if (!doc || doc.querySelector("h1")?.textContent !== "Writing a component") return "the heading is not an h1";
if (doc.querySelector("h2")?.textContent !== "What goes in") return "## is not an h2";
const p1 = doc.querySelector("p");
if (p1.querySelector("strong")?.textContent !== "one file") return "**bold** is not strong";
const ems = [...p1.querySelectorAll("em")].map((e) => e.textContent);
if (ems.join("|") !== "own styles|light or dark") return `*italic* and _italic_ give ${ems}`;
if (p1.querySelector("del")?.textContent !== "needs a build step") return "~~struck~~ is not del";
const a = p1.querySelector("a");
if (!a || a.getAttribute("href") !== "https://quillolang.org/components/" || a.textContent !== "the gallery" || a.title !== "Quillo UI") return "the link is wrong";
const ol = doc.querySelector("ol");
if (!ol || ol.querySelectorAll("li").length !== 3 || ol.querySelectorAll("li")[1].querySelector("code")?.textContent !== "let name_css = css") return "the numbered list or its code span is wrong";
const bq = doc.querySelector("blockquote");
if (!bq || !bq.querySelector("p") || !bq.textContent.includes("Views first") || !bq.textContent.includes("already does")) return "the quote is not a blockquote with its lines";
const ul = doc.querySelector("ul");
const boxes = ul.querySelectorAll("input[type=checkbox]");
if (boxes.length !== 2 || !boxes[0].checked || boxes[1].checked || !boxes[0].disabled) return "task items are not checked and unchecked boxes";
if (ul.querySelectorAll("li")[0].textContent.trim() !== "Read the README") return "a task item lost its text";
if (!ul.querySelectorAll("li")[2].textContent.includes("*escaped* stars")) return "a backslash does not keep the star";
const pre = doc.querySelector("pre code");
if (!pre || pre.className !== "language-sh" || pre.textContent !== "scripts/build.sh && scripts/test.sh button") return "the fenced code is wrong";
if (!doc.querySelector("hr")) return "--- is not a rule";
const last = [...doc.querySelectorAll(":scope > p")].pop();
if (doc.querySelector("script") || doc.querySelector("b") || !last.textContent.includes("<script>alert(1)</script>") || !last.textContent.includes("<b>not bold</b>")) return "HTML got through";
if (!last.querySelector("br")) return "two trailing spaces do not break the line";
const bad = [...last.querySelectorAll("a")].find((l) => l.textContent === "bad link");
if (!bad || bad.getAttribute("href")?.startsWith("javascript:")) return "a javascript: link is not blocked";
if (last.querySelector("img") || !last.textContent.includes("a picture")) return "an image shows with images off";
const live = $("#markdown-view-demo-live");
if (live.querySelector("strong")?.textContent !== "Markdown" || live.querySelector("code")?.textContent !== "code") return "the live view does not render its text";
const box = $("textarea[name=markdown-view-demo-input]");
type(box, "## Changed\n\n- one\n- two"); await wait();
if (live.querySelector("h2")?.textContent !== "Changed" || live.querySelectorAll("ul li").length !== 2) return `typing did not re-render: ${live.innerHTML}`;
type(box, "Type some **Markdown** here, with a [link](https://quillolang.org) and `code`."); await wait();
