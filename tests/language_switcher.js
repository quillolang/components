const btn = $$(".ui-lang-btn")[0];
const menu = document.getElementById("language-switcher-demo");
if (!btn || !menu || !menu.hasAttribute("popover") || btn.getAttribute("popovertarget") !== "language-switcher-demo") return "the button does not open a popover list";
if (!btn.textContent.includes("English") || btn.getAttribute("aria-label") !== "Language: English") return `the button does not show the current language: ${btn.textContent}`;
if (btn.querySelector("[lang=en]")?.textContent !== "English") return "the name is not marked with its lang";
btn.scrollIntoView({ block: "center" });
btn.click(); await wait();
if (!menu.matches(":popover-open")) return "clicking does not open the list";
const items = [...menu.querySelectorAll("a.ui-lang-item")];
if (items.length !== 5 || items[1].getAttribute("hreflang") !== "pt" || items[1].getAttribute("href") !== "#pt") return "the languages are not links with hreflang";
if (items[1].querySelector("[lang=pt]")?.textContent !== "Português") return "a language is not written with its lang";
const cur = items.filter((a) => a.hasAttribute("aria-current"));
if (cur.length !== 1 || !cur[0].textContent.includes("English") || !cur[0].querySelector("svg")) return "the current language is not marked with a check";
if (!items[4].querySelector(".ui-lang-flag")?.textContent.includes("🇯🇵")) return "the flag is not shown";
if (menu.querySelector("ul").getAttribute("aria-label") !== "Language") return "the list is not labelled";
btn.click(); await wait();
if (menu.matches(":popover-open")) return "clicking again does not close it";
const live = $$(".ui-lang-btn")[2];
if (live.textContent.trim() !== "FR") return `short does not show the code: ${live.textContent.trim()}`;
live.click(); await wait();
const lm = document.getElementById("language-switcher-demo-live");
const it = [...lm.querySelectorAll("button.ui-lang-item")].find((b) => b.textContent.includes("Italiano"));
it.click(); await wait();
if (lm.matches(":popover-open")) return "picking does not close the list";
if (!live.closest(".demo-row").querySelector(".demo-note").textContent.includes("it") || live.textContent.trim() !== "IT") return "on_select did not reach the note or the button";
