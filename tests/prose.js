const art = $("#prose-demo-article");
if (!art || !art.classList.contains("ui-prose")) return "the article is not a .ui-prose";
const cs = (el, pseudo) => getComputedStyle(el, pseudo);
const size = (el) => parseFloat(cs(el).fontSize);
const p = art.querySelector("p"), h1 = art.querySelector("h1"), h2 = art.querySelector("h2"), h3 = art.querySelector("h3");
if (!(size(h1) > size(h2) && size(h2) > size(h3) && size(h3) > size(p))) return "the headings do not step down to the text";
if (cs(h1).marginTop !== "0px") return "the first child keeps its top margin";
if (cs(art.lastElementChild).marginBottom !== "0px") return "the last child keeps its bottom margin";
const probe = document.createElement("span"); probe.style.color = "var(--ui-accent)"; art.append(probe);
const accent = cs(probe).color; probe.remove();
if (cs(art.querySelector("a")).color !== accent) return "links are not in the accent colour";
if (cs(art.querySelector("blockquote")).borderLeftWidth === "0px") return "a blockquote has no bar";
const code = art.querySelector("li code");
if (!/mono|Menlo|Consolas/i.test(cs(code).fontFamily) || cs(code).backgroundColor === "rgba(0, 0, 0, 0)") return "inline code is not monospace on a background";
const pre = art.querySelector("pre");
if (cs(pre).overflowX !== "auto" || cs(pre).borderTopWidth === "0px") return "a code block does not scroll in a box";
if (cs(art.querySelector("pre code")).backgroundColor !== "rgba(0, 0, 0, 0)") return "code in a pre has its own background";
const th = art.querySelector("th");
if (cs(th).borderBottomWidth === "0px" || cs(th).textAlign !== "left" || cs(th).fontWeight !== "600") return "table headers are not styled";
if (cs(art.querySelector("ol")).paddingLeft === "0px") return "lists have no indent";
if (parseFloat(cs(art.querySelector("li")).marginTop) <= 0) return "list items have no spacing";
if (art.getBoundingClientRect().width > 68 * size(p) + 4) return "the measure is wider than 68ch";
if (cs(art.querySelector("hr")).borderTopWidth === "0px") return "a rule is not drawn";
const small = $("#prose-demo-small"), large = $("#prose-demo-large");
if (!(size(small.querySelector("p")) < size(p) && size(p) < size(large.querySelector("p")))) return "size sm and lg do not change the text";
if (small.getBoundingClientRect().width > 30 * size(small.querySelector("p")) + 4) return "width=30ch is not applied";
