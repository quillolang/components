const host = $(".ui-toast-host"), note = () => $(".demo-note").textContent;
const toasts = () => [...host.querySelectorAll(":scope > li")];
if (!host || host.tagName !== "OL" || host.getAttribute("aria-label") !== "Notifications") return "no named toast host";
if (toasts().length !== 0) return "the host does not start empty";
const statics = $$(".demo-narrow .ui-toast");
if (statics.length !== 2 || !statics[0].classList.contains("ui-toast-success") || statics[0].querySelector(".ui-toast-title").textContent !== "Invoice sent") return "the Toast view does not draw its title and tone";
if (statics[1].querySelector(".ui-toast-action")?.textContent !== "Renew") return "the Toast view does not draw its action";
$("#toast-demo-save").click(); await wait();
let ts = toasts();
if (ts.length !== 1 || !ts[0].textContent.includes("Saved (1)") || ts[0].getAttribute("role") !== "status") return `toast_show did not add a status toast: ${host.innerHTML.slice(0, 200)}`;
if (!ts[0].querySelector(".ui-toast-success") || ts[0].querySelector(".ui-toast-x")?.getAttribute("aria-label") !== "Dismiss") return "the toast has no tone or Dismiss button";
await wait(3300);
if (toasts().length !== 0) return "a 3-second toast did not go by itself";
$("#toast-demo-delete").click(); await wait();
if (note() !== "The message is deleted.") return "the delete did not happen";
const undo = toasts()[0]?.querySelector(".ui-toast-action");
if (!undo || undo.textContent !== "Undo") return "no Undo action";
undo.click(); await wait();
if (note() !== "The message is here." || toasts().length !== 0) return `the action did not run and close the toast: ${note()}`;
$("#toast-demo-error").click(); await wait();
ts = toasts();
if (ts[0]?.getAttribute("role") !== "alert" || ts[0].querySelector(".ui-toast-title").textContent !== "Offline") return "a danger toast is not an alert with its title";
await wait(5500);
if (toasts().length !== 1) return "seconds: 0 did not keep the toast";
ts[0].querySelector(".ui-toast-x").click(); await wait();
if (toasts().length !== 0) return "Dismiss did not close it";
for (let i = 0; i < 4; i++) { $("#toast-demo-save").click(); await wait(60); }
await wait();
ts = toasts();
if (ts.length !== 3 || !ts.at(-1).textContent.includes("Saved (5)") || ts[0].textContent.includes("Saved (2)")) return `limit=3 did not drop the oldest: ${ts.map((t) => t.textContent.trim())}`;
host.dispatchEvent(new PointerEvent("pointerenter")); await wait(3500);
if (toasts().length !== 3) return "hovering did not hold the timers";
