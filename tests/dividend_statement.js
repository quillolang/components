const s = $("#dividend-statement-demo");
if (!s) return "no statement";
const row = (cls) => [...s.querySelector(`.ui-dividend-statement-${cls}`).children].map((c) => c.textContent.trim());
const d = row("dividend");
if (d.join("|") !== "Dividend on share capitalAverage share capital|₱18,437.50|6.5%|₱1,198.44") return `the dividend: ${d}`;
const p = row("patronage");
if (p.join("|") !== "Patronage refundInterest paid on loans|₱24,512.80|12%|₱2,941.54") return `the refund: ${p}`;
if (row("gross")[3] !== "₱4,139.98") return `gross: ${row("gross")}`;
const t = row("tax");
if (t[0] !== "Withholding tax" || t[2] !== "10%" || t[3].replace(/\s+/g, "") !== "−minus₱414.00") return `tax: ${t}`;
if (row("net")[3] !== "₱3,725.98") return `net: ${row("net")}`;
if (s.querySelector(".ui-dividend-statement-title").textContent !== "Dividend and patronage refund, 2025") return "the title";
if (!s.querySelector(".ui-dividend-statement-foot").textContent.includes("Paid Mar 31, 2026 to Savings account •••• 4821")) return `the footer: ${s.querySelector(".ui-dividend-statement-foot").textContent}`;
if (s.querySelectorAll("tbody th[scope=row]").length !== 5) return "the rows are not headed";
const c = $("#dividend-statement-demo-cu");
if (c.querySelector(".ui-dividend-statement-patronage") || c.querySelector(".ui-dividend-statement-tax") || c.querySelector(".ui-dividend-statement-gross")) return "rows shown without their figures";
const cd = [...c.querySelector(".ui-dividend-statement-dividend").children].map((x) => x.textContent.trim());
if (cd[1] !== "$2,350.00" || cd[2] !== "3.25%" || cd[3] !== "$76.38" || !cd[0].includes("Average share balance")) return `the credit union's dividend: ${cd}`;
if (c.querySelector(".ui-dividend-statement-net td:last-child").textContent !== "$76.38") return "net without tax";
if (c.querySelector(".ui-dividend-statement-foot").textContent.trim() !== "Credited to Share savings •••• 0377") return "credited without paid";
