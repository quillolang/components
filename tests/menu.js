const nav = $("#menu-demo");
if (!nav || nav.tagName !== "NAV" || nav.getAttribute("aria-label") !== "Settings") return "the menu is not a labelled <nav>";
const titles = [...nav.querySelectorAll(".ui-menu-title")].map((t) => t.textContent);
if (titles.join() !== "Account,Workspace") return `the sections are ${titles}`;
const cur = nav.querySelectorAll("[aria-current]");
if (cur.length !== 1 || !cur[0].textContent.includes("Notifications") || cur[0].getAttribute("aria-current") !== "page") return "the active item is not marked once";
if (cur[0].querySelector(".ui-menu-badge")?.textContent !== "3") return "the badge does not show";
if (!nav.querySelector(".ui-menu-icon svg path")) return "an SVG path icon is not drawn";
const off = [...nav.querySelectorAll("a")].find((a) => a.textContent.includes("Integrations"));
if (off.getAttribute("aria-disabled") !== "true" || off.tabIndex !== -1) return "a disabled link is not aria-disabled and out of the tab order";
if (!nav.querySelector("[role=separator]")) return "the divider is not a separator";
if (!nav.querySelector("a.ui-menu-danger")?.textContent.includes("Sign out")) return "tone: danger is missing";
const live = $("#menu-demo-live");
const btns = [...live.querySelectorAll("button.ui-menu-item")];
if (btns.length !== 4) return `expected 4 buttons, found ${btns.length}`;
if (btns[0].getAttribute("aria-keyshortcuts") !== "F2" || btns[0].querySelector(".ui-menu-key")?.textContent !== "F2") return "the shortcut is not shown and said";
if (!btns[2].disabled) return "disabled: true does not disable the button";
btns[1].click(); await wait();
const note = live.closest(".demo-stack").querySelector(".demo-note").textContent;
if (!note.includes("Duplicate")) return `on_select was not called: ${note}`;
