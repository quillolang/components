const z = $("#news-quiz-demo");
if (!z || z.getAttribute("aria-labelledby") !== "news-quiz-demo-title" || z.querySelector("h3").textContent !== "The week in news, Oct 30") return "the quiz is not a labelled section";
const count = () => z.querySelector(".ui-nquiz-count").textContent;
const choices = () => [...z.querySelectorAll(".ui-nquiz-choice")];
const verdict = () => z.querySelector(".ui-nquiz-verdict")?.textContent;
if (count() !== "Question 1 of 3" || choices().length !== 4) return `start: ${count()}, ${choices().length} choices`;
if (choices().map((c) => c.querySelector(".ui-nquiz-letter").textContent).join("") !== "ABCD") return "letters";
if (z.querySelector(".ui-nquiz-btn")) return "Next shows before a pick";
if (!z.querySelector(".ui-nquiz-track span:first-child").classList.contains("ui-nquiz-now")) return "the track";
choices()[1].click(); await wait();
if (!choices()[1].classList.contains("ui-nquiz-right") || verdict() !== "Right!") return `a right pick: ${verdict()}`;
if (!choices()[0].classList.contains("ui-nquiz-faded") || choices()[0].getAttribute("aria-disabled") !== "true") return "the others are not faded and disabled";
if (z.querySelector('[role="status"] .ui-nquiz-explain').textContent !== "Nairobi will be the first African city to host it. Read the story") return `explain: ${z.querySelector(".ui-nquiz-explain")?.textContent}`;
if (!choices()[1].textContent.includes(", your answer")) return "screen readers do not hear which was picked";
choices()[0].click(); await wait();
if (choices()[0].classList.contains("ui-nquiz-wrong") || verdict() !== "Right!") return "a second pick changed the answer";
const next = z.querySelector(".ui-nquiz-btn");
if (next.textContent !== "Next question") return "Next question";
next.click(); await wait(200);
if (count() !== "Question 2 of 3" || document.activeElement?.id !== "news-quiz-demo-q") return "the focus does not go to the next question";
if (z.querySelectorAll(".ui-nquiz-choice").length !== 3 || z.querySelector(".ui-nquiz-right, .ui-nquiz-wrong")) return "the second question starts marked";
if (!z.querySelector(".ui-nquiz-track span:first-child").classList.contains("ui-nquiz-r")) return "the track keeps a right answer green";
choices()[0].click(); await wait();
if (!choices()[0].classList.contains("ui-nquiz-wrong") || !choices()[2].classList.contains("ui-nquiz-right")) return "a wrong pick does not show the right one";
if (verdict() !== "Not quite: it was C, No change.") return `wrong verdict: ${verdict()}`;
z.querySelector(".ui-nquiz-btn").click(); await wait(200);
choices()[2].click(); await wait();
if ($("#news-quiz-demo-note").textContent !== "on_finish gave 2 of 3") return `on_finish: ${$("#news-quiz-demo-note").textContent}`;
const see = z.querySelector(".ui-nquiz-btn");
if (see.textContent !== "See your score") return "the last button";
see.click(); await wait(200);
const score = z.querySelector(".ui-nquiz-score");
if (!score || score.textContent !== "2 / 3 right" || document.activeElement !== score) return `the score: ${score?.textContent}`;
if (z.querySelector(".ui-nquiz-say").textContent !== "Well read.") return "two of three is well read";
if ([...z.querySelectorAll(".ui-nquiz-marks li")].map((l) => l.className).join() !== "ui-nquiz-r,ui-nquiz-w,ui-nquiz-r") return "the marks";
z.querySelector(".ui-nquiz-end .ui-nquiz-btn").click(); await wait(200);
if (count() !== "Question 1 of 3" || z.querySelector(".ui-nquiz-track .ui-nquiz-r, .ui-nquiz-track .ui-nquiz-w") || z.querySelector(".ui-nquiz-right")) return "Play again does not start over";
