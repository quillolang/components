const stacks = $$(".ui-avs");
if (stacks.length !== 5) return `expected 5 stacks, found ${stacks.length}`;
const [team, reviewers, viewing, owners, big] = stacks;
const avs = (s) => [...s.querySelectorAll(".ui-avs-av:not(.ui-avs-more)")];
if (avs(team).length !== 4) return `max=4 shows ${avs(team).length}`;
if (team.getAttribute("role") !== "group" || team.getAttribute("aria-label") !== "Project members") return "the group is not named";
const more = team.querySelector(".ui-avs-more");
if (more?.textContent !== "+3") return `the rest: ${more?.textContent}`;
if (more.getAttribute("aria-label") !== "and Linus Torvalds, Margaret Hamilton, Dennis Ritchie") return `the rest is said as "${more.getAttribute("aria-label")}"`;
const [ada, grace, alan] = avs(team);
if (ada.tagName !== "A" || ada.getAttribute("href") !== "#avatar_stack" || ada.getAttribute("aria-label") !== "Ada Lovelace") return "href does not make a named link";
if (alan.tagName !== "SPAN" || alan.getAttribute("role") !== "img" || alan.getAttribute("aria-label") !== "Alan Turing") return "an avatar is not a named image";
if (alan.querySelector("span").textContent !== "AT") return "initials";
const hue = (el, pre) => [...el.classList].find((c) => c.startsWith(pre))?.slice(pre.length);
const avatar = document.querySelector('.ui-avatar[aria-label="Alan Turing"]');
if (avatar && hue(avatar, "ui-avatar-c") !== hue(alan, "ui-avs-c")) return "the colour is not the one Avatar gives the name";
if (new Set(avs(team).concat(avs(owners)).map((e) => hue(e, "ui-avs-c"))).size < 3) return "names do not spread over the colours";
grace.scrollIntoView(); await wait(300);
const pic = grace.querySelector("img");
for (let i = 0; i < 20 && !pic.complete; i++) await wait(100);
if (pic.naturalWidth === 0) return "the picture did not load";
const tip = ada.parentElement.querySelector(".ui-avs-tip");
if (tip.textContent !== "Ada Lovelace" || getComputedStyle(tip).display !== "none") return "the tooltip is missing or showing";
ada.focus(); await wait(100);
if (getComputedStyle(tip).display !== "block") return "focusing the link does not show its name";
if (!(tip.getBoundingClientRect().bottom <= ada.getBoundingClientRect().top)) return "the tooltip is not above";
ada.blur();
more.focus(); await wait(100);
if (getComputedStyle(more.parentElement.querySelector(".ui-avs-tip")).display !== "block") return "the +N does not list the rest on focus";
more.blur();
const [a, b] = team.querySelectorAll(".ui-avs-av");
if (!(b.getBoundingClientRect().left < a.getBoundingClientRect().right)) return "the avatars do not overlap";
if (reviewers.querySelector(".ui-avs-more")) return "three people under max show a +N";
if (Math.round(avs(reviewers)[0].getBoundingClientRect().width) !== 32) return "size=sm is not 32px";
if (viewing.querySelector(".ui-avs-more").textContent !== "+125") return `total=128 with 3 shown: ${viewing.querySelector(".ui-avs-more").textContent}`;
if (viewing.querySelector(".ui-avs-more").getAttribute("aria-label") !== "and Katherine Johnson, Linus Torvalds and 123 more") return `the rest of a total: ${viewing.querySelector(".ui-avs-more").getAttribute("aria-label")}`;
if (getComputedStyle(avs(owners)[0]).borderRadius === "50%") return "shape=square is round";
if (big.querySelector(".ui-avs-tip") || big.querySelector("[tabindex]")) return "tooltips={false} still has tooltips";
if (Math.round(avs(big)[0].getBoundingClientRect().width) !== 72) return "size=xl is not 72px";
