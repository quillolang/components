const a = $("aside#post-updates-demo.ui-bupd");
if (!a || a.getAttribute("aria-label") !== "Changes to this post") return "the aside and its name";
if (!a.classList.contains("ui-bupd-fix")) return "a correction does not mark the note";
const d = a.querySelector("details");
if (!d.open) return "with a correction the list is not open to start with";
const head = a.querySelector(".ui-bupd-head");
if (head.textContent.replace(/\s+/g, " ").trim() !== "Corrected Oct 28, 2026" || head.querySelector("time").getAttribute("datetime") !== "2026-10-28T09:30:00Z") return `the summary reads ${head.textContent}`;
const sub = a.querySelector(".ui-bupd-sub").textContent.replace(/\s+/g, " ").trim();
if (sub !== "3 changes, 1 correction since it was published on Oct 14, 2026") return `the line reads "${sub}"`;
const items = [...a.querySelectorAll("li.ui-bupd-item")];
if (items.map((i) => i.querySelector("time").textContent).join("|") !== "Oct 28, 2026|Oct 20, 2026|Oct 16, 2026") return "the changes are not newest first";
if (items.map((i) => i.querySelector(".ui-bupd-kind").textContent).join() !== "Correction,Addition,Update") return "the kinds";
if (!items[0].classList.contains("ui-bupd-correction") || items[0].querySelector(".ui-bupd-text strong")?.textContent !== "11 KB") return "Markdown in a change";
if (items[1].querySelector(".ui-bupd-text a")?.getAttribute("href") !== "#post_updates-prefetch" || items[2].querySelector("code")?.textContent !== "every") return "links and code";
if (items[1].querySelector("p")) return "inline Markdown is wrapped in a paragraph";
const red = getComputedStyle(items[0].querySelector(".ui-bupd-kind")).color, blue = getComputedStyle(items[2].querySelector(".ui-bupd-kind")).color;
if (red === blue) return "a correction looks like an update";
const more = a.querySelector(".ui-bupd-more");
if (more.getAttribute("aria-hidden") !== "true" || getComputedStyle(more.querySelector(".ui-bupd-opened")).display === "none") return "open, it does not offer to hide";
d.querySelector("summary").click(); await wait(50);
if (d.open || a.querySelector(".ui-bupd-list").checkVisibility()) return "the summary does not close it";
if (getComputedStyle(more.querySelector(".ui-bupd-shut")).display === "none") return "closed, it does not offer to see what changed";
d.querySelector("summary").click();
const p = $("#post-updates-demo-plain");
if (p.classList.contains("ui-bupd-fix") || p.querySelector("details").open) return "without a correction it starts closed and unmarked";
if (p.querySelector(".ui-bupd-head").textContent.replace(/\s+/g, " ").trim() !== "Updated Sep 5, 2026") return "the plain summary";
if (!p.querySelector(".ui-bupd-sub").textContent.trim().startsWith("1 change since")) return "one change";
