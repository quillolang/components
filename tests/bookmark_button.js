if (all.length !== 7) return `expected 7 buttons, found ${all.length}`;
if (first.getAttribute("aria-pressed") !== "false" || first.textContent.trim() !== "Save") return "it does not start as Save, unpressed";
if (getComputedStyle(first.querySelector("svg")).fill !== "none") return "the bookmark starts filled";
first.click(); await wait();
if (first.getAttribute("aria-pressed") !== "true" || first.textContent.trim() !== "Saved" || !first.classList.contains("ui-bookmark-button-on")) return "pressing does not make it Saved";
if (getComputedStyle(first.querySelector("svg")).fill === "none") return "the bookmark is not filled when saved";
if (note() !== "Saved for later.") return `on_change did not reach the note: ${note()}`;
first.click(); await wait();
if (first.textContent.trim() !== "Save" || note() !== "Not saved.") return "pressing again does not unsave";
const named = all[1], hidden = named.querySelector("input[type=hidden][name=saved]");
if (!hidden || hidden.disabled) return "saved={true} with name does not send it";
named.click(); await wait();
if (!hidden.disabled) return "unsaving still sends it";
const icon = all[2];
