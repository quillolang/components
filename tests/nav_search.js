// alone: it listens to the whole page (its "/" shortcut)
const input = $("#nav-search-demo"), form = input.closest("form");
if (!form || form.getAttribute("role") !== "search" || form.method !== "get" || input.type !== "search" || input.name !== "q") return "it is not a search form with a search field named q";
if (input.getAttribute("aria-label") !== "Search" || input.getAttribute("aria-keyshortcuts") !== "/") return "the field is not named, or the shortcut not told";
const rest = input.getBoundingClientRect().width;
if (Math.abs(rest - 160) > 2) return `at rest it is ${rest}px wide, not 160`;
const note = () => form.closest(".demo-stack").querySelector(".demo-note").textContent;
type(input, "routes"); await wait(300);
if (!note().includes("Typing: routes")) return `on_input did not reach the note: ${note()}`;
const open = input.getBoundingClientRect().width;
if (Math.abs(open - 280) > 2) return `with text it is ${open}px wide, not 280`;
const clear = form.querySelector(".ui-navsearch-clear");
if (getComputedStyle(clear).display === "none") return "the clear button does not show with text";
form.requestSubmit(); await wait();
if (!note().includes('Searched for "routes"')) return `on_submit did not reach the note: ${note()}`;
key(input, "Escape"); await wait();
if (input.value !== "" || !note().includes('Searched')) return "Escape did not clear the text";
key(input, "Escape"); await wait();
if (document.activeElement === input) return "Escape on an empty box did not leave it";
document.body.dispatchEvent(new KeyboardEvent("keydown", { key: "/", bubbles: true, cancelable: true })); await wait();
if (document.activeElement !== input) return "/ did not focus the box";
input.blur();
const other = $("#nav-search-demo-plain");
other.focus();
other.dispatchEvent(new KeyboardEvent("keydown", { key: "/", bubbles: true, cancelable: true })); await wait();
if (document.activeElement !== other) return "/ inside another field stole the focus";
other.blur();
type(other, "views"); await wait(200);
if (Math.abs(other.getBoundingClientRect().width - 240) > 2 || other.closest("form").getAttribute("action") !== "#nav_search") return "a plain one does not take its own widths and action";
type(other, "quillo"); await wait();
