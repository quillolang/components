const usd = (n, code = "USD") => new Intl.NumberFormat("en-US", { style: "currency", currency: code }).format(n);
const amt = $("#fx-quote-ticket-desk-amount");
const t = amt.closest(".ui-fxticket");
const rate = () => Number(t.querySelector(".ui-fxticket-price").dataset.rate);
const counter = () => t.querySelector(".ui-fxticket-counter").textContent.trim();
if (amt.name !== "desk_amount" || amt.value !== "250000") return "the amount field";
if (!t.querySelector('input[name="desk_side"][value="buy"]').checked) return "buy is not picked to start";
let r = rate();
const ask = Number(t.querySelectorAll(".ui-fxticket-side span")[1].textContent);
if (r !== ask || counter() !== usd(250000 * r)) return `buying 250,000 EUR at ${r} (ask ${ask}) reads ${counter()}`;
const sell = t.querySelector('input[value="sell"]'); sell.click(); await wait();
r = rate();
const bid = Number(t.querySelectorAll(".ui-fxticket-side span")[0].textContent);
if (r !== bid || r >= ask || counter() !== usd(250000 * r)) return `selling at ${r} (bid ${bid}) reads ${counter()}`;
if (!t.querySelector(".ui-fxticket-confirm").textContent.includes("Confirm sell €250,000.00")) return `the button reads ${t.querySelector(".ui-fxticket-confirm").textContent}`;
type(amt, "1,000,000"); await wait();
if (counter() !== usd(1000000 * rate())) return `a million reads ${counter()}`;
type(amt, "0"); await wait();
if (!t.querySelector(".ui-fxticket-confirm").disabled || counter() !== "—") return "a zero amount can be confirmed";
type(amt, "250000"); await wait();
t.querySelector('input[value="buy"]').click(); await wait();
const q = t.dataset.quote;
let left = Number(t.querySelector("[data-left]").dataset.left);
if (!(left >= 0 && left <= 6)) return `the countdown reads ${left}`;
let n = 0;
while (t.dataset.quote === q && n++ < 40) await wait(250);
if (t.dataset.quote === q) return "no new quote when it ran out";
if (t.classList.contains("ui-fxticket-expired") || Number(t.querySelector("[data-left]").dataset.left) < 4) return "the new quote's countdown did not start again";
if (!t.querySelector(".ui-fxticket-quote-no").textContent.includes(t.dataset.quote)) return "the quote number";
// It ticks: the seconds left go down while the quote stands (waited for, not timed).
const q2 = t.dataset.quote, from = Number(t.querySelector("[data-left]").dataset.left);
let ticked = false;
for (let k = 0; k < 16 && !ticked; k++) { await wait(150); ticked = t.dataset.quote === q2 && Number(t.querySelector("[data-left]").dataset.left) < from; }
if (!ticked) return "the countdown does not tick";
r = rate();
const want = `buy 250000 EUR at ${t.querySelector(".ui-fxticket-price").dataset.rate}`;
t.querySelector(".ui-fxticket-confirm").click(); await wait();
const done = t.querySelector(".ui-fxticket-done");
if (!done || !done.textContent.replace(/\s+/g, " ").includes(`Bought €250,000.00 at ${r.toFixed(5)} for ${usd(250000 * r)}`)) return `after Confirm: ${done?.textContent}`;
const note = $("#fx-quote-ticket-demo-note").textContent;
if (!note.startsWith(want) || !note.endsWith(" USD")) return `on_confirm gave: ${note} (wanted ${want})`;
done.querySelector("button").click(); await wait();
if (!t.querySelector(".ui-fxticket-confirm")) return "New deal does not bring the ticket back";
const s = $("#fx-quote-ticket-usdjpy-amount").closest(".ui-fxticket");
if (s.getAttribute("action") !== "#deals" || s.getAttribute("method") !== "post") return "the form's action";
const fd = new FormData(s);
if (fd.get("side") !== "sell" || fd.get("amount") !== "100000" || fd.get("pair") !== "USD/JPY" || fd.get("rate") !== "156.238") return `the form sends ${[...fd]}`;
if (s.querySelector(".ui-fxticket-counter").textContent.trim() !== "¥15,623,800") return `USD/JPY counter ${s.querySelector(".ui-fxticket-counter").textContent}`;
n = 0;
while (!s.classList.contains("ui-fxticket-expired") && n++ < 30) await wait(250);
if (!s.classList.contains("ui-fxticket-expired")) return "the quote does not run out";
if (!s.querySelector(".ui-fxticket-confirm").disabled || !s.querySelector(".ui-fxticket-gone a")) return "a run-out quote can be confirmed, or offers no new one";
