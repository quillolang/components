const grid = $("ul#quick-actions-demo.ui-qa");
if (!grid || grid.getAttribute("aria-label") !== "Quick actions") return "the grid is not a named list";
const items = grid.querySelectorAll("li > .ui-qa-item");
if (items.length !== 6) return `6 actions, found ${items.length}`;
const [order, add, exp, billing, settings, del] = items;
if (order.tagName !== "A" || order.getAttribute("href") !== "#quick_actions") return "an action with href is not a link";
if (add.tagName !== "BUTTON" || add.type !== "button") return "an action without href is not a plain button";
if (order.querySelector(".ui-qa-label")?.textContent !== "New order" || !order.querySelector(".ui-qa-icon svg")) return "the label or SVG icon is missing";
if (exp.querySelector(".ui-qa-hint")?.textContent !== "CSV of this month" || billing.querySelector(".ui-qa-hint")) return "the hint is wrong";
if (billing.querySelector(".ui-qa-icon")?.textContent !== "💳" || !billing.classList.contains("ui-qa-warning")) return "a text icon or the tone is wrong";
if (!del.disabled) return "disabled does not disable the button";
if (getComputedStyle(add.querySelector(".ui-qa-icon")).color === getComputedStyle(order.querySelector(".ui-qa-icon")).color) return "tones colour the icon the same";
add.click(); await wait();
if (!grid.closest(".demo-stack").querySelector(".demo-note").textContent.includes("Picked: Add customer.")) return "on_select did not reach the note";
if (new Set([...items].map((i) => Math.round(i.getBoundingClientRect().top))).size !== 1) return "six at 130px do not fit one row";
const form = $("form");
const reports = form.querySelectorAll(".ui-qa-item");
if (reports.length !== 3 || reports[0].type !== "submit" || reports[0].name !== "report" || reports[0].value !== "sales") return "name and value do not make a submit button";
if (!form.querySelector(".ui-qa").classList.contains("ui-qa-cols")) return "columns is not set";
let submitted = false;
const hold = (e) => { e.preventDefault(); submitted = e.submitter?.value === "stock"; };
form.addEventListener("submit", hold);
reports[1].click(); await wait();
form.removeEventListener("submit", hold);
if (!submitted) return "a submit action does not submit the form with itself";
