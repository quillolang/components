const radios = $$("input[name=shipping-demo-live]");
if (radios.length !== 4 || radios.some((r) => r.type !== "radio")) return `expected 4 radios, got ${radios.length}`;
const fs = radios[0].closest("fieldset");
if (fs.querySelector("legend")?.textContent !== "Shipping") return "no legend";
if (!radios[0].checked || radios[0].value !== "standard") return "value does not check the option";
const cards = radios.map((r) => r.closest(".ui-shipping-opt"));
if (cards[0].querySelector(".ui-shipping-price").textContent !== "Free" || !cards[0].querySelector(".ui-shipping-price").classList.contains("ui-shipping-free")) return "0 does not read Free in green";
if (cards[1].querySelector(".ui-shipping-price").textContent !== "$12.90" || cards[1].querySelector(".ui-shipping-time").textContent !== "1–2 business days") return "price or time missing";
if (cards[2].querySelector(".ui-shipping-hint")?.textContent !== "Order by 4 pm") return "the hint is missing";
if (!radios[3].disabled) return "disabled: true does not disable the option";
if (cards[0].tagName !== "LABEL" || cards[0].htmlFor !== radios[0].id) return "a card is not a label for its radio";
cards[1].click(); await wait();
if (!radios[1].checked || !$(".demo-note").textContent.includes("by express")) return `clicking express: ${$(".demo-note").textContent}`;
if (getComputedStyle(cards[1]).borderTopColor === getComputedStyle(cards[2]).borderTopColor) return "the chosen card does not look chosen";
const eur = $$("input[name=shipping-demo-eur]");
if (!eur[0].required) return "required is not passed on";
if (eur[0].closest(".ui-shipping-opt").querySelector(".ui-shipping-price").textContent.replace(/\s/g, " ") !== "4,95 €") return "de-DE EUR is not written";
const efs = eur[0].closest("fieldset");
if (!efs.classList.contains("ui-shipping-invalid") || document.getElementById(efs.getAttribute("aria-describedby"))?.textContent !== "Pick a delivery option") return "the error is not shown and tied to the group";
