if (document.documentElement.scrollWidth > innerWidth) return "widens the page";
const charts = $$("figure.ui-multiples");
if (charts.length !== 2) return `expected 2 small multiples, found ${charts.length}`;
if (/NaN|Infinity|undefined/.test(charts.map((c) => c.innerHTML).join(""))) return "a chart has NaN, Infinity or undefined in it";
const [sales, signups] = charts;
if (sales.getAttribute("aria-label") !== "Weekly sales by store") return "the label does not name the chart";
const panels = [...sales.querySelectorAll(".ui-multiples-panel")];
if (panels.length !== 6) return `6 groups made ${panels.length} panels`;
const top0 = panels[0].getBoundingClientRect().top;
if (panels.filter((p) => Math.abs(p.getBoundingClientRect().top - top0) < 1).length !== 3) return "columns={3} does not put three across";
// One shared scale: every panel's axis reads the same.
const axis = (p) => [...p.querySelectorAll(".ui-multiples-grid-line span")].map((s) => s.textContent).join();
if (new Set(panels.map(axis)).size !== 1 || axis(panels[0]) !== "$0,$100k") return `shared axes: ${panels.map(axis)}`;
if (!panels[0].querySelector(".ui-multiples-area")) return "kind=\"area\" has no fill";
const rows = [...sales.querySelectorAll("tbody tr")];
const val = (i, p) => Number(rows[i].querySelectorAll("td")[p].textContent.replace(/[$,]/g, ""));
if (panels[0].querySelector(".ui-multiples-last").textContent !== rows[11].querySelectorAll("td")[0].textContent) return "the panel's figure is not its latest value";
const pts = panels[0].querySelector(".ui-multiples-line").getAttribute("d").slice(1).split(" L").map((p) => p.split(",").map(Number));
if (pts.length !== 12 || pts[0][0] !== 0 || pts[11][0] !== 100) return "the line does not span the panel";
if (Math.abs(pts[3][1] - (100 - val(3, 0) / 1000)) > 0.01) return `week 4 is drawn at ${pts[3][1]}`;
const cols = panels[0].querySelectorAll(".ui-multiples-col");
if (cols.length !== 12) return "not a hover column per label";
const plot = panels[0].querySelector(".ui-multiples-plot").getBoundingClientRect(), c0 = cols[0].getBoundingClientRect(), c11 = cols[11].getBoundingClientRect();
if (Math.abs(c0.left - plot.left) > 0.5 || Math.abs(c11.right - plot.right) > 0.5) return "hover columns are not inside the plot";
const tip = cols[3].querySelector(".ui-multiples-tip");
if (getComputedStyle(tip).display !== "none") return "the tooltip shows before hover";
if (tip.textContent !== `W4${rows[3].querySelectorAll("td")[0].textContent}`) return `tooltip: ${tip.textContent}`;
if ([...panels[0].querySelectorAll(".ui-multiples-x span")].map((s) => s.textContent).join() !== "W1,W12") return "the first and last labels";
if (rows.length !== 12 || sales.querySelectorAll("thead th").length !== 7) return "the screen reader table";
if (!sales.querySelector(".ui-multiples-grid").hasAttribute("aria-hidden")) return "the drawing is not hidden from screen readers";

const sp = [...signups.querySelectorAll(".ui-multiples-panel")];
if (axis(sp[0]) !== "0,4k" || axis(sp[2]) !== "0,400") return `shared={false}: ${sp.map(axis)}`;
const bars = sp[0].querySelectorAll(".ui-multiples-bar");
if (bars.length !== 6) return "kind=\"bar\" does not draw a bar per label";
if (bars[5].style.getPropertyValue("--b").trim() !== "78%" || bars[5].style.getPropertyValue("--a").trim() !== "0%") return `3,120 of 4,000 is ${bars[5].getAttribute("style")}`;
if (Math.abs(bars[5].getBoundingClientRect().height - 70 * 0.78) > 1) return "height={70} with the bar to scale";
if (sp[3].querySelectorAll(".ui-multiples-bar").length !== 5) return "a null value has a bar";
if (getComputedStyle(bars[0]).backgroundColor === getComputedStyle(panels[0].querySelector(".ui-multiples-line")).stroke) return "color={3} is not applied";
