const [wide, narrow] = $$(".ui-shell");
if (!wide || !narrow) return "expected two shells";
const shown = (el) => el && getComputedStyle(el).display !== "none";
const ws = wide.querySelector("aside.ui-shell-side");
if (!shown(ws) || ws.matches(":popover-open")) return "when wide, the sidebar shows in the page";
if (shown(wide.querySelector(".ui-shell-header .ui-shell-btn"))) return "when wide, the menu button shows";
const cur = ws.querySelectorAll('nav a[aria-current="page"]');
if (cur.length !== 1 || !cur[0].textContent.includes("Overview")) return "the current page is not marked aria-current";
if (!ws.querySelector(".ui-shell-icon")) return "nav icons are missing";
if (!wide.querySelector("main.ui-shell-content h2")) return "the children are not in <main>";
if (!wide.querySelector(".ui-shell-bar").textContent.includes("Invite")) return "the header slot is missing";
const side = narrow.querySelector("aside.ui-shell-side");
const open = narrow.querySelector(".ui-shell-header .ui-shell-btn");
if (shown(side)) return "when narrow, the sidebar still shows";
if (!shown(open) || open.getAttribute("popovertarget") !== side.id) return "when narrow, there is no menu button for the sidebar";
open.click(); await wait(350);
if (!side.matches(":popover-open")) return "the menu button does not open the sidebar";
const r = side.getBoundingClientRect();
if (Math.abs(r.left) > 1 || r.width > 291 || r.height < innerHeight - 1) return `the drawer is not at the left edge: ${JSON.stringify(r)}`;
side.querySelector(".ui-shell-btn").click(); await wait();
if (side.matches(":popover-open")) return "the close button does not close the drawer";
