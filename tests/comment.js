const first = $("#comment-demo-first");
if (!first || first.tagName !== "ARTICLE" || first.getAttribute("aria-label") !== "Comment by Ana Silva") return "the comment is not a labelled article";
if (first.querySelector(".ui-comment-avatar").textContent.trim() !== "AS") return "the avatar does not show the initials";
if (first.querySelector("time").getAttribute("datetime") !== "2026-10-28T09:12:00Z" || first.querySelector("time").textContent !== "2 h") return "the time is wrong";
if (!first.querySelector(".ui-comment-text").textContent.includes("\nAsking")) return "line breaks in the text are lost";
const like = first.querySelector("[aria-pressed]");
if (like.getAttribute("aria-label") !== "Like, 12 likes" || like.textContent.trim() !== "12") return `the like button says ${like.textContent}`;
const replies = first.querySelectorAll(":scope > .ui-comment-replies > .ui-comment");
if (replies.length !== 2) return `expected 2 replies in the first comment, found ${replies.length}`;
if (replies[0].querySelector(".ui-comment-role")?.textContent !== "Author") return "the role badge is missing";
if (!replies[0].querySelector(".ui-comment-replies .ui-comment")) return "a reply's reply is not nested";
if (!replies[1].querySelector(".ui-comment-avatar img")) return "an avatar image is not shown";
if ($("#comment-demo-quiet").querySelector(".ui-comment-actions")) return "actions={false} still shows the buttons";
const live = $("#comment-demo-live");
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
const lbtn = live.querySelector("[aria-pressed]");
lbtn.click(); await wait();
if (lbtn.getAttribute("aria-pressed") !== "true" || !note().includes("You liked it") || lbtn.textContent.trim() !== "4") return `on_like(true) did not reach the note: ${note()} / ${lbtn.textContent}`;
lbtn.click(); await wait();
if (lbtn.getAttribute("aria-pressed") !== "false" || !note().includes("Not liked")) return "on_like(false) did not unlike";
const rbtn = [...live.querySelectorAll(".ui-comment-btn")].find((b) => b.textContent.trim() === "Reply");
rbtn.click(); await wait();
if (!note().includes("Reply pressed 1 time")) return `on_reply did not reach the note: ${note()}`;
