const g = $("#property-grid-demo");
const note = () => g.closest(".demo-stack").querySelector(".demo-note").textContent;
const row = (f) => g.querySelector(`[data-field="${f}"]`);
if (g.getAttribute("role") !== "group" || g.getAttribute("aria-label") !== "Button properties") return "the grid is not a named group";
const heads = [...g.querySelectorAll(".ui-propgrid-head")];
if (heads.map((h) => h.getAttribute("aria-expanded")).join() !== "true,true,false") return "open at first";
if (!g.querySelector("#property-grid-demo-g2").hidden) return "a folded group shows";
const width = g.querySelector("#property-grid-demo-width");
if (width.type !== "number" || width.name !== "props.width" || width.value !== "120") return "the number field";
if (g.querySelector("label[for=property-grid-demo-width]").textContent !== "Width") return "the label is not tied to its field";
if (row("width").querySelector(".ui-propgrid-unit").textContent !== "px") return "unit";
if (g.querySelector("#property-grid-demo-padding").getAttribute("aria-describedby") !== "property-grid-demo-padding-hint") return "the hint describes the field";
type(width, "240"); await wait();
if (note() !== "on_change: width = 240. on_values: width is 240.") return `on_change with a number: ${note()}`;
if (!row("width").classList.contains("ui-propgrid-changed")) return "a changed value is not marked";
const reset = row("width").querySelector(".ui-propgrid-reset");
if (!reset || reset.getAttribute("aria-label") !== "Reset Width") return "no reset button";
reset.click(); await wait();
if (width.value !== "120" || row("width").classList.contains("ui-propgrid-changed") || !note().startsWith("on_change: width = 120.")) return `reset: ${width.value}, ${note()}`;
const align = g.querySelector("#property-grid-demo-align");
align.value = "center"; align.dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (!note().startsWith('on_change: align = "center"')) return `select: ${note()}`;
const rounded = g.querySelector("#property-grid-demo-rounded");
if (!rounded.checked || rounded.type !== "checkbox") return "bool";
rounded.click(); await wait();
if (!note().startsWith("on_change: rounded = false") || row("rounded").querySelector(".ui-propgrid-code").textContent !== "false") return `bool: ${note()}`;
if ([...g.querySelectorAll("input[name='props.rounded']")].length !== 2) return "an unchecked bool sends nothing";
const color = g.querySelector("#property-grid-demo-color");
if (color.type !== "color" || color.value !== "#5b4bdb") return "colour";
heads[2].click(); await wait();
if (heads[2].getAttribute("aria-expanded") !== "true" || g.querySelector("#property-grid-demo-g2").hidden) return "opening a group";
if (row("id").querySelector(".ui-propgrid-ro").textContent !== "btn-7" || row("id").querySelector("input[type=hidden]").name !== "props.id") return "readonly";
if (g.querySelector("#property-grid-demo-created").type !== "date") return "date";
heads[0].click(); await wait();
if (!g.querySelector("#property-grid-demo-g0").hidden) return "folding a group";
