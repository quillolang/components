const radios = $$("input[name=payment-demo-live]");
if (radios.length !== 4 || radios.some((r) => r.type !== "radio")) return `expected 4 radios, got ${radios.length}`;
const cards = radios.map((r) => r.closest(".ui-pay-opt"));
const names = cards.map((c) => c.querySelector(".ui-pay-name").textContent);
if (names.join() !== "Credit or debit card,PayPal,Apple Pay,Google Pay") return `names: ${names}`;
if (radios[0].closest("fieldset").querySelector("legend")?.textContent !== "Pay with") return "no legend";
if (!radios[0].checked) return "value does not check card";
if (cards.some((c) => !c.querySelector(".ui-pay-icon svg path"))) return "a built-in mark is not drawn";
const brands = [...cards[0].querySelectorAll(".ui-pay-brand")].map((b) => b.getAttribute("aria-label"));
if (brands.join() !== "Visa,MC,Amex") return `brands: ${brands}`;
if (cards[1].querySelector(".ui-pay-brands")) return "PayPal shows brands";
cards[2].click(); await wait();
if (!radios[2].checked || !$(".demo-note").textContent.includes("with apple")) return `clicking Apple Pay: ${$(".demo-note").textContent}`;
if (getComputedStyle(cards[2]).borderTopColor === getComputedStyle(cards[1]).borderTopColor) return "the chosen card does not look chosen";
const more = $$("input[name=payment-demo-more]");
const mc = more.map((r) => r.closest(".ui-pay-opt"));
if (!more[0].required) return "required is not passed on";
if (mc[1].querySelector(".ui-pay-hint")?.textContent !== "Pay in 30 days, or in 3 parts") return "the built-in hint of later is missing";
if (mc[2].querySelector(".ui-pay-name").textContent !== "Pay by invoice" || mc[2].querySelector(".ui-pay-icon").textContent.trim() !== "🧾" || mc[2].querySelector(".ui-pay-hint").textContent !== "Business accounts only") return "a custom option is wrong";
if (!more[3].disabled || mc[3].querySelector(".ui-pay-name").textContent !== "Cash on delivery") return "a map with a built-in value does not take its words, or disabled is ignored";
