const sends = (el, name) => {
    const form = document.createElement("form");
    el.parentElement.insertBefore(form, el); form.appendChild(el);
    const v = new FormData(form).getAll(name);
    form.parentElement.insertBefore(el, form); form.remove();
    return v.join();
};
