const combo = $("#kbd-demo-combo");
if (!combo || combo.tagName !== "KBD") return "the combination is not a kbd";
const keys = [...combo.querySelectorAll("kbd.ui-kbd-key")];
if (keys.length !== 3) return `Ctrl+Shift+P has ${keys.length} keys`;
const shown = keys.map((k) => k.querySelector("[aria-hidden]")?.textContent ?? k.textContent);
if (shown.join() !== "⌃,⇧,P") return `the keys show ${shown}`;
const read = keys.map((k) => k.querySelector(".ui-sr")?.textContent ?? k.textContent);
if (read.join() !== "Control,Shift,P") return `screen readers get ${read}`;
const pluses = combo.querySelectorAll(".ui-kbd-plus");
if (pluses.length !== 2 || pluses[0].getAttribute("aria-hidden") !== "true") return "the plus signs are missing or read out";
const cmdk = $("#kbd-demo-cmdk");
if ([...cmdk.querySelectorAll("kbd.ui-kbd-key")].map((k) => k.textContent.replace("Command", "")).join() !== "⌘,K") return "a list of keys is not shown";
const plain = $("#kbd-demo-plain");
if (plain.textContent.replace(/\s|\+/g, "") !== "CtrlC") return `symbols={false} shows ${plain.textContent}`;
const one = $("#kbd-demo-one");
if (one.tagName !== "KBD" || one.textContent.trim() !== "Esc" || one.querySelector("kbd")) return "a single key is not one plain kbd";
const r = keys[0].getBoundingClientRect(), r2 = keys[2].getBoundingClientRect();
if (Math.abs(r.top - r2.top) > 1 || r2.left <= r.right) return "the keys are not in one row";
if (getComputedStyle(keys[0]).borderBottomWidth === "0px") return "a key has no border";
const sizes = $$(".demo-row")[2].querySelectorAll(".ui-kbd");
const h = (el) => el.querySelector(".ui-kbd-key").getBoundingClientRect().height;
if (!(h(sizes[0]) < h(sizes[1]) && h(sizes[1]) < h(sizes[2]))) return "the sizes do not grow";
if (!$(".demo-note").querySelector("kbd")) return "a Kbd does not sit inside a paragraph";
