const log = $("#btt-demo-log");
const wrap = log.querySelector(".ui-btt"), btn = wrap.querySelector("button");
const visible = (b) => getComputedStyle(b).visibility === "visible";
if (btn.getAttribute("aria-label") !== "Back to the newest") return "the button has no name";
if (visible(btn)) return "the button shows before scrolling";
log.scrollTop = 600; log.dispatchEvent(new Event("scroll")); await wait(400);
if (!visible(btn) || !wrap.classList.contains("ui-btt-shown")) return "scrolling down did not show the button";
const lr = log.getBoundingClientRect(), br = btn.getBoundingClientRect();
if (br.bottom > lr.bottom || br.bottom < lr.bottom - 40 || br.right > lr.right || br.right < lr.right - 40) return `the button is not in the box's bottom right corner: ${JSON.stringify(br)} in ${JSON.stringify(lr)}`;
btn.click();
for (let i = 0; i < 30 && log.scrollTop > 0; i++) await wait(100);
if (log.scrollTop !== 0) return `clicking did not scroll to the top: ${log.scrollTop}`;
await wait(300);
if (visible(btn)) return "at the top again, the button still shows";
if (document.activeElement !== log) return "the focus did not move to the target";
// The window's own.
const page = [...$$(".ui-btt")].find((w) => !w.classList.contains("ui-btt-inline"));
const pb = page.querySelector("button");
if (getComputedStyle(page).position !== "fixed" || !pb.textContent.includes("Back to top") || pb.hasAttribute("aria-label")) return "the page's button is not fixed with its label shown";
const was = scrollY;
scrollTo(0, 0); await wait(300);
if (visible(pb)) return "at the top of the page, the page's button shows";
scrollTo(0, 2400); await wait(400);
if (!visible(pb)) return "far down the page, the page's button does not show";
const r = pb.getBoundingClientRect();
if (innerWidth - r.right > 30 || innerHeight - r.bottom > 30) return "the page's button is not in the window's corner";
pb.click();
for (let i = 0; i < 40 && scrollY > 0; i++) await wait(100);
if (scrollY !== 0) return `clicking did not scroll the page to the top: ${scrollY}`;
scrollTo(0, was);
