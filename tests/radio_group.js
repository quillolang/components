const sizes = $$("input[name=size]");
if (sizes.length !== 4 || sizes.some((r) => r.type !== "radio")) return "the size group is not 4 radios";
if (sizes.find((r) => r.checked)?.value !== "m") return "value did not check Medium";
if (!sizes[3].disabled) return "a disabled option is not disabled";
if (sizes.some((r) => r.labels.length !== 1)) return "every radio needs its own label";
const fs = sizes[0].closest("fieldset");
if (!fs.querySelector("legend")?.textContent.includes("Size")) return "the group has no legend";
if (!document.getElementById(fs.getAttribute("aria-describedby"))?.textContent.includes("small")) return "the hint is not tied to the group";
const ship = $$("input[name=ship]");
if (!ship[0].required) return "required is not on the radios";
const sfs = ship[0].closest("fieldset");
if (sfs.getAttribute("aria-invalid") !== "true") return "an error does not set aria-invalid on the group";
if (!document.getElementById(sfs.getAttribute("aria-describedby"))?.textContent.includes("Choose")) return "the error is not tied to the group";
if (ship[1].value !== "Express, next day") return "a string option is not its own value";
const plans = $$("input[name=plan]");
const card = plans[2].closest("label");
if (getComputedStyle(card).borderTopStyle !== "solid") return "cards are not bordered";
card.click(); await wait();
if (!plans[2].checked || !$(".demo-note").textContent.includes("team")) return `on_change did not update: ${$(".demo-note").textContent}`;
if (getComputedStyle(card).borderTopColor === getComputedStyle(plans[0].closest("label")).borderTopColor) return "the chosen card does not stand out";
