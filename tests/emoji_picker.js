const all = $("#emoji-picker-demo-all");
const grid = $("#emoji-picker-demo-all-grid");
const opts = () => [...grid.querySelectorAll("input[type=radio]")];
const tabs = () => [...all.querySelectorAll("[role=tab]")];
const hidden = all.querySelector("input[type=hidden][name=emoji]");
if (tabs().length !== 8 || all.querySelector("[role=tablist]")?.getAttribute("aria-label") !== "Categories") return "the eight category tabs are missing";
if (tabs()[0].getAttribute("aria-selected") !== "true" || tabs()[0].getAttribute("aria-label") !== "Smileys") return "the first tab is not Smileys, selected";
if (grid.getAttribute("role") !== "radiogroup" || document.getElementById(grid.getAttribute("aria-labelledby"))?.textContent !== "Smileys") return "the grid is not a radiogroup named by its category";
if (opts().length !== 20 || opts()[0].value !== "😀" || opts()[0].getAttribute("aria-label") !== "grinning face") return `the smileys: ${opts().length} ${opts()[0]?.value}`;
if (hidden.value !== "") return "nothing should be picked at first";
tabs()[2].click(); await wait();
if (tabs()[2].getAttribute("aria-selected") !== "true" || opts()[0].value !== "🐶") return "clicking a tab does not show its emoji";
tabs()[2].focus(); key(tabs()[2], "ArrowRight"); await wait(80);
if (tabs()[3].getAttribute("aria-selected") !== "true" || document.activeElement !== tabs()[3] || opts()[0].value !== "🍎") return "ArrowRight does not move to the next tab";
key(tabs()[3], "End"); await wait(80);
if (tabs()[7].getAttribute("aria-selected") !== "true" || tabs()[7].tabIndex !== 0 || tabs()[0].tabIndex !== -1) return "End does not go to the last tab with a roving tabindex";
const search = $("#emoji-picker-demo-all-search");
type(search, "party"); await wait();
if (opts().map((r) => r.value).join() !== "🥳,🎉") return `"party" found: ${opts().map((r) => r.value)}`;
if (all.querySelector("[role=tablist]")) return "the tabs should hide while searching";
if (!grid.previousElementSibling.textContent.includes("party")) return "the heading does not say what was searched";
opts()[1].click(); await wait();
if (hidden.value !== "🎉" || !all.querySelector(".ui-emoji-picker-status").textContent.includes("party popper")) return `picking did not set the value: ${hidden.value}`;
type(search, "qqqq"); await wait();
if (opts().length !== 0 || !grid.textContent.includes("No emoji match")) return "no matches does not say so";
type(search, ""); await wait();
if (!all.querySelector("[role=tablist]")) return "clearing the search does not bring the tabs back";
const live = $("#emoji-picker-demo-live");
const ltabs = [...live.querySelectorAll("[role=tab]")];
if (ltabs[4].getAttribute("aria-selected") !== "true") return "a starting value does not open its category (Travel)";
const lopts = [...$("#emoji-picker-demo-live-grid").querySelectorAll("input")];
if (lopts.find((r) => r.checked)?.value !== "🌴") return "the starting value is not checked";
lopts.find((r) => r.value === "🚀").click(); await wait();
if (!$(".demo-note").textContent.includes("🚀")) return `on_change: ${$(".demo-note").textContent}`;
