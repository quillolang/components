const art = $("#pullquote-demo-article");
const right = $("#pullquote-demo-right"), left = $("#pullquote-demo-left"), full = $("#pullquote-demo-full");
if (!right || right.tagName !== "ASIDE" || !left || !full) return "the pull quotes are not asides";
const cs = (el, p) => getComputedStyle(el, p);
if (cs(right).float !== "right" || cs(left).float !== "left" || cs(full).float !== "none") return "the sides do not float as they should";
const aw = art.getBoundingClientRect().width;
if (right.getBoundingClientRect().width > aw * 0.5 || left.getBoundingClientRect().width > aw * 0.5) return "a side quote takes more than half the column";
if (right.getBoundingClientRect().right < art.getBoundingClientRect().right - 2) return "the right quote is not at the right edge";
if (left.getBoundingClientRect().left > art.getBoundingClientRect().left + 2) return "the left quote is not at the left edge";
if (full.getBoundingClientRect().width < aw - 2) return "a full quote does not span the column";
const para = right.nextElementSibling.getBoundingClientRect();
if (!(para.top < right.getBoundingClientRect().bottom && para.left < right.getBoundingClientRect().left)) return "the text does not flow beside the right quote";
if (!(parseFloat(cs(right).fontSize) > parseFloat(cs(art.querySelector(":scope > p")).fontSize))) return "the quote is not larger than the text";
const t = right.querySelector(".ui-pullquote-text");
if (!cs(t, "::before").content.includes("“") || !cs(t, "::after").content.includes("”")) return "the quote marks are missing";
if (right.getAttribute("aria-hidden") !== "true") return "repeated={true} does not hide it from screen readers";
if (left.hasAttribute("aria-hidden")) return "a quote that is not repeated is hidden";
if (left.querySelector(".ui-pullquote-by")?.textContent !== "Ada Lovelace") return "the author is missing";
if (right.querySelector(".ui-pullquote-by")) return "a quote without an author has a byline";
if (cs(full).borderTopWidth === "0px" || cs(full).textAlign !== "center") return "the full quote is not ruled and centred";
