const [main, small] = $$(".ui-image-compare");
if (!main || !small) return "expected two comparisons";
const range = main.querySelector("input[type=range]");
if (!range || range.getAttribute("aria-label") !== "Divider between before and after") return "the divider is not a labelled range";
if (range.value !== "50" || range.getAttribute("aria-valuetext") !== "50% Day, 50% Night") return `it starts at ${range.value}: "${range.getAttribute("aria-valuetext")}"`;
const before = main.querySelector(".ui-image-compare-before"), after = main.querySelector(".ui-image-compare-after");
if (before.alt !== "A cottage on a hill (Day)" || after.alt !== "A cottage on a hill (Night)") return `the alts are "${before.alt}" / "${after.alt}"`;
const tags = [...main.querySelectorAll(".ui-image-compare-tag")].map((t) => t.textContent);
if (tags.join() !== "Day,Night") return `the tags are ${tags}`;
const box = main.getBoundingClientRect();
const lineX = () => main.querySelector(".ui-image-compare-line").getBoundingClientRect().left + 1 - box.left;
if (Math.abs(lineX() / box.width - 0.5) > 0.01) return "the line is not in the middle";
const rr = range.getBoundingClientRect();
if (Math.abs(rr.width - box.width) > 2 || Math.abs(rr.height - box.height) > 2) return "the range does not cover the pictures, so a drag would miss it";
type(range, "20"); await wait();
if (Math.abs(lineX() / box.width - 0.2) > 0.01) return `moved to 20, the line is at ${lineX() / box.width}`;
if (!getComputedStyle(before).clipPath.includes("80%")) return `the before picture is clipped as ${getComputedStyle(before).clipPath}`;
if ($("#image-compare-demo-note").textContent !== "The divider is at 20%.") return `on_change: ${$("#image-compare-demo-note").textContent}`;
if (range.getAttribute("aria-valuetext") !== "20% Day, 80% Night") return "the value text does not follow";
const sr = small.querySelector("input");
if (sr.value !== "25" || small.querySelector(".ui-image-compare-tag")) return "at=25 or hidden labels are not applied";
const s = small.getBoundingClientRect();
if (Math.abs(s.width / s.height - 4 / 3) > 0.03) return "ratio 4/3 is not applied";
if (!sr.getAttribute("aria-valuetext").includes("25% before")) return "without labels the value text has no words";
