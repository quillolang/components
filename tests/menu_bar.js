const bar = $(".ui-menu-bar"), tops = [...bar.querySelectorAll(".ui-menu-bar-top")], note = () => $(".demo-note").textContent;
const menu = (i) => document.getElementById(`menubar-demo-menu-${i}`), shown = (i) => menu(i).matches(":popover-open");
const items = (i) => [...menu(i).querySelectorAll("[role=menuitem], [role=menuitemcheckbox]")];
if (bar.getAttribute("role") !== "menubar" || tops.length !== 4 || tops.map((t) => t.textContent).join() !== "File,Edit,View,Help") return "not a menubar of File, Edit, View, Help";
if (tops[0].getAttribute("aria-haspopup") !== "menu" || tops[0].getAttribute("aria-expanded") !== "false" || shown(0)) return "File is not a closed menu button";
if (tops.map((t) => t.tabIndex).join() !== "0,-1,-1,-1") return "only the first top button takes the Tab";
tops[0].click(); await wait();
if (!shown(0) || tops[0].getAttribute("aria-expanded") !== "true") return "clicking File does not open it";
if (menu(0).getAttribute("role") !== "menu" || menu(0).getAttribute("aria-labelledby") !== tops[0].id) return "the menu is not named by its button";
const file = items(0);
if (file.length !== 5 || file[1].querySelector(".ui-menu-bar-key")?.textContent !== "Ctrl O" || file[1].getAttribute("aria-keyshortcuts") !== "Ctrl+O") return "items or shortcuts are wrong";
if (file[3].tagName !== "A" || file[3].getAttribute("href") !== "#menu_bar") return "an item with an href is not a link";
if (!file[4].classList.contains("ui-menu-bar-danger") || menu(0).querySelectorAll("[role=separator]").length !== 2) return "tone or dividers are missing";
tops[1].dispatchEvent(new PointerEvent("pointerenter")); await wait();
if (shown(0) || !shown(1) || tops[1].getAttribute("aria-expanded") !== "true") return "resting the pointer on Edit while File is open does not switch";
if (items(1)[0].getAttribute("aria-disabled") !== "true") return "Undo is not disabled";
key(tops[1], "ArrowRight"); await wait();
if (shown(1) || !shown(2)) return "ArrowRight on an open menu's button does not open the next";
key(tops[2], "Escape"); await wait();
if (shown(2) || document.activeElement !== tops[2]) return "Escape does not close and keep the focus on View";
key(tops[2], "ArrowDown"); await wait();
const view = items(2);
if (!shown(2) || document.activeElement !== view[0]) return "ArrowDown does not open View on its first item";
if (view[0].getAttribute("role") !== "menuitemcheckbox" || view[0].getAttribute("aria-checked") !== "true" || !view[0].querySelector(".ui-menu-bar-tick")) return "Sidebar is not a ticked checkbox item";
if (view[1].getAttribute("aria-checked") !== "false" || view[1].querySelector(".ui-menu-bar-tick")) return "Status bar is not an unticked checkbox item";
key(view[0], "ArrowDown"); await wait(50);
if (document.activeElement !== view[1]) return "ArrowDown does not move to the next item";
key(view[1], "End"); await wait(50);
if (document.activeElement !== view[2]) return "End does not move to the last";
key(view[2], "ArrowDown"); await wait(50);
if (document.activeElement !== view[0]) return "ArrowDown from the last does not wrap";
key(view[0], "ArrowLeft"); await wait();
if (shown(2) || !shown(1) || document.activeElement !== items(1)[2]) return "ArrowLeft in a menu does not open the previous on its first enabled item";
items(1)[0].click(); await wait();
if (!shown(1) || note() !== "Did: nothing yet") return "a disabled item did something";
items(1)[2].click(); await wait();
if (shown(1) || note() !== "Did: Cut" || document.activeElement !== tops[1]) return `choosing Cut: ${note()}, focus back: ${document.activeElement === tops[1]}`;
tops[2].click(); await wait();
items(2)[0].click(); await wait();
if (note() !== "Did: Sidebar") return "on_select is not called for a checkbox item";
tops[2].click(); await wait();
if (items(2)[0].getAttribute("aria-checked") !== "false") return "the tick does not follow the state";
menu(2).hidePopover(); await wait();
if (tops[2].getAttribute("aria-expanded") !== "false") return "closing the popover does not update the button";
key(tops[2], "ArrowLeft"); await wait(50);
if (document.activeElement !== tops[1] || tops[1].tabIndex !== 0) return "ArrowLeft on a closed bar does not move the focus";
