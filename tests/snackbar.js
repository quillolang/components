const host = $(".ui-snackbar-host");
if (!host || host.getAttribute("role") !== "status" || host.getAttribute("aria-label") !== "Notifications") return "the host is not a named status region";
if (host.querySelector(".ui-snackbar")) return "a snackbar shows before anything was shown";
const note = () => $(".demo-note").textContent;
$("#snackbar-demo-archive").click(); await wait();
let bar = host.querySelector(".ui-snackbar");
if (!bar || bar.querySelector(".ui-snackbar-text")?.textContent !== "Message archived") return `snackbar_show did not show the message: ${bar?.textContent}`;
if (getComputedStyle(host).position !== "fixed") return "the host is not fixed to the window";
const action = bar.querySelector(".ui-snackbar-action");
if (!action || action.textContent !== "Undo") return "no Undo action";
action.click(); await wait();
if (!note().startsWith("Archived 1, restored 1")) return `on_action did not reach the note: ${note()}`;
if (host.querySelector(".ui-snackbar")) return "the action did not close it";
// Two at once: the second waits its turn.
$("#snackbar-demo-saved").click(); $("#snackbar-demo-failed").click(); await wait();
const bars = host.querySelectorAll(".ui-snackbar");
if (bars.length !== 1) return `${bars.length} snackbars show at once`;
if (!bars[0].classList.contains("ui-snackbar-success") || bars[0].textContent.trim() !== "Draft saved×") return `the first in line is not "Draft saved": ${bars[0].textContent}`;
await wait(2300);
bar = host.querySelector(".ui-snackbar");
if (!bar || !bar.classList.contains("ui-snackbar-danger") || !bar.textContent.includes("Could not send")) return `after 2 s the next did not show: ${bar?.textContent}`;
await wait(1500);
if (!host.querySelector(".ui-snackbar-danger")) return "seconds: 0 did not keep it";
const x = bar.querySelector(".ui-snackbar-x");
if (!x || x.getAttribute("aria-label") !== "Dismiss") return "no close button";
x.click(); await wait();
if (host.querySelector(".ui-snackbar")) return "Dismiss did not close it";
$("#snackbar-demo-archive").click(); await wait();
bar = host.querySelector(".ui-snackbar");
bar.querySelector(".ui-snackbar-action").focus(); key(bar.querySelector(".ui-snackbar-action"), "Escape"); await wait();
if (host.querySelector(".ui-snackbar")) return "Escape did not close it";
if (!note().startsWith("Archived 2, restored 1")) return `Escape ran the action: ${note()}`;
