const box = $("#newsletter-form-demo-plain");
if (!box || box.type !== "email" || box.name !== "email" || !box.required) return "the box is not a required email input named email";
const form = box.closest("form");
if (!form || form.method !== "post" || !form.getAttribute("action").endsWith("/subscribe")) return "the row is not a form posting to the action";
if (form.querySelector("input[name=list]")?.value !== "product") return "list is not sent as a hidden field";
if (form.querySelector("button[type=submit]")?.textContent.trim() !== "Subscribe") return "the submit button is not labelled Subscribe";
if (box.getAttribute("aria-label") !== "Email address" || box.getAttribute("autocomplete") !== "email") return "the box has no name or autofill";
const bad = $("#newsletter-form-demo-error");
if (bad.value !== "ada@example" || bad.getAttribute("aria-invalid") !== "true") return "value and error do not reach the box";
if (!$("#newsletter-form-demo-error-error[role=alert]")?.textContent.includes("email address")) return "the error is not shown";
if (!bad.closest(".ui-newsletter-form").classList.contains("ui-newsletter-form-sm")) return "small={true} is not applied";
const live = $("#newsletter-form-demo-live");
if (!live.closest(".ui-newsletter-form").querySelector(".ui-newsletter-form-title")?.textContent.includes("Stay in the loop")) return "the title is missing";
type(live, "ada@example.com");
