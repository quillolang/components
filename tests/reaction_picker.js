const [grp, one] = $$(".ui-reaction-picker"), note = () => $(".demo-note").textContent;
const chips = (g) => [...g.querySelectorAll(".ui-reaction-picker-chip:not(.ui-reaction-picker-add)")];
const count = (c) => c.lastElementChild.textContent, pressed = (c) => c.getAttribute("aria-pressed") === "true";
const sent = () => [...grp.querySelectorAll("input[type=hidden][name=reaction]")].map((i) => i.value);
if (grp.getAttribute("role") !== "group" || chips(grp).length !== 3) return "not a group of 3 chips";
const [up, heart] = chips(grp);
if (!pressed(up) || count(up) !== "12" || up.getAttribute("aria-label") !== "Thumbs up, 12") return `the first chip: ${up.outerHTML}`;
if (sent().join() !== "👍,🎉") return `mine are sent as ${sent()}`;
heart.click(); await wait();
if (!pressed(heart) || count(heart) !== "5" || note() !== "Added ❤️") return `reacting with the heart: ${count(heart)}, ${note()}`;
if (sent().join() !== "👍,❤️,🎉") return `after the heart, sent: ${sent()}`;
up.click(); await wait();
if (pressed(up) || count(up) !== "11" || note() !== "Removed 👍" || sent().join() !== "❤️,🎉") return "taking the thumbs up back";
chips(grp)[2].click(); await wait();
if (chips(grp).length !== 2) return "a reaction whose count fell to 0 stays in the row";
const add = grp.querySelector(".ui-reaction-picker-add"), menu = document.getElementById("react-demo-menu");
if (!add || add.getAttribute("popovertarget") !== "react-demo-menu" || !menu) return "no add button opening its menu";
add.click(); await wait();
if (!menu.matches(":popover-open")) return "the add button does not open the menu";
const choices = [...menu.querySelectorAll(".ui-reaction-picker-choice")].map((b) => b.textContent);
if (choices.join() !== "🎉,😄,🤔,🚀") return `the menu offers ${choices} (those in the row should be left out)`;
menu.querySelector(".ui-reaction-picker-choice[aria-label=Rocket]").click(); await wait();
if (menu.matches(":popover-open")) return "picking does not close the menu";
const rocket = chips(grp).at(-1);
if (rocket.title !== "Rocket" || count(rocket) !== "1" || !pressed(rocket) || note() !== "Added 🚀") return "a new reaction is not added as mine with 1";
const [agree, disagree] = chips(one);
if (!one.classList.contains("ui-reaction-picker-sm") || !pressed(agree) || count(agree) !== "8") return "the single picker does not start right";
disagree.click(); await wait();
if (pressed(agree) || count(agree) !== "7" || !pressed(disagree) || count(disagree) !== "3") return "single does not move the reaction";
