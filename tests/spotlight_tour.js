const dlg = $("dialog.ui-spotlight-tour"), trig = $$("button.ui-btn").find((b) => b.textContent === "Take the tour"), note = () => $(".demo-note").textContent;
const title = () => document.getElementById("tour-demo-title").textContent, hole = () => dlg.querySelector(".ui-spotlight-tour-hole"), card = () => dlg.querySelector(".ui-spotlight-tour-card");
const next = () => dlg.querySelector(".ui-spotlight-tour-next"), backBtn = () => [...dlg.querySelectorAll(".ui-spotlight-tour-btn")].find((b) => !b.classList.contains("ui-spotlight-tour-next"));
if (!dlg || dlg.open || dlg.getAttribute("aria-labelledby") !== "tour-demo-title" || dlg.getAttribute("aria-describedby") !== "tour-demo-text") return "the tour is not a named, described, closed dialog";
trig.click(); await wait(400);
if (!dlg.open || title() !== "Search") return `the trigger does not start at the first step: ${title()}`;
const t = document.getElementById("tour-demo-search").getBoundingClientRect(), h = hole().getBoundingClientRect();
if (Math.abs(h.left - (t.left - 6)) > 2 || Math.abs(h.top - (t.top - 6)) > 2 || Math.abs(h.width - (t.width + 12)) > 2) return `the hole is not over the search box: ${JSON.stringify(h)} vs ${JSON.stringify(t)}`;
if (!getComputedStyle(hole()).boxShadow.includes("200vmax") && !/\d{3,}px/.test(getComputedStyle(hole()).boxShadow)) return "the page is not dimmed around the hole";
const c = card().getBoundingClientRect();
if (c.top < t.bottom || c.top > t.bottom + 30) return "the card is not under the element";
if (!card().textContent.includes("1 of 3") || !backBtn().disabled || next().textContent !== "Next") return "the first step does not say 1 of 3 with Back disabled";
if (document.activeElement !== next()) return "the focus is not on Next";
next().click(); await wait(400);
const nb = document.getElementById("tour-demo-new").getBoundingClientRect(), h2 = hole().getBoundingClientRect();
if (title() !== "New order" || Math.abs(h2.left - (nb.left - 6)) > 2) return "Next does not light the second element";
key(dlg, "ArrowLeft"); await wait(300);
if (title() !== "Search") return "ArrowLeft does not go back";
key(dlg, "ArrowRight"); key(dlg, "ArrowRight"); await wait(400);
if (title() !== "That's it" || !hole().classList.contains("ui-spotlight-tour-hole-none") || !card().classList.contains("ui-spotlight-tour-card-mid")) return "a step without its element does not show the card in the middle";
if (next().textContent !== "Done" || !card().textContent.includes("3 of 3")) return "the last step does not say Done";
next().click(); await wait();
if (dlg.open || note() !== "Finished.") return `Done does not finish: ${note()}`;
trig.click(); await wait(300);
next().click(); await wait(300);
dlg.querySelector(".ui-spotlight-tour-x").click(); await wait();
if (dlg.open || note() !== "Ended at step 2.") return `ending the tour does not say where: ${note()}`;
trig.click(); await wait(300);
if (title() !== "Search") return "starting again does not go back to the first step";
dlg.close(); await wait();
