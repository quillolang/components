const nav = $("#side-nav-demo");
if (!nav || nav.tagName !== "NAV" || nav.getAttribute("aria-label") !== "Main") return "the navigation is not a labelled <nav>";
const cur = nav.querySelectorAll('[aria-current="page"]');
if (cur.length !== 1 || !cur[0].textContent.includes("Inbox")) return "the current page is not marked";
if (cur[0].querySelector(".ui-sidenav-badge")?.textContent !== "12") return "the badge does not show";
if (!nav.querySelector(".ui-sidenav-icon svg path")) return "an SVG path icon is not drawn";
const groups = [...nav.querySelectorAll("details")];
if (groups.length !== 3) return `expected 3 groups, found ${groups.length}`;
if (groups.some((g) => g.open)) return "a group without the current page starts open";
const projects = groups[0];
projects.querySelector("summary").click(); await wait();
if (!projects.open) return "clicking a group does not open it";
const mobile = groups[1];
if (mobile.parentElement.closest("details") !== projects) return "Mobile app is not nested in Projects";
mobile.querySelector("summary").click(); await wait();
const ios = [...mobile.querySelectorAll("a")].find((a) => a.textContent.includes("iOS"));
if (!ios || ios.getBoundingClientRect().height === 0) return "the nested group's links do not show";
const title = nav.querySelector(".ui-sidenav-title");
if (title?.textContent !== "Workspace" || nav.querySelector(`ul[aria-labelledby="${title.id}"]`) === null) return "the section has no title naming its list";
const fold = nav.querySelector(".ui-sidenav-fold");
const wide = nav.getBoundingClientRect().width;
if (wide < 200) return `the sidebar is ${wide}px wide`;
fold.click(); await wait(400);
if (!nav.classList.contains("ui-sidenav-folded") || nav.getBoundingClientRect().width > 64) return `folding did not narrow it: ${nav.getBoundingClientRect().width}`;
const text = cur[0].querySelector(".ui-sidenav-text");
if (text.getBoundingClientRect().width > 1 || text.textContent !== "Inbox") return "folded, the label still shows, or is gone for screen readers";
if (cur[0].getAttribute("title") !== "Inbox") return "folded, the link has no tooltip";
if (ios.getBoundingClientRect().height !== 0) return "folded, nested links still show";
if (!$$(".demo-note")[0].textContent.includes("icons only")) return "on_toggle was not called";
if (!fold.textContent.includes("Expand sidebar")) return "the fold button does not say it expands";
projects.querySelector("summary").click(); await wait(400);
if (nav.classList.contains("ui-sidenav-folded") || !projects.open) return "a group's icon does not unfold the sidebar and open it";
const slim = $("#side-nav-demo-slim");
if (!slim.classList.contains("ui-sidenav-folded")) return "collapsed does not start folded";
const sg = [...slim.querySelectorAll("details")];
if (!sg[0].open || !sg[1].open || sg[2].open) return "the groups holding the current page are not open";
if (!sg[0].classList.contains("ui-sidenav-holds")) return "the group holding the current page is not marked";
const help = [...slim.querySelectorAll("a")].find((a) => a.textContent.includes("Help"));
if (help.querySelector(".ui-sidenav-initial")?.textContent !== "H" || getComputedStyle(help.querySelector(".ui-sidenav-initial")).display === "none") return "folded, a link without an icon does not show its initial";
fold.click(); await wait(300); fold.click(); await wait(300);
