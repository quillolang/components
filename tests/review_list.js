const list = $("#rl-all");
const titles = () => [...list.querySelectorAll(".ui-review-card-name")].map((n) => n.textContent);
const count = () => list.querySelector(".ui-review-list-count").textContent.trim();
if (list.getAttribute("aria-label") !== "Reviews") return "the list is not named";
if (titles().join() !== "Ola N.,Marta R.,Jun K.,Sam T.") return `newest first, four shown: ${titles()}`;
if (count() !== "7 reviews") return `count: ${count()}`;
const more = list.querySelector(".ui-review-list-more");
if (!more || more.textContent.trim() !== "Show 3 more") return `more: ${more?.textContent}`;
const stars = [...list.querySelectorAll(".ui-review-list-star")];
if (stars[0].getAttribute("aria-pressed") !== "true" || stars[0].textContent.replace(/\s+/g, "") !== "All7") return "All is not pressed with its count";
if (stars[1].getAttribute("aria-label") !== "5 stars, 2" || stars[3].getAttribute("aria-label") !== "3 stars, 1") return "the star counts";
if (stars.some((b) => b.disabled)) return "a star with reviews is disabled";
stars[1].click(); await wait();
if (titles().join() !== "Ola N.,Sam T." || count() !== "2 of 7 reviews with 5 stars" || stars[1].getAttribute("aria-pressed") !== "true" || stars[0].getAttribute("aria-pressed") !== "false") return `5 stars filter: ${titles()} / ${count()}`;
if (list.querySelector(".ui-review-list-more")) return "Show more shows when everything fits";
stars[1].click(); await wait();
if (titles().length !== 4 || stars[0].getAttribute("aria-pressed") !== "true") return "clicking the star again does not clear the filter";
const sel = list.querySelector("select[name=sort]");
sel.value = "helpful"; sel.dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (titles().join() !== "Ivo P.,Marta R.,Jun K.,Lea B.") return `most helpful: ${titles()}`;
sel.value = "lowest"; sel.dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (titles()[0] !== "Ivo P." || titles()[1] !== "Jun K.") return `lowest: ${titles()}`;
sel.value = "oldest"; sel.dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (titles()[0] !== "Ivo P." || titles()[3] !== "Sam T.") return `oldest: ${titles()}`;
list.querySelector(".ui-review-list-more").click(); await wait();
if (titles().length !== 7 || list.querySelector(".ui-review-list-more")) return "Show more does not show the rest";
if (getComputedStyle([...list.querySelectorAll(".ui-review-card")].at(-1)).borderBottomStyle !== "none") return "the last review keeps its line";
const vote = list.querySelector(".ui-review-card-vote");
if (vote.type !== "submit" || vote.name !== "helpful") return "in a form the Helpful buttons submit";
const live = $("#rl-live");
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
const btn = live.querySelector("#review-rl-live-a1 .ui-review-card-vote");
btn.click(); await wait();
if (note() !== "Voted: a1." || btn.getAttribute("aria-pressed") !== "true") return `on_helpful: ${note()}`;
btn.click(); await wait();
if (note() !== "Voted: none." || btn.getAttribute("aria-pressed") !== "false") return `voting again: ${note()}`;
