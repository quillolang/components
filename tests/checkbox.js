const rem = $("input[name=remember]");
if (!rem || rem.type !== "checkbox" || !rem.checked) return "remember is not a checked checkbox";
if (rem.labels.length !== 1 || !rem.labels[0].textContent.includes("Remember me")) return "the label is not tied to the input";
const hint = document.getElementById(rem.getAttribute("aria-describedby"));
if (!hint || !hint.textContent.includes("30 days")) return "the hint is not tied to the checkbox";
const box = (i) => getComputedStyle(i.nextElementSibling);
const mixed = $("input[name=mixed]");
if (box(mixed).backgroundColor === box($("input[name=off]")).backgroundColor) return "the indeterminate box is not filled";
const terms = $("input[name=terms]");
if (!terms.required || terms.getAttribute("aria-invalid") !== "true") return "the terms checkbox is not required and aria-invalid";
const before = rem.checked;
rem.labels[0].click(); await wait(50);
if (rem.checked === before) return "clicking the label does not toggle it";
const days = $$("input[name=days]");
if (days.length !== 5 || days.filter((d) => d.checked).map((d) => d.value).join() !== "Mon,Wed") return "the group's values are not the checked ones";
if (!$("fieldset legend") || !$$("fieldset legend").some((l) => l.textContent === "Days")) return "the group has no legend";
if (new Set(days.map((d) => d.id)).size !== 5) return "the group's checkboxes do not have distinct ids";
const topics = $$("input[name=topics]");
const all = $$("input[type=checkbox]").find((i) => i.labels[0]?.textContent.includes("All topics"));
if (!all.indeterminate) return "indeterminate is not set on the input inside a component";
topics[1].click(); await wait(); topics[2].click(); await wait();
if (!$(".demo-note").textContent.includes("3 of 3")) return `on_change(value, checked) did not update the list: ${$(".demo-note").textContent}`;
if (!all.checked) return "select all did not follow the group";
all.click(); await wait();
if (!$(".demo-note").textContent.includes("0 of 3") || topics.some((t) => t.checked)) return "unchecking all did not clear the group";
