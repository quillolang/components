const live = $$(".ui-volume-control")[0];
const btn = live.querySelector(".ui-volume-control-btn"), range = live.querySelector("input[type=range]");
const note = () => $("#volume-control-demo-note").textContent;
if (!range || range.getAttribute("aria-label") !== "Volume" || range.value !== "0.6" || range.getAttribute("aria-valuetext") !== "60%") return `the slider starts at ${range?.value} "${range?.getAttribute("aria-valuetext")}"`;
if (btn.getAttribute("aria-label") !== "Mute" || btn.getAttribute("aria-pressed") !== "false") return "the mute button is not named";
type(range, "0.25"); await wait();
if (note() !== "Level: 25%") return `on_change: ${note()}`;
if (range.style.getPropertyValue("--f").trim() !== "25%") return "the fill does not follow";
btn.click(); await wait();
if (btn.getAttribute("aria-label") !== "Unmute" || btn.getAttribute("aria-pressed") !== "true" || range.value !== "0" || note() !== "Level: 0%") return `mute: ${btn.getAttribute("aria-label")} ${range.value} ${note()}`;
btn.click(); await wait();
if (range.value !== "0.25" || note() !== "Level: 25%") return `unmute did not bring the level back: ${range.value} ${note()}`;
btn.click(); type(range, "0.9"); await wait();
if (btn.getAttribute("aria-pressed") !== "false" || note() !== "Level: 90%") return "moving the slider does not unmute";
const [named, quiet, vertical] = $$("#volume-control-demo-others .ui-volume-control");
if (named.querySelector("input").name !== "alerts" || named.querySelector("input").getAttribute("aria-label") !== "Alert volume") return "name / label are not applied";
if (!named.classList.contains("ui-volume-control-sm")) return "size sm is not applied";
if (quiet.querySelector(".ui-volume-control-btn").getAttribute("aria-pressed") !== "true" || quiet.querySelector("input").value !== "0") return "muted does not start muted";
quiet.querySelector(".ui-volume-control-btn").click(); await wait();
if (quiet.querySelector("input").value !== "0.3") return "unmuting does not restore the level given";
if (vertical.querySelector("input").getAttribute("aria-orientation") !== "vertical") return "vertical is not said";
const vr = vertical.querySelector("input").getBoundingClientRect();
if (vr.height <= vr.width) return "the vertical slider is not taller than wide";
