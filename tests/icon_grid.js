const box = $("#icon-grid-demo");
const tiles = () => $$(".ui-icon-grid-tile");
const count = () => $(".ui-icon-grid-count").textContent.trim();
if (!box || box.type !== "search" || box.labels.length !== 1) return "the search box is not a labelled search input";
const total = tiles().length;
if (total < 40) return `only ${total} tiles`;
if (count() !== `${total} of ${total}`) return `the count says ${count()}`;
if (!tiles()[0].querySelector("svg.ui-icon") || tiles()[0].querySelector(".ui-icon-grid-name").textContent !== tiles()[0].querySelector("svg").dataset.icon) return "a tile does not show the icon with its name";
type(box, "arrow"); await wait();
const names = tiles().map((t) => t.querySelector(".ui-icon-grid-name").textContent);
if (names.join() !== "arrow-up,arrow-down,arrow-left,arrow-right") return `"arrow" shows ${names}`;
if (count() !== `4 of ${total}`) return `after typing the count says ${count()}`;
tiles()[2].click(); await wait();
if (tiles()[2].getAttribute("aria-pressed") !== "true" || tiles()[0].getAttribute("aria-pressed") !== "false") return "the tile clicked is not marked pressed";
if ($(".demo-note").textContent !== '<Icon name="arrow-left"/>') return `on_pick did not reach the note: ${$(".demo-note").textContent}`;
type(box, "zzz"); await wait();
if (tiles().length !== 0 || !$(".ui-icon-grid-empty")?.textContent.includes("zzz")) return "no matches does not say so";
type(box, ""); await wait();
if (tiles().length !== total) return "clearing the search does not show them all";
