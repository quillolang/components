const eur = $("#currency-pair-card-demo-eur");
const side = (c, s) => c.querySelector(`[data-side="${s}"] .ui-fxpair-price`);
const parts = (el) => [...el.children].map((x) => x.textContent).join("|");
if (!eur.classList.contains("ui-fxpair-up")) return "a rise is not marked up";
if (parts(side(eur, "bid")) !== "1.08|42|1" || side(eur, "bid").getAttribute("aria-label") !== "1.08421") return `the bid splits as ${parts(side(eur, "bid"))}`;
if (parts(side(eur, "ask")) !== "1.08|42|9") return `the ask splits as ${parts(side(eur, "ask"))}`;
if (getComputedStyle(side(eur, "bid").querySelector(".ui-fxpair-big")).fontSize !== "26px") return "the pip digits are not big";
if (eur.querySelector(".ui-fxpair-spread b").textContent !== "0.8") return `spread ${eur.querySelector(".ui-fxpair-spread b").textContent}`;
const chg = eur.querySelector(".ui-fxpair-chg").textContent.replace(/\s+/g, " ").trim();
if (chg !== "↑up+23.5 pips (+0.22%)") return `the change reads "${chg}"`;
const range = [...eur.querySelectorAll(".ui-fxpair-range b")].map((b) => b.textContent);
if (range.join(" ") !== "1.08133 1.08502") return `low and high: ${range}`;
if (eur.querySelector(".ui-fxpair-dot").style.left !== "79.13%") return `the dot stands at ${eur.querySelector(".ui-fxpair-dot").style.left}`;
const paths = eur.querySelectorAll(".ui-fxpair-spark path");
if (paths.length !== 2 || !eur.querySelector(".ui-fxpair-spark line")) return "the sparkline and its open line";
const d = paths[1].getAttribute("d");
if (!d.startsWith("M0,") || !d.includes(" L200,") || d.split(" L").length !== 9) return `the sparkline runs ${d}`;
if (eur.querySelector(".ui-fxpair-title a")?.getAttribute("href") !== "#eurusd") return "href";
if (eur.querySelector(".ui-fxpair-name").textContent !== "Euro / US dollar") return "the known name";
if (eur.querySelector(".ui-fxpair-foot").textContent !== "Indicative, 14:05 UTC") return "updated";
const jpy = $("#currency-pair-card-demo-jpy");
if (!jpy.classList.contains("ui-fxpair-down") || jpy.querySelector(".ui-fxpair-chg").dataset.pips !== "-65.8") return `USD/JPY change: ${jpy.querySelector(".ui-fxpair-chg").dataset.pips}`;
if (parts(side(jpy, "bid")) !== "156.|23|8" || jpy.querySelector(".ui-fxpair-spread b").textContent !== "1.3") return `USD/JPY pips: ${parts(side(jpy, "bid"))}`;
const c = getComputedStyle(jpy.querySelector(".ui-fxpair-spark path:last-child")).stroke;
const probe = document.createElement("span"); probe.style.color = getComputedStyle(jpy).getPropertyValue("--ui-danger").trim(); jpy.appendChild(probe);
const red = getComputedStyle(probe).color; probe.remove();
if (c !== red) return `a falling day is not drawn red: ${c}`;
const php = $("#currency-pair-card-demo-php");
if (php.querySelector(".ui-fxpair-chg") || php.querySelector(".ui-fxpair-range") || php.querySelector(".ui-fxpair-spark")) return "without open, range and values there is nothing to show for them";
if (php.querySelector(".ui-fxpair-spread b").textContent !== "3.5" || php.querySelector(".ui-fxpair-name").textContent !== "US dollar / Philippine peso") return "USD/PHP";
