const map = $("#roadmap-demo");
if (map.tagName !== "SECTION" || map.getAttribute("aria-label") !== "Product roadmap") return "not a named section";
const cols = [...map.querySelectorAll(".ui-roadmap-col")];
if (cols.map((c) => c.querySelector("h3").textContent).join() !== "Now,Next,Later,Shipped") return "the columns";
if (cols.map((c) => c.querySelector(".ui-roadmap-count").textContent).join() !== "2,2,2,0") return "the counts";
const list = cols[0].querySelector("ul");
if (list.getAttribute("aria-labelledby") !== "roadmap-demo-col-0" || document.getElementById("roadmap-demo-col-0").textContent !== "Now") return "a column's list is not named by its title";
const first = cols[0].querySelector(".ui-roadmap-item");
const status = first.querySelector(".ui-roadmap-status");
if (status.textContent.trim() !== "In progress" || !status.classList.contains("ui-roadmap-in-progress")) return `status: ${status.textContent}`;
if (first.querySelector(".ui-roadmap-tag").textContent !== "ui" || first.querySelector(".ui-roadmap-date").textContent !== "Nov 2026") return "tag and date";
if (first.querySelector(".ui-roadmap-votes").getAttribute("aria-label") !== "214 votes") return "votes";
if (!cols[0].querySelectorAll(".ui-roadmap-status")[1].classList.contains("ui-roadmap-blocked")) return "blocked";
if (cols[1].querySelector(".ui-roadmap-item-title a")?.getAttribute("href") !== "#roadmap") return "href";
const odd = cols[2].querySelectorAll(".ui-roadmap-status")[1];
if (odd.textContent.trim() !== "Someday" || odd.className !== "ui-roadmap-status") return "an unknown status is grey";
if (cols[3].querySelector("ul") || cols[3].querySelector(".ui-roadmap-empty").textContent !== "Nothing here yet.") return "an empty column";
const r = cols.map((c) => c.getBoundingClientRect());
if (!(Math.abs(r[0].top - r[1].top) < 1 && r[0].right < r[1].left)) return "the columns are not side by side";
