const rs = $("#reader-settings-demo"), btn = $("#reader-settings-demo-toggle"), panel = $("#reader-settings-demo-panel");
const body = rs?.querySelector(".ui-breader-body");
if (!body || !body.querySelector("h2") || !body.querySelector("a")) return "the text is not inside";
localStorage.removeItem("reader-settings-demo");
const cs = () => getComputedStyle(body);
if (btn.getAttribute("aria-expanded") !== "false" || panel.checkVisibility() || btn.getAttribute("aria-controls") !== "reader-settings-demo-panel") return "the settings are not closed to start with";
if (cs().fontSize !== "18px" || !cs().fontFamily.includes("Georgia")) return `it does not start at 18px serif: ${cs().fontSize} ${cs().fontFamily}`;
btn.click(); await wait();
if (btn.getAttribute("aria-expanded") !== "true" || !panel.checkVisibility() || panel.getAttribute("aria-label") !== "Reading settings") return "the button does not open the settings";
const [smaller, larger] = panel.querySelectorAll(".ui-breader-size button");
larger.click(); await wait(); larger.click(); await wait();
if (cs().fontSize !== "22px" || panel.querySelector("output").textContent !== "22px" || body.dataset.size !== "22") return `two presses of A+: ${cs().fontSize}`;
larger.click(); await wait(); larger.click(); await wait();
if (!larger.disabled || cs().fontSize !== "26px") return "A+ does not stop at 26px";
const radio = (group, v) => panel.querySelector(`input[name="reader-settings-demo-${group}"][value="${v}"]`);
radio("font", "sans").click(); await wait();
if (cs().fontFamily.includes("Georgia") || !body.classList.contains("ui-breader-sans")) return "Sans does not change the font";
const w0 = body.getBoundingClientRect().width;
radio("line-length", "narrow").click(); await wait();
const w1 = body.getBoundingClientRect().width;
if (!(w1 < w0) || body.dataset.width !== "narrow") return `narrow is not narrower: ${w0} to ${w1}`;
radio("line-spacing", "loose").click(); await wait();
if (Math.abs(parseFloat(cs().lineHeight) / parseFloat(cs().fontSize) - 1.95) > 0.01) return `loose spacing: ${cs().lineHeight}`;
const bg = cs().backgroundColor;
radio("colours", "dark").click(); await wait(400);
if (!body.classList.contains("ui-dark") || cs().backgroundColor === bg) return "Dark does not change the colours";
const page = getComputedStyle(rs.querySelector(".ui-breader-toggle")).backgroundColor;
if (page === cs().backgroundColor && !matchMedia("(prefers-color-scheme: dark)").matches) return "Dark changed the whole page, not only the text";
const kept = JSON.parse(localStorage.getItem("reader-settings-demo") || "null");
if (!kept || kept.size !== 26 || kept.font !== "sans" || kept.width !== "narrow" || kept.spacing !== "loose" || kept.theme !== "dark") return `kept: ${JSON.stringify(kept)}`;
key(radio("font", "sans"), "Escape"); await wait();
if (panel.checkVisibility() || btn.getAttribute("aria-expanded") !== "false" || document.activeElement !== btn) return "Escape does not close the settings and return the focus";
btn.click(); await wait();
panel.querySelector(".ui-breader-reset").click(); await wait(400);
if (cs().fontSize !== "18px" || body.classList.contains("ui-dark") || !body.classList.contains("ui-breader-serif") || localStorage.getItem("reader-settings-demo") !== null) return "Reset does not put it back";
if (!radio("colours", "auto").checked || !radio("font", "serif").checked) return "Reset does not pick the defaults";
if (smaller.disabled) return "at 18px A− is disabled";
btn.click(); await wait();
