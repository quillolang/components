const end = $(".form-actions-demo-end");
if (!end || getComputedStyle(end).justifyContent !== "flex-end") return "the default row is not aligned to the end";
const [cancel, save] = end.querySelectorAll("button");
if (save.type !== "submit" || save.getBoundingClientRect().left <= cancel.getBoundingClientRect().right) return "the buttons are not in a row in order";
if (save.getBoundingClientRect().right > end.getBoundingClientRect().right || end.getBoundingClientRect().right - save.getBoundingClientRect().right > 2) return "the last button does not sit at the right edge";
const between = $(".form-actions-demo-between");
if (!between.classList.contains("ui-form-actions-divider") || getComputedStyle(between).borderTopStyle !== "solid") return "divider draws no line";
const [back, draft, next] = between.querySelectorAll("button");
const br = between.getBoundingClientRect();
if (back.getBoundingClientRect().left - br.left > 2) return "between: the first button is not at the left";
if (br.right - next.getBoundingClientRect().right > 2) return "between: the last button is not at the right";
if (draft.getBoundingClientRect().left - back.getBoundingClientRect().right < 100) return "between: the rest are not pushed to the right";
const start = $(".form-actions-demo-start");
const note = start.querySelector(".ui-form-actions-note");
if (!note || note.textContent !== "Saved 2 minutes ago") return "note is not shown";
if (start.querySelector("button").getBoundingClientRect().left - start.getBoundingClientRect().left > 2) return "align=start: the first button is not at the left";
if (note.getBoundingClientRect().left <= start.querySelectorAll("button")[1].getBoundingClientRect().right) return "the note is not at the other side";
const center = $(".form-actions-demo-center");
const cb = center.querySelector("button").getBoundingClientRect(), cr = center.getBoundingClientRect();
if (Math.abs((cb.left + cb.right) / 2 - (cr.left + cr.right) / 2) > 4) return "align=center does not centre the button";
