const save = $("#split-demo-save"), toggle = $("#split-demo-save-toggle"), menu = document.getElementById("split-demo-save-menu");
if (!save || !toggle || !menu) return "the buttons or the menu are missing";
if (save.type !== "submit" || save.name !== "action" || save.value !== "save") return "the main button does not send action=save";
if (toggle.getAttribute("aria-haspopup") !== "menu" || toggle.getAttribute("aria-expanded") !== "false" || !toggle.getAttribute("aria-label")) return "the toggle is not a labelled, closed menu button";
if (menu.getAttribute("role") !== "menu" || menu.getAttribute("aria-labelledby") !== toggle.id) return "the menu has no role or name";
const s = save.getBoundingClientRect(), t = toggle.getBoundingClientRect();
if (Math.abs(t.left - s.right) > 1.5 || Math.abs(t.top - s.top) > 0.5) return "the two buttons are not joined";
if (getComputedStyle(save).borderTopRightRadius !== "0px" || getComputedStyle(toggle).borderTopLeftRadius !== "0px") return "the inner corners are not square";
toggle.scrollIntoView({ block: "center" });
toggle.click(); await wait();
if (!menu.matches(":popover-open") || toggle.getAttribute("aria-expanded") !== "true") return "the toggle does not open the menu";
const items = [...menu.querySelectorAll("[role=menuitem]")];
if (items.length !== 3) return `expected 3 items, found ${items.length}`;
if (document.activeElement !== items[0]) return "opening does not focus the first item";
if (items[0].type !== "submit" || items[0].name !== "action" || items[0].value !== "draft") return "an item with a value does not send action=draft";
if (items[2].tagName !== "A" || !items[2].getAttribute("href")) return "an item with an href is not a link";
if (!menu.querySelector("[role=separator]") || items.some((i) => i.parentElement.getAttribute("role") !== "none")) return "the separator or the items' role=none is missing";
const m = menu.getBoundingClientRect(), wrap = save.parentElement.getBoundingClientRect();
if (CSS.supports("position-area: bottom") && (m.top < wrap.bottom - 1 || m.top > wrap.bottom + 10)) return "the menu is not under the buttons";
key(items[0], "ArrowDown"); await wait(50);
if (document.activeElement !== items[1]) return "ArrowDown did not move to the next item";
key(items[1], "End"); await wait(50);
if (document.activeElement !== items[2]) return "End did not move to the last";
key(items[2], "ArrowDown"); await wait(50);
if (document.activeElement !== items[0]) return "ArrowDown from the last did not wrap";
key(items[0], "ArrowUp"); await wait(50);
if (document.activeElement !== items[2]) return "ArrowUp from the first did not wrap";
key(items[2], "Escape"); await wait();
if (menu.matches(":popover-open") || document.activeElement !== toggle || toggle.getAttribute("aria-expanded") !== "false") return "Escape did not close the menu and focus the toggle";
key(toggle, "ArrowUp"); await wait();
if (!menu.matches(":popover-open") || document.activeElement !== items[2]) return "ArrowUp on the toggle did not open at the last item";
menu.hidePopover(); await wait();
const off = $("#split-demo-off");
if (!off.disabled || !$("#split-demo-off-toggle").disabled) return "disabled does not disable both buttons";
if (!$("#split-demo-delete").classList.contains("ui-btn-danger")) return "tone is not passed on";
const mt = $("#split-demo-merge-toggle"), mm = document.getElementById("split-demo-merge-menu");
const note = () => $$(".demo-note").at(-1).textContent;
$("#split-demo-merge").click(); await wait();
if (note() !== "Did: merged") return `on_click was not called: ${note()}`;
mt.click(); await wait();
const mi = [...mm.querySelectorAll("[role=menuitem]")];
if (mi[2].getAttribute("aria-disabled") !== "true") return "disabled: true is not aria-disabled";
key(mi[0], "End"); await wait(50);
if (document.activeElement !== mi[1]) return "End landed on a disabled item";
mi[2].click(); await wait();
if (!mm.matches(":popover-open") || note() !== "Did: merged") return "clicking a disabled item did something";
mi[1].click(); await wait();
if (mm.matches(":popover-open")) return "picking an item did not close the menu";
if (note() !== "Did: Rebase and merge") return `on_select was not called: ${note()}`;
