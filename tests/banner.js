const all = $$("[role=region].ui-banner");
if (all.length !== 5) return `expected 5 banners, found ${all.length}`;
const [news, maint, ready, payments, preview] = all;
if (news.getAttribute("aria-label") !== "Announcement") return "a banner is not a named region";
const link = news.querySelector("a.ui-banner-link");
if (!link || link.getAttribute("href") !== "#banner" || link.textContent !== "See what's new →") return `the link: ${link?.outerHTML}`;
if (!news.classList.contains("ui-banner-accent") || !news.classList.contains("ui-banner-solid")) return "the defaults are accent and solid";
if (getComputedStyle(news).backgroundColor === getComputedStyle(ready).backgroundColor) return "solid and soft look the same";
if (maint.querySelector("strong")?.textContent !== "Maintenance") return "the title is not bold";
if (payments.querySelector(".ui-banner-x")) return "dismissable={false} still has a close button";
const body = news.querySelector(".ui-banner-body").getBoundingClientRect(), box = news.getBoundingClientRect();
if (Math.abs((body.left + body.right) / 2 - (box.left + box.right) / 2) > 2) return "the message is not centred";
const x = news.querySelector(".ui-banner-x");
if (x.getAttribute("aria-label") !== "Dismiss") return "the close button has no name";
x.click(); await wait();
if (news.isConnected && news.offsetParent) return "dismissing does not hide it";
if ($$("[role=region].ui-banner").length !== 4) return "the other banners went too";
if (sessionStorage.getItem("ui-banner:demo-maintenance") !== null) return "a banner without remember was remembered";
maint.querySelector(".ui-banner-x").click(); await wait();
if (sessionStorage.getItem("ui-banner:demo-maintenance") !== "1") return "remember does not keep the dismissal for the session";
sessionStorage.removeItem("ui-banner:demo-maintenance");
if ($$("[role=region].ui-banner").length !== 3) return "the remembered banner did not hide";
