const n = $("nav#series-nav-demo.ui-bseries");
if (!n || n.getAttribute("aria-label") !== "Series: Building a blog in Quillo") return "the nav and its name";
if (n.querySelector(".ui-bseries-count").textContent !== "Part 2 of 5") return `it says ${n.querySelector(".ui-bseries-count").textContent}`;
if (n.querySelector(".ui-bseries-name a")?.getAttribute("href") !== "#series_nav") return "the series' name is not a link";
const bar = [...n.querySelectorAll(".ui-bseries-bar li")].map((l) => l.className || "-");
if (bar.join() !== "ui-bseries-done,ui-bseries-here,-,-,-" || n.querySelector(".ui-bseries-bar").getAttribute("aria-hidden") !== "true") return `the bar: ${bar}`;
const d = n.querySelector("details.ui-bseries-list");
if (d.open || d.querySelector("summary").textContent !== "All 5 parts") return "the list is not closed, or its summary";
const list = d.querySelector("ol");
if (list.checkVisibility()) return "the closed list shows";
d.querySelector("summary").click(); await wait(50);
if (!d.open || !list.checkVisibility() || list.getBoundingClientRect().height < 100) return "the summary does not open the list";
const items = [...list.querySelectorAll("li")];
if (items.length !== 5) return `${items.length} parts listed`;
const cur = list.querySelectorAll("[aria-current]");
if (cur.length !== 1 || cur[0].getAttribute("aria-current") !== "page" || cur[0].textContent !== "A database of posts") return "this part is not aria-current=page";
if (getComputedStyle(items[1], "::before").width !== "22px") return "the parts have no numbers";
if (!items[0].classList.contains("ui-bseries-done") || !items[1].classList.contains("ui-bseries-here")) return "read and current parts are not marked";
const soon = items[4].querySelector(".ui-bseries-soon");
if (!soon || items[4].querySelector("a") || soon.querySelector("small").textContent !== "Coming Nov 12") return "a part not out yet";
const prev = n.querySelector("a.ui-bseries-prev"), next = n.querySelector("a.ui-bseries-next");
if (prev?.getAttribute("href") !== "#series_nav-1" || prev.rel !== "prev" || prev.textContent !== "← Part 1Routes and pages") return `previous: ${prev?.textContent}`;
if (next?.getAttribute("href") !== "#series_nav-3" || next.rel !== "next" || !next.textContent.startsWith("Part 3 →")) return `next: ${next?.textContent}`;
if (!(prev.getBoundingClientRect().right < next.getBoundingClientRect().left)) return "previous and next are not side by side";
d.querySelector("summary").click();
const e = $("#series-nav-demo-end");
if (!e.querySelector("details").open || !e.classList.contains("ui-bseries-bottom")) return "open and position";
if (e.querySelector(".ui-bseries-count").textContent !== "Part 4 of 5") return "the last part out";
const up = e.querySelector("div.ui-bseries-next.ui-bseries-soon");
if (!up || up.querySelector("small").textContent !== "Part 5, coming Nov 12" || e.querySelector("a.ui-bseries-next")) return "the next part, not out yet, is not said so";
if (e.querySelectorAll(".ui-bseries-bar .ui-bseries-done").length !== 3) return "three parts read";
