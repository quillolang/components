const cards = $("ul#blog-list-demo.ui-blog-cards");
if (!cards) return "the card grid with its id is missing";
const posts = cards.querySelectorAll("li.ui-blog-post");
if (posts.length !== 3) return `3 posts, found ${posts.length}`;
const [a, b, c] = posts;
const title = a.querySelector("h3.ui-blog-title a");
if (!title || title.getAttribute("href") !== "#blog_list" || !title.textContent.startsWith("Quillo 2.0")) return "the title is not a link to href";
if (a.querySelector("a.ui-blog-pic img")?.getAttribute("src").slice(0, 14) !== "data:image/svg") return "the picture is missing";
const time = a.querySelector(".ui-blog-meta time");
if (!time || time.getAttribute("datetime") !== "2026-10-14" || time.textContent !== "Oct 14, 2026") return `the date: ${time?.outerHTML}`;
const tags = b.querySelectorAll(".ui-blog-tags a.ui-blog-tag");
if (tags.length !== 2 || tags[1].getAttribute("href") !== "#blog_list-tag-Deep%20dive" || tags[1].textContent !== "Deep dive") return "tags are not links to tag_href plus the tag";
if (a.querySelector(".ui-blog-author")?.textContent !== "Ada Lovelace" || a.querySelector(".ui-avatar")?.textContent.trim() !== "AL") return "the author and avatar are missing";
if (a.querySelector(".ui-blog-meta").textContent.includes("4 min read") !== true || c.querySelector(".ui-blog-meta").textContent.includes("min")) return "read_time is wrong";
if (new Set([...posts].map((p) => Math.round(p.getBoundingClientRect().top))).size !== 1) return "three cards at 280px do not fit in one row";
const rows = $$("ul.ui-blog")[1];
if (!rows.classList.contains("ui-blog-rows") || rows.querySelectorAll(":scope > li").length !== 2) return "the rows list is missing";
if (rows.querySelector("span.ui-blog-tag") == null || rows.querySelector("a.ui-blog-tag")) return "without tag_href the tags are still links";
const r = rows.querySelector("li");
if (!(r.querySelector(".ui-blog-body").getBoundingClientRect().right <= r.querySelector(".ui-blog-pic").getBoundingClientRect().left)) return "in rows the picture is not to the side";
