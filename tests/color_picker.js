const text = $("#color-picker-cp-demo-brand");
const hidden = $("input[type=hidden][name=cp-demo-brand]");
const cp = text.closest(".ui-color-picker");
const chip = cp.querySelector(".ui-color-picker-chip"), panel = cp.querySelector(".ui-color-picker-panel");
if (hidden.value !== "#5b4bdb" || text.value !== "#5b4bdb") return `starts as ${hidden.value} / ${text.value}`;
if (text.labels[0]?.textContent.trim().replace("*", "") !== "Brand colour") return "the hex box is not labelled";
if (text.name) return "the hex box has a name: only the hidden input should be sent";
if (!panel.hidden || chip.getAttribute("aria-expanded") !== "false") return "the panel starts open";
chip.click(); await wait();
if (panel.hidden || chip.getAttribute("aria-expanded") !== "true" || panel.getAttribute("role") !== "dialog") return "the chip did not open the panel";
const area = panel.querySelector("[role=slider]");
area.scrollIntoView({ block: "center" }); await wait(50);
const r = area.getBoundingClientRect();
const at = (x, y) => area.dispatchEvent(new PointerEvent("pointerdown", { clientX: r.left + x * r.width, clientY: r.top + y * r.height, bubbles: true, cancelable: true, pointerId: 1 }));
at(0.5, 0.25); await wait();
if (area.getAttribute("aria-valuetext") !== "Saturation 50%, brightness 75%") return `the middle, a quarter down: ${area.getAttribute("aria-valuetext")}`;
at(1, 0); await wait();
if (area.getAttribute("aria-valuetext") !== "Saturation 100%, brightness 100%") return `top right: ${area.getAttribute("aria-valuetext")}`;
const hue = panel.querySelector("input[type=range]");
type(hue, "0"); await wait();
if (hidden.value !== "#ff0000") return `hue 0 at full saturation and brightness: ${hidden.value}`;
key(area, "ArrowDown"); await wait();
if (area.getAttribute("aria-valuetext") !== "Saturation 100%, brightness 99%" || hidden.value !== "#fc0000") return `ArrowDown: ${area.getAttribute("aria-valuetext")} ${hidden.value}`;
at(0, 1); area.dispatchEvent(new PointerEvent("pointerup", { bubbles: true, pointerId: 1 })); await wait();
if (hidden.value !== "#000000" || text.value !== "#000000") return `bottom left is not black: ${hidden.value}`;
const sw = panel.querySelector('button[aria-label="#0b6bcb"]');
sw.click(); await wait();
if (hidden.value !== "#0b6bcb" || sw.getAttribute("aria-pressed") !== "true") return `a swatch did not pick: ${hidden.value}`;
key(area, "Escape"); await wait();
if (!panel.hidden) return "Escape did not close the panel";
type(text, "#19F"); await wait();
if (hidden.value !== "#1199ff") return `#19F was not read: ${hidden.value}`;
type(text, "nope"); await wait();
if (text.getAttribute("aria-invalid") !== "true" || !cp.querySelector("[role=alert]")?.textContent.includes("#1e90ff")) return "a wrong hex says nothing";
if (text.validity.valid) return "a wrong hex would still be sent";
if (hidden.value !== "#1199ff") return "a wrong hex changed the colour";
type(text, "2e8b57"); await wait();
if (hidden.value !== "#2e8b57" || text.getAttribute("aria-invalid") === "true" || !text.validity.valid) return `fixing it: ${hidden.value}`;
if (text.value !== "#2e8b57") return `the box was not tidied: ${text.value}`;
chip.click(); await wait();
text.dispatchEvent(new FocusEvent("focusout", { bubbles: true, relatedTarget: document.body })); await wait();
if (!panel.hidden) return "leaving the picker did not close the panel";
// on_change, and a picker of swatches only.
const live = $("#color-picker-cp-demo-accent").closest(".ui-color-picker");
live.querySelector(".ui-color-picker-chip").click(); await wait();
live.querySelector('button[aria-label="#e5484d"]').click(); await wait();
if (!live.closest(".demo-stack").querySelector(".demo-note").textContent.includes("#e5484d")) return "on_change did not update the note";
live.querySelector(".ui-color-picker-chip").click(); await wait();
const lab = $("#color-picker-cp-demo-label").closest(".ui-color-picker");
if (lab.querySelector("[role=slider]") || lab.querySelector("input[type=range]")) return "area={false} still shows the square";
if (!lab.querySelector('button[aria-label="Red"][aria-pressed=true]')) return "named swatches are not labelled, or the chosen one is not pressed";
if ($("#color-picker-cp-demo-bad").getAttribute("aria-invalid") !== "true") return "error does not mark it";
