const box = $("#currency-input-ci-demo-price");
const hidden = $("input[type=hidden][name=ci-demo-price]");
const host = box.closest(".ui-currency-input");
if (box.value !== "1,234.50" || hidden.value !== "1234.50") return `value={1234.5} shows "${box.value}" and sends "${hidden.value}"`;
if (box.name) return "the visible box itself would be sent";
if (box.inputMode !== "decimal") return "the box does not bring up a number pad";
if (host.querySelector(".ui-currency-input-symbol")?.textContent !== "$" || host.querySelector(".ui-currency-input-code")?.textContent !== "USD") return "the symbol and code are not shown";
if (!box.labels[0]?.textContent.includes("Price")) return "the label is not tied to the box";
type(box, "1234567.891"); await wait();
if (box.value !== "1,234,567.89" || hidden.value !== "1234567.89") return `typing shows "${box.value}" and sends "${hidden.value}"`;
type(box, "12a3"); await wait();
if (box.value !== "123" || hidden.value !== "123.00") return `letters got in: "${box.value}" / "${hidden.value}"`;
type(box, "-5"); await wait();
if (box.value !== "5") return `a minus got in without negative: "${box.value}"`;
type(box, "99.5"); box.blur(); box.dispatchEvent(new FocusEvent("blur")); await wait();
if (box.value !== "99.50") return `leaving does not pad the decimals: "${box.value}"`;
type(box, ""); await wait();
if (box.value !== "" || hidden.value !== "") return "emptying the box does not empty the value";
// Caret: typing a digit in the middle keeps the caret after it once the groups move.
type(box, "1234"); box.setSelectionRange(2, 2);
box.value = "12x34"; box.setSelectionRange(3, 3); box.dispatchEvent(new Event("input", { bubbles: true })); await wait();
if (box.value !== "1,234") return `cleaning in the middle: "${box.value}"`;
const budget = $("#currency-input-ci-demo-budget");
const bh = budget.closest(".ui-currency-input");
if (bh.querySelector(".ui-currency-input-symbol")?.textContent !== "€" || bh.querySelector(".ui-currency-input-box").lastElementChild.classList.contains("ui-currency-input-code")) return "symbol_after does not put € at the end";
type(budget, "1234567,5"); await wait();
if (budget.value !== "1.234.567,5" || $("input[name=ci-demo-budget]").value !== "1234567.50") return `locale de: "${budget.value}" / ${$("input[name=ci-demo-budget]").value}`;
const fee = $("#currency-input-ci-demo-fee");
const note = () => fee.closest(".demo-stack").querySelector(".demo-note").textContent;
type(fee, "1500.75"); await wait();
if (fee.value !== "1,500" || note() !== "The fee is 1500 yen.") return `JPY: "${fee.value}", note: ${note()}`;
type(fee, ""); await wait();
if (note() !== "No fee yet.") return "on_change is not given null when emptied";
const refund = $("#currency-input-ci-demo-refund");
if (refund.value !== "-250.00" || $("input[name=ci-demo-refund]").value !== "-250.00") return `negative start: "${refund.value}"`;
const bad = $("#currency-input-ci-demo-bad");
if (bad.getAttribute("aria-invalid") !== "true" || !bad.closest(".ui-currency-input").querySelector("[role=alert]")) return "error does not mark the box";
if (bad.closest(".ui-currency-input").querySelector(".ui-currency-input-symbol")?.textContent !== "₹") return "INR has no rupee sign";
