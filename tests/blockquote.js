const figs = $$("figure.ui-bq");
if (figs.length !== 4) return `expected 4 quotes, found ${figs.length}`;
const ada = $("#blockquote-demo-ada");
if (ada.tagName !== "FIGURE" || !ada.querySelector("blockquote") || ada.querySelector("blockquote").parentElement !== ada) return "the quote is not a blockquote in a figure";
if (!ada.querySelector("blockquote").textContent.includes("Jacquard loom")) return "the text is not in the blockquote";
const by = ada.querySelector("figcaption.ui-bq-by");
if (!by || !by.textContent.includes("Ada Lovelace") || by.querySelector("cite")?.textContent !== "Notes on the Analytical Engine, 1843") return "the author and source are not in the caption";
if (!by.textContent.includes("Ada Lovelace, Notes")) return `the caption reads "${by.textContent.trim()}"`;
if (getComputedStyle(ada.querySelector("blockquote")).borderLeftWidth === "0px") return "the bar variant has no bar";
const grace = $("#blockquote-demo-grace");
const link = grace.querySelector("cite a");
if (!link || link.getAttribute("href") !== "https://en.wikipedia.org/wiki/Grace_Hopper") return "the source is not a link to href";
if (grace.querySelector("blockquote").getAttribute("cite") !== "https://en.wikipedia.org/wiki/Grace_Hopper") return "href is not the blockquote's cite";
if (!getComputedStyle(grace, "::before").content.includes("“")) return "the marks variant has no opening quote mark";
if (getComputedStyle(grace.querySelector("blockquote")).borderLeftWidth !== "0px") return "the marks variant has a bar";
const plain = $("#blockquote-demo-plain");
if (getComputedStyle(plain.querySelector("blockquote")).borderLeftWidth !== "0px" || getComputedStyle(plain, "::before").content !== "none") return "plain is not plain";
if (!(parseFloat(getComputedStyle(plain).fontSize) > parseFloat(getComputedStyle(ada).fontSize))) return "size=lg is not larger";
if (plain.querySelector("figcaption").textContent.includes(",")) return "an author alone gets a comma";
if ($("#blockquote-demo-bare").querySelector("figcaption")) return "a quote with no author or source has a caption";
