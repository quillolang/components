const [g1, g2] = $$(".ui-pgallery");
if (!g1 || !g2) return "expected 2 galleries";
const img = (g) => g.querySelector(".ui-pgallery-stage img");
const tabs = (g) => [...g.querySelectorAll("[role=tab]")];
const count = (g) => g.querySelector(".ui-pgallery-count").textContent.replace(/\s+/g, " ").trim();
if (tabs(g1).length !== 5 || g1.querySelector("[role=tablist]").getAttribute("aria-label") !== "Pictures of Trail runner") return "the thumbnails are not named tabs";
if (!img(g1).src.includes("shoe1") || img(g1).alt !== "From the side") return "the first picture does not show first";
if (tabs(g1)[0].getAttribute("aria-selected") !== "true" || tabs(g1)[1].tabIndex !== -1) return "the first tab is not selected";
if (count(g1) !== "1 of / 5") return `the counter reads "${count(g1)}"`;
tabs(g1)[2].click(); await wait();
if (!img(g1).src.includes("shoe3") || tabs(g1)[2].getAttribute("aria-selected") !== "true") return "clicking a thumbnail does not switch";
if (!$(".demo-note").textContent.includes("picture 3: The sole")) return `on_change did not reach the note: ${$(".demo-note").textContent}`;
key(tabs(g1)[2], "ArrowRight"); await wait();
if (!img(g1).src.includes("shoe4") || document.activeElement !== tabs(g1)[3]) return "ArrowRight does not move and focus the next";
key(tabs(g1)[3], "End"); await wait();
if (!img(g1).src.includes("shoe5")) return "End does not go to the last";
g1.querySelector(".ui-pgallery-next").click(); await wait();
if (!img(g1).src.includes("shoe1")) return "Next after the last does not loop";
g1.querySelector(".ui-pgallery-prev").click(); await wait();
if (!img(g1).src.includes("shoe5")) return "Previous from the first does not loop back";
const stage = g1.querySelector(".ui-pgallery-stage");
stage.dispatchEvent(new PointerEvent("pointerdown", { clientX: 300, bubbles: true }));
stage.dispatchEvent(new PointerEvent("pointerup", { clientX: 150, bubbles: true })); await wait();
if (!img(g1).src.includes("shoe1")) return "a swipe left does not go to the next";
if (stage.getAttribute("role") !== "tabpanel" || !stage.getAttribute("aria-label").includes("From the side")) return "the stage is not a named panel";
if (!img(g2).src.includes("pack2") || tabs(g2)[1].getAttribute("aria-selected") !== "true") return "selected={1} does not start on the second";
if (g2.querySelector(".ui-pgallery-nav")) return "arrows={false} still draws arrows";
if (g2.querySelector(".ui-pgallery-thumbs").getBoundingClientRect().right > g2.querySelector(".ui-pgallery-stage").getBoundingClientRect().left + 1) return "thumbs=left does not put them beside";
