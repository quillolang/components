const t = $("#csv-table-demo-prices");
const table = t.querySelector("table");
if (table.getAttribute("aria-label") !== "Price list (prices.csv)" || t.querySelector(".ui-csvtable-cap").textContent !== "Price list (prices.csv)") return "the caption";
const heads = [...table.querySelectorAll("th")].map((h) => h.textContent);
if (heads.join() !== "sku,name,price,stock,note") return `the header: ${heads}`;
const rows = [...table.querySelectorAll("tbody tr")].map((r) => [...r.children].map((c) => c.textContent));
if (rows.length !== 4) return `expected 4 rows, found ${rows.length}`;
if (rows[0][1] !== "Bolt, M6 x 20" || rows[0][3] !== "12,400") return `a quoted comma: ${rows[0]}`;
if (rows[2][1] !== 'Washer "wide"') return `a doubled quote: ${rows[2][1]}`;
if (rows[3][4] !== "Back-ordered;\nships in May") return `a line break in a field: ${JSON.stringify(rows[3][4])}`;
if (rows[0][4] !== "" || rows[0].length !== 5) return "an empty last field";
const cls = [...table.querySelectorAll("tbody tr:first-child td")].map((c) => c.classList.contains("ui-csvtable-num"));
if (cls.join() !== "false,false,true,true,false") return `number columns: ${cls}`;
if (!table.querySelectorAll("th")[2].classList.contains("ui-csvtable-num")) return "the header of a number column is not right-aligned";
if (t.querySelector(".ui-csvtable-more")) return "a table under its limit says there are more";
const s = $("#csv-table-demo-tsv");
const sh = [...s.querySelectorAll("th")].map((h) => h.textContent);
if (sh.join() !== "Column 1,Column 2,Column 3") return `header={false}: ${sh}`;
const srows = [...s.querySelectorAll("tbody tr")];
if (srows.length !== 5 || srows[0].children[1].textContent !== "Lisbon" || srows[0].children[2].textContent !== "1200") return "a tab-separated row";
if (s.querySelector(".ui-csvtable-more")?.textContent !== "and 9 more rows") return `the limit: ${s.querySelector(".ui-csvtable-more")?.textContent}`;
if (s.querySelector("[role=region]").getAttribute("aria-label") !== "Visitors by year" || s.querySelector("[role=region]").tabIndex !== 0) return "the scroll region";
