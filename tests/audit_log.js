const a = $("#audit-log-demo");
const rows = () => [...a.querySelectorAll("tbody tr:not(.ui-auditlog-empty)")];
const count = () => a.querySelector(".ui-auditlog-count").textContent.trim();
const note = () => a.closest(".demo-stack").querySelector(".demo-note").textContent;
if (a.querySelector("table").getAttribute("aria-label") !== "Audit log") return "the table is not named";
if ([...a.querySelectorAll("th")].map((t) => t.textContent).join() !== "When,Who,Action,Target,IP") return "the columns";
if (rows().length !== 10 || count() !== "30 entries") return `the first page: ${rows().length} rows, "${count()}"`;
const first = rows()[0];
if (first.querySelector("time").getAttribute("datetime") !== "2026-10-28T12:00:00Z") return "not newest first";
if (first.querySelector("time").textContent !== "Oct 28, 2026, 12:00") return `the time in Lisbon (UTC+0 then): ${first.querySelector("time").textContent}`;
const actions = rows().map((r) => r.querySelector(".ui-auditlog-action"));
const del = actions.find((x) => x.textContent === "api_key.delete");
const inv = actions.find((x) => x.textContent === "user.invite");
if (!del.classList.contains("ui-auditlog-danger") || !inv.classList.contains("ui-auditlog-success")) return "action tones";
if (first.querySelector(".ui-auditlog-ip").textContent !== "—" || rows()[1].querySelector(".ui-auditlog-ip").textContent !== "81.2.69.101") return "the IP column";
if (first.children[3].textContent.trim() !== "—") return "a missing target is not a dash";
const older = [...a.querySelectorAll(".ui-auditlog-pages button")].find((b) => b.textContent === "Older");
older.click(); await wait();
if (rows()[0].querySelector("time").getAttribute("datetime") !== "2026-10-27T23:30:00Z") return `Older: ${rows()[0].querySelector("time").getAttribute("datetime")}`;
const who = a.querySelector(`#audit-log-demo-who`);
if ([...who.options].map((o) => o.value).join() !== ",ada@example.com,alan@example.com,grace@example.com") return "the people filter";
who.value = "grace@example.com"; who.dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (rows().some((r) => r.querySelector(".ui-auditlog-who").textContent !== "grace@example.com")) return "the person filter kept others";
if (count() !== "10 of 30 entries" || note() !== "on_filter: 10 matching. Times are shown in Europe/Lisbon.") return `after the person filter: "${count()}", ${note()}`;
const act = a.querySelector(`#audit-log-demo-action`);
act.value = "user.remove"; act.dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (rows().some((r) => r.querySelector(".ui-auditlog-action").textContent !== "user.remove" || r.querySelector(".ui-auditlog-who").textContent !== "grace@example.com")) return "two filters together";
const n2 = rows().length;
if (!note().startsWith(`on_filter: ${n2} matching`)) return `on_filter after two filters: ${note()}`;
act.value = ""; act.dispatchEvent(new Event("change", { bubbles: true }));
who.value = ""; who.dispatchEvent(new Event("change", { bubbles: true })); await wait();
type(a.querySelector(".ui-auditlog-search"), "mobile app"); await wait();
if (rows().length === 0 || rows().some((r) => !r.textContent.includes("From the mobile app"))) return "the search does not look in the detail";
type(a.querySelector(".ui-auditlog-search"), "nobody here"); await wait();
if (a.querySelector(".ui-auditlog-empty")?.textContent.trim() !== "No entries match." || count() !== "0 of 30 entries") return "no match";
if (a.querySelector(".ui-auditlog-pages")) return "pages show with nothing to page";
