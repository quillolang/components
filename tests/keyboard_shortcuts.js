const mac = navigator.platform.includes("Mac");
const press = (target, k, mods = {}) => { const e = new KeyboardEvent("keydown", { key: k, bubbles: true, cancelable: true, ...mods }); target.dispatchEvent(e); return e.defaultPrevented; };
// Other tests on the page may have pressed keys already (Escape): look at the end of the log.
const log = () => $(".demo-note").textContent.replace(/^Last done: /, "").replace(/\.$/, "").split(", ");
const ends = (...xs) => log().slice(-xs.length).join() === xs.join();
const note = () => $(".demo-note").textContent;
const table = $("table.ui-kbsc");
if (!table || table.querySelector("caption").textContent !== "Keyboard shortcuts") return "no list of shortcuts";
const cell = (td) => (td.children.length ? [...td.children].map((c) => c.textContent).join(" ") : td.textContent).trim();
const rows = [...table.querySelectorAll("tbody tr")].map((r) => [...r.cells].map(cell).join(" "));
const save = mac ? "Save ⌘S or ⌘Enter" : "Save Ctrl+S or Ctrl+Enter";
if (rows.length !== 4 || rows[0] !== save) return `the rows: ${rows}`;
if (rows[1] !== (mac ? "New item ⌥N" : "New item Alt+N") || rows[2] !== "Show help ?" || rows[3] !== "Close Esc") return `the rows: ${rows}`;
const mod = mac ? { metaKey: true } : { ctrlKey: true };
if (!press(document.body, "s", mod)) return "mod+s was not taken (its default not prevented)";
await wait();
if (!ends("saved")) return `mod+s: ${note()}`;
press(document.body, "Enter", mod); await wait();
if (!ends("saved", "saved")) return `the second combo: ${note()}`;
if (press(document.body, "s")) return "s alone was taken as mod+s";
press(document.body, "s", mac ? { ctrlKey: true } : { metaKey: true }); await wait();
if (!ends("saved", "saved")) return "the wrong modifier ran it";
press(document.body, "n", { altKey: true }); await wait();
press(document.body, "?", { shiftKey: true }); await wait();
if (!ends("saved", "saved", "new item", "help")) return `alt+n and ?: ${note()}`;
press(document.body, "G", { shiftKey: true }); await wait();
if (ends("g")) return "Shift+G ran the binding for g";
const field = $("input[name=kbsc_try]");
if (press(field, "g")) return "a key typed into a field was taken";
press(field, "s", mod); await wait();
if (!ends("saved", "saved", "new item", "help")) return "mod+s in a field ran it (in_fields is false)";
press(field, "Escape"); await wait();
if (!ends("saved", "new item", "help", "closed")) return `Escape in a field (in_fields: true): ${note()}`;
press(document.body, "g"); await wait();
if (!ends("closed", "g")) return `g: ${note()}`;
