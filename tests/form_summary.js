const sections = $$(".ui-form-summary-section");
if (sections.length !== 4) return `expected 4 sections over the two summaries, found ${sections.length}`;
const [account, plan] = sections;
if (account.querySelector("h3")?.textContent !== "Account" || account.getAttribute("aria-label") !== "Account") return "a section is not titled";
const edit = account.querySelector("a.ui-form-summary-edit");
if (!edit || edit.getAttribute("href") !== "#account" || edit.getAttribute("aria-label") !== "Edit Account") return "href does not make a named Edit link";
const pairs = (s) => [...s.querySelectorAll(".ui-form-summary-item")].map((i) => `${i.querySelector("dt").textContent}=${i.querySelector("dd").textContent.trim()}`);
if (pairs(account).join("|") !== "Name=Ada Lovelace|Email=ada@example.com|Newsletter=Yes") return `the account items: ${pairs(account)}`;
if (pairs(plan).join("|") !== "Plan=Team|Seats=4|Add-ons=Audit log, SSO|Coupon=—") return `lists, numbers and null are not written right: ${pairs(plan)}`;
if (!account.querySelector("dl") || account.querySelectorAll("dt").length !== 3) return "the items are not a definition list";
if (plan.querySelector(".ui-form-summary-empty")?.getAttribute("aria-label") !== "empty") return "an empty value is not named for screen readers";
const ship = sections[2];
const btn = ship.querySelector("button.ui-form-summary-edit");
if (!btn || btn.type !== "button" || btn.getAttribute("aria-label") !== "Edit Shipping") return "on_edit does not make an Edit button";
if (!ship.closest(".ui-form-summary").classList.contains("ui-form-summary-one")) return "columns={1} is not applied";
btn.click(); await wait();
if (!$(".demo-note").textContent.includes('on_edit got "ship"')) return `on_edit did not give the key: ${$(".demo-note").textContent}`;
sections[3].querySelector("button").click(); await wait();
if (!$(".demo-note").textContent.includes('"pay"')) return "the second section's key is wrong";
