const [docs, people] = $$(".ui-sl");
const box = docs.querySelector("input[type=search]");
const hits = (el) => [...el.querySelectorAll(".ui-sl-hit")];
const titles = (el) => hits(el).map((h) => h.querySelector(".ui-sl-title").textContent);
const count = (el) => el.querySelector(".ui-sl-count").textContent.trim();
if (box.value !== "server" || box.getAttribute("aria-label") !== "Search the guide") return "the box does not start with its query and name";
if (docs.querySelector(".ui-sl-count").getAttribute("role") !== "status") return "the count is not a live region";
if (count(docs) !== "7 results") return `query "server" counts: ${count(docs)}`;
if (!hits(docs)[0].querySelector("mark")) return "matches are not marked";
type(box, "form"); await wait();
if (titles(docs).join() !== "Uploads,Forms without JavaScript") return `"form" finds: ${titles(docs)}`;
if (count(docs) !== "2 results") return `the count says ${count(docs)}`;
type(box, "BROWSER state"); await wait();
if (titles(docs).join() !== "Components,Live data") return `two words find: ${titles(docs)}`;
const marks = [...hits(docs)[0].querySelectorAll("mark")].map((m) => m.textContent.toLowerCase());
if (!marks.includes("browser") || !marks.includes("state")) return `both words are not marked: ${marks}`;
type(box, ""); await wait();
const chips = () => [...docs.querySelectorAll(".ui-sl-chip")];
if (chips().map((c) => c.textContent.replace(/\s+/g, " ").trim()).join("|") !== "All 8|Server 4|Browser 3|Data 3|Forms 2") return `facets: ${chips().map((c) => c.textContent.trim())}`;
chips()[3].click(); await wait();
if (chips()[3].getAttribute("aria-pressed") !== "true" || titles(docs).join() !== "Database,Records,Live data") return `the Data facet keeps ${titles(docs)}`;
type(box, "zzz"); await wait();
const emptyEl = docs.querySelector(".ui-sl-empty");
if (!emptyEl || !emptyEl.textContent.includes("Nothing in the guide") || count(docs) !== "No results") return "no match does not show the empty state";
type(box, ""); chips()[0].click(); await wait();
if (count(docs) !== "8 results") return `All gives back everything: ${count(docs)}`;
key(box, "ArrowDown"); await wait();
if (document.activeElement !== hits(docs)[0]) return "ArrowDown in the box does not go to the first result";
key(hits(docs)[0], "ArrowDown"); await wait();
if (document.activeElement !== hits(docs)[1]) return "ArrowDown does not move to the next result";
key(hits(docs)[1], "End"); await wait();
if (document.activeElement !== hits(docs).at(-1)) return "End does not go to the last result";
key(document.activeElement, "Home"); await wait();
key(hits(docs)[0], "ArrowUp"); await wait();
if (document.activeElement !== box) return "ArrowUp from the first result does not go back to the box";
if (hits(docs)[0].tagName !== "A" || !hits(docs)[0].getAttribute("href")) return "an item with href is not a link";
const pbox = people.querySelector("input");
if (people.querySelector("label")?.textContent !== "Find a colleague") return "show_label does not show the label";
if (hits(people).length !== 4 || count(people) !== "4 of 8 results") return `limit 4 shows ${hits(people).length}, "${count(people)}"`;
type(pbox, "research"); await wait();
if (titles(people).join() !== "Katherine Johnson,Radia Perlman,Annie Easley") return `"research" finds ${titles(people)}`;
key(pbox, "Enter"); await wait();
const note = people.closest(".demo-stack").querySelector(".demo-note").textContent;
if (note !== "Picked Katherine Johnson.") return `Enter in the box did not pick the first: ${note}`;
hits(people)[1].click(); await wait();
if (people.closest(".demo-stack").querySelector(".demo-note").textContent !== "Picked Radia Perlman.") return "clicking a result does not call on_select";
key(pbox, "Escape"); await wait();
if (pbox.value !== "") return "Escape does not clear the box";
