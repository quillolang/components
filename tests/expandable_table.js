const t = $("#expandable-table-demo-orders table");
if (!t || t.getAttribute("aria-label") !== "Orders") return "the table is not named";
const btns = () => [...t.querySelectorAll(".ui-expandable-btn")];
if (btns().length !== 3) return `expected 3 buttons, found ${btns().length}`;
if (t.querySelectorAll(".ui-expandable-panel").length !== 0) return "a panel is open at first";
const b = btns()[0];
if (b.getAttribute("aria-expanded") !== "false" || b.getAttribute("aria-controls") !== "expandable-table-demo-orders-panel-o-1041") return "the button's ARIA is wrong";
if (b.getAttribute("aria-label") !== "Show details of #1041") return `the button is named ${b.getAttribute("aria-label")}`;
b.click(); await wait();
const panel = t.querySelector("#expandable-table-demo-orders-panel-o-1041");
if (!panel || b.getAttribute("aria-expanded") !== "true") return "clicking did not open the panel";
if (panel.tagName !== "TR" || panel.previousElementSibling.dataset.id !== "o-1041") return "the panel is not the row after its row";
if (panel.querySelector("td").getAttribute("colspan") !== "4") return "the panel does not span the table";
const dts = [...panel.querySelectorAll("dt")].map((d) => d.textContent);
const dds = [...panel.querySelectorAll("dd")].map((d) => d.textContent.trim());
if (dts.join() !== "Email,Shipped,Items" || dds.join("|") !== "orders@northwind.example|Mar 14, 2026|3") return `fields: ${dts} = ${dds}`;
if (!panel.querySelector(".ui-expandable-text")?.textContent.includes("neighbour")) return "the detail text is missing";
if (b.getAttribute("aria-label") !== "Hide details of #1041") return "the open button is not named Hide";
btns()[2].click(); await wait();
if (t.querySelectorAll(".ui-expandable-panel").length !== 2) return "a second row did not open beside the first";
const p3 = t.querySelector("#expandable-table-demo-orders-panel-o-1043");
if ([...p3.querySelectorAll("dd")][1].textContent.trim() !== "Mar 18, 2026") return "the third panel's date";
b.click(); await wait();
if (t.querySelector("#expandable-table-demo-orders-panel-o-1041") || b.getAttribute("aria-expanded") !== "false" || t.querySelectorAll(".ui-expandable-panel").length !== 1) return "clicking again did not close";
btns()[1].click(); await wait();
const p2 = t.querySelector("#expandable-table-demo-orders-panel-o-1042");
if (!p2 || p2.querySelector(".ui-expandable-text")) return "an empty note still shows a paragraph";
if ([...p2.querySelectorAll("dd")][1].textContent.trim() !== "—") return "a null field is not a dash";
if (t.querySelector("tbody td.ui-expandable-right")?.textContent.trim() !== "$1,240.50") return "money is not formatted";
