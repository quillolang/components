const link = $("#notification-bell-demo");
if (!link || link.tagName !== "A" || link.getAttribute("href") !== "#notification_bell") return "href does not make it a link";
if (link.getAttribute("aria-label") !== "Notifications, 3 unread") return `screen readers hear: ${link.getAttribute("aria-label")}`;
if (link.querySelector(".ui-bell-count")?.textContent !== "3") return "the count badge is missing";
const r = link.getBoundingClientRect(), b = link.querySelector(".ui-bell-count").getBoundingClientRect();
if (b.left < r.left + r.width / 2 || b.top > r.top + r.height / 2) return "the badge is not on the top right corner";
const none = $$("a.ui-bell")[1];
if (none.querySelector(".ui-bell-count") || none.getAttribute("aria-label") !== "Notifications") return "count 0 still shows a badge, or says unread";
if ($("#notification-bell-demo-many").querySelector(".ui-bell-count")?.textContent !== "99+") return "past the limit the badge does not say 99+";
const dot = $("#notification-bell-demo-dot").querySelector(".ui-bell-count");
if (!dot?.classList.contains("ui-bell-dot") || dot.textContent !== "" || dot.getBoundingClientRect().width > 14) return "dot does not show a plain dot";
const panel = $("#notification-bell-demo-panel"), pop = document.getElementById("notification-bell-demo-pop");
if (panel.tagName !== "BUTTON" || panel.getAttribute("popovertarget") !== "notification-bell-demo-pop") return "target does not point the button at the popover";
panel.click(); await wait();
if (!pop.matches(":popover-open")) return "clicking does not open the popover";
panel.click(); await wait();
const live = $("#notification-bell-demo-live");
const note = () => live.closest(".demo-row").querySelector(".demo-note").textContent;
if (live.querySelector(".ui-bell-count")?.textContent !== "2") return "the live bell does not start at 2";
$("#notification-bell-demo-more").click(); await wait();
if (live.querySelector(".ui-bell-count")?.textContent !== "3" || !note().includes("3 unread")) return "the count does not follow the state";
live.click(); await wait();
if (live.querySelector(".ui-bell-count") || !note().includes("All read")) return `on_click did not clear the count: ${note()}`;
