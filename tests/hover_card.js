const [ada, repo, plan] = $$(".ui-hc");
const card = (h) => h.querySelector(".ui-hc-card");
const shown = (h) => getComputedStyle(card(h)).display !== "none" && getComputedStyle(card(h)).visibility === "visible";
const trig = (h) => h.querySelector(".ui-hc-trigger");
if (trig(ada).tagName !== "A" || trig(ada).getAttribute("href") !== "#hover_card") return "href does not make the trigger a link";
if (trig(repo).tagName !== "BUTTON") return "without href the trigger is not a button";
if (trig(ada).getAttribute("aria-describedby") !== card(ada).id || card(ada).id !== "hc-ada") return "the trigger is not described by its card";
if (shown(ada)) return "the card shows before anything happens";
if (ada.closest("p").querySelectorAll(".ui-hc").length !== 2) return "the cards broke out of their paragraph";
ada.scrollIntoView({ block: "center" });
ada.dispatchEvent(new PointerEvent("pointerenter", { pointerType: "mouse" })); await wait(100);
if (shown(ada)) return "the card shows before the delay";
await wait(700);
if (!shown(ada) || Number(getComputedStyle(card(ada)).opacity) < 0.99) return "resting the pointer does not show the card";
const c = card(ada).getBoundingClientRect(), t = trig(ada).getBoundingClientRect();
if (c.top < t.bottom || Math.abs(c.left - t.left) > 2) return `the card is not beside its trigger: ${JSON.stringify([c.top, c.bottom, c.left, t.top, t.bottom, t.left])}`;
ada.dispatchEvent(new PointerEvent("pointerleave", { pointerType: "mouse" })); await wait(400);
if (shown(ada)) return "leaving does not hide the card";
trig(ada).focus(); await wait(800);
if (!shown(ada)) return "focus does not show the card";
card(ada).querySelector("a").focus(); await wait(300);
if (!shown(ada)) return "the card hides when focus moves into it";
key(card(ada).querySelector("a"), "Escape"); await wait(300);
if (shown(ada)) return "Escape does not hide the card";
trig(ada).blur(); card(ada).querySelector("a").blur(); document.body.focus(); await wait(300);
trig(repo).click(); await wait(100);
if (!shown(repo)) return "a click on a button trigger does not show its card at once";
key(trig(repo), "Escape"); await wait(300);
if (shown(repo)) return "Escape does not hide a card shown by a click";
trig(repo).blur(); await wait(200);
plan.scrollIntoView({ block: "center" });
trig(plan).focus(); await wait(600);
if (!shown(plan)) return "delay={200} is not used";
const pc = card(plan).getBoundingClientRect(), pt = trig(plan).getBoundingClientRect();
if (pc.bottom > pt.top) return "placement top does not put the card above";
trig(plan).blur();
