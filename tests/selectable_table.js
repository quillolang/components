const t = $("#selectable-table-demo-users");
const head = t.querySelector("thead input");
const boxes = () => [...t.querySelectorAll("tbody input")];
const rows = () => [...t.querySelectorAll("tbody tr")];
const count = () => t.querySelector(".ui-selectable-count [role=status]").textContent.trim();
const hidden = () => [...t.querySelectorAll("input[type=hidden][name=user]")].map((i) => i.value).join();
const note = () => t.closest(".demo-stack").querySelector(".demo-note").textContent;
if (t.querySelector("table").getAttribute("aria-label") !== "Users" || t.querySelector("table").getAttribute("aria-multiselectable") !== "true") return "the table is not a named multiselectable table";
if (boxes().length !== 5) return `expected 5 checkboxes, found ${boxes().length}`;
if (!boxes()[2].checked || boxes()[0].checked) return "selected={[3]} does not check the third row";
if (rows()[2].getAttribute("aria-selected") !== "true" || rows()[0].getAttribute("aria-selected") !== "false") return "rows do not say whether they are selected";
if (count() !== "1 of 5 selected" || hidden() !== "3") return `at first: "${count()}", hidden ${hidden()}`;
if (!head.indeterminate || head.getAttribute("aria-checked") !== "mixed") return "the header checkbox is not half-checked";
if (boxes()[0].getAttribute("aria-label") !== "Select Ada Lovelace") return `the checkbox is named ${boxes()[0].getAttribute("aria-label")}`;
boxes()[0].click(); await wait();
if (!boxes()[0].checked || count() !== "2 of 5 selected" || hidden() !== "1,3") return `clicking a checkbox: "${count()}", hidden ${hidden()}`;
if (note() !== "on_change: 1, 3") return `on_change: ${note()}`;
rows()[4].querySelector("td:last-child").click(); await wait();
if (!boxes()[4].checked || count() !== "3 of 5 selected") return "clicking a row did not check it";
boxes()[4].dispatchEvent(new MouseEvent("click", { bubbles: true, shiftKey: true })); await wait();
boxes()[1].dispatchEvent(new MouseEvent("click", { bubbles: true, shiftKey: true })); await wait();
if (count() !== "5 of 5 selected" || !head.checked || head.indeterminate) return `Shift+click did not check the range: "${count()}", all=${head.checked}`;
if (head.getAttribute("aria-label") !== "Unselect all rows") return "the header is not named Unselect all";
head.click(); await wait();
if (count() !== "0 of 5 selected" || boxes().some((b) => b.checked) || hidden() !== "") return `the header did not clear all: "${count()}"`;
if (t.querySelector(".ui-selectable-clear")) return "Clear shows with nothing selected";
head.click(); await wait();
if (count() !== "5 of 5 selected" || !boxes().every((b) => b.checked)) return "the header did not check all";
t.querySelector(".ui-selectable-clear").click(); await wait();
if (count() !== "0 of 5 selected" || note() !== "on_change: nothing") return `Clear: "${count()}", ${note()}`;
// limit
const l = $("#selectable-table-demo-limit");
const lb = () => [...l.querySelectorAll("tbody input")];
lb()[0].click(); lb()[1].click(); await wait();
if (!lb()[2].disabled || !lb()[3].disabled || lb()[0].disabled) return "limit={2} does not disable the rest";
if (l.querySelector("[role=status]").textContent.trim() !== "2 of 4 selected (up to 2)") return `the limit count line: ${l.querySelector("[role=status]").textContent}`;
l.querySelector("thead input").click(); await wait();
if (lb().filter((b) => b.checked).length !== 0) return "select all with everything checked did not clear";
l.querySelector("thead input").click(); await wait();
if (lb().filter((b) => b.checked).length !== 2) return "select all past the limit checked more than the limit";
