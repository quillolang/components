const lo = $("input[name=rs-demo-price_min]"), hi = $("input[name=rs-demo-price_max]");
if (!lo || !hi || lo.type !== "range" || hi.type !== "range") return "the form would not get price_min and price_max";
if (lo.value !== "40" || hi.value !== "250" || lo.min !== "0" || lo.max !== "500" || lo.step !== "10") return `start: ${lo.value}–${hi.value}`;
const fs = lo.closest("fieldset");
if (document.getElementById(fs.getAttribute("aria-labelledby"))?.textContent !== "Price") return "the group is not named Price";
if (lo.getAttribute("aria-label") !== "Price, lowest" || hi.getAttribute("aria-label") !== "Price, highest") return "the thumbs are not named";
if (lo.getAttribute("aria-valuetext") !== "$40") return `valuetext: ${lo.getAttribute("aria-valuetext")}`;
const out = fs.querySelector("output");
if (out.textContent.trim() !== "$40 – $250") return `shown: ${out.textContent}`;
const track = fs.querySelector(".ui-range-slider-track");
if (track.style.getPropertyValue("--lo").trim() !== "8%" || track.style.getPropertyValue("--hi").trim() !== "50%") return `fill: ${track.getAttribute("style")}`;
type(lo, "100"); await wait();
if (out.textContent.trim() !== "$100 – $250" || lo.getAttribute("aria-valuetext") !== "$100") return `moving the low thumb: ${out.textContent}`;
if (track.style.getPropertyValue("--lo").trim() !== "20%") return "the fill did not follow";
type(lo, "400"); await wait();
if (lo.value !== "250" || out.textContent.trim() !== "$250 – $250") return `the low thumb crossed the high one: ${lo.value}`;
if (!lo.classList.contains("ui-range-slider-top")) return "the thumb moved last is not on top";
type(hi, "10"); await wait();
if (hi.value !== "250") return `the high thumb went under the low one: ${hi.value}`;
// gap 1: the age thumbs stay a year apart; on_change gets both.
const alo = $("input[name=rs-demo-age_min]"), ahi = $("input[name=rs-demo-age_max]");
type(alo, "60"); await wait();
if (alo.value !== "39") return `gap 1 did not hold: ${alo.value}`;
type(ahi, "70"); await wait();
const note = alo.closest(".demo-stack").querySelector(".demo-note").textContent;
if (note !== "Showing people aged 39 to 70.") return `on_change: ${note}`;
const km = $("input[name=rs-demo-km_max]");
if (km.getAttribute("aria-valuetext") !== "10.5 km") return `format: ${km.getAttribute("aria-valuetext")}`;
if (!$("input[name=rs-demo-off_min]").closest("fieldset").disabled) return "disabled is not passed";
