const all = $$(".ui-delivery");
if (all.length !== 6) return `expected 6, found ${all.length}`;
const when = (e) => e.querySelector(".ui-delivery-when").textContent.replace(/\s+/g, " ").trim();
const times = (e) => [...e.querySelectorAll("time")].map((t) => t.getAttribute("datetime"));
const iso = (d) => d.toISOString().slice(0, 10);
const today = new Date(); today.setUTCHours(12);
const plus = (n) => { const d = new Date(today); d.setUTCDate(d.getUTCDate() + n); return iso(d); };
if (times(all[0]).join() !== `${plus(2)},${plus(4)}`) return `2–4 days from today gives ${times(all[0])}, expected ${plus(2)},${plus(4)}`;
if (!/^\w{3} \d{1,2}( \w{3})? – \w{3} \d{1,2} \w{3}$/.test(when(all[0]))) return `it reads "${when(all[0])}"`;
if (!all[0].textContent.startsWith("Arrives")) return "the label is missing";
if (!all[0].querySelector("svg")) return "the truck is missing";
const t1 = new Date(times(all[1])[0] + "T12:00:00Z").getUTCDay();
if (t1 === 0 || t1 === 6) return "business_days lands on a weekend";
if (all[1].querySelector(".ui-delivery-cutoff")?.textContent !== "· Order by 2 pm") return "the cutoff is missing";
if (when(all[2]) !== "today" || !all[2].textContent.startsWith("Collect") || all[2].querySelector("svg")) return `0 days reads "${all[2].textContent}"`;
if (when(all[3]) !== "Wed 4 – Fri 6 Nov" || times(all[3]).join() !== "2026-11-04,2026-11-06") return `from 2 Nov, 2–4 days reads "${when(all[3])}"`;
if (when(all[4]) !== "Fri 30 Oct – Mon 2 Nov") return `across a month it reads "${when(all[4])}"`;
if (when(all[5]) !== "Fri 6 – Tue 10 Nov" || times(all[5]).join() !== "2026-11-06,2026-11-10") return `3 business days from Thu 5 Nov reads "${when(all[5])}" ${times(all[5])}`;
if (!all[5].classList.contains("ui-delivery-sm")) return "size=sm is not set";
