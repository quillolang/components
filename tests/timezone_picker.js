const sel = $("#timezone-picker-demo-all");
if (!sel || sel.tagName !== "SELECT" || sel.name !== "tz") return "the picker is not a named select";
if (sel.labels.length !== 1 || !sel.labels[0].textContent.includes("Time zone")) return "the label is not tied to the select";
if (sel.value !== "Europe/Lisbon") return `value did not choose the zone: ${sel.value}`;
const groups = [...sel.querySelectorAll("optgroup")].map((g) => g.label);
if (!groups.includes("Europe") || !groups.includes("Asia") || groups.indexOf("Africa") > groups.indexOf("Europe")) return `regions are wrong: ${groups}`;
if (sel.options.length < 90) return `expected the built-in list, found ${sel.options.length} zones`;
const lisbon = sel.querySelector("option[value='Europe/Lisbon']");
if (!/^\(UTC[+-]\d\d:\d\d\) Lisbon$/.test(lisbon.textContent.trim())) return `the option does not show its offset: ${lisbon.textContent}`;
const kolkata = sel.querySelector("option[value='Asia/Kolkata']");
if (!kolkata.textContent.includes("+05:30")) return `Kolkata's offset: ${kolkata.textContent}`;
const utc = sel.querySelector("option[value='UTC']");
if (!utc || utc.closest("optgroup") || !utc.textContent.includes("(UTC+00:00)")) return "UTC is not a plain option with a zero offset";
const europe = [...sel.querySelector("optgroup[label=Europe]").querySelectorAll("option")].map((o) => o.textContent.trim());
const offs = europe.map((t) => t.slice(4, 10));
if (offs.join() !== [...offs].sort().join()) return `a region is not in offset order: ${europe.slice(0, 4)}`;
if (!document.getElementById(sel.getAttribute("aria-describedby"))?.textContent.includes("daylight")) return "the hint is not tied to the select";
if (!sel.required) return "required did not reach the select";
const small = $("#timezone-picker-demo-small");
if (small.options[0].value !== "" || !small.options[0].disabled || !small.options[0].selected) return "the placeholder is not a disabled first option";
if (small.options.length !== 4) return `zones={...} should give only those: ${small.options.length}`;
const live = $("#timezone-picker-demo-live");
if (live.value !== "Asia/Tokyo") return `the live picker starts on ${live.value}`;
live.value = "Europe/Berlin"; live.dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (!$(".demo-note").textContent.includes("Europe/Berlin")) return `on_change did not update the note: ${$(".demo-note").textContent}`;
if (!$("select[name=tz_locked]").disabled) return "disabled did not reach the select";
