const [fmt, rows, tools] = $$("[role=toolbar]");
if (!fmt || !rows || !tools) return "expected three toolbars";
if (fmt.getAttribute("aria-label") !== "Formatting" || fmt.getAttribute("aria-orientation") !== "horizontal") return "the toolbar has no label or orientation";
const items = [...fmt.querySelectorAll("button, select")];
const tabbable = items.filter((b) => b.tabIndex === 0);
if (tabbable.length !== 1 || tabbable[0] !== items[0]) return `Tab should reach only the first control: ${tabbable.map((b) => b.textContent)}`;
items[0].focus(); key(items[0], "ArrowRight"); await wait();
if (document.activeElement !== items[1] || items[1].tabIndex !== 0 || items[0].tabIndex !== -1) return "ArrowRight did not move focus and the tab stop";
key(items[1], "ArrowLeft"); key(items[0], "ArrowLeft"); await wait();
if (document.activeElement !== items.at(-1)) return "ArrowLeft from the first did not wrap to the last";
key(items.at(-1), "Home"); await wait();
if (document.activeElement !== items[0]) return "Home did not go to the first";
key(items[0], "End"); await wait();
if (document.activeElement.textContent.trim() !== "Publish") return "End did not go to the last";
// A page in the background gets no focus events from .focus(): send what the browser would.
const focus = (el) => { el.focus(); if (!document.hasFocus()) el.dispatchEvent(new FocusEvent("focusin", { bubbles: true })); };
const select = fmt.querySelector("select");
focus(select); await wait();
if (select.tabIndex !== 0) return "focusing a control does not make it the tab stop";
key(select, "ArrowRight"); await wait();
if (document.activeElement !== select) return "the arrow keys left the select";
const bold = fmt.querySelector('button[aria-label="Bold"]');
focus(bold); bold.click(); await wait();
if (bold.getAttribute("aria-pressed") !== "true" || bold.tabIndex !== 0) return `a toggle in the toolbar does not toggle or take the tab stop: ${bold.getAttribute("aria-pressed")} ${bold.tabIndex} ${bold.isConnected}`;
if (fmt.querySelectorAll("[role=separator]").length !== 3) return "the separators are missing";
if (fmt.querySelectorAll("[role=group]").length !== 3) return "the groups are not role=group";
const spacer = fmt.querySelector(".ui-toolbar-spacer");
const pub = [...fmt.querySelectorAll("button")].at(-1);
if (Math.abs(pub.getBoundingClientRect().right - fmt.getBoundingClientRect().right) > 8) return "the spacer did not push Publish to the end";
const rb = [...rows.querySelectorAll("button")];
if (rb.at(-1).getBoundingClientRect().top <= rb[0].getBoundingClientRect().top) return "the narrow toolbar does not wrap";
if (rows.scrollWidth > rows.clientWidth + 1) return "the narrow toolbar overflows";
rb[0].focus(); key(rb[0], "End"); await wait();
if (document.activeElement !== rb[3]) return "End landed on a disabled control";
const tb = [...tools.querySelectorAll("button")];
tb[0].focus(); key(tb[0], "ArrowRight"); await wait();
if (document.activeElement !== tb[0]) return "ArrowRight moved in a vertical toolbar";
key(tb[0], "ArrowDown"); await wait();
if (document.activeElement !== tb[1]) return "ArrowDown did not move in a vertical toolbar";
document.activeElement.blur();
