if (/NaN|Infinity|undefined/.test(charts.map((c) => c.innerHTML).join(""))) return "a sankey chart has NaN, Infinity or undefined in it";
const [traffic, budget] = charts;
if (traffic.getAttribute("aria-label") !== "Where sign-ups come from") return "the label does not name the chart";
const nodes = Object.fromEntries([...traffic.querySelectorAll(".ui-sankey-node")].map((n) => [n.dataset.name, n]));
if (Object.keys(nodes).length !== 8) return `8 nodes made ${Object.keys(nodes).length}`;
const left = (n) => n.getBoundingClientRect().left;
const plot = traffic.querySelector(".ui-sankey-plot").getBoundingClientRect();
if (Math.abs(left(nodes.Search) - plot.left) > 0.5 || Math.abs(left(nodes.Pricing) - left(nodes.Docs)) > 0.5) return "the first two columns are not lined up";
