if (!(left(nodes.Search) < left(nodes.Blog) && left(nodes.Blog) < left(nodes.Left))) return "nodes are not in columns by their flows";
const top = (n) => parseFloat(n.style.top), h = (n) => parseFloat(n.style.height);
// Heights follow what flows through: Search 8,800 and Email 2,200.
if (Math.abs(h(nodes.Search) / h(nodes.Email) - 4) > 0.01) return "node heights are not in proportion";
const col = [nodes.Social, nodes.Search, nodes.Email].sort((a, b) => top(a) - top(b));
for (let i = 1; i < 3; i++) if (top(col[i]) < top(col[i - 1]) + h(col[i - 1]) + 3.9) return "nodes in a column overlap";
if (Math.min(...Object.values(nodes).map(top)) < -0.01 || Math.max(...Object.values(nodes).map((n) => top(n) + h(n))) > 100.01) return "a node is outside the plot";
// Bands: each as wide as its value, stacked to fill their nodes.
const bands = [...traffic.querySelectorAll(".ui-sankey-band")];
if (bands.length !== 13) return `13 links made ${bands.length} bands`;
