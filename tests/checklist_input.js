const boxes = $$("input[name=setup]");
if (boxes.length !== 5 || boxes.some((b) => b.type !== "checkbox")) return "the list is not 5 checkboxes";
if (boxes.map((b) => b.checked).join() !== "true,true,false,false,false") return `values and checked did not tick the first two: ${boxes.map((b) => b.checked)}`;
if (boxes.map((b) => b.value).join() !== "project,invite,domain,billing,deploy") return "the values are wrong";
if (!boxes[4].disabled) return "a disabled item is not disabled";
const fs = boxes[0].closest("fieldset");
if (fs.querySelector("legend")?.textContent !== "Getting started") return "the label is not the legend";
const count = fs.querySelector("#checklist-input-demo-setup-count");
const said = () => [...count.querySelectorAll("span")].map((s) => s.textContent.trim()).join(" ");
if (!count || count.getAttribute("aria-live") !== "polite" || said() !== "2 of 5 done 40%") return `the count: ${count?.textContent}`;
const bar = fs.querySelector("[role=progressbar]");
if (bar.getAttribute("aria-valuenow") !== "2" || bar.getAttribute("aria-valuemax") !== "5" || bar.querySelector("span").style.getPropertyValue("--p").trim() !== "40%") return "the bar does not show 2 of 5";
if (!document.getElementById(boxes[1].getAttribute("aria-describedby"))?.textContent.includes("email")) return "an item's hint is not tied to it";
if (!(fs.getAttribute("aria-describedby") || "").includes("checklist-input-demo-setup-hint")) return "the hint is not tied to the group";
boxes[2].click(); await wait();
if (said() !== "3 of 5 done 60%" || bar.getAttribute("aria-valuenow") !== "3") return `ticking did not count: ${count.textContent}`;
if (getComputedStyle(boxes[2].parentElement.querySelector(".ui-checklist-input-text > span")).textDecorationLine !== "line-through") return "a ticked item is not struck through";
boxes[0].click(); await wait();
if (said() !== "2 of 5 done 40%") return `unticking did not count down: ${count.textContent}`;
const live = $$("input[name=launch]");
live[1].click(); live[0].click(); await wait();
if ($(".demo-note").textContent.trim() !== "Ticked: Write the announcement, Tag the release") return `on_change is not in the items' order: ${$(".demo-note").textContent}`;
live[2].click(); await wait();
const lfs = live[0].closest("fieldset");
if (!lfs.classList.contains("ui-checklist-input-done") || !lfs.querySelector(".ui-checklist-input-all")?.textContent.includes("All done")) return "ticking everything does not say All done";
