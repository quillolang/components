const w = sizes.map((t) => Math.round(t.getBoundingClientRect().width));
if (w.join() !== "32,48,64,96,128,40") return `sizes are ${w}`;
if (sizes[0].querySelector("img")?.alt !== "Red") return "the alt is not on the image";
