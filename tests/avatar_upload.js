const input = $("#avatar-upload-au-demo-photo");
const host = input.closest(".ui-avatar-upload");
if (input.type !== "file" || input.name !== "au-demo-photo" || input.accept !== "image/*") return "the picker is not a file input named for the form";
if (input.required) return "a field with a picture already is required";
if (!input.getAttribute("aria-labelledby") || !document.getElementById(input.getAttribute("aria-labelledby"))?.textContent.includes("Profile photo")) return "the input is not labelled";
const pic = () => host.querySelector(".ui-avatar-upload-pic");
if (!pic().querySelector("img") || pic().getAttribute("role") !== "img") return "the picture from src is not shown";
if (getComputedStyle(pic()).borderTopLeftRadius !== "50%" && !getComputedStyle(pic()).borderTopLeftRadius.endsWith("px")) return "a circle is not round";
if (host.querySelector(".ui-avatar-upload-btn")?.textContent.trim() !== "Change") return "the button does not say Change";
if ($("input[name=au-demo-photo_remove]")?.value !== "") return "the remove flag is not empty to start";
const pick = async (el, files) => {
    const dt = new DataTransfer();
    for (const f of files) dt.items.add(f);
    el.files = dt.files;
    el.dispatchEvent(new Event("change", { bubbles: true }));
    await wait();
};
const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="8" height="8"><rect width="8" height="8" fill="teal"/></svg>';
await pick(input, [new File([svg], "me.svg", { type: "image/svg+xml" })]);
if (!pic().querySelector("img")?.src.startsWith("blob:")) return "the picture picked is not previewed";
if (!host.querySelector(".ui-avatar-upload-meta")?.textContent.includes("me.svg")) return "the file's name is not shown";
if (input.files.length !== 1) return "the input does not hold the file";
await pick(input, [new File([new Uint8Array(2200000)], "huge.jpg", { type: "image/jpeg" })]);
const err = host.querySelector("[role=alert]");
if (!err || !err.textContent.includes("up to 2 MB") || input.files.length !== 0) return `a file too large was taken: ${err?.textContent}`;
if (!pic().querySelector("img")?.src.startsWith("blob:")) return "refusing a file threw the picture before away";
await pick(input, [new File(["x"], "notes.txt", { type: "text/plain" })]);
if (!host.querySelector("[role=alert]")?.textContent.includes("Choose a picture")) return "a file that is not a picture was taken";
host.querySelector(".ui-avatar-upload-remove").click(); await wait();
if (pic().querySelector("img") || pic().textContent.trim() !== "AL") return "Remove does not go back to the initials";
if ($("input[name=au-demo-photo_remove]").value !== "1") return "Remove does not set the remove flag";
if (host.querySelector("[role=alert]")) return "Remove does not clear the error";
if (document.activeElement !== input) return "Remove does not put the focus on the picker";
const logo = $("#avatar-upload-au-demo-logo");
const live = logo.closest(".demo-stack");
if (!live.querySelector(".ui-avatar-upload").classList.contains("ui-avatar-upload-square")) return "shape=square is not marked";
if (live.querySelector(".ui-avatar-upload-pic").textContent.trim() !== "Q") return "initials are not shown when there is no picture";
await pick(logo, [new File([svg], "logo.svg", { type: "image/svg+xml" })]);
if (live.querySelector(".demo-note").textContent !== "Picked logo.svg (image/svg+xml).") return `on_change: ${live.querySelector(".demo-note").textContent}`;
live.querySelector(".ui-avatar-upload-remove").click(); await wait();
if (live.querySelector(".demo-note").textContent !== "No file picked.") return "on_change is not given null on Remove";
const fresh = $("#avatar-upload-au-demo-new");
if (!fresh.required || fresh.getAttribute("aria-invalid") !== "true") return "required and error are not on a new picker";
if (!$("#avatar-upload-au-demo-off").disabled) return "disabled is not passed through";
