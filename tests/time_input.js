const sent = (n) => $(`input[type=hidden][name=${n}]`).value;
const hh = $("#time-input-ti-demo-start-h"), mm = $("#time-input-ti-demo-start-m");
if (sent("ti-demo-start") !== "09:30" || hh.value !== "09" || mm.value !== "30") return `starts as ${sent("ti-demo-start")} (${hh.value}:${mm.value})`;
if (hh.getAttribute("role") !== "spinbutton" || hh.getAttribute("aria-label") !== "Hours" || hh.getAttribute("aria-valuenow") !== "9") return "hours is not a spinbutton at 9";
if (hh.getAttribute("aria-valuemax") !== "23" || mm.getAttribute("aria-valuemax") !== "59") return "the limits are not given";
if (!hh.closest("fieldset").querySelector("legend").textContent.includes("Starts at")) return "the group has no legend";
if (hh.name || mm.name) return "a part has a name: only the hidden input should be sent";
key(hh, "ArrowUp"); await wait();
if (sent("ti-demo-start") !== "10:30" || hh.getAttribute("aria-valuenow") !== "10") return `ArrowUp: ${sent("ti-demo-start")}`;
key(mm, "ArrowDown"); await wait();
if (sent("ti-demo-start") !== "10:29") return `ArrowDown on minutes: ${sent("ti-demo-start")}`;
key(hh, "Home"); await wait();
if (sent("ti-demo-start") !== "00:29") return `Home: ${sent("ti-demo-start")}`;
key(hh, "ArrowDown"); await wait();
if (sent("ti-demo-start") !== "23:29") return `ArrowDown from 0 did not wrap: ${sent("ti-demo-start")}`;
// Typing: two digits, then on to the minutes.
const eh = $("#time-input-ti-demo-end-h"), em = $("#time-input-ti-demo-end-m");
if (sent("ti-demo-end") !== "" || eh.value !== "" || eh.placeholder !== "--") return "an empty one is not empty";
type(eh, "1"); await wait();
if (eh.value !== "01" || document.activeElement !== eh) return `"1" should wait for a second digit: ${eh.value}`;
type(eh, "017"); await wait();
if (eh.value !== "17" || document.activeElement !== em) return `"17" did not move to the minutes: ${eh.value}`;
if (sent("ti-demo-end") !== "") return "half a time is sent";
type(em, "7"); await wait();
if (sent("ti-demo-end") !== "17:07") return `"7" in the minutes: ${sent("ti-demo-end")}`;
type(eh, "9"); await wait();
if (sent("ti-demo-end") !== "09:07") return `"9" in the hours: ${sent("ti-demo-end")}`;
key(em, "Backspace"); await wait();
if (sent("ti-demo-end") !== "" || em.value !== "") return "Backspace did not empty the minutes";
key(em, "ArrowLeft"); await wait();
if (document.activeElement !== eh) return "ArrowLeft did not go back to the hours";
// 12-hour clock with a 15-minute step, 08:00 to 20:00.
const ph = $("#time-input-ti-demo-pickup-h"), pmi = $("#time-input-ti-demo-pickup-m"), ap = $("#time-input-ti-demo-pickup-p");
const note = () => ph.closest(".demo-stack").querySelector(".demo-note").textContent;
if (ph.value !== "06" || ap.value !== "PM" || sent("ti-demo-pickup") !== "18:30") return `12-hour start: ${ph.value} ${ap.value} / ${sent("ti-demo-pickup")}`;
key(pmi, "ArrowUp"); await wait();
if (sent("ti-demo-pickup") !== "18:45") return `step 15: ${sent("ti-demo-pickup")}`;
key(pmi, "ArrowUp"); await wait();
if (sent("ti-demo-pickup") !== "18:00") return `minutes wrap: ${sent("ti-demo-pickup")}`;
key(ap, "a"); await wait();
if (sent("ti-demo-pickup") !== "08:00" || ap.value !== "AM") return `"a" should make it AM, kept to 08:00 at least: ${sent("ti-demo-pickup")}`;
key(ap, "ArrowUp"); await wait();
if (sent("ti-demo-pickup") !== "20:00") return `AM to PM past the max is kept to 20:00: ${sent("ti-demo-pickup")}`;
if (note() !== "The form sends 20:00.") return `on_change: ${note()}`;
type(ph, "3"); await wait();
if (sent("ti-demo-pickup") !== "15:00" || ph.value !== "03") return `typing 3 at PM: ${sent("ti-demo-pickup")}`;
const alarm = $("#time-input-ti-demo-alarm-h");
if (alarm.getAttribute("aria-invalid") !== "true" || !$("#time-input-ti-demo-alarm-error[role=alert]")) return "error does not mark it";
