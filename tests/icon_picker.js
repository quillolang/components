const all = $("#icon-picker-demo-all");
const grid = $("#icon-picker-demo-all-grid");
const opts = () => [...grid.querySelectorAll("input[type=radio]")];
const hidden = all.querySelector("input[type=hidden][name=icon]");
if (!grid || grid.getAttribute("role") !== "radiogroup" || grid.getAttribute("aria-label") !== "Category icon") return "the grid is not a named radiogroup";
if (opts().length !== 51) return `expected 51 icons, found ${opts().length}`;
if (opts().some((r) => !r.parentElement.querySelector("svg path"))) return "an icon is not drawn";
if (hidden?.value !== "star" || opts().find((r) => r.checked)?.value !== "star") return "value did not pick the star";
if (opts().find((r) => r.value === "map-pin").getAttribute("aria-label") !== "map pin") return "an icon has no name for screen readers";
if (all.querySelector(".ui-icon-picker-legend")?.textContent.trim() !== "Category icon") return "the label is not the legend";
if (opts()[0].getAttribute("form") !== "ui-icon-picker-none") return "the radios should belong to no form (the hidden input carries the value)";
const search = $("#icon-picker-demo-all-search");
if (search.getAttribute("aria-controls") !== "icon-picker-demo-all-grid" || search.getAttribute("aria-label") !== "Search icons") return "the search is not named or tied to the grid";
type(search, "bin"); await wait();
if (opts().map((r) => r.value).join() !== "trash") return `"bin" found: ${opts().map((r) => r.value)}`;
type(search, "arrow-"); await wait();
if (opts().length !== 4) return `"arrow-" should find the four arrows: ${opts().length}`;
if (!all.querySelector(".ui-icon-picker-status").textContent.includes("4 of 51")) return `the count: ${all.querySelector(".ui-icon-picker-status").textContent}`;
opts()[2].click(); await wait();
if (hidden.value !== "arrow-right" || !all.querySelector(".ui-icon-picker-status").textContent.includes("arrow right")) return `picking did not set the value: ${hidden.value}`;
type(search, "zzzz"); await wait();
if (opts().length !== 0 || !grid.textContent.includes("No icons match")) return "no matches does not say so";
if (hidden.value !== "arrow-right") return "filtering lost the value";
type(search, ""); await wait();
const live = $("#icon-picker-demo-live-grid");
const lr = [...live.querySelectorAll("input")];
if (lr.length !== 8 || $("#icon-picker-demo-live-search")) return "only= and search={false} do not apply";
if (lr.find((r) => r.checked)?.value !== "heart") return "the live picker does not start on heart";
lr[1].click(); await wait();
if ($(".demo-note").textContent.trim() !== "Picked star.") return `on_change: ${$(".demo-note").textContent}`;
