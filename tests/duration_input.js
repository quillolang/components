const fs = $("#duration-input-di-demo-length");
const hidden = $("input[type=hidden][name=di-demo-length]");
const part = (p) => $(`#duration-input-di-demo-length-${p}`);
const total = () => $("#duration-input-di-demo-length-total").textContent;
if (fs.tagName !== "FIELDSET" || !fs.querySelector("legend")?.textContent.includes("Length")) return "no fieldset with a legend";
if (hidden.value !== "5400" || part("h").value !== "01" || part("m").value !== "30" || part("s").value !== "00") return `5400 shows ${part("h").value}:${part("m").value}:${part("s").value}`;
if (part("m").getAttribute("aria-label") !== "Minutes" || part("m").getAttribute("aria-valuemax") !== "59") return "the parts are not named spinbuttons";
if (total() !== "1 hour, 30 minutes") return `the total in words: ${total()}`;
type(part("s"), "45"); await wait();
if (hidden.value !== "5445" || total() !== "1 hour, 30 minutes, 45 seconds") return `seconds: ${hidden.value}`;
type(part("h"), "2"); await wait();
if (document.activeElement !== part("h")) return "one digit moved on too early";
type(part("h"), "02"); await wait();
if (document.activeElement !== part("m")) return "two digits did not move on to the minutes";
key(part("m"), "ArrowUp"); await wait();
if (part("m").value !== "31" || hidden.value !== `${2 * 3600 + 31 * 60 + 45}`) return `ArrowUp: ${part("m").value}`;
part("m").dispatchEvent(new KeyboardEvent("keydown", { key: "ArrowDown", shiftKey: true, bubbles: true, cancelable: true })); await wait();
if (part("m").value !== "21") return `Shift+ArrowDown: ${part("m").value}`;
type(part("m"), "90"); await wait();
if (part("m").value !== "90") return "minutes past 59 are not kept while typing";
part("m").blur(); fs.dispatchEvent(new FocusEvent("focusout", { bubbles: true, relatedTarget: null })); await wait();
if (part("h").value !== "03" || part("m").value !== "30" || hidden.value !== `${3 * 3600 + 30 * 60 + 45}`) return `90 minutes did not carry: ${part("h").value}:${part("m").value}`;
type(part("h"), ""); type(part("m"), ""); type(part("s"), ""); await wait();
if (hidden.value !== "" || total() !== "No duration") return "emptying every part does not empty the value";
const cook = $("#duration-input-di-demo-cook-m");
const note = () => cook.closest(".demo-stack").querySelector(".demo-note").textContent;
if ($("#duration-input-di-demo-cook-s")) return "seconds={false} still shows seconds";
type(cook, "40"); await wait();
if (note() !== "2400 seconds.") return `on_change: ${note()}`;
const lap = $("#duration-input-di-demo-lap-m");
if ($("#duration-input-di-demo-lap-h") || lap.getAttribute("aria-valuemax") !== "9999" || !lap.required) return "hours={false} does not let the minutes run on";
if ($("#duration-input-di-demo-bad-h").getAttribute("aria-invalid") !== "true") return "error does not mark the parts";
