const n = $(".ui-assembly-notice");
if (!n || n.querySelector("h3").textContent !== "38th Annual General Assembly") return "the title";
const fact = (cls) => n.querySelector(`.ui-assembly-notice-${cls} dd`)?.textContent;
if (fact("when") !== "Saturday, March 14, 2026" + "9:00 AM to 1:00 PM · registration from 7:30 AM") return `when: ${fact("when")}`;
if (n.querySelector(".ui-assembly-notice-when time").getAttribute("datetime") !== "2026-03-14") return "the date is not a <time>";
if (!fact("where").startsWith("Municipal Gymnasium") || !fact("where").includes("Rizal Avenue")) return `where: ${fact("where")}`;
const link = n.querySelector(".ui-assembly-notice-where a");
if (link?.getAttribute("href") !== "https://meet.example.org/bmpc-aga-2026" || link.target !== "_blank" || !link.textContent.includes("opens in a new tab")) return "the online link";
if (!fact("quorum").startsWith("25% of the 4,812")) return "the quorum";
const items = [...n.querySelectorAll(".ui-assembly-notice-agenda > li")];
if (items.length !== 8 || n.querySelector(".ui-assembly-notice-agenda").tagName !== "OL") return `agenda: ${items.length}`;
if (items[3].querySelector(".ui-assembly-notice-detail")?.textContent !== "The audited financial statements for 2025" || items[0].textContent !== "Call to order and invocation") return "agenda items";
if (!n.querySelector(".ui-assembly-notice-by").textContent.includes("Board Secretary") || !n.querySelector(".ui-assembly-notice-by").textContent.includes("February 12, 2026")) return "who gives notice";
const f = n.querySelector("form");
if (!f || f.method !== "post") return "no RSVP form";
if (!f.querySelector(".ui-assembly-notice-due").textContent.includes("March 6, 2026")) return "the answer-by date";
const num = $("#assembly-notice-demo-number");
if (num.value !== "M-004217" || !num.required || !num.labels[0].textContent.startsWith("Member number")) return "the member number field";
const radios = [...f.querySelectorAll("input[name=attendance]")].map((r) => r.value).join(",");
if (radios !== "in_person,online,absent") return `attendance: ${radios}`;
if (f.checkValidity()) return "the form is valid without an answer";
f.querySelector("input[value=online]").click();
if (!f.checkValidity()) return "the form is not valid once answered";
const sent = new FormData(f);
if (sent.get("attendance") !== "online" || sent.get("assembly") !== "aga-2026" || sent.get("name") !== "Lourdes Villanueva" || !sent.has("question")) return `the form sends ${[...sent.entries()]}`;
