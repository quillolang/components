const timers = $$("[role=timer]");
if (timers.length !== 4) return `expected 4 countdowns, found ${timers.length}`;
const [year, sale, seat, early] = timers;
const nums = (t) => [...t.querySelectorAll(".ui-cd-num")].map((n) => n.textContent);
const names = [...year.querySelectorAll(".ui-cd-name")].map((n) => n.textContent);
if (names.join() !== "Days,Hours,Minutes,Seconds") return `units: ${names}`;
const left = (Date.UTC(2027, 0, 1) - Date.now()) / 1000;
const shown = nums(year).map(Number);
const secs = shown[0] * 86400 + shown[1] * 3600 + shown[2] * 60 + shown[3];
if (Math.abs(secs - left) > 3) return `it shows ${secs} s left, there are ${Math.round(left)}`;
if (!/^\d\d$/.test(nums(year)[1])) return "hours are not two digits";
if (year.getAttribute("aria-label") !== "New Year (UTC) in" || year.querySelector(".ui-cd-label").textContent !== "New Year (UTC) in") return "the label";
if (!/^\d+ days, \d+ hours?, \d+ minutes?, \d+ seconds?$/.test(year.querySelector(".ui-sr").textContent)) return `screen readers hear "${year.querySelector(".ui-sr").textContent}"`;
if (nums(sale).length !== 3) return "less than a day shows days";
const before = seat.querySelector(".ui-cd-clock").textContent;
// 10 minutes from when the page loaded, which may be a while before this runs.
if (!/^00:(0\d|10):\d\d$/.test(before)) return `the inline clock reads ${before}`;
const s0 = nums(year)[3];
await wait(2100);
if (nums(year)[3] === s0 || seat.querySelector(".ui-cd-clock").textContent === before) return "it does not tick";
if (early.querySelector(".ui-cd-ended")?.textContent !== "Early-bird sale has ended" || early.querySelector(".ui-cd-num")) return "a past date does not show ended";
if (early.querySelector("[aria-live]").textContent !== "Early-bird sale has ended") return "the end is not announced";
const start = $$("button").find((b) => b.textContent === "Start");
start.click(); await wait(300);
const live = $$("[role=timer]")[4];
if (!live || !/^00:00:0[23]$/.test(live.querySelector(".ui-cd-clock")?.textContent)) return `the 3 s countdown reads ${live?.textContent}`;
await wait(3300);
if (live.querySelector(".ui-cd-ended")?.textContent !== "Launched") return `after 3 s it reads ${live.textContent}`;
if (!$$(".demo-note").some((n) => n.textContent === "on_end called 1 time")) return "on_end was not called once";
