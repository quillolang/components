const [sq, free] = $$(".ui-image-crop");
if (!sq || !free) return "expected two croppers";
const val = (root, n) => root.querySelector(`input[type=hidden][name=${n}]`)?.value;
const crop = (root, p) => ["x", "y", "w", "h"].map((k) => val(root, `${p}_${k}`)).join(",");
for (let i = 0; i < 20 && val(sq, "avatar_w") === ""; i++) await wait(100);
// 800 x 500, a square box at 80% of the height, centred.
if (crop(sq, "avatar") !== "200,50,400,400") return `the square box starts at ${crop(sq, "avatar")}`;
if (crop(free, "banner") !== "100,50,400,200") return `crop={...} starts at ${crop(free, "banner")}`;
const box = sq.querySelector(".ui-image-crop-box");
if (box.getAttribute("role") !== "group" || box.getAttribute("aria-label") !== "Crop area" || box.tabIndex !== 0) return "the box is not a focusable, named group";
if (!box.getAttribute("aria-description").startsWith("400 by 400 pixels")) return "the box does not say its size";
const frame = sq.querySelector(".ui-image-crop-frame").getBoundingClientRect();
const br = box.getBoundingClientRect();
if (Math.abs(br.width - br.height) > 2 || Math.abs(br.width / frame.width - 0.5) > 0.01) return "the box drawn is not the crop";
key(box, "ArrowRight"); await wait();
if (crop(sq, "avatar") !== "216,50,400,400") return `ArrowRight moves it to ${crop(sq, "avatar")}`;
if ($("#image-crop-demo-note").textContent !== "Crop 400 × 400 at 216, 50.") return `on_change: ${$("#image-crop-demo-note").textContent}`;
box.dispatchEvent(new KeyboardEvent("keydown", { key: "ArrowLeft", shiftKey: true, bubbles: true })); await wait();
if (crop(sq, "avatar") !== "216,50,384,384") return `Shift+ArrowLeft resizes to ${crop(sq, "avatar")} (held square)`;
for (let i = 0; i < 20; i++) key(box, "ArrowUp");
await wait();
if (val(sq, "avatar_y") !== "0") return "the box moves out of the picture";
// Drag the box, then a corner (a made-up pointer cannot be captured, so capturing does nothing here).
const cap = (el) => { el.setPointerCapture = () => {}; };
cap(box); sq.querySelectorAll(".ui-image-crop-handle").forEach(cap);
const pe = (el, t, x, y) => el.dispatchEvent(new PointerEvent(t, { bubbles: true, cancelable: true, pointerId: 1, button: 0, clientX: x, clientY: y }));
const fx = frame.left, fy = frame.top, s = frame.width / 800;
let b = box.getBoundingClientRect();
pe(box, "pointerdown", b.left + 20, b.top + 20);
pe(box, "pointermove", b.left + 20 - 100 * s, b.top + 20 + 40 * s);
pe(box, "pointerup", b.left + 20 - 100 * s, b.top + 20 + 40 * s); await wait();
if (Math.abs(val(sq, "avatar_x") - 116) > 1 || Math.abs(val(sq, "avatar_y") - 40) > 1) return `dragging the box puts it at ${crop(sq, "avatar")}`;
const se = sq.querySelector(".ui-image-crop-se"), sr = se.getBoundingClientRect();
pe(se, "pointerdown", sr.left + 8, sr.top + 8);
pe(se, "pointermove", sr.left + 8 - 184 * s, sr.top + 8);
pe(se, "pointerup", sr.left + 8 - 184 * s, sr.top + 8); await wait();
if (Math.abs(val(sq, "avatar_w") - 200) > 1 || Math.abs(val(sq, "avatar_h") - 200) > 1) return `pulling the corner in gives ${crop(sq, "avatar")}`;
const fb = free.querySelector(".ui-image-crop-box"); cap(fb); free.querySelectorAll(".ui-image-crop-handle").forEach(cap);
const nw = free.querySelector(".ui-image-crop-nw"), nr = nw.getBoundingClientRect(), fs = free.querySelector(".ui-image-crop-frame").getBoundingClientRect().width / 800;
pe(nw, "pointerdown", nr.left + 8, nr.top + 8);
pe(nw, "pointermove", nr.left + 8 - 50 * fs, nr.top + 8 + 100 * fs);
pe(nw, "pointerup", nr.left + 8 - 50 * fs, nr.top + 8 + 100 * fs); await wait();
const f = crop(free, "banner").split(",").map(Number);
if (Math.abs(f[0] - 50) > 2 || Math.abs(f[1] - 150) > 2 || Math.abs(f[2] - 450) > 2 || Math.abs(f[3] - 100) > 2) return `a free box's corner gives ${f} (any shape)`;
if (!free.querySelector(".ui-image-crop-size").textContent.includes("×")) return "the size line is missing";
