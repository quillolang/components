const nav = $("#scrollspy-demo"), art = document.getElementById("scrollspy-demo-article");
if (!nav || nav.tagName !== "NAV" || nav.getAttribute("aria-label") !== "Sections") return "it is not a labelled <nav>";
const links = [...nav.querySelectorAll("a")];
if (links.length !== 5 || links[1].getAttribute("href") !== "#scrollspy-demo-setup") return "the links do not go to the sections";
const cur = () => links.filter((a) => a.hasAttribute("aria-current")).map((a) => a.textContent);
const note = () => $(".demo-note").textContent;
if (cur().join() !== "Introduction" || links[0].getAttribute("aria-current") !== "location") return `at first the current one is ${cur()}`;
const [a, b] = links.map((l) => l.getBoundingClientRect());
if (b.top <= a.bottom - 1) return "the links are not one under another";
const h = (id) => document.getElementById(id);
art.scrollTop = h("scrollspy-demo-api").getBoundingClientRect().top - art.getBoundingClientRect().top; await wait(300);
if (cur().join() !== "API" || !note().includes("API")) return `scrolled to API, the current one is ${cur()}; note: ${note()}`;
art.scrollTop = art.scrollHeight; await wait(300);
if (cur().join() !== "FAQ") return `at the bottom, the current one is ${cur()}`;
art.scrollTop = 0; await wait(300);
if (cur().join() !== "Introduction") return `back at the top, the current one is ${cur()}`;
const hash = location.hash;
links[2].click(); await wait(50);
if (cur().join() !== "Usage") return "clicking did not mark the link at once";
for (let i = 0; i < 30; i++) { await wait(100); if (Math.abs(h("scrollspy-demo-usage").getBoundingClientRect().top - art.getBoundingClientRect().top - 8) < 2) break; }
const off = h("scrollspy-demo-usage").getBoundingClientRect().top - art.getBoundingClientRect().top;
if (Math.abs(off - 8) > 2) return `clicking did not scroll the section to the top (offset 8): ${off}`;
if (location.hash !== "#scrollspy-demo-usage" || document.activeElement !== h("scrollspy-demo-usage")) return "the address bar or the focus did not move to the section";
await wait(300);
if (cur().join() !== "Usage" || !note().includes("Usage")) return `after the jump, the current one is ${cur()}`;
const row = $("#scrollspy-demo-row");
if (!row.classList.contains("ui-scrollspy-horizontal") || row.getAttribute("aria-label") !== "Sections, across") return "the horizontal one is not horizontal or labelled";
const rl = [...row.querySelectorAll("a")];
if (new Set(rl.map((l) => Math.round(l.getBoundingClientRect().top))).size !== 1) return "the horizontal links are not in one row";
if (rl.filter((l) => l.hasAttribute("aria-current")).map((l) => l.textContent).join() !== "Usage") return "the row does not follow the same box";
history.replaceState(history.state, "", location.pathname + location.search + hash);
art.scrollTop = 0; document.activeElement.blur(); await wait(300);
