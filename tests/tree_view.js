const tree = $$("[role=tree]")[0];
const items = () => [...tree.querySelectorAll("[role=treeitem]")];
const names = () => items().map((i) => i.querySelector(".ui-tree-label").textContent);
const item = (t) => items().find((i) => i.querySelector(".ui-tree-label").textContent === t);
const posted = () => tree.parentElement.querySelector("input[type=hidden][name=file]")?.value;
if (tree.getAttribute("aria-label") !== "Project files") return "the tree is not named";
if (names().join() !== "src,main.qwe,ui,db,static,README.md,quillo.toml") return `at first: ${names()}`;
const main = item("main.qwe");
if (main.getAttribute("aria-selected") !== "true" || main.tabIndex !== 0 || posted() !== "src/main.qwe") return "the selected item is not selected, focusable and posted";
if (items().filter((i) => i.tabIndex === 0).length !== 1) return "more than one Tab stop";
if (item("src").getAttribute("aria-expanded") !== "true" || item("static").getAttribute("aria-expanded") !== "false") return "aria-expanded is wrong";
if (main.hasAttribute("aria-expanded")) return "a leaf has aria-expanded";
if (main.getAttribute("aria-level") !== "2" || main.getAttribute("aria-posinset") !== "1" || main.getAttribute("aria-setsize") !== "3") return "level/posinset/setsize are wrong";
main.focus();
key(main, "ArrowDown"); await wait();
if (document.activeElement !== item("ui")) return "ArrowDown did not move the focus";
key(item("ui"), "ArrowRight"); await wait();
if (item("ui").getAttribute("aria-expanded") !== "true" || !names().includes("modal.qwe")) return "ArrowRight did not open";
key(item("ui"), "ArrowRight"); await wait();
if (document.activeElement !== item("button.qwe")) return "ArrowRight on an open item did not go to its first child";
if (item("button.qwe").getAttribute("aria-level") !== "3") return "a nested item's level";
key(item("button.qwe"), "ArrowLeft"); await wait();
if (document.activeElement !== item("ui")) return "ArrowLeft on a leaf did not go to the parent";
key(item("ui"), "ArrowLeft"); await wait();
if (names().includes("modal.qwe")) return "ArrowLeft did not close";
key(item("ui"), "End"); await wait();
if (document.activeElement !== item("quillo.toml")) return "End";
key(item("quillo.toml"), "Home"); await wait();
if (document.activeElement !== item("src")) return "Home";
key(item("src"), "r"); await wait();
if (document.activeElement !== item("README.md")) return "typing r did not jump to README.md";
key(item("README.md"), "Enter"); await wait();
if (item("README.md").getAttribute("aria-selected") !== "true" || posted() !== "README.md" || main.getAttribute("aria-selected") !== "false") return "Enter did not select";
key(item("README.md"), "Home"); await wait();
key(item("src"), "*"); await wait();
if (item("static").getAttribute("aria-expanded") !== "true") return "* did not open the siblings";
item("static").click(); await wait();
if (item("static").getAttribute("aria-expanded") !== "false" || posted() !== "static") return "a click does not select and toggle";
