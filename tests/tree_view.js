const rt = $$("[role=tree]")[1];
const r = (t) => [...rt.querySelectorAll("[role=treeitem]")].find((i) => i.querySelector(".ui-tree-label").textContent === t);
const note = () => rt.closest(".demo-stack").querySelector(".demo-note").textContent;
const sent = () => [...rt.parentElement.querySelectorAll("input[type=hidden][name=regions]")].map((i) => i.value).join();
if (r("Europe").getAttribute("aria-checked") !== "mixed" || r("Frankfurt").getAttribute("aria-checked") !== "true" || r("Stockholm").getAttribute("aria-checked") !== "false") return "tri-state is wrong at first";
if (r("Americas").getAttribute("aria-checked") !== "mixed") return "a grandparent with one checked leaf is not mixed";
if (sent() !== "eu-fra,eu-dub,us-east") return `posted regions: ${sent()}`;
r("Europe").querySelector(".ui-tree-check").click(); await wait();
if (r("Europe").getAttribute("aria-checked") !== "true" || r("Stockholm").getAttribute("aria-checked") !== "true") return "checking a mixed parent did not check all";
if (!note().startsWith("4 regions")) return `on_check: ${note()}`;
r("Europe").focus(); key(r("Europe"), " "); await wait();
if (r("Europe").getAttribute("aria-checked") !== "false" || r("Dublin").getAttribute("aria-checked") !== "false") return "Space on a checked parent did not uncheck all";
if (note() !== "1 region: us-east") return `on_check after Space: ${note()}`;
key(r("Europe"), "ArrowDown"); await wait();
if (document.activeElement !== r("Frankfurt")) return "the checkbox tree's arrows";
