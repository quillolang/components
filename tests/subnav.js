const nav = $("#subnav-demo");
if (!nav || nav.tagName !== "NAV" || nav.getAttribute("aria-label") !== "Section") return "it is not a labelled <nav>";
if (nav.querySelector(".ui-subnav-title")?.textContent !== "quillo/components") return "the title is missing";
const links = [...nav.querySelectorAll("a.ui-subnav-link")];
if (links.length !== 6) return `expected 6 links, found ${links.length}`;
const cur = links.filter((a) => a.getAttribute("aria-current") === "page");
if (cur.length !== 1 || !cur[0].textContent.includes("Issues")) return "the current page is not marked once";
if (cur[0].querySelector(".ui-subnav-badge")?.textContent !== "24" || !links[0].querySelector(".ui-subnav-icon svg")) return "the badge or the icon is missing";
if (getComputedStyle(cur[0]).boxShadow === getComputedStyle(links[0]).boxShadow) return "the current link has no underline";
if (!nav.querySelector(".ui-subnav-end .ui-btn")) return "children are not at the end";
const tops = links.map((a) => Math.round(a.getBoundingClientRect().top));
if (new Set(tops).size !== 1) return "the links are not in one row";
const pill = $("#subnav-demo-pill");
if (!pill.classList.contains("ui-subnav-pill") || pill.getAttribute("aria-label") !== "Period") return "the pill variant is not applied";
const pc = pill.querySelector("[aria-current=page]");
if (!pc?.textContent.includes("This month") || getComputedStyle(pc).backgroundColor === getComputedStyle(pill.querySelector("a")).backgroundColor) return "the current pill does not look it";
const narrow = $("#subnav-demo-narrow").querySelector("ul");
if (narrow.scrollWidth <= narrow.clientWidth + 1) return "a narrow row does not overflow sideways";
if (getComputedStyle(narrow).overflowX !== "auto" && getComputedStyle(narrow).overflowX !== "scroll") return "a narrow row cannot scroll";
