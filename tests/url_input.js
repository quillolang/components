const site = $("#url-input-ui-demo-site");
const host = site.closest(".ui-url-input");
if (site.name !== "ui-demo-site" || site.type !== "text" || site.inputMode !== "url") return "with a protocol the box is not a text input for the rest";
if (host.querySelector(".ui-url-input-protocol")?.textContent !== "https://") return "the protocol is not shown";
if (!site.getAttribute("aria-describedby")?.includes(host.querySelector(".ui-url-input-protocol").id)) return "the protocol does not describe the box";
if (!site.labels[0]?.textContent.includes("Website")) return "the label is not tied to the box";
const ok = host.querySelector(".ui-url-input-ok");
if (getComputedStyle(ok).opacity !== "0") return "the tick shows while empty";
type(site, "not a url"); await wait();
if (site.validity.valid) return "'not a url' passes";
type(site, "example.com/about"); await wait();
if (!site.validity.valid || getComputedStyle(ok).opacity !== "1") return "a plain host and path does not pass with a tick";
if (site.closest(".demo-stack").querySelector(".demo-note").textContent !== "The form sends https://example.com/about.") return `on_change: ${site.closest(".demo-stack").querySelector(".demo-note").textContent}`;
const link = $("#url-input-ui-demo-link");
if (link.type !== "url" || link.value !== "https://quillolang.org") return "without a protocol the box is not type=url with the value";
if (!link.validity.valid) return "a whole address does not pass";
type(link, "quillolang.org"); await wait();
if (link.validity.valid) return "an address without a scheme passes a type=url box";
const repo = $("#url-input-ui-demo-repo");
if (repo.getAttribute("aria-invalid") !== "true" || !repo.closest(".ui-url-input").querySelector("[role=alert]")) return "error does not mark the box";
if (repo.closest(".ui-url-input").querySelector(".ui-url-input-protocol")?.textContent !== "https://github.com/") return "a longer protocol prefix is not shown";
