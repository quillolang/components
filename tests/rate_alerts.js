const rate = $("#rate-alerts-fx-rate");
const f = rate.closest(".ui-fxalert");
const items = () => [...f.querySelectorAll(".ui-fxalert-item")];
const item = (id) => f.querySelector(`.ui-fxalert-item[data-id="${id}"]`);
const msg = () => $("#rate-alerts-fx-msg").textContent.trim();
const add = f.querySelector(".ui-fxalert-add");
const note = () => $("#rate-alerts-demo-note").textContent;
const pick = (el, v) => { el.value = v; el.dispatchEvent(new Event("change", { bubbles: true })); };
if (items().length !== 2) return "the alerts given";
if (item("a1").querySelector(".ui-fxalert-state").textContent !== "57.5 pips away" || item("a1").classList.contains("ui-fxalert-hit")) return `a1: ${item("a1").querySelector(".ui-fxalert-state").textContent}`;
if (!item("a2").classList.contains("ui-fxalert-hit") || item("a2").querySelector(".ui-fxalert-state").textContent !== "Reached") return "an alert the rate passed is not marked reached";
if (!item("a1").querySelector(".ui-fxalert-what").textContent.includes("EUR/USD above 1.09000")) return `a1 reads ${item("a1").textContent}`;
if (rate.placeholder !== "1.08425" || !f.querySelector(".ui-fxalert-now").textContent.includes("EUR/USD is at 1.08425")) return "the rate now";
add.click(); await wait();
if (msg() !== "Enter the rate to be told at." || rate.getAttribute("aria-invalid") !== "true") return `empty: ${msg()}`;
type(rate, "abc"); add.click(); await wait();
if (msg() !== "“abc” is not a rate." || items().length !== 2) return `abc: ${msg()}`;
pick($("#rate-alerts-fx-pair"), "GBP/USD"); pick($("#rate-alerts-fx-direction"), "below"); await wait();
type(rate, "1.2700"); await wait();
if (msg() !== "") return `a fair rate warns: ${msg()}`;
add.click(); await wait();
if (items().length !== 3 || !item("a3") || !item("a3").classList.contains("ui-fxalert-below")) return "Add does not add";
if (item("a3").querySelector(".ui-fxalert-state").textContent !== "53.9 pips away") return `a3: ${item("a3").querySelector(".ui-fxalert-state").textContent}`;
if (rate.value !== "" || note() !== "Added a3: GBP/USD below 1.2700") return `after Add: "${rate.value}" ${note()}`;
if (!f.querySelector('[aria-live="polite"]').textContent.includes("Alert set: GBP/USD below 1.27000")) return "screen readers are not told";
type(rate, "1.27"); add.click(); await wait();
if (items().length !== 3 || msg() !== "There is already an alert for GBP/USD below 1.27000.") return `a second one: ${msg()}`;
type(rate, "1.28"); await wait();
if (!msg().startsWith("GBP/USD is already below 1.28000") || !$("#rate-alerts-fx-msg").classList.contains("ui-fxalert-warn")) return `a passed rate: ${msg()}`;
const rm = item("a1").querySelector(".ui-fxalert-remove");
if (rm.getAttribute("aria-label") !== "Remove the alert for EUR/USD above 1.09000" || rm.name !== "remove" || rm.value !== "a1") return "the remove button";
rm.click(); await wait();
if (item("a1") || items().length !== 2 || note() !== "Removed a1") return `remove: ${note()}`;
const d = $("#rate-alerts-desk-rate").closest("form");
if (d.getAttribute("action") !== "#alerts" || $("#rate-alerts-desk-pair").name !== "desk_pair" || $("#rate-alerts-desk-pair").options.length !== 2) return "the posted form";
if (!d.querySelector(".ui-fxalert-empty") || d.querySelector(".ui-fxalert-now")) return "no alerts, no rates";
