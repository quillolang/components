const docs = $("input[name=q]");
if (docs.type !== "search" || docs.form?.method !== "get") return "the first box is not a search input in a GET form";
if (docs.getAttribute("aria-label") !== "Search") return "a box with no label is not called Search";
const clear = docs.parentElement.querySelector(".ui-search-input-clear");
if (!clear) return "no clear button on a box with text";
clear.click(); await wait();
if (docs.value !== "") return `the clear button left: ${docs.value}`;
if (docs.parentElement.querySelector(".ui-search-input-clear")) return "the clear button stays on an empty box";
if (document.activeElement !== docs) return "clearing does not put the focus back in the box";
type(docs, "tabs"); await wait();
if (new FormData(docs.form).get("q") !== "tabs") return "the form does not send q";
const book = $("input[name=book]");
const note = () => book.closest(".demo-stack").querySelector(".demo-note").textContent;
type(book, "the"); await wait();
if (!note().startsWith("3 of 8")) return `on_input did not filter: ${note()}`;
if (!book.parentElement.querySelector(".ui-search-input-clear")) return "no clear button after typing";
key(book, "Escape"); await wait();
if (book.value !== "" || !note().startsWith("8 of 8")) return `Escape did not clear: "${book.value}", ${note()}`;
type(book, "war"); await wait();
key(book, "Enter"); await wait();
if (!book.closest(".demo-stack").textContent.includes("Enter pressed with “war”")) return "on_submit was not called on Enter";
if (!$("input[name=d]").disabled) return "disabled is not applied";
