const svgs = $$("svg.ui-spark");
if (svgs.length !== 9) return `expected 9 sparklines, found ${svgs.length}`;
if (/NaN|Infinity/.test($(".demo-stack").innerHTML)) return "a sparkline has NaN or Infinity in it";
const label = (i) => svgs[i].getAttribute("aria-label");
if (label(0) !== "Signups: 12 to 30") return `the label is "${label(0)}"`;
if (label(2) !== "Trend: 3 to 14") return `the default label is "${label(2)}"`;
const pts = (s) => s.querySelector(".ui-spark-line").getAttribute("d").slice(1).split(" L").map((p) => p.split(",").map(Number));
const line = pts(svgs[0]);
if (line.length !== 7) return `7 values made ${line.length} points`;
const ys = line.map((p) => p[1]);
if (Math.max(...ys) !== 29 || Math.min(...ys) !== 3) return `the line does not span the height with padding: ${ys}`;
if (line[0][0] !== 3 || line[6][0] !== 117) return `the line does not span the width: ${line[0][0]}..${line[6][0]}`;
const dot = svgs[0].querySelector(".ui-spark-dot");
if (Number(dot.getAttribute("cx")) !== 117 || Number(dot.getAttribute("cy")) !== 3) return "the last point's dot is misplaced";
if (!svgs[1].querySelector(".ui-spark-fill")?.getAttribute("d").endsWith("Z")) return "area has no fill";
if (svgs[3].querySelectorAll("rect").length !== 7) return "bar does not draw a bar per value";
if (label(5) !== "Empty: no data" || !svgs[5].querySelector(".ui-spark-none")) return "no values: no dashed line";
const one = pts(svgs[6]);
if (one.length !== 2 || one[0][1] !== 16 || one[1][1] !== 16 || label(6) !== "One value: 7") return `one value: ${JSON.stringify(one)} ${label(6)}`;
if (pts(svgs[7]).some((p) => p[1] !== 16)) return "equal values are not a flat line in the middle";
const net = [...svgs[8].querySelectorAll("rect")];
const zero = Math.max(...net.map((r) => Number(r.getAttribute("y")) + Number(r.getAttribute("height"))).filter((_, i) => [0, 2, 4].includes(i) === false));
const below = net.filter((_, i) => [0, 2, 4].includes(i));
if (below.some((r) => Math.abs(Number(r.getAttribute("y")) - zero) > 0.25)) return "negative bars do not hang from zero";
if (net.some((r) => Number(r.getAttribute("height")) <= 0)) return "a bar has no height";
