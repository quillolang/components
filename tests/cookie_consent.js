localStorage.removeItem("ui-cookies:demo-live"); localStorage.removeItem("ui-cookies:demo-short");
const banners = $$(".ui-cookie");
if (banners.length !== 2) return `expected 2 banners, found ${banners.length}`;
const [live, short] = banners;
if (live.getAttribute("role") !== "region" || live.getAttribute("aria-label") !== "Cookie consent") return "the banner is not a named region";
if (live.querySelector(".ui-cookie-title")?.textContent !== "Cookies" || live.querySelector("a")?.getAttribute("href") !== "#cookie_consent") return "the title or the policy link";
if (!live.classList.contains("ui-cookie-inline")) return "position inline";
const btns = (b) => [...b.querySelectorAll(".ui-cookie-row .ui-cookie-btn")].map((x) => x.textContent);
if (btns(live).join() !== "Settings,Only necessary,Accept all") return `the buttons: ${btns(live)}`;
const settings = live.querySelector(".ui-cookie-row .ui-cookie-btn");
if (settings.getAttribute("aria-expanded") !== "false" || live.querySelector(".ui-cookie-settings")) return "settings start open";
settings.click(); await wait();
if (settings.getAttribute("aria-expanded") !== "true") return "settings did not open";
const boxes = [...live.querySelectorAll(".ui-cookie-settings input[type=checkbox]")];
if (boxes.length !== 3 || !boxes[0].checked || !boxes[0].disabled || boxes[1].checked) return "the categories: necessary always on, the rest off";
boxes[1].click(); await wait();
[...live.querySelectorAll(".ui-cookie-settings .ui-cookie-btn")].at(-1).click(); await wait();
const note = () => $(".demo-note").textContent;
if (note() !== "Analytics on, marketing off.") return `saving the choices gave: ${note()}`;
if (live.isConnected && live.offsetParent) return "the banner did not go after saving";
const kept = JSON.parse(localStorage.getItem("ui-cookies:demo-live") || "null");
if (!kept || kept.necessary !== true || kept.analytics !== true || kept.marketing !== false) return `kept: ${JSON.stringify(kept)}`;
if (btns(short).join() !== "Choose,No thanks,OK") return `the short banner's words: ${btns(short)}`;
if (short.querySelector(".ui-cookie-title")) return "title={null} still shows a title";
short.querySelectorAll(".ui-cookie-row .ui-cookie-btn")[1].click(); await wait();
const kept2 = JSON.parse(localStorage.getItem("ui-cookies:demo-short") || "null");
if (!kept2 || kept2.necessary !== true || kept2.stats !== false) return `reject kept: ${JSON.stringify(kept2)}`;
if ($$(".ui-cookie").length !== 0) return "a banner is still there";
localStorage.removeItem("ui-cookies:demo-live"); localStorage.removeItem("ui-cookies:demo-short");
