const plain = $("#skeleton-table-demo-plain");
if (!plain || plain.getAttribute("aria-hidden") !== "true") return "without a label it is not aria-hidden";
if (plain.querySelectorAll("thead th").length !== 4) return "the header does not have 4 columns";
if (plain.querySelectorAll("tbody tr").length !== 5) return "rows={5}";
if (plain.querySelectorAll("tbody td").length !== 20) return "5 rows by 4 columns";
const bars = plain.querySelectorAll("tbody tr:first-child .ui-sktable-bar");
if (bars.length !== 4 || bars[0].offsetWidth === bars[1].offsetWidth) return "the bars do not vary by column";
const rows = plain.querySelectorAll("tbody tr");
if (rows[0].querySelector(".ui-sktable-bar").offsetWidth === rows[1].querySelector(".ui-sktable-bar").offsetWidth) return "the bars do not vary by row";
if (getComputedStyle(bars[0]).animationName !== "ui-sktable-shine") return "no shimmer";
const orders = $("#skeleton-table-demo-orders");
if (orders.getAttribute("role") !== "status" || orders.querySelector(".ui-sr")?.textContent !== "Loading orders") return "with a label it is not a status";
if (orders.querySelectorAll("tbody tr").length !== 4 || orders.querySelectorAll("thead th").length !== 5) return "rows={4} columns={5}";
if (!orders.classList.contains("ui-sktable-striped")) return "striped";
const small = $("#skeleton-table-demo-small");
if (small.querySelector("thead")) return "header={false} still has a header";
const cells = small.querySelectorAll("tbody tr:first-child td");
const w = [...cells].map((c) => c.querySelector(".ui-sktable-bar").offsetWidth / c.clientWidth);
if (!(w[0] > w[1] && w[1] > w[2])) return `widths={[80, 40, 25]} gave ${w.map((x) => Math.round(x * 100))}`;
if (!(small.querySelector("td").offsetHeight < plain.querySelector("td").offsetHeight)) return "size sm is not shorter";
