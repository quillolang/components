const box = $("#scroll-progress-demo-box");
const bar = box.querySelector(".ui-scrollprog");
if (!bar || bar.getAttribute("role") !== "progressbar" || bar.getAttribute("aria-label") !== "Article progress") return "the bar is not a named progressbar";
if (bar.getAttribute("aria-valuenow") !== "0" || bar.querySelector(".ui-scrollprog-fill").style.width !== "0%") return `it does not start empty: ${bar.getAttribute("aria-valuenow")}`;
if (getComputedStyle(bar).position !== "sticky" || bar.offsetHeight !== 4) return "in a box it is not sticky, 4px tall";
const room = box.scrollHeight - box.clientHeight;
box.scrollTop = Math.round(room / 2); box.dispatchEvent(new Event("scroll")); await wait(300);
const half = Number(bar.getAttribute("aria-valuenow"));
if (Math.abs(half - 50) > 2) return `half way down it says ${half}%`;
if (Math.abs(bar.querySelector(".ui-scrollprog-fill").getBoundingClientRect().width - bar.getBoundingClientRect().width / 2) > 3) return "the fill is not half the width";
if ($(".demo-note").textContent !== `Read ${half}% of the box.`) return `on_change: ${$(".demo-note").textContent}`;
if (Math.abs(bar.getBoundingClientRect().top - box.getBoundingClientRect().top) > 2) return "the bar did not stick to the box's top edge";
box.scrollTop = room; box.dispatchEvent(new Event("scroll")); await wait(300);
if (bar.getAttribute("aria-valuenow") !== "100" || bar.getAttribute("aria-valuetext") !== "100%") return "at the bottom it is not 100%";
box.scrollTop = 0; box.dispatchEvent(new Event("scroll")); await wait(300);
const page = $$(".ui-scrollprog").find((b) => !b.classList.contains("ui-scrollprog-inline"));
if (!page || getComputedStyle(page).position !== "fixed" || page.getBoundingClientRect().top !== 0) return "the page's bar is not fixed to the top";
const was = scrollY;
scrollTo(0, 0); await wait(300);
if (page.getAttribute("aria-valuenow") !== "0") return `at the top of the page it says ${page.getAttribute("aria-valuenow")}%`;
scrollTo(0, document.documentElement.scrollHeight); await wait(300);
if (page.getAttribute("aria-valuenow") !== "100") return `at the bottom of the page it says ${page.getAttribute("aria-valuenow")}%`;
scrollTo(0, was); await wait(300);
