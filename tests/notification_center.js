const panel = document.getElementById("nc-demo"), bell = $("button[popovertarget=nc-demo]"), note = () => $(".demo-note").textContent;
const badge = () => bell.querySelector(".ui-notification-center-badge")?.textContent, items = () => [...panel.querySelectorAll(".ui-notification-center-item")];
if (!bell || bell.getAttribute("aria-label") !== "Notifications, 3 unread" || badge() !== "3") return `the bell does not say 3 unread: ${bell?.getAttribute("aria-label")}`;
if (panel.matches(":popover-open") || panel.getAttribute("role") !== "dialog" || panel.getAttribute("aria-labelledby") !== "nc-demo-title") return "the panel is not a closed, named dialog";
bell.click(); await wait();
if (!panel.matches(":popover-open")) return "the bell does not open the panel";
if (items().length !== 4 || items().filter((i) => i.classList.contains("ui-notification-center-unread")).length !== 3) return "not 4 items, 3 unread";
if (!items()[0].textContent.includes(", unread") || items()[3].textContent.includes(", unread")) return "screen readers are not told which are unread";
if (items()[1].tagName !== "A" || items()[0].tagName !== "BUTTON") return "an item with an href is not a link";
const [all, un] = panel.querySelectorAll(".ui-notification-center-tab");
un.click(); await wait();
if (items().length !== 3 || un.getAttribute("aria-pressed") !== "true" || !un.textContent.includes("(3)")) return "Unread does not filter";
items()[0].click(); await wait();
if (note() !== "Read 1." || badge() !== "2" || bell.getAttribute("aria-label") !== "Notifications, 2 unread") return `opening one does not mark it read: ${note()}, badge ${badge()}`;
if (items().length !== 2) return "a read item stays under Unread";
all.click(); await wait();
if (items().length !== 4 || !items()[0].classList.contains("ui-notification-center-read")) return "All does not show them all, the first read";
items()[0].click(); await wait();
if (note() !== "Read 1.") return "marking a read one again called on_read";
const markAll = panel.querySelector(".ui-notification-center-head .ui-notification-center-link");
markAll.click(); await wait();
if (note() !== "Read all." || bell.querySelector(".ui-notification-center-badge") || bell.getAttribute("aria-label") !== "Notifications" || !markAll.disabled) return "Mark all as read does not clear the count";
un.click(); await wait();
if (panel.querySelector(".ui-notification-center-empty")?.textContent !== "You're all caught up.") return "nothing unread does not say so";
if (panel.querySelector(".ui-notification-center-foot a")?.getAttribute("href") !== "#notification_center") return "no See all link";
panel.hidePopover(); await wait();
const other = $("button[popovertarget=nc-demo-empty]");
if (other.querySelector(".ui-notification-center-badge") || other.getAttribute("aria-label") !== "Notifications") return "with nothing unread the bell has a count";
