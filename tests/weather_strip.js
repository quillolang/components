localStorage.removeItem("ui-weather-unit");
const w = $("#weather-strip-demo-lisbon");
if (!w || w.tagName !== "SECTION" || w.getAttribute("aria-label") !== "Weather in Lisbon") return "the strip is not a named section";
const big = () => w.querySelector(".ui-wx-temp").textContent;
const temps = (el) => [...el.querySelectorAll(".ui-wx-hours .ui-wx-t")].map((t) => t.textContent);
if (big() !== "Now 18° Celsius") return `now reads "${big()}"`;
if (w.querySelector(".ui-wx-place a")?.getAttribute("href") !== "#weather-lisbon") return "the place's link";
if (w.querySelector(".ui-wx-desc").textContent.replace(/\s+/g, " ").trim() !== "Partly cloudy · H 21° L 12° · Feels like 17°") return `desc: ${w.querySelector(".ui-wx-desc").textContent}`;
if (temps(w).join(" ") !== "18° 20° 19° 17° 16° 15° 13° 12°") return `hours: ${temps(w)}`;
const items = [...w.querySelectorAll(".ui-wx-hours li")];
if (items.length !== 8 || items[2].querySelector(".ui-wx-rain").textContent !== ", chance of rain 40%") return "the rain chance";
if (items[5].querySelector(".ui-wx-rain").checkVisibility({ visibilityProperty: true })) return "a 5% chance shows";
if (items[0].querySelectorAll("svg.ui-wx-icon").length !== 1 || !items[1].querySelector(".ui-wx-sun") || !items[4].querySelector(".ui-wx-bolt")) return "the sky pictures";
if (items[3].querySelector(".ui-sr").textContent !== "Rain, ") return "the condition in words for screen readers";
const [c, f] = w.querySelectorAll(".ui-wx-units button");
if (c.getAttribute("aria-pressed") !== "true" || f.getAttribute("aria-pressed") !== "false") return "°C is not picked to start";
f.click(); await wait();
if (f.getAttribute("aria-pressed") !== "true" || w.dataset.unit !== "F") return "°F is not picked";
if (big() !== "Now 64° Fahrenheit") return `in °F now reads "${big()}"`;
if (temps(w).join(" ") !== "64° 68° 66° 63° 61° 59° 55° 54°") return `hours in °F: ${temps(w)}`;
if (!w.querySelector(".ui-wx-desc").textContent.includes("H 70° L 54°")) return "high and low in °F";
if ($("#weather-strip-demo-note").textContent !== "on_unit gave F") return "on_unit";
if (localStorage.getItem("ui-weather-unit") !== null) return "a strip without remember kept the unit";
c.click(); await wait();
if (big() !== "Now 18° Celsius") return "back to °C";
const ch = $("#weather-strip-demo-chicago");
if (ch.dataset.unit !== "C" || ch.querySelector(".ui-wx-temp").textContent !== "Now -2° Celsius") return `show="C" from °F: ${ch.querySelector(".ui-wx-temp").textContent}`;
if (temps(ch)[0] !== "-1° -7°" || ch.querySelector(".ui-wx-desc b").textContent !== "Light snow") return `days: ${temps(ch)}`;
