const form = $("#form-demo-signup");
if (!form || form.tagName !== "FORM" || form.method !== "post" || !form.action.endsWith("/signup")) return "the form is not a <form method=post action=/signup>";
if (!form.classList.contains("ui-form") || form.classList.contains("ui-form-grid")) return "a stacked form carries the wrong classes";
const summary = form.querySelector(".ui-form-errors");
if (!summary || summary.getAttribute("role") !== "alert" || form.firstElementChild !== summary) return "the error summary is not an alert at the top";
if (!summary.querySelector("h3")?.textContent.includes("There is a problem")) return "the summary has no heading";
const links = [...summary.querySelectorAll("a")].map((a) => a.getAttribute("href"));
if (links.join() !== "#form-demo-email,#form-demo-terms") return `the summary links to ${links}`;
const submit = form.querySelector(".ui-form-submit button[type=submit]");
if (!submit || submit.textContent.trim() !== "Create account" || form.lastElementChild !== submit.parentElement) return "the submit row is not last with the submit button";
const cancel = form.querySelector(".ui-form-cancel");
if (!cancel || cancel.tagName !== "A" || cancel.textContent !== "Cancel") return "cancel_href gives no Cancel link";
if (!new FormData(form).has("name") || !new FormData(form).has("email")) return "the fields would not be sent";
const grid = $("#form-demo-grid");
if (!grid.classList.contains("ui-form-grid") || getComputedStyle(grid).gridTemplateColumns.split(" ").length !== 2) return "layout grid does not make two columns";
const bio = grid.querySelector(".ui-form-field-full");
if (!bio) return "full={true} does not mark the field";
const bioRect = bio.getBoundingClientRect(), gridRect = grid.getBoundingClientRect();
if (Math.abs(bioRect.width - gridRect.width) > 2) return "a full field does not take the whole row";
if (!grid.querySelector(".ui-form-submit-start") || grid.querySelector(".ui-form-submit button[type=reset]")?.textContent !== "Reset") return "actions and actions_align are not in the submit row";
const live = $("#form-demo-live");
if (!live.classList.contains("ui-form-inline")) return "layout inline is not marked";
type(live.querySelector("input[name=q]"), "Ada"); await wait();
live.querySelector("button[type=submit]").click(); await wait();
const note = live.closest(".demo-stack").querySelector(".demo-note").textContent;
if (!note.includes('"q":"Ada"') || !note.includes('"in":"People"')) return `on_submit did not get the fields: ${note}`;
