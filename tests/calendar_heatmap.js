const maps = $$("figure.ui-ch");
if (maps.length !== 2) return `expected 2 heatmaps, found ${maps.length}`;
const [year, runs] = maps;
const days = [...year.querySelectorAll("rect.ui-ch-day")];
if (days.length !== 365) return `a year shows ${days.length} days, not 365`;
if (days[0].dataset.date !== "2025-10-29" || days[364].dataset.date !== "2026-10-28") return `the days run ${days[0].dataset.date} to ${days[364].dataset.date}`;
// Weekdays down, weeks across: 2026-10-28 is a Wednesday, the fourth row with Sunday first.
const y = (r) => Number(r.getAttribute("y")), x = (r) => Number(r.getAttribute("x"));
if (y(days[364]) !== 18 + 3 * 13) return `Wednesday is at y=${y(days[364])}`;
const sunday = days.find((d) => d.dataset.date === "2026-10-25");
if (y(sunday) !== 18 || x(sunday) !== x(days[364])) return "the week does not start on Sunday in one column";
if (days.some((d, i) => i > 0 && x(d) < x(days[i - 1]))) return "the weeks are not in order";
const title = days.find((d) => d.dataset.date === "2026-03-14").querySelector("title").textContent;
if (!/^(No|\d+) commits? on Sat, Mar 14, 2026$/.test(title)) return `a day's title is "${title}"`;
const levels = new Set(days.map((d) => [...d.classList].find((c) => /^ui-ch-l\d$/.test(c))));
if (levels.size !== 5) return `the days use ${levels.size} shades, not 5`;
const fills = [0, 1, 2, 3, 4].map((l) => getComputedStyle(year.querySelector(`.ui-ch-l${l}`)).fill);
if (new Set(fills).size !== 5) return "the five shades are not distinct";
const months = [...year.querySelectorAll("text")].map((t) => t.textContent).filter((t) => !["Mon", "Wed", "Fri"].includes(t));
if (months.join() !== "Nov,Dec,Jan,Feb,Mar,Apr,May,Jun,Jul,Aug,Sep,Oct") return `the months read ${months}`;
const total = year.querySelector(".ui-ch-total").textContent;
const sum = days.reduce((s, d) => s + (Number(d.querySelector("title").textContent.split(" ")[0]) || 0), 0);
if (total !== `${sum.toLocaleString("en-US")} commits in the last year`) return `the total says "${total}", the days add up to ${sum}`;
const label = year.querySelector("svg").getAttribute("aria-label");
if (year.querySelector("svg").getAttribute("role") !== "img" || !label.startsWith("Commits: ") || !label.includes("busiest day")) return `aria-label: ${label}`;
const legend = year.querySelector(".ui-ch-legend");
if (!legend.textContent.includes("Less") || !legend.textContent.includes("More") || legend.querySelectorAll("rect").length !== 5) return "the legend is not Less, five shades, More";
const rdays = runs.querySelectorAll("rect.ui-ch-day");
if (rdays.length !== 120) return `Jul 1 to Oct 28 is ${rdays.length} days, not 120`;
if (rdays[0].dataset.date !== "2026-07-01" || y(rdays[0]) !== 18 + 2 * 13) return "week_start=monday does not put Wednesday third";
if (!runs.querySelector(".ui-ch-total").textContent.includes("km run from Jul 1, 2026 to Oct 28, 2026")) return `the range: ${runs.querySelector(".ui-ch-total").textContent}`;
if (runs.querySelector("text").textContent !== "Jul") return "the short range does not start with July";
if (getComputedStyle(runs.querySelector(".ui-ch-l4")).fill === fills[4]) return "tone=success is not applied";
const svg = year.querySelector("svg").getBoundingClientRect();
if (svg.width < 500) return "the year is drawn too small";
