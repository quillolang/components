const live = $$(".ui-perms")[0];
const table = live.querySelector("table");
if (table.getAttribute("aria-label") !== "Permissions") return "the table is not named";
const box = (r, p) => live.querySelector(`input[name=permissions][value="${r}:${p}"]`);
if (live.querySelectorAll("input[name=permissions]").length !== 15) return "3 roles by 5 permissions should be 15 boxes";
if (!box("owner", "read").checked || !box("owner", "read").disabled) return "a locked role's ticks are not shown disabled";
if (box("owner", "read").getAttribute("aria-label") !== "Read for Owner") return "a cell is not named";
if (!box("editor", "write").checked || box("viewer", "write").checked) return "granted does not tick the right boxes";
const groups = [...live.querySelectorAll("tr.ui-perms-group th")].map((t) => t.textContent);
if (groups.join() !== "Content,Team,Billing") return `the groups: ${groups}`;
if (live.querySelector("tbody th[scope=row] .ui-perms-label").textContent.trim() !== "Read" || !live.querySelector(".ui-perms-hint")?.textContent.includes("Create and edit")) return "a permission's label or hint is missing";
const heads = [...live.querySelectorAll("thead th")];
if (!heads[1].querySelector(".ui-perms-locked") || heads[1].querySelector("input")) return "the locked role has a column box";
const edAll = heads[2].querySelector("input[type=checkbox]");
if (!edAll || edAll.getAttribute("aria-label") !== "All permissions for Editor" || edAll.checked || !edAll.indeterminate) return "the editor's column box is not indeterminate at 3 of 5";
if (!heads[2].textContent.includes("3 of 5") || !heads[1].textContent.includes("5 of 5")) return "the counts are wrong";
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
box("viewer", "write").click(); await wait();
if (!box("viewer", "write").checked || note() !== "Last change: viewer gets write.") return `ticking: ${note()}`;
box("viewer", "write").click(); await wait();
if (box("viewer", "write").checked || note() !== "Last change: viewer loses write.") return `clearing: ${note()}`;
edAll.click(); await wait();
if (!["read", "write", "publish", "invite", "billing"].every((p) => box("editor", p).checked)) return "the column box did not tick all";
if (!heads[2].textContent.includes("5 of 5") || !heads[2].querySelector("input").checked) return "ticking all does not update the count";
edAll.click(); await wait();
if (["read", "write", "publish", "invite", "billing"].some((p) => box("editor", p).checked) || !heads[2].textContent.includes("0 of 5")) return "the column box did not clear all";
const form = $("#permissions-matrix-demo-form");
const data = new FormData(form);
if (data.getAll("grant").join() !== "owner:read" || data.has("permissions")) return `the form sends ${[...data.entries()]}`;
if (form.querySelector("thead input[type=checkbox]")?.getAttribute("form") !== "ui-perms-none") return "the column boxes belong to the form";
