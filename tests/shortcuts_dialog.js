const dlg = $("dialog.ui-shortcuts-dialog"), trig = $("button.ui-btn");
const rows = () => [...dlg.querySelectorAll(".ui-shortcuts-dialog-row")], heads = () => [...dlg.querySelectorAll("h3")].map((h) => h.textContent);
if (!dlg || dlg.open || dlg.getAttribute("aria-label") !== "Keyboard shortcuts") return "not a closed, named dialog";
if (trig.textContent !== "Shortcuts" || trig.getAttribute("aria-keyshortcuts") !== "?") return "the trigger does not say ? opens it";
const box = document.createElement("input"); document.body.append(box); box.focus();
box.dispatchEvent(new KeyboardEvent("keydown", { key: "?", bubbles: true, cancelable: true })); await wait();
box.remove();
if (dlg.open) return "? in a text box opened it";
document.body.dispatchEvent(new KeyboardEvent("keydown", { key: "?", bubbles: true, cancelable: true })); await wait();
if (!dlg.open) return "? does not open it";
if (heads().join() !== "General,Inbox,Editing" || rows().length !== 11) return `groups: ${heads()}, rows ${rows().length}`;
const pal = rows()[0];
if (pal.querySelector("dt").textContent !== "Open the command palette" || [...pal.querySelectorAll("kbd")].map((k) => k.textContent).join() !== "Ctrl,K") return "Ctrl K is not drawn as two keys";
if (pal.querySelector("dd").getAttribute("aria-label") !== "Ctrl+K") return "screen readers do not get Ctrl+K";
const seq = rows().find((r) => r.textContent.includes("Go to the inbox"));
if (seq.querySelector("dd").getAttribute("aria-label") !== "G, then I" || !seq.querySelector("dd").textContent.includes("then")) return "G then I is not a sequence";
const find = dlg.querySelector("input[type=search]");
if (document.activeElement !== find || find.getAttribute("aria-label") !== "Filter shortcuts") return "the filter box is not focused";
type(find, "ctrl"); await wait();
if (heads().join() !== "General,Editing" || rows().length !== 5) return `"ctrl" leaves ${heads()} / ${rows().length}`;
type(find, "archive"); await wait();
if (rows().length !== 1 || rows()[0].querySelector("dt").textContent !== "Archive") return "filtering by label";
type(find, "zzz"); await wait();
if (rows().length || dlg.querySelector(".ui-shortcuts-dialog-empty")?.textContent !== "No shortcuts match.") return "no match does not say so";
dlg.querySelector(".ui-shortcuts-dialog-x").click(); await wait();
if (dlg.open) return "the close button does not close it";
trig.click(); await wait();
if (!dlg.open || find.value !== "" || rows().length !== 11) return "the button does not open it afresh";
dlg.close();
