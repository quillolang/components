const plans = $$("input[name=rc-demo-plan]");
if (plans.length !== 3 || plans.some((r) => r.type !== "radio")) return "the plans are not 3 radios";
if (plans.find((r) => r.checked)?.value !== "pro") return "value did not choose Pro";
if (!plans[2].disabled) return "a disabled option is not disabled";
if (plans.some((r) => r.labels.length !== 1)) return "every card needs to be its radio's label";
const fs = plans[0].closest("fieldset");
if (fs.getAttribute("role") !== "radiogroup" || !fs.querySelector("legend")?.textContent.includes("Plan")) return "the group is not a radiogroup with a legend";
if (!document.getElementById(fs.getAttribute("aria-describedby"))?.textContent.includes("Change it")) return "the hint is not tied to the group";
const pro = plans[1].closest("label"), hobby = plans[0].closest("label");
if (pro.querySelector(".ui-radio-cards-meta")?.textContent !== "$12/mo" || !pro.querySelector(".ui-radio-cards-desc")?.textContent.includes("Unlimited")) return "meta and description are not on the card";
if (getComputedStyle(pro).borderTopColor === getComputedStyle(hobby).borderTopColor) return "the chosen card does not stand out";
hobby.click(); await wait();
if (!plans[0].checked || plans[1].checked) return "clicking a card does not choose it";
if (getComputedStyle(hobby).borderTopColor === getComputedStyle(pro).borderTopColor) return "the mark did not move to the card clicked";
const sizes = $$("input[name=rc-demo-size]");
const note = () => sizes[0].closest(".demo-stack").querySelector(".demo-note").textContent;
if (sizes.find((r) => r.checked)?.value !== "m" || note() !== "Size M it is.") return "the live group does not start on M";
if (getComputedStyle(sizes[0].closest(".ui-radio-cards-list")).gridTemplateColumns.split(" ").length !== 4) return "columns={4} does not make four columns";
sizes[3].closest("label").click(); await wait();
if (note() !== "Size XL it is.") return `on_change did not update the note: ${note()}`;
const ship = $$("input[name=rc-demo-ship]");
const sfs = ship[0].closest("fieldset");
if (!ship[0].required || sfs.getAttribute("aria-invalid") !== "true") return "required and error are not on the group";
if (!document.getElementById(sfs.getAttribute("aria-describedby"))?.textContent.includes("Choose how")) return "the error is not tied to the group";
if (sfs.querySelectorAll(".ui-radio-cards-icon").length !== 2) return "icons are not shown";
