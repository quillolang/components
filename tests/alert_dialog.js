const dlg = $("#alert-demo-done"), trig = $$("button.ui-btn").find((b) => b.textContent === "Export done"), note = () => $(".demo-note").textContent;
if (!dlg || dlg.tagName !== "DIALOG" || dlg.getAttribute("role") !== "alertdialog") return "not an alertdialog <dialog>";
if (dlg.getAttribute("aria-labelledby") !== "alert-demo-done-title" || document.getElementById("alert-demo-done-title").textContent !== "Export done") return "it is not named by its title";
if (dlg.getAttribute("aria-describedby") !== "alert-demo-done-body" || !document.getElementById("alert-demo-done-body").textContent.includes("on its way")) return "it is not described by its message";
if (!trig || trig.getAttribute("commandfor") !== "alert-demo-done" || trig.getAttribute("command") !== "show-modal") return "the trigger does not open it with command=show-modal";
if (dlg.open) return "it starts open";
trig.click(); await wait();
if (!dlg.open) return "the trigger does not open it (the browser may not support command=show-modal)";
const ok = dlg.querySelector("form[method=dialog] button");
if (!ok || ok.textContent !== "OK" || document.activeElement !== ok) return "OK is not a dialog form button with the focus";
if (!dlg.classList.contains("ui-alert-dialog-success")) return "tone is not on the dialog";
ok.click(); await wait();
if (dlg.open) return "OK does not close it";
const failed = $("#alert-demo-failed");
if (failed.querySelector("form button").textContent !== "Try again" || !failed.classList.contains("ui-alert-dialog-danger")) return "ok and tone are not taken";
const live = $("#alert-demo-live");
$$("button.ui-btn").find((b) => b.textContent === "Session ended").click(); await wait();
if (!live.open) return "the live one does not open";
live.querySelector("form button").click(); await wait();
if (live.open || note() !== "Closed 1 time.") return `on_close did not reach the note: ${note()}`;
