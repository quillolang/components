const box = $("#email-input-ei-demo-email");
const host = box.closest(".ui-email-input");
const note = () => box.closest(".demo-stack").querySelector(".demo-note").textContent;
const leave = () => { box.blur(); box.dispatchEvent(new FocusEvent("blur")); };
if (box.type !== "email" || box.name !== "ei-demo-email" || !box.required) return "the box is not a required email input named for the form";
if (!box.labels[0]?.textContent.includes("Email")) return "the label is not tied to the box";
type(box, "ada@gmial.com"); await wait();
if (host.querySelector(".ui-email-input-suggest")) return "a suggestion shows while still typing";
if (note() !== "The form sends ada@gmial.com.") return `on_change: ${note()}`;
leave(); await wait();
const sug = host.querySelector(".ui-email-input-suggest");
if (!sug || sug.getAttribute("role") !== "status" || sug.querySelector(".ui-email-input-take")?.textContent !== "ada@gmail.com") return `gmial.com got no suggestion: ${sug?.textContent}`;
sug.querySelector(".ui-email-input-take").click(); await wait();
if (box.value !== "ada@gmail.com" || note() !== "The form sends ada@gmail.com." || host.querySelector(".ui-email-input-suggest")) return `taking the suggestion: "${box.value}", ${note()}`;
if (document.activeElement !== box) return "taking the suggestion does not put the focus back";
type(box, "ada@gmail.com"); leave(); await wait();
if (host.querySelector(".ui-email-input-suggest")) return "a right domain gets a suggestion";
type(box, "ada@outlook.con"); leave(); await wait();
if (host.querySelector(".ui-email-input-take")?.textContent !== "ada@outlook.com") return ".con is not fixed to .com";
type(box, "ada@mycompany.con"); leave(); await wait();
if (host.querySelector(".ui-email-input-take")?.textContent !== "ada@mycompany.com") return "an unknown domain ending .con is not fixed";
type(box, "ada@yaho.com"); leave(); await wait();
if (host.querySelector(".ui-email-input-take")?.textContent !== "ada@yahoo.com") return "a letter dropped is not caught";
host.querySelector(".ui-email-input-keep").click(); await wait();
if (host.querySelector(".ui-email-input-suggest") || box.value !== "ada@yaho.com") return "Keep it does not dismiss the suggestion";
leave(); await wait();
if (host.querySelector(".ui-email-input-suggest")) return "a dismissed suggestion comes back";
type(box, "ada@zz.io"); leave(); await wait();
if (host.querySelector(".ui-email-input-suggest")) return "a short unknown domain is matched to a service";
const work = $("#email-input-ei-demo-work");
leave(); work.focus(); work.blur(); work.dispatchEvent(new FocusEvent("blur")); await wait();
if (work.closest(".ui-email-input").querySelector(".ui-email-input-take")?.textContent !== "grace@example.com") return "domains={[...]} is not used for suggestions";
const bad = $("#email-input-ei-demo-bad");
if (bad.getAttribute("aria-invalid") !== "true" || !bad.closest(".ui-email-input").querySelector("[role=alert]")) return "error does not mark the box";
