if (document.documentElement.scrollWidth > innerWidth) return "widens the page";
const chart = $("figure.ui-parcoords");
if (!chart) return "no parallel coordinates chart";
if (/NaN|Infinity|undefined/.test(chart.innerHTML)) return "the chart has NaN, Infinity or undefined in it";
if (chart.getAttribute("aria-label") !== "Cars compared") return "the label does not name the chart";
const axes = [...chart.querySelectorAll(".ui-parcoords-axis")];
if (axes.length !== 4) return `4 measures made ${axes.length} axes`;
if (axes.map((a) => a.querySelector(".ui-parcoords-name").textContent).join() !== "Price,Power,Weight,Economy") return "the axes are not named";
const ticks = (a) => [...a.querySelectorAll(".ui-parcoords-tick")].map((t) => t.textContent).join();
if (ticks(axes[0]) !== "$0,$25k,$50k,$75k,$100k,$125k") return `Price's ticks: ${ticks(axes[0])}`;
if (ticks(axes[1]) !== "100,200,300,400") return `Power's ticks: ${ticks(axes[1])}`;
if (ticks(axes[3]) !== "0,10,20,30,40") return `zero={true} on Economy: ${ticks(axes[3])}`;
const plot = chart.querySelector(".ui-parcoords-plot").getBoundingClientRect();
if (Math.abs(axes[0].getBoundingClientRect().left - plot.left) > 1 || Math.abs(axes[3].getBoundingClientRect().left - plot.right) > 1.5) return "the axes do not span the plot";
const lines = [...chart.querySelectorAll(".ui-parcoords-line")];
if (lines.length !== 9) return `9 records made ${lines.length} lines`;
// The Civic: $24,000 of 0-125k, 158 hp of 100-400, 1,280 kg of 1k-2.5k, 36 mpg of 0-40.
const civic = lines[0].getAttribute("d");
if (civic !== "M0,80.8 L33.33,80.67 L66.67,81.33 L100,10") return `the Civic's line: ${civic}`;
const m3 = lines.find((l) => l.querySelector("title").textContent.startsWith("Model 3"));
if ((m3.getAttribute("d").match(/L/g) || []).length !== 2) return "a missing value does not end the line";
if (m3.querySelector("title").textContent !== "Model 3 (USA): Price $42,000, Power 283 hp, Weight 1,760 kg, Economy —") return `title: ${m3.querySelector("title").textContent}`;
const colors = new Set(lines.map((l) => getComputedStyle(l).stroke));
if (colors.size !== 3) return `three origins made ${colors.size} colours`;
if (chart.querySelectorAll(".ui-parcoords-legend li").length !== 3) return "no legend of the groups";
if (getComputedStyle(lines[0]).pointerEvents !== "visiblestroke" && getComputedStyle(lines[0]).pointerEvents !== "visibleStroke") return "lines cannot be hovered";
const rows = [...chart.querySelectorAll("tbody tr")];
if (rows.length !== 9 || rows[0].textContent !== "CivicJapan$24,000158 hp1,280 kg36 mpg") return `the table: ${rows[0].textContent}`;
if (!chart.querySelector(".ui-parcoords-wrap").hasAttribute("aria-hidden")) return "the drawing is not hidden from screen readers";
