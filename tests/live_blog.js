const b = $("#live-blog-demo");
if (!b || b.tagName !== "SECTION" || b.getAttribute("aria-label") !== "Election night live") return "the blog is not a named section";
const times = () => [...b.querySelectorAll(".ui-lvb-feed .ui-lvb-time")].map((t) => t.textContent);
if (b.querySelector(".ui-lvb-status").textContent !== "Live" || b.querySelector("[data-count]").textContent !== "11 updates") return "the head";
const pin = b.querySelector(".ui-lvb-pinned");
if (!pin || pin.querySelector(".ui-lvb-title").textContent !== "What we know so far" || pin.querySelectorAll(":scope > p:not(.ui-lvb-top)").length !== 2) return "the pinned entry and its paragraphs";
if (pin.compareDocumentPosition(b.querySelector(".ui-lvb-feed")) !== Node.DOCUMENT_POSITION_FOLLOWING) return "the pinned entry is not above the feed";
if (times().join() !== "21:48,21:40,21:31,21:15,20:58") return `the first page: ${times()}`;
const k = b.querySelector(".ui-lvb-feed .ui-lvb-entry");
if (!k.classList.contains("ui-lvb-key") || k.querySelector(".ui-lvb-flag-key")?.textContent !== "Key event" || k.querySelector(".ui-lvb-tag").textContent !== "Senate") return "the key event's marks";
if (k.querySelector("time").getAttribute("datetime") !== "2026-11-03T21:48:00-05:00" || k.querySelector(".ui-lvb-by").textContent !== "Ada Lovelace, decision desk") return "time and author";
const more = () => b.querySelector(".ui-lvb-more");
if (more()?.textContent.trim() !== "Show 5 more updates") return `more: ${more()?.textContent}`;
more().click(); await wait();
if (times().length !== 10 || more()?.textContent.trim() !== "Show 1 more update") return `after one more page: ${times().length}, ${more()?.textContent}`;
more().click(); await wait();
if (times().length !== 11 || more()) return "the last page";
const [all, keyed] = b.querySelectorAll(".ui-lvb-seg button");
if (all.getAttribute("aria-pressed") !== "true" || keyed.getAttribute("aria-pressed") !== "false") return "aria-pressed to start";
keyed.click(); await wait();
if (times().join() !== "21:48,21:15,20:00" || keyed.getAttribute("aria-pressed") !== "true") return `key events only: ${times()}`;
const order = b.querySelector(".ui-lvb-order");
order.click(); await wait();
if (times().join() !== "20:00,21:15,21:48" || !order.textContent.includes("Oldest first")) return `oldest first: ${times()}`;
all.click(); await wait();
if (times()[0] !== "19:00" || times().length !== 11) return `all, oldest first: ${times()}`;
order.click(); await wait();
if (times()[0] !== "21:48") return "newest first again";
// The key events' links: they show the entry, on a later page too, and take the focus to it.
const links = [...b.querySelectorAll(".ui-lvb-keys a")];
if (links.map((a) => a.getAttribute("href")).join() !== "#live-blog-demo-u11,#live-blog-demo-u8,#live-blog-demo-u4") return "the key event links";
if (links[0].textContent !== "21:48Ohio Senate race called") return `a key link reads ${links[0].textContent}`;
links[2].click(); await wait(400);
const u4 = document.getElementById("live-blog-demo-u4");
if (!u4 || document.activeElement !== u4) return "the key event link does not take the focus to its entry";
