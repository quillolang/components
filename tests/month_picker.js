const btn = $("#month-picker-mp-demo-period");
const host = btn.closest(".ui-month-picker");
const pop = host.querySelector("[role=dialog]");
const hidden = $("input[type=hidden][name=mp-demo-period]");
const year = () => pop.querySelector("h2").textContent.trim();
const focused = () => document.activeElement?.getAttribute("aria-label");
if (btn.textContent.trim() !== "March 2026" || hidden.value !== "2026-03") return `it starts as ${btn.textContent.trim()} / ${hidden.value}`;
if (btn.getAttribute("aria-haspopup") !== "dialog" || btn.getAttribute("aria-expanded") !== "false" || !pop.hidden) return "the button does not say it opens a dialog, or it starts open";
if (!btn.getAttribute("aria-labelledby").includes(`${btn.id}-label`)) return "the button is not named by the label";
btn.click(); await wait();
if (pop.hidden || btn.getAttribute("aria-expanded") !== "true" || year() !== "2026") return "the button did not open the grid on 2026";
if (focused() !== "March 2026" || document.activeElement.getAttribute("aria-selected") !== "true") return `the focus is on ${focused()}`;
if (pop.querySelectorAll("[role=gridcell]").length !== 12 || pop.querySelector("[aria-current=date]")?.getAttribute("aria-label") !== "October 2026") return "twelve months with this one marked are not shown";
const k = async (name) => { key(document.activeElement, name); await wait(80); };
await k("ArrowRight"); if (focused() !== "April 2026") return `ArrowRight: ${focused()}`;
await k("ArrowDown"); if (focused() !== "August 2026") return `ArrowDown: ${focused()}`;
await k("PageDown"); if (focused() !== "August 2027" || year() !== "2027") return `PageDown: ${focused()} in ${year()}`;
await k("Home"); if (focused() !== "January 2027") return `Home: ${focused()}`;
await k("ArrowLeft"); if (focused() !== "December 2026" || year() !== "2026") return `ArrowLeft into the year before: ${focused()}`;
await k("Enter");
if (hidden.value !== "2026-12" || btn.textContent.trim() !== "December 2026" || !pop.hidden || document.activeElement !== btn) return `Enter picked ${hidden.value}`;
btn.click(); await wait();
pop.querySelector("[aria-label='Next year']").click(); await wait();
if (year() !== "2027") return "Next year did not turn the year";
key(document.activeElement, "Escape"); await wait();
if (!pop.hidden || document.activeElement !== btn) return "Escape did not close and go back to the button";
const live = $("input[type=hidden][name=mp-demo-start]").closest(".ui-month-picker");
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
if (live.querySelector(".ui-month-picker-trigger") || live.querySelector("[role=group]")?.hidden) return "inline={true} does not show the grid in the page";
const cell = (l) => live.querySelector(`[aria-label='${l}']`);
if (cell("March 2026")?.getAttribute("aria-disabled") !== "true" || cell("April 2026")?.getAttribute("aria-disabled") === "true") return "earliest is not kept";
cell("March 2026").click(); await wait();
if (note() !== "No month picked.") return "a month before earliest was picked";
cell("November 2026").click(); await wait();
if (note() !== "Starting 2026-11.") return `on_change: ${note()}`;
if (live.querySelector("[aria-label='Previous year']").getAttribute("aria-disabled") !== "true") return "it can go to a year before earliest";
const exp = $("#month-picker-mp-demo-exp");
if (exp.getAttribute("aria-invalid") !== "true" || !exp.textContent.includes("Choose a month")) return "error or placeholder is not shown";
