const [rename, fromState] = $$("dialog.ui-prompt-dialog"), note = () => $(".demo-note").textContent;
const trig = $$("button.ui-btn").find((b) => b.textContent === "Rename"), stateBtn = $$("button.ui-btn").find((b) => b.textContent.startsWith("Reject"));
if (!rename || rename.getAttribute("aria-label") !== "Rename file" || rename.open) return "the dialog is not named, closed, to start";
trig.click(); await wait();
if (!rename.open) return "the trigger does not open it";
const input = rename.querySelector("input[name=value]");
if (document.activeElement !== input || input.value !== "notes.txt" || !input.required) return "the field does not start focused with the value, required";
if (rename.querySelector("label span").textContent !== "New name" || !rename.textContent.includes("Keep the ending.")) return "label or hint missing";
if (input.id !== "prompt-demo-name" || document.getElementById(input.getAttribute("aria-describedby"))?.textContent !== "Keep the ending.") return "the hint does not describe the field";
if (rename.querySelector("form").getAttribute("method") !== "dialog") return "not a dialog form";
rename.querySelector("button[type=button]").click(); await wait();
if (rename.open || !note().includes("Rename cancelled.")) return `Cancel: ${note()}`;
trig.click(); await wait();
type(input, "notes.md");
rename.querySelector("form").requestSubmit(); await wait();
if (rename.open || !note().startsWith("File: notes.md. Renamed to notes.md.")) return `submitting: ${note()}`;
trig.click(); await wait();
type(input, "");
rename.querySelector("form").requestSubmit(); await wait();
if (!rename.open) return "an empty required value submitted";
rename.close(); await wait();
stateBtn.click(); await wait();
if (!fromState.open) return "open={state} does not open it";
const r = fromState.querySelector("input");
if (r.placeholder !== "Tell them why" || !fromState.textContent.includes("goes to the person")) return "placeholder or children missing";
type(r, "Too late"); fromState.querySelector("form").requestSubmit(); await wait();
if (fromState.open || !note().includes("Rejected: Too late")) return `on_submit from state: ${note()}`;
stateBtn.click(); await wait();
if (!fromState.open) return "on_submit did not set the state back, so it cannot open again";
fromState.close(); await wait();
if (!note().includes("Not rejected.")) return "closing without an answer does not call on_cancel";
