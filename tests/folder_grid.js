const grid = $("#fg-drive");
const tiles = () => [...grid.querySelectorAll("[role=option]")];
const sel = () => tiles().filter((t) => t.getAttribute("aria-selected") === "true").map((t) => t.querySelector(".ui-folder-grid-name").textContent);
const note = () => grid.closest(".demo-stack").querySelector(".demo-note").textContent;
const posted = () => [...grid.parentElement.querySelectorAll("input[type=hidden][name=picked]")].map((i) => i.value).join();
if (grid.getAttribute("role") !== "listbox" || grid.getAttribute("aria-label") !== "My drive" || grid.getAttribute("aria-multiselectable") !== "true") return "not a named multi-select listbox";
if (tiles().length !== 8) return "8 tiles";
if (!tiles()[0].querySelector(".ui-folder-grid-folder") || tiles()[0].querySelector(".ui-folder-grid-meta").textContent !== "12 items" || tiles()[1].querySelector(".ui-folder-grid-meta").textContent !== "1 item" || tiles()[2].querySelector(".ui-folder-grid-meta").textContent !== "Folder") return "folders";
const pdf = tiles()[3].querySelector(".ui-folder-grid-file");
if (pdf.textContent !== "PDF" || !pdf.classList.contains("ui-folder-grid-k-pdf") || tiles()[3].querySelector(".ui-folder-grid-meta").textContent !== "2.4 MB") return "a file's icon and size";
if (sel().join() !== "Q3 report.pdf" || posted() !== "d1") return `selected at first: ${sel()} / ${posted()}`;
if (tiles().filter((t) => t.tabIndex === 0).length !== 1) return "more than one Tab stop";
tiles()[1].click(); await wait();
if (sel().join() !== "Photos" || note() !== "Picked: f2. Nothing opened.") return `a click picks one: ${sel()} / ${note()}`;
tiles()[4].dispatchEvent(new MouseEvent("click", { bubbles: true, shiftKey: true })); await wait();
if (sel().join() !== "Photos,Archive,Q3 report.pdf,Budget 2027.xlsx") return `Shift picks a range: ${sel()}`;
tiles()[2].dispatchEvent(new MouseEvent("click", { bubbles: true, metaKey: true })); await wait();
if (sel().includes("Archive") || sel().length !== 3) return `⌘ takes one away: ${sel()}`;
tiles()[7].querySelector(".ui-folder-grid-check").click(); await wait();
if (!sel().includes("notes.md") || sel().length !== 4) return "the check adds one";
if (posted() !== "f2,d1,d2,d5") return `hidden inputs: ${posted()}`;
const t0 = tiles()[0];
t0.focus(); const f0 = tiles().indexOf(document.activeElement); key(t0, "Escape"); await wait();
if (f0 !== 0) return `focus() did not focus tile 0: ${f0}`;
if (sel().length !== 0 || !note().startsWith("Picked: none")) return "Escape picks none";
key(document.activeElement, "ArrowRight"); await wait();
if (document.activeElement !== tiles()[1] || tiles()[1].tabIndex !== 0) return `ArrowRight moves the focus: active ${tiles().indexOf(document.activeElement)} ${document.activeElement.tagName}.${document.activeElement.className}, tab0 ${tiles().findIndex((t) => t.tabIndex === 0)}`;
const cols = tiles().filter((t) => t.offsetTop === tiles()[0].offsetTop).length;
if (cols < 2 || cols > 7) return `the demo grid should have 2 to 7 columns here, has ${cols}`;
key(document.activeElement, "ArrowLeft"); await wait();
key(document.activeElement, "ArrowDown"); await wait();
if (document.activeElement !== tiles()[cols]) return `ArrowDown goes a row down (${cols} columns)`;
key(document.activeElement, "ArrowDown"); await wait();
if (cols + cols >= 8 && document.activeElement !== tiles()[cols]) return "ArrowDown on the last row stays";
key(document.activeElement, "ArrowUp"); await wait();
if (cols + cols >= 8 && document.activeElement !== tiles()[0]) return "ArrowUp goes a row up";
key(document.activeElement, "ArrowDown"); await wait();
key(document.activeElement, " "); await wait();
if (sel().join() !== tiles()[cols].querySelector(".ui-folder-grid-name").textContent) return `Space picks: ${sel()}`;
key(document.activeElement, "End"); await wait();
if (document.activeElement !== tiles()[7]) return "End";
key(document.activeElement, "Home"); await wait();
if (document.activeElement !== tiles()[0]) return "Home";
document.activeElement.dispatchEvent(new KeyboardEvent("keydown", { key: "a", ctrlKey: true, bubbles: true, cancelable: true })); await wait();
if (sel().length !== 8) return "Ctrl+A picks all";
key(document.activeElement, "Enter"); await wait();
if (!note().endsWith("Opened Contracts.")) return `Enter opens: ${note()}`;
tiles()[5].dispatchEvent(new MouseEvent("dblclick", { bubbles: true })); await wait();
if (!note().endsWith("Opened Team offsite.jpg.")) return "double-click opens";
const single = $("#fg-single");
if (single.getAttribute("aria-multiselectable") !== "false") return "multiple={false}";
const st = [...single.querySelectorAll("[role=option]")];
st[0].click(); await wait();
st[1].dispatchEvent(new MouseEvent("click", { bubbles: true, metaKey: true })); await wait();
if (st.filter((t) => t.getAttribute("aria-selected") === "true").length !== 1) return "a single grid picks one only";
if ($("#fg-empty") || !$$(".ui-folder-grid-empty").some((e) => e.textContent === "The trash is empty.")) return "an empty grid";
