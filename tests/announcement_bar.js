const bars = $$("[role=region].ui-announce");
if (bars.length !== 4) return `expected 4 bars, found ${bars.length}`;
const [news, pricing, maint, ready] = bars;
if (news.getAttribute("aria-label") !== "Announcement") return "a bar is not a named region";
if (news.getBoundingClientRect().height > 44) return "the bar is not slim";
const link = news.querySelector("a.ui-announce-link");
if (!link || link.getAttribute("href") !== "#announcement_bar" || link.textContent !== "Read the post →") return `the link: ${link?.outerHTML}`;
if (pricing.querySelector(".ui-announce-badge")?.textContent !== "New" || news.querySelector(".ui-announce-badge")) return "the badge is wrong";
if (!pricing.classList.contains("ui-announce-neutral") || getComputedStyle(pricing).backgroundColor === getComputedStyle(news).backgroundColor) return "tones look the same";
if (maint.querySelector(".ui-announce-x")) return "dismissable={false} still has a close button";
const x = news.querySelector(".ui-announce-x");
if (!x || x.getAttribute("aria-label") !== "Dismiss") return "the close button has no name";
x.click(); await wait();
if (news.isConnected && news.offsetParent) return "dismissing does not hide it";
if ($$("[role=region].ui-announce").length !== 3) return "the other bars went too";
if (localStorage.getItem("ui-announcement:demo-v2") !== "1") return "remember does not keep the dismissal";
localStorage.removeItem("ui-announcement:demo-v2");
const note = pricing.closest(".demo-stack").querySelector(".demo-note");
pricing.querySelector(".ui-announce-x").click(); await wait();
if (!note.textContent.includes("on_dismiss was called")) return "on_dismiss did not reach the note";
