const lo = $("#min-max-input-demo-price-min"), hi = $("#min-max-input-demo-price-max");
if (!lo || !hi || lo.type !== "number" || lo.name !== "price_min" || hi.name !== "price_max") return "the boxes are not number inputs named _min and _max";
if (lo.value !== "10" || hi.value !== "200") return `low and high did not fill the boxes: ${lo.value} / ${hi.value}`;
if (lo.min !== "0" || hi.max !== "1000" || lo.step !== "5") return "the bounds and step do not reach the boxes";
if (lo.getAttribute("aria-label") !== "Minimum (€)" || hi.getAttribute("aria-label") !== "Maximum (€)") return `the boxes' names: ${lo.getAttribute("aria-label")}`;
const fs = lo.closest("fieldset");
if (fs.querySelector("legend")?.textContent.trim() !== "Price") return "the label is not the legend";
if (!document.getElementById(lo.getAttribute("aria-describedby"))?.textContent.includes("in order")) return "the hint is not tied to the boxes";
type(lo, "500"); await wait();
if (hi.value !== "500") return `a minimum above the maximum did not raise the maximum: ${hi.value}`;
type(hi, "40"); await wait();
if (lo.value !== "40" || hi.value !== "40") return `a maximum below the minimum did not lower the minimum: ${lo.value} / ${hi.value}`;
type(hi, "5000"); await wait();
if (hi.value !== "1000") return `the maximum was not kept inside the bound: ${hi.value}`;
type(lo, "-3"); await wait();
if (lo.value !== "0") return `the minimum was not kept inside the bound: ${lo.value}`;
type(lo, ""); await wait();
if (lo.value !== "" || hi.value !== "1000") return "an emptied box should stay empty";
const alo = $("#min-max-input-demo-live-min"), ahi = $("#min-max-input-demo-live-max");
type(alo, "70"); await wait();
if ($(".demo-note").textContent.trim() !== "From 70 to 70.") return `on_change did not give the pair in order: ${$(".demo-note").textContent}`;
type(ahi, ""); await wait();
if ($(".demo-note").textContent.trim() !== "From 70 to any.") return `on_change with an empty box: ${$(".demo-note").textContent}`;
const w = $("#min-max-input-demo-small-min");
if (!w.required || w.getAttribute("aria-invalid") !== "true" || !$("#min-max-input-demo-small-error[role=alert]")) return "required and error do not reach the boxes";
if (!w.closest(".ui-min-max-input").classList.contains("ui-min-max-input-sm")) return "size sm is not applied";
if (!$("input[name=locked_min]").disabled) return "disabled did not reach the boxes";
