const live = $("#feed-item-demo-live");
if (live.tagName !== "ARTICLE") return "not an article";
if (live.querySelector(".ui-feed-item-name").textContent !== "Ada Lovelace" || live.querySelector(".ui-feed-item-handle").textContent !== "@ada") return "name and handle";
if (!live.querySelector(".ui-feed-item-tick") || !live.querySelector(".ui-sr")?.textContent.includes("verified")) return "verified";
const when = live.querySelector(".ui-feed-item-head a time");
if (!when || when.getAttribute("datetime") !== "2026-10-28T09:00:00Z" || when.textContent !== "2h" || when.parentElement.getAttribute("href") !== "#feed_item") return "the time links to href";
if (!live.querySelector(".ui-feed-item-text").textContent.includes("\n")) return "line breaks are not kept";
if (live.querySelector(".ui-feed-item-media img")?.getAttribute("src") !== "https://picsum.photos/seed/engine/800/400") return "media";
const acts = [...live.querySelectorAll(".ui-feed-item-act")];
if (acts.map((b) => b.getAttribute("aria-label")).join("|") !== "Like, 128|Comments, 12|Share, 4") return `buttons: ${acts.map((b) => b.getAttribute("aria-label"))}`;
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
const like = acts[0];
if (like.getAttribute("aria-pressed") !== "false") return "liked starts false";
like.click(); await wait();
if (note() !== "Liked." || like.getAttribute("aria-pressed") !== "true" || like.getAttribute("aria-label") !== "Like, 129") return `on_like: ${note()} ${like.getAttribute("aria-label")}`;
like.click(); await wait();
if (note() !== "Unliked." || like.getAttribute("aria-label") !== "Like, 128") return "unlike";
acts[1].click(); await wait();
if (note() !== "Comment box opened.") return "on_comment";
acts[2].click(); await wait();
if (note() !== "Share sheet opened.") return "on_share";
const plain = $("#feed-item-demo-plain");
if (plain.querySelectorAll(".ui-feed-item-act").length !== 2 || plain.querySelector(".ui-feed-item-share")) return "a count left out still shows its button";
if (plain.querySelector(".ui-avatar img")?.getAttribute("src") !== "https://i.pravatar.cc/80?img=47") return "src";
if (plain.querySelector(".ui-feed-item-head a")) return "no href, no link";
const quoted = $$(".ui-feed-item")[2];
if (!quoted.querySelector(".ui-feed-item-media")?.textContent.includes("A quoted post") || quoted.querySelector(".ui-feed-item-acts")) return "children as media, no counts no buttons";
if (getComputedStyle(live.querySelector(".ui-feed-item-slot")).display !== "none") return "an empty children slot shows";
