const docs = $("#fl-docs");
const names = (el) => [...el.querySelectorAll(".ui-fl-name > a, .ui-fl-name > span:not(.ui-fl-icon)")].map((a) => a.textContent.trim());
if (docs.closest("form")?.getAttribute("action") !== "/files/delete" || docs.closest("form").method !== "post") return "delete_action does not make a POST form";
if (names(docs).join() !== "Brand assets.zip,Budget 2027.xlsx,Contract draft.docx,notes.md,Q3 report.pdf,Team offsite.jpg") return `by name: ${names(docs)}`;
const th = (t) => [...docs.querySelectorAll("th")].find((h) => h.textContent.trim() === t);
if (th("Name").getAttribute("aria-sort") !== "ascending") return "Name is not marked as sorted";
const row = docs.querySelector("tbody tr");
const cells = [...row.children].map((c) => c.textContent.trim());
if (cells[2] !== "17.6 MB" || cells[3] !== "Aug 30, 2026") return `the first row shows ${cells}`;
if (row.querySelector(".ui-fl-icon").textContent !== "ZIP" || !row.querySelector(".ui-fl-k-archive")) return "the zip has no archive icon";
const dl = row.querySelector("a[download]");
if (!dl || dl.getAttribute("download") !== "Brand assets.zip" || dl.getAttribute("aria-label") !== "Download Brand assets.zip") return "there is no named download link";
const del = row.querySelector("button.ui-fl-del");
if (del.type !== "submit" || del.name !== "delete" || del.value !== "5") return "Delete does not send delete=id";
th("Size").querySelector("button").click(); await wait();
if (names(docs)[0] !== "Brand assets.zip" || th("Size").getAttribute("aria-sort") !== "descending") return `Size sorts largest first: ${names(docs)}`;
th("Size").querySelector("button").click(); await wait();
if (names(docs)[0] !== "notes.md") return `Size again sorts smallest first: ${names(docs)}`;
const sel = docs.querySelector("select");
sel.value = "modified"; sel.dispatchEvent(new Event("change", { bubbles: true })); await wait();
if (names(docs)[0] !== "Brand assets.zip" || th("Modified").getAttribute("aria-sort") !== "ascending") return `the select sorts by date: ${names(docs)}`;
const dir = docs.querySelector(".ui-fl-tool:not([aria-pressed])");
dir.focus(); dir.click(); await wait();
if (document.activeElement !== dir) return "the direction button loses focus when clicked";
if (names(docs)[0] !== "notes.md") return `the direction button does not reverse: ${names(docs)}`;
const boxes = () => [...docs.querySelectorAll("tbody input[type=checkbox]")];
boxes()[0].click(); boxes()[2].click(); await wait();
const all = docs.querySelector("thead input[type=checkbox]");
if (!all.indeterminate) return "Pick all is not mixed with some picked";
if (!docs.querySelector(".ui-fl-sum").textContent.includes("2 of 6 picked")) return `the summary says ${docs.querySelector(".ui-fl-sum").textContent}`;
const sent = new FormData(docs.closest("form")).getAll("files");
if (sent.join() !== "6,2") return `a form would send ${sent}`;
all.click(); await wait();
if (boxes().some((b) => !b.checked) || all.indeterminate) return "Pick all does not pick every file";
all.click(); await wait();
if (boxes().some((b) => b.checked)) return "Pick all again does not unpick";
const [listBtn, gridBtn] = docs.querySelectorAll(".ui-fl-pair button");
gridBtn.click(); await wait();
if (gridBtn.getAttribute("aria-pressed") !== "true" || !docs.querySelector(".ui-fl-grid") || docs.querySelector("table")) return "Grid does not switch to tiles";
if (docs.querySelectorAll(".ui-fl-tile").length !== 6) return "the grid does not show every file";
listBtn.click(); await wait();
if (!docs.querySelector("table")) return "List does not switch back";
const live = $("#fl-live");
if (!live.querySelector(".ui-fl-grid")) return "layout=grid does not start as a grid";
if (names(live)[0] !== "notes.md") return `order_by modified descending starts with ${names(live)[0]}`;
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
live.querySelectorAll(".ui-fl-tile input")[1].click(); await wait();
if (note() !== "Picked: Contract draft.docx.") return `on_select: ${note()}`;
live.querySelector('.ui-fl-del[aria-label="Delete notes.md"]').click(); await wait();
if (names(live).includes("notes.md") || live.querySelectorAll(".ui-fl-tile").length !== 5) return "on_delete does not take the file away";
live.querySelector(".ui-fl-bulk").click(); await wait();
if (names(live).includes("Contract draft.docx")) return "Delete picked does not delete the picked file";
if ($("#fl-none .ui-fl-empty")?.textContent !== "The archive is empty.") return "an empty list does not say so";
