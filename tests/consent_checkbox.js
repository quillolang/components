const terms = $("#consent-checkbox-demo-terms");
if (!terms || terms.type !== "checkbox" || terms.name !== "terms" || terms.value !== "1") return "the consent is not a named checkbox worth 1";
if (!terms.required) return "it is not required by default";
if (terms.checkValidity()) return "an unticked required box should be invalid";
const text = terms.labels[0].querySelector(".ui-consent-checkbox-text");
if (!text.textContent.replace(/\s+/g, " ").includes("I agree to the terms of service and the privacy policy")) return `the built-in sentence: ${text.textContent}`;
const links = [...text.querySelectorAll("a")];
if (links.length !== 2 || links[0].textContent !== "terms of service" || links[1].textContent !== "privacy policy") return "the two links are missing";
if (links.some((a) => a.target !== "_blank" || !a.rel.includes("noopener"))) return "the links do not open in a new tab";
if (!document.getElementById(terms.getAttribute("aria-describedby"))?.textContent.includes("new tab")) return "the hint is not tied to the box";
terms.labels[0].click(); await wait();
if (!terms.checked || !terms.checkValidity()) return "clicking the text did not tick the box";
const mk = $("#consent-checkbox-demo-marketing");
if (mk.required || !mk.labels[0].textContent.includes("new releases")) return "children text or required={false} did not reach the box";
const age = $("#consent-checkbox-demo-error");
if (age.getAttribute("aria-invalid") !== "true" || !$("#consent-checkbox-demo-error-error[role=alert]")) return "error does not mark the box";
if (age.labels[0].querySelector("a")?.textContent !== "age policy" || age.labels[0].querySelectorAll("a").length !== 1) return "terms_label or a single link is wrong";
const live = $("#consent-checkbox-demo-live");
live.click(); await wait();
if (!$(".demo-note").textContent.includes("Rules accepted")) return `on_change did not update: ${$(".demo-note").textContent}`;
live.click(); await wait();
if (!$(".demo-note").textContent.includes("not accepted")) return "on_change is not given false when unticked";
