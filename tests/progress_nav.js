const nav = $("nav.ui-prognav");
if (!nav || nav.getAttribute("aria-label") !== "Progress") return "it is not a labelled <nav>";
const items = [...nav.querySelectorAll("li")];
const phases = items.map((li) => ["done", "current", "coming"].find((p) => li.classList.contains(`ui-prognav-${p}`)));
if (phases.join(" ") !== "done done current coming") return `the phases are ${phases}`;
const kinds = items.map((li) => li.firstElementChild.tagName);
if (kinds.join(" ") !== "A A SPAN SPAN") return `done steps link and the others do not: ${kinds}`;
if (items[0].querySelector("a").getAttribute("href") !== "#pn-cart") return "a done step does not link to its href";
if (nav.querySelectorAll("[aria-current=step]").length !== 1 || items[2].querySelector("[aria-current=step]") === null) return "this step is not aria-current=step";
if (!items[0].querySelector(".ui-prognav-mark svg") || items[2].querySelector(".ui-prognav-mark").textContent.trim() !== "3") return "done steps have no check, or this one no number";
if (!items[0].textContent.includes("(done)")) return "screen readers are not told a step is done";
if (items[0].querySelector(".ui-prognav-hint")?.textContent !== "3 items") return "the hint is not shown";
const tops = items.map((li) => Math.round(li.getBoundingClientRect().top));
if (new Set(tops).size !== 1) return "the steps are not in one row";
const live = $("#progress-nav-demo-live") ?? $$("nav.ui-prognav")[1];
const all = [...live.querySelectorAll("li")];
if (all.some((li, i) => li.firstElementChild.tagName !== (i === 1 ? "SPAN" : "A"))) return "with ahead, the coming steps are not links too (and this one is plain)";
all[3].querySelector("a").click(); await wait();
const note = live.closest(".demo-stack").querySelector(".demo-note").textContent;
if (!note.includes("Step 4 of 4") || !all[3].classList.contains("ui-prognav-current") || !all[2].classList.contains("ui-prognav-done")) return `on_select did not move to step 4: ${note}`;
if (location.hash === "#pn-review") return "on_select did not stop the link being followed";
const vert = $$("nav.ui-prognav")[2];
if (!vert.classList.contains("ui-prognav-vertical") || vert.getAttribute("aria-label") !== "Setup") return "the vertical one is not vertical or labelled";
const vl = [...vert.querySelectorAll("li")];
if (vl.some((li) => !li.classList.contains("ui-prognav-done")) || vert.querySelector("[aria-current]")) return "current = len(steps) does not mark everything done";
const [a, b] = vl.map((li) => li.getBoundingClientRect());
if (b.top <= a.bottom - 1) return "vertical steps are not one under another";
