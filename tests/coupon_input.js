const boxes = $$(".ui-coupon");
if (boxes.length !== 2) return `expected 2, found ${boxes.length}`;
const [live, pre] = boxes;
const input = live.querySelector("input[name=coupon-demo]");
const btn = () => live.querySelector(".ui-coupon-btn");
const msg = () => live.querySelector(".ui-coupon-msg").textContent;
if (!input || live.querySelector("label").htmlFor !== input.id || live.querySelector("label").textContent !== "Promo code") return "the input is not labelled";
if (!btn().disabled || btn().textContent !== "Apply") return "Apply is enabled with nothing typed";
type(input, "nope"); await wait();
if (btn().disabled) return "Apply stays disabled after typing";
btn().click(); await wait();
if (msg() !== '"NOPE" is not a code we know' || input.getAttribute("aria-invalid") !== "true" || live.querySelector(".ui-coupon-msg").getAttribute("role") !== "alert") return `a bad code: "${msg()}"`;
if (!live.classList.contains("ui-coupon-invalid")) return "a bad code is not marked invalid";
type(input, "expired"); key(input, "Enter"); await wait();
if (msg() !== "That code has expired") return `Enter did not apply: "${msg()}"`;
type(input, "save10"); key(input, "Enter"); await wait();
if (msg() !== "10% off applied" || !live.classList.contains("ui-coupon-applied") || input.value !== "SAVE10" || !input.readOnly) return `SAVE10: "${msg()}", value ${input.value}`;
if (btn().textContent !== "Remove" || btn().getAttribute("aria-label") !== "Remove code SAVE10") return "an applied code has no Remove";
if (!$(".demo-note").textContent.includes("Code SAVE10 is applied")) return `on_apply: ${$(".demo-note").textContent}`;
const f = document.createElement("form"); live.parentElement.insertBefore(f, live); f.appendChild(live);
const sent = new FormData(f).get("coupon-demo"); f.parentElement.insertBefore(live, f); f.remove();
if (sent !== "SAVE10") return `a form would send ${sent}`;
btn().click(); await wait();
if (input.value !== "" || input.readOnly || msg() !== "" || !$(".demo-note").textContent.includes("No code applied")) return "Remove does not clear the code (on_remove)";
const pin = pre.querySelector("input");
if (pin.value !== "WELCOME" || !pin.readOnly || pre.querySelector(".ui-coupon-msg").textContent !== "Welcome gift: 15% off your first order") return "applied= does not start applied";
if (!pre.classList.contains("ui-coupon-sm")) return "size=sm is not set";
