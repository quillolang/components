const nav = $("nav.ui-alpha");
if (!nav || nav.getAttribute("aria-label") !== "Index") return "it is not a labelled <nav>";
const cells = [...nav.querySelectorAll("li > *")];
if (cells.length !== 27 || cells[0].textContent !== "A" || cells[26].textContent !== "#") return `expected A..Z and #, found ${cells.length}: ${cells.map((c) => c.textContent).join("")}`;
const links = cells.filter((c) => c.tagName === "A").map((c) => c.textContent);
if (links.join("") !== "ABDFHKMNRS#") return `the links are ${links.join("")}`;
if (cells[0].getAttribute("href") !== "#alpha-A" || cells[26].getAttribute("href") !== "#alpha-other") return "the hrefs are wrong";
const c = cells[2];
if (c.tagName !== "SPAN" || c.getAttribute("aria-disabled") !== "true" || !c.classList.contains("ui-alpha-off")) return "a letter with nothing is not disabled";
if (getComputedStyle(c).color === getComputedStyle(cells[0]).color) return "a disabled letter does not look it";
const tops = cells.map((x) => Math.round(x.getBoundingClientRect().top));
if (new Set(tops).size !== 1) return "the letters are not in one row";
const live = $$("nav.ui-alpha")[1];
if (live.querySelector("[aria-current]")?.textContent !== "C" || live.querySelectorAll("li").length !== 26) return "the live one does not start on C without #";
const p = [...live.querySelectorAll("a")].find((a) => a.textContent === "P");
p.click(); await wait();
if (live.querySelector("[aria-current]")?.textContent !== "P" || !live.closest(".demo-stack").querySelector(".demo-note").textContent.includes("with P")) return "on_select did not mark P and reach the note";
const greek = $$("nav.ui-alpha")[2];
if (greek.querySelectorAll("a").length !== 24 || greek.querySelector("a").textContent !== "Α") return "another alphabet is not used";
