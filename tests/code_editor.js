const box = $("#code-editor-ce-demo-source");
const host = box.closest(".ui-code-editor");
const gutter = () => [...host.querySelectorAll(".ui-code-editor-gutter span")].map((s) => s.textContent).join();
const set = (v, a, b = a) => { box.value = v; box.dispatchEvent(new Event("input", { bubbles: true })); box.setSelectionRange(a, b); };
const press = (k, extra = {}) => box.dispatchEvent(new KeyboardEvent("keydown", { key: k, bubbles: true, cancelable: true, ...extra }));
if (box.tagName !== "TEXTAREA" || box.name !== "ce-demo-source" || box.spellcheck) return "the box is not a named textarea without spellcheck";
if (gutter() !== "1,2,3,4,5") return `the line numbers are ${gutter()}`;
if (host.querySelector(".ui-code-editor-lang")?.textContent !== "quillo") return "the language is not shown";
if (getComputedStyle(box).fontFamily === getComputedStyle(host).fontFamily) return "the code is not in a monospace face";
set("ab", 2); press("Tab"); await wait();
if (box.value !== "ab  " || box.selectionStart !== 4) return `Tab from column 2: "${box.value}"`;
set("a\nb", 0, 3); press("Tab"); await wait();
if (box.value !== "    a\n    b") return `Tab over lines: "${box.value}"`;
press("Tab", { shiftKey: true }); await wait();
if (box.value !== "a\nb") return `Shift+Tab: "${box.value}"`;
set("    if x {", 10); press("Enter"); await wait();
if (box.value !== "    if x {\n        " || box.selectionStart !== 19) return `Enter after {: ${JSON.stringify(box.value)}`;
set("fn f() {}", 8); press("Enter"); await wait();
if (box.value !== "fn f() {\n    \n}" || box.selectionStart !== 13) return `Enter between braces: ${JSON.stringify(box.value)}`;
set("  plain", 7); press("Enter"); await wait();
if (box.value !== "  plain\n  ") return `Enter keeps the indent: ${JSON.stringify(box.value)}`;
if (gutter() !== "1,2") return `the line numbers do not follow: ${gutter()}`;
set("f()", 2); press(")"); await wait();
if (box.value !== "f()" || box.selectionStart !== 3) return "a closing bracket typed before its twin is doubled";
set("x", 1); press("Escape"); const t = new KeyboardEvent("keydown", { key: "Tab", bubbles: true, cancelable: true }); box.dispatchEvent(t); await wait();
if (t.defaultPrevented || box.value !== "x") return "Escape then Tab does not let the focus leave";
const q = $("#code-editor-ce-demo-query");
const note = () => q.closest(".demo-stack").querySelector(".demo-note").textContent;
q.focus(); q.setSelectionRange(q.value.length, q.value.length);
q.dispatchEvent(new KeyboardEvent("keydown", { key: "Tab", bubbles: true, cancelable: true })); await wait();
if (!q.value.endsWith("active  ")) return `tab_size={2}: ${JSON.stringify(q.value)}`;
if (note() !== `3 lines, ${q.value.length} characters.`) return `on_change: ${note()}`;
