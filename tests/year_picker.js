const btn = $("#year-picker-yp-demo-model");
const host = btn.closest(".ui-year-picker");
const pop = host.querySelector("[role=dialog]");
const hidden = $("input[type=hidden][name=yp-demo-model]");
const decade = () => pop.querySelector("h2").textContent.trim();
const focused = () => document.activeElement?.textContent.trim();
if (btn.textContent.trim() !== "2019" || hidden.value !== "2019") return `it starts as ${btn.textContent.trim()} / ${hidden.value}`;
if (btn.getAttribute("aria-haspopup") !== "dialog" || !pop.hidden) return "the button does not open a dialog, or it starts open";
btn.click(); await wait();
if (pop.hidden || decade() !== "2010 – 2019") return `the grid opened on ${decade()}`;
if (focused() !== "2019" || document.activeElement.getAttribute("aria-selected") !== "true") return `the focus is on ${focused()}`;
const cells = [...pop.querySelectorAll("[role=gridcell]")];
if (cells.length !== 12 || cells[0].textContent !== "2009" || !cells[0].classList.contains("ui-year-picker-outside") || cells[11].textContent !== "2020") return "the decade with a year either side is not shown";
const k = async (name) => { key(document.activeElement, name); await wait(80); };
await k("ArrowRight"); if (focused() !== "2020" || decade() !== "2020 – 2029") return `ArrowRight past the decade: ${focused()} ${decade()}`;
await k("End"); if (focused() !== "2027") return `End is kept to latest: ${focused()}`;
if (pop.querySelector("[data-y='2028']").getAttribute("aria-disabled") !== "true") return "a year after latest is not disabled";
await k("PageUp"); if (focused() !== "2017" || decade() !== "2010 – 2019") return `PageUp: ${focused()}`;
await k("ArrowUp"); if (focused() !== "2013") return `ArrowUp: ${focused()}`;
await k("Enter");
if (hidden.value !== "2013" || !pop.hidden || document.activeElement !== btn) return `Enter picked ${hidden.value}`;
btn.click(); await wait();
pop.querySelector("[aria-label='Previous ten years']").click(); await wait();
if (decade() !== "2000 – 2009") return `Previous ten years: ${decade()}`;
key(document.activeElement, "Escape"); await wait();
if (!pop.hidden || document.activeElement !== btn) return "Escape did not close and go back to the button";
const live = $("input[type=hidden][name=yp-demo-grad]").closest(".ui-year-picker");
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
if (live.querySelector(".ui-year-picker-trigger") || live.querySelector("[role=group]").hidden) return "inline={true} does not show the grid";
if (live.querySelector("[aria-current=date]")?.textContent !== "2026") return "this year is not marked";
live.querySelector("[data-y='2024']").click(); await wait();
if (note() !== "Class of 2024.") return `on_change: ${note()}`;
if ($("#year-picker-yp-demo-sm").getAttribute("aria-invalid") !== "true") return "error does not mark the button";
