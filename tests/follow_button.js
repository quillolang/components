const all = $$("button.ui-follow-button"), first = all[0], note = () => $(".demo-note").textContent;
if (all.length !== 5) return `expected 5 buttons, found ${all.length}`;
const text = (b) => b.querySelector(".ui-follow-button-text").textContent;
if (text(first) !== "Follow" || first.hasAttribute("aria-pressed")) return "it does not start as Follow without aria-pressed";
first.click(); await wait();
if (text(first) !== "Following" || !first.classList.contains("ui-follow-button-on")) return "pressing does not make it Following";
if (note() !== "Following Ada.") return `on_change did not reach the note: ${note()}`;
const un = first.querySelector(".ui-follow-button-un");
if (!un || un.textContent !== "Unfollow" || getComputedStyle(un).visibility !== "hidden") return "Unfollow is not there, hidden, while following";
first.click(); await wait();
if (text(first) !== "Follow" || note() !== "Not following Ada.") return "pressing again does not unfollow";
const named = all[1], hidden = named.querySelector("input[type=hidden][name=follow]");
if (text(named) !== "Following" || !hidden || hidden.disabled) return "following={true} with name does not send it";
named.click(); await wait();
if (!hidden.disabled) return "unfollowing still sends it";
if (text(all[3]) !== "Subscribe") return "the labels are not taken";
all[3].click(); await wait();
if (text(all[3]) !== "Subscribed" || all[3].querySelector(".ui-follow-button-un").textContent !== "Unsubscribe") return "the pressed labels are not taken";
if (!all[4].disabled) return "disabled does not disable";
if (all[2].getBoundingClientRect().height >= first.getBoundingClientRect().height) return "sm is not smaller";
