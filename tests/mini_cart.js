const btns = $$("button.ui-mini-cart-btn");
if (btns.length !== 3) return `expected 3 bags, found ${btns.length}`;
const [live, plain, empty] = btns;
const panel = (b) => document.getElementById(b.getAttribute("popovertarget"));
if (live.getAttribute("aria-label") !== "Cart, 4 items" || live.querySelector(".ui-mini-cart-count").textContent !== "4") return `the bag says ${live.getAttribute("aria-label")} / ${live.querySelector(".ui-mini-cart-count")?.textContent}`;
if (!panel(live)?.hasAttribute("popover") || panel(live).getAttribute("role") !== "dialog") return "the panel is not a popover dialog";
live.scrollIntoView({ block: "center" });
live.click(); await wait();
const p = panel(live);
if (!p.matches(":popover-open")) return "clicking the bag does not open the panel";
const names = [...p.querySelectorAll(".ui-mini-cart-name")].map((n) => n.textContent);
if (names.join() !== "Trail runner,Wool beanie,Merino socks, 3 pairs") return `items: ${names}`;
const metas = [...p.querySelectorAll(".ui-mini-cart-meta")].map((n) => n.textContent);
if (metas[0] !== "1 × $89.00 · Size 42, Black" || metas[1] !== "2 × $24.00") return `metas: ${metas}`;
if (p.querySelector(".ui-mini-cart-sub").textContent.replace("Subtotal", "") !== "$166.00") return `subtotal: ${p.querySelector(".ui-mini-cart-sub").textContent}`;
if (p.querySelector("a.ui-mini-cart-main")?.getAttribute("href") !== "#checkout_steps" || p.querySelectorAll("a.ui-mini-cart-go")[0].getAttribute("href") !== "#cart_item") return "the links are wrong";
if (CSS.supports("position-area: bottom")) { const b = live.getBoundingClientRect(), r = p.getBoundingClientRect(); if (r.top < b.bottom - 1) return "the panel is not under the bag"; }
p.querySelectorAll(".ui-mini-cart-x")[1].click(); await wait();
if ([...p.querySelectorAll(".ui-mini-cart-name")].length !== 2 || live.querySelector(".ui-mini-cart-count").textContent !== "2") return "× does not drop the item and the count";
if (p.querySelector(".ui-mini-cart-sub").textContent.replace("Subtotal", "") !== "$118.00") return "the subtotal is not worked out again";
if (!$(".demo-note").textContent.includes("Removed: beanie")) return `on_remove: ${$(".demo-note").textContent}`;
live.click(); await wait();
if (p.matches(":popover-open")) return "clicking again does not close it";
plain.click(); await wait();
const pp = panel(plain);
if (pp.querySelector(".ui-mini-cart-x")) return "without on_remove there are × buttons";
if (pp.querySelector(".ui-mini-cart-sub").textContent.replace("Subtotal", "").replace(/\s/g, " ") !== "166,00 €") return `de-DE subtotal: ${pp.querySelector(".ui-mini-cart-sub").textContent}`;
plain.click(); await wait();
if (empty.querySelector(".ui-mini-cart-count") || empty.getAttribute("aria-label") !== "Cart, 0 items") return "an empty bag shows a count";
empty.click(); await wait();
const pe = panel(empty);
if (pe.querySelector(".ui-mini-cart-empty")?.textContent !== "Your cart is empty" || pe.querySelector(".ui-mini-cart-main")) return "an empty cart does not say so, or offers checkout";
empty.click(); await wait();
