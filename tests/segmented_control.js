const view = $$("input[name=sc-view]");
if (view.length !== 3 || view[0].type !== "radio") return "the options are not radio buttons";
if (view.find((r) => r.checked)?.value !== "Week") return "value does not pick Week";
if ($("input[name=sc-align]:checked")?.value !== "Left") return "with no value, the first option is not picked";
if (!$$("input[name=sc-off]").every((r) => r.disabled)) return "disabled does not disable every option";
const group = view[0].closest(".ui-segmented");
if (group.getAttribute("role") !== "radiogroup" || group.getAttribute("aria-label") !== "View") return "the group has no role or label";
view[2].closest("label").click(); await wait();
if (!view[2].checked || view[1].checked) return "clicking Month did not pick it";
const picked = getComputedStyle(view[2].nextElementSibling).backgroundColor, other = getComputedStyle(view[1].nextElementSibling).backgroundColor;
if (picked === other) return "the picked segment does not look raised";
const form = document.createElement("form");
group.parentElement.insertBefore(form, group); form.appendChild(group);
const sent = new FormData(form).get("sc-view");
form.parentElement.insertBefore(group, form); form.remove();
if (sent !== "Month") return `a form sends ${sent}`;
const full = $$("input[name=sc-full]").map((r) => r.nextElementSibling.getBoundingClientRect().width);
if (Math.max(...full) - Math.min(...full) > 1) return "full segments are not the same width";
const monthly = $("input[name=sc-plan][value=m]");
monthly.closest("label").click(); await wait();
const note = monthly.closest(".demo-stack").querySelector(".demo-note").textContent;
if (!note.includes("a month")) return `on_change did not update the note: ${note}`;
