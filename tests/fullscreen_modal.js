const [terms, edit] = $$("dialog.ui-fullscreen-modal"), note = () => $(".demo-note").textContent;
const trig = $$("button.ui-btn").find((b) => b.textContent === "Read the terms"), fromState = $$("button.ui-btn").find((b) => b.textContent.startsWith("Edit profile"));
if (!terms || terms.open || terms.getAttribute("aria-label") !== "Terms of service") return "the dialog is not named, closed, to start";
if (trig.getAttribute("aria-haspopup") !== "dialog") return "the trigger does not say it opens a dialog";
trig.click(); await wait(300);
if (!terms.open) return "the trigger does not open it";
const r = terms.getBoundingClientRect();
if (Math.abs(r.width - innerWidth) > 1 || Math.abs(r.height - innerHeight) > 1 || r.top !== 0 || r.left !== 0) return `it does not fill the window: ${JSON.stringify(r)}`;
const bar = terms.querySelector(".ui-fullscreen-modal-bar"), body = terms.querySelector(".ui-fullscreen-modal-body");
if (bar.querySelector("h2").textContent !== "Terms of service" || bar.querySelector(".ui-fullscreen-modal-x").getAttribute("aria-label") !== "Close") return "the bar has no title or named close button";
if (getComputedStyle(document.documentElement).overflow !== "hidden") return "the page behind still scrolls";
if (body.scrollHeight <= body.clientHeight) return "the body does not scroll";
body.scrollTop = 400; await wait(50);
if (Math.abs(bar.getBoundingClientRect().top) > 1) return "the bar does not stay while the body scrolls";
const inner = terms.querySelector(".ui-fullscreen-modal-inner").getBoundingClientRect();
if (inner.width > 721 || Math.abs((inner.left + inner.right) / 2 - innerWidth / 2) > 2) return "the body is not 720px at most, centred";
if (terms.querySelector(".ui-fullscreen-modal-done")) return "a done button shows without done";
bar.querySelector(".ui-fullscreen-modal-x").click(); await wait();
if (terms.open) return "the close button does not close it";
fromState.click(); await wait(300);
if (!edit.open) return "open={state} does not open it";
const done = edit.querySelector(".ui-fullscreen-modal-done");
if (!done || done.textContent !== "Save") return "done is not shown in the bar";
done.click(); await wait();
if (edit.open || note() !== "Saved 1 time.") return `done does not call on_done and close: ${note()}`;
fromState.click(); await wait(300);
if (!edit.open) return "on_close did not set the state back, so it cannot open again";
edit.close(); await wait();
if (note() !== "Saved 1 time.") return "closing without done called on_done";
