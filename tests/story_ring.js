const live = $("#story-ring-demo-live");
const row = live.querySelector("ul.ui-story-ring");
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
if (!row || row.getAttribute("aria-label") !== "Stories") return "the row is not a labelled list";
const items = () => [...row.querySelectorAll("li")];
if (items().length !== 7 || !items()[0].classList.contains("ui-story-ring-you")) return `expected you and 6 people, found ${items().length}`;
const you = items()[0].querySelector("button");
if (!you || you.getAttribute("aria-label") !== "Add to your story" || !you.querySelector(".ui-story-ring-plus")) return "your story is not a button with a +";
const ana = items()[1].querySelector("button");
if (ana.getAttribute("aria-label") !== "Ana Silva, 3 new stories" || !ana.querySelector(".ui-story-ring-avatar img")) return `Ana is heard as ${ana.getAttribute("aria-label")}`;
if (items()[2].querySelector("button").getAttribute("aria-label") !== "Ben Okafor, new story") return "a person without a count is not heard as new";
if (items()[3].querySelector(".ui-story-ring-avatar").textContent.trim() !== "LC") return "initials are not shown without a picture";
if (items()[1].querySelector(".ui-story-ring-name").textContent !== "Ana Silva") return "the name is not under the avatar";
if (row.scrollWidth <= row.clientWidth && row.clientWidth < 500) return "the row does not scroll";
ana.click(); await wait();
if (!items()[1].classList.contains("ui-story-ring-seen") || items()[1].querySelector("button").getAttribute("aria-label") !== "Ana Silva, seen") return "opening a story did not mark it seen";
if (note() !== "Seen: Ana Silva.") return `on_open did not reach the note: ${note()}`;
you.click(); await wait();
if (!note().includes("Add pressed 1")) return `on_add did not reach the note: ${note()}`;
const links = $("#story-ring-demo-links").querySelector("ul");
if (!links.classList.contains("ui-story-ring-sm") || links.getAttribute("aria-label") !== "Team stories") return "size sm or the label is not applied";
const a = [...links.querySelectorAll("a.ui-story-ring-item")];
if (a.length !== 3 || a[0].getAttribute("href") !== "#story_ring" || a[0].getAttribute("aria-label") !== "Add to your story") return "with hrefs, the items are not links";
if (!a[1].closest("li").classList.contains("ui-story-ring-seen") || a[1].getAttribute("aria-label") !== "Ben Okafor, seen") return "a seen story is not grey";
const seenBg = getComputedStyle(a[1].querySelector(".ui-story-ring-circle")).backgroundImage;
const newBg = getComputedStyle(a[2].querySelector(".ui-story-ring-circle")).backgroundImage;
if (seenBg === newBg || newBg === "none") return "a new story's ring is not the gradient";
