const mrr = $("#kpi-card-demo-mrr");
if (!mrr || mrr.querySelector(".ui-kpicard-label").textContent !== "Monthly recurring revenue" || mrr.querySelector(".ui-kpicard-value").textContent !== "$128,400") return "label and value";
const d = mrr.querySelector(".ui-kpicard-delta");
if (!mrr.classList.contains("ui-kpicard-good") || d.textContent.replace(/\s+/g, "") !== "↑up+8.2%") return `the change reads "${d.textContent.trim()}"`;
if (mrr.querySelector(".ui-kpicard-change > span:last-child").textContent !== "vs last month") return "the period is missing";
const line = mrr.querySelector(".ui-kpicard-trend");
if (!line || line.dataset.kind !== "line" || line.querySelectorAll("path").length !== 2) return "the line trend is not drawn";
const dd = line.querySelector("path:last-child").getAttribute("d");
if (!dd.startsWith("M0,37") || !dd.endsWith("100,3")) return `the line runs ${dd}`;
const link = mrr.querySelector(".ui-kpicard-foot a");
if (!link || link.getAttribute("href") !== "#mrr" || !link.textContent.startsWith("View")) return "the footer link";
const churn = $("#kpi-card-demo-churn");
if (!churn.classList.contains("ui-kpicard-good") || !churn.querySelector(".ui-kpicard-delta").textContent.includes("-0.4 pts")) return 'good="down" does not make a fall good';
const bars = churn.querySelectorAll(".ui-kpicard-trend rect");
if (churn.querySelector(".ui-kpicard-trend").dataset.kind !== "bars" || bars.length !== 7) return `bars: ${bars.length}`;
if (Number(bars[0].getAttribute("height")) <= Number(bars[6].getAttribute("height"))) return "the tallest bar is not the highest value";
if (churn.querySelector(".ui-kpicard-foot")) return "a card without href or note has a footer";
const s = $("#kpi-card-demo-signups");
if (!s.classList.contains("ui-kpicard-flat") || !s.classList.contains("ui-kpicard-info") || !s.querySelector(".ui-kpicard-delta").textContent.includes("→")) return "zero change and tone";
if (s.querySelector(".ui-kpicard-foot span").textContent !== "Updated 5 min ago" || s.querySelector(".ui-kpicard-foot a")) return "the note";
const e = $("#kpi-card-demo-errors");
if (!e.classList.contains("ui-kpicard-bad") || e.querySelector(".ui-kpicard-foot a").textContent !== "See the log →") return "a rise with good=down, and link_label";
const c = getComputedStyle(e.querySelector(".ui-kpicard-trend")).color;
const danger = getComputedStyle(e).getPropertyValue("--ui-danger").trim();
const probe = document.createElement("span"); probe.style.color = danger; e.appendChild(probe);
const same = getComputedStyle(probe).color === c; probe.remove();
if (!same) return `the bad trend is not in the danger colour: ${c}`;
