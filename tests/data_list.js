const p = $("#data-list-demo-projects");
if (!p || p.tagName !== "UL" || p.getAttribute("aria-label") !== "Projects") return "the list is not a named <ul>";
const rows = [...p.querySelectorAll(".ui-datalist-row")];
if (rows.length !== 3) return `expected 3 rows, found ${rows.length}`;
if (rows[0].querySelector(".ui-datalist-title a")?.getAttribute("href") !== "#p1") return "the title link";
const meta = [...rows[0].querySelectorAll(".ui-datalist-meta li")].map((m) => m.textContent);
if (meta.join("|") !== "Design|Due Nov 4|6 tasks") return `meta: ${meta}`;
if (getComputedStyle(rows[0].querySelectorAll(".ui-datalist-meta li")[1], "::before").content !== '"·"') return "no dots between facts";
const badge = rows[1].querySelector(".ui-datalist-badge");
if (badge.textContent !== "At risk" || !badge.classList.contains("ui-datalist-warning")) return "the badge";
if (rows[0].querySelector(".ui-datalist-desc")?.textContent !== "New home page, pricing and docs layout.") return "description";
const open = rows[0].querySelector("a.ui-datalist-act");
if (!open || open.getAttribute("aria-label") !== "Open: Website redesign") return "a link action and its name";
if (rows[2].querySelector(".ui-datalist-actions") || rows[2].querySelector("a")) return "a row without actions or href";
const inv = $("#data-list-demo-invoices");
const note = () => inv.closest(".demo-stack").querySelector(".demo-note").textContent;
const btn = (i, k) => inv.querySelectorAll(".ui-datalist-row")[i].querySelector(`button[data-action=${k}]`);
if (inv.querySelector(".ui-datalist-pic").textContent.trim() !== "PDF") return "icon_text";
if (!btn(0, "void").classList.contains("ui-datalist-danger")) return "a danger action";
btn(1, "remind").click(); await wait();
if (note() !== "on_action: remind inv-1042.") return `on_action: ${note()}`;
btn(0, "void").click(); await wait();
if (inv.querySelectorAll(".ui-datalist-row").length !== 1 || note() !== "on_action: void inv-1041.") return "void did not remove the row";
btn(0, "void").click(); await wait();
if (inv.querySelector(".ui-datalist-empty")?.textContent !== "No invoices left.") return "empty";
