if (document.documentElement.scrollWidth > innerWidth) return "widens the page";
const charts = $$("figure.ui-rangec");
if (charts.length !== 2) return `expected 2 range charts, found ${charts.length}`;
if (/NaN|Infinity|undefined/.test(charts.map((c) => c.innerHTML).join(""))) return "a range chart has NaN, Infinity or undefined in it";
const [temps, forecast] = charts;
if (temps.getAttribute("aria-label") !== "Temperature in Montreal, low to high") return "the label does not name the chart";
const bars = [...temps.querySelectorAll(".ui-rangec-bar")];
if (bars.length !== 12) return `12 months made ${bars.length} bars`;
const ticks = [...temps.querySelectorAll(".ui-rangec-y span")].map((s) => s.textContent).join();
if (ticks !== "-10,0,10,20,30") return `the axis ticks are ${ticks}`;
// July, 15 to 28 on an axis from -10 to 30: from 62.5% for 32.5%.
const jul = bars[6];
if (jul.style.getPropertyValue("--a").trim() !== "62.5%" || jul.style.getPropertyValue("--b").trim() !== "32.5%") return `July's bar is ${jul.getAttribute("style")}`;
const plot = temps.querySelector(".ui-rangec-plot").getBoundingClientRect(), jr = jul.getBoundingClientRect();
if (Math.abs(jr.height - 220 * 0.325) > 1 || Math.abs(plot.bottom - jr.bottom - 220 * 0.625) > 1) return "July's bar is not drawn from 15 to 28";
const zero = temps.querySelector(".ui-rangec-zero").getBoundingClientRect();
const jan = bars[0].getBoundingClientRect();
if (!(jan.top < zero.top && jan.bottom > zero.top)) return "January's bar does not cross 0";
const marks = temps.querySelectorAll(".ui-rangec-mark");
if (marks.length !== 12 || marks[6].style.getPropertyValue("--a").trim() !== "77.5%") return "the middle value is not marked at 21";
const vals = [...temps.querySelectorAll(".ui-rangec-col")[6].querySelectorAll(".ui-rangec-val")].map((v) => v.textContent).join();
if (vals !== "28°,15°") return `value_labels: ${vals}`;
const tip = temps.querySelectorAll(".ui-rangec-tip")[0];
if (getComputedStyle(tip).display !== "none") return "the tooltip shows before hover";
if (tip.textContent !== "JanHigh2°Value-2°Low-6°Range8°") return `tooltip: ${tip.textContent}`;
const row = temps.querySelector("tbody tr").textContent;
if (row !== "Jan-6°-2°2°" || temps.querySelectorAll("tbody tr").length !== 12) return `the screen reader table: ${row}`;
if (!temps.querySelector(".ui-rangec-frame").hasAttribute("aria-hidden")) return "the drawing is not hidden from screen readers";

if (forecast.querySelector(".ui-rangec-bar")) return "band={true} still draws bars";
const area = forecast.querySelector(".ui-rangec-area");
if (!area || !area.getAttribute("d").endsWith("Z")) return "band={true} draws no band";
const pts = area.getAttribute("d").replace("Z", "").split(/ ?[ML] ?/).filter(Boolean);
if (pts.length !== 12) return `the band has ${pts.length} corners, not 12`;
if (forecast.querySelectorAll(".ui-rangec-edge").length !== 2 || !forecast.querySelector(".ui-rangec-line")) return "the band has no edges or middle line";
if (!forecast.classList.contains("ui-rangec-s7")) return "color={7} is not applied";
if (getComputedStyle(forecast.querySelector(".ui-rangec-line")).stroke === getComputedStyle(temps.querySelector(".ui-rangec-bar")).backgroundColor) return "the colours do not differ";
if (forecast.querySelectorAll(".ui-rangec-col")[5].querySelector("b").textContent !== "$62,500") return "the band's tooltip";
if (forecast.querySelector(".ui-rangec-y span").textContent !== "$40k") return "the axis does not take the prefix";
