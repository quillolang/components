const alerts = $$(".ui-alert");
const byText = (t) => $$(".ui-alert").find((a) => a.textContent.includes(t));
if (alerts.length < 9) return `expected at least 9 alerts, found ${alerts.length}`;
if (byText("Payment failed").getAttribute("role") !== "alert") return "a danger alert is role=alert";
if (byText("Invoice sent").getAttribute("role") !== "status") return "a success alert is role=status";
if (!byText("Invoice sent").querySelector("svg.ui-alert-icon")) return "the tone's icon is missing";
if (byText("Maintenance").querySelector("svg")) return "icon={false} still shows an icon";
if (!byText("Solid, danger.").classList.contains("ui-alert-solid")) return "variant=solid is not applied";
const trial = byText("trial ends");
trial.querySelector(".ui-alert-x").click(); await wait();
if (byText("trial ends")) return "on_dismiss did not hide the alert";
const again = $$("button").find((b) => b.textContent.includes("Show it again"));
if (!again) return "the note after dismissing is missing";
again.click(); await wait();
if (!byText("trial ends")) return "the alert did not come back";
const own = byText("Placed straight in a page");
if (own.getAttribute("role") !== "status") return "DismissibleAlert has no role";
own.querySelector(".ui-alert-x").click(); await wait();
if (byText("Placed straight in a page")) return "DismissibleAlert did not hide itself";
