if (document.documentElement.scrollWidth > innerWidth) return "widens the page";
const charts = $$("figure.ui-hmap");
if (charts.length !== 3) return `expected 3 heatmaps, found ${charts.length}`;
if (/NaN|Infinity|undefined/.test(charts.map((c) => c.innerHTML).join(""))) return "a heatmap has NaN, Infinity or undefined in it";
const [visits, corr, uptime] = charts;
if (visits.getAttribute("aria-label") !== "Visits by weekday and hour") return "the label does not name the chart";
if (visits.querySelector("figcaption")?.textContent !== "Visits by weekday and hour") return "show_label does not write the label";
const cells = [...visits.querySelectorAll(".ui-hmap-cell")];
if (cells.length !== 84) return `7 rows of 12 made ${cells.length} cells`;
if (!visits.querySelector(".ui-hmap-grid").hasAttribute("aria-hidden")) return "the drawing is not hidden from screen readers";
// The screen reader table has the numbers; the colours follow them.
const rows = [...visits.querySelectorAll("table.ui-sr tbody tr")];
if (rows.length !== 7 || rows[0].querySelector("th").textContent !== "Mon") return "the table has no row per weekday";
const nums = rows.flatMap((r) => [...r.querySelectorAll("td")].map((td) => Number(td.textContent.replace(/,/g, ""))));
if (nums.length !== 84) return `the table has ${nums.length} values`;
const lo = Math.min(...nums), hi = Math.max(...nums);
const strength = (c) => parseFloat(c.style.getPropertyValue("--v"));
if (strength(cells[nums.indexOf(hi)]) !== 100) return "the highest value is not the full colour";
if (strength(cells[nums.indexOf(lo)]) !== 8) return "the lowest value is not the lightest colour";
const mid = nums.findIndex((v) => v > lo && v < hi);
const want = 8 + (nums[mid] - lo) / (hi - lo) * 92;
if (Math.abs(strength(cells[mid]) - want) > 0.02) return `a value between is drawn at ${strength(cells[mid])}%, not ${want}%`;
const bgHi = getComputedStyle(cells[nums.indexOf(hi)]).backgroundColor, bgLo = getComputedStyle(cells[nums.indexOf(lo)]).backgroundColor;
if (bgHi === bgLo) return "the cells are not coloured by value";
if (Math.abs(cells[0].getBoundingClientRect().height - 28) > 0.5 || Math.abs(cells[12].getBoundingClientRect().height - 28) > 0.5) return "rows are not 28px high";
const tip = cells[6].querySelector(".ui-hmap-tip");
if (getComputedStyle(tip).display !== "none") return "the tooltip shows before hover";
if (tip.querySelector("strong").textContent !== "Mon · 12:00" || tip.querySelector("b").textContent !== String(nums[6])) return `tooltip: ${tip.textContent}`;
if (!cells[0].classList.contains("ui-hmap-l") || !cells[11].classList.contains("ui-hmap-r")) return "the edge cells' tooltips do not stay inside";
const legend = [...visits.querySelectorAll(".ui-hmap-legend span:not(.ui-hmap-bar)")].map((s) => s.textContent);
if (legend[0] !== String(lo) || legend[2] !== String(hi)) return `the scale reads ${legend}`;
if (visits.querySelectorAll(".ui-hmap-cl").length !== 12 || visits.querySelector(".ui-hmap-cl").textContent !== "00:00") return "the column labels";

if (!corr.classList.contains("ui-hmap-div")) return "diverging={true} is not two-sided";
const cc = [...corr.querySelectorAll(".ui-hmap-cell")];
if (cc.length !== 25) return "the correlation matrix is not 5 by 5";
if (cc[0].querySelector(".ui-hmap-val")?.textContent !== "1.00") return "cell_values with decimals={2} does not write 1.00";
if (!cc[1].classList.contains("ui-hmap-s8") || strength(cc[1]) !== 62) return "-0.62 is not red at 62%";
if (!cc[4].classList.contains("ui-hmap-s1") || strength(cc[4]) !== 38) return "0.38 is not blue at 38%";
if (getComputedStyle(cc[1]).backgroundColor === getComputedStyle(cc[4]).backgroundColor) return "the two sides share a colour";
if (!cc[0].classList.contains("ui-hmap-strong")) return "a strong cell's text is not light";
const cl = [...corr.querySelectorAll(".ui-hmap-legend span:not(.ui-hmap-bar)")].map((s) => s.textContent).join();
if (cl !== "-1.00,0.00,1.00") return `the diverging scale reads ${cl}`;

const empty = uptime.querySelectorAll(".ui-hmap-empty");
if (empty.length !== 1) return "a null value is not one hatched cell";
if (empty[0].querySelector(".ui-hmap-val") || empty[0].querySelector("b").textContent !== "—") return "the empty cell shows a value";
if (uptime.querySelectorAll("tbody tr")[1].querySelectorAll("td")[1].textContent !== "—") return "the table does not say the value is missing";
if (uptime.querySelector(".ui-hmap-val").textContent !== "99.95%") return "suffix is not written";
if (!uptime.querySelector(".ui-hmap-cell").classList.contains("ui-hmap-s3")) return "color={3} is not the third colour";
