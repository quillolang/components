const tips = $$(".ui-tooltip");
if (tips.length < 6) return `expected 6 tooltips, found ${tips.length}`;
const first = tips[0], tip = first.querySelector("[role=tooltip]");
if (!tip || first.getAttribute("aria-describedby") !== tip.id) return "the wrapper is not described by its tooltip";
if (new Set(tips.map((t) => t.getAttribute("aria-describedby"))).size !== tips.length) return "tooltip ids are not distinct";
if (getComputedStyle(tip).display !== "none") return "the tooltip shows before hover or focus";
first.querySelector("button").focus(); await wait(400);
if (getComputedStyle(tip).display === "none" || getComputedStyle(tip).opacity !== "1") return "focusing the button does not show its tooltip";
const b = tip.getBoundingClientRect(), t = first.getBoundingClientRect();
if (!(b.bottom <= t.top)) return "a top tooltip is not above its target";
const left = tips[2].querySelector("[role=tooltip]");
tips[2].querySelector("button").focus(); await wait(400);
if (!(left.getBoundingClientRect().right <= tips[2].getBoundingClientRect().left)) return "a left tooltip is not to the left";
const bottom = tips[1].querySelector("[role=tooltip]");
tips[1].querySelector("button").focus(); await wait(400);
if (!(bottom.getBoundingClientRect().top >= tips[1].getBoundingClientRect().bottom)) return "a bottom tooltip is not below";
document.activeElement.blur(); await wait(300);
if (getComputedStyle(tip).display !== "none") return "the tooltip stays after focus leaves";
if (document.documentElement.scrollWidth > innerWidth) return "hidden tooltips widen the page";
