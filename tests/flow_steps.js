const simple = $("#flow-steps-demo-simple");
if (simple.tagName !== "OL" || simple.getAttribute("aria-label") !== "Release") return "not a named <ol>";
const items = [...simple.querySelectorAll(".ui-flow-steps-item")];
if (items.map((i) => i.querySelector(".ui-flow-steps-title").textContent).join() !== "Write,Review,Merge,Deploy") return "the steps";
if (simple.querySelectorAll(".ui-flow-steps-arrow").length !== 3 || items[3].querySelector(".ui-flow-steps-arrow")) return "an arrow between each two, none after the last";
const r = items.map((i) => i.querySelector(".ui-flow-steps-box").getBoundingClientRect());
if (!(r[0].right < r[1].left && Math.abs(r[0].top - r[1].top) < 1)) return "horizontal boxes are not in a row";
const a = items[0].querySelector(".ui-flow-steps-arrow").getBoundingClientRect();
if (!(a.left >= r[0].right - 1 && a.right <= r[1].left + 1)) return "the arrow is not between the boxes";
const order = $("#flow-steps-demo-order");
const oi = [...order.querySelectorAll(".ui-flow-steps-item")];
if (oi.map((i) => i.querySelector(".ui-flow-steps-num").textContent).join() !== "1,2,3,4") return "numbered";
if (oi[2].getAttribute("aria-current") !== "step" || !oi[2].classList.contains("ui-flow-steps-current")) return "the current step";
if (!oi[0].querySelector(".ui-sr")?.textContent.includes("done") || !oi[3].classList.contains("ui-flow-steps-coming")) return "done and coming";
if (oi[1].querySelector(".ui-flow-steps-then").textContent !== "within a day") return "words on the arrow";
const v = $("#flow-steps-demo-vertical");
const vr = [...v.querySelectorAll(".ui-flow-steps-box")].map((b) => b.getBoundingClientRect());
if (!(vr[0].bottom < vr[1].top && Math.abs(vr[0].left - vr[1].left) < 1)) return "vertical boxes are not stacked";
if (!v.querySelector(".ui-flow-steps-item").classList.contains("ui-flow-steps-info")) return "tone";
