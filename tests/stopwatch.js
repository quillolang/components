const sw = $(".ui-stopwatch");
const time = () => sw.querySelector(".ui-stopwatch-time").textContent;
const btns = () => [...sw.querySelectorAll(".ui-stopwatch-buttons button")];
const byText = (t) => btns().find((b) => b.textContent === t);
const note = () => sw.closest(".demo-stack").querySelector(".demo-note").textContent;
const secs = (s) => { const [m, rest] = s.split(":"); return Number(m) * 60 + Number(rest); };
if (sw.getAttribute("role") !== "group" || sw.getAttribute("aria-label") !== "Run") return "the stopwatch is not a named group";
if (time() !== "00:00.00" || !byText("Start") || !byText("Reset").disabled) return `it starts at ${time()} with ${btns().map((b) => b.textContent)}`;
if (sw.querySelector("[role=timer]") === null) return "the time is not a timer";
byText("Start").click(); await wait(600);
if (!byText("Stop") || !byText("Lap")) return "running does not show Stop and Lap";
const t1 = secs(time());
if (t1 < 0.4 || t1 > 1.2) return `after 0.6 s it reads ${time()}`;
byText("Lap").click(); await wait(400);
byText("Lap").click(); await wait(100);
const laps = () => [...sw.querySelectorAll(".ui-stopwatch-lap")];
if (laps().length !== 2 || !laps()[0].textContent.startsWith("Lap 2")) return "laps are not listed newest first";
if (!laps().some((l) => l.classList.contains("ui-stopwatch-fast")) || !laps().some((l) => l.classList.contains("ui-stopwatch-slow"))) return "the fastest and slowest are not marked";
const lap2 = secs(laps()[0].querySelectorAll("span")[1].textContent);
if (lap2 < 0.3 || lap2 > 0.7) return `lap 2 lasted ${lap2}`;
byText("Stop").click(); await wait();
const stopped = time();
await wait(300);
if (time() !== stopped) return "it keeps running after Stop";
if (!byText("Resume") || byText("Reset").disabled) return "stopped, it does not offer Resume and Reset";
if (!sw.querySelector("[aria-live]").textContent.startsWith("Stopped at")) return "stopping is not announced";
if (note() !== "start · lap 1 · lap 2 · stop ok") return `the callbacks reached the note as: ${note()}`;
// Space on the stopwatch starts and stops it; L takes a lap.
sw.focus(); key(sw, " "); await wait(300);
if (!byText("Stop") || secs(time()) <= secs(stopped)) return "Space did not resume it";
key(sw, "l"); await wait();
if (laps().length !== 3) return "L did not take a lap";
key(sw, " "); await wait();
if (!byText("Resume")) return "Space did not stop it";
byText("Reset").click(); await wait();
if (time() !== "00:00.00" || laps().length !== 0 || !byText("Start")) return "Reset did not clear it";
if (!note().endsWith("reset")) return "on_reset was not called";
const sm = $("#stopwatch-demo-sm .ui-stopwatch");
if (!sm.classList.contains("ui-stopwatch-sm") || sm.getAttribute("aria-label") !== "Plank") return "size sm or the label are not applied";
sm.querySelector(".ui-stopwatch-go").click(); await wait(200);
if ([...sm.querySelectorAll(".ui-stopwatch-buttons button")].some((b) => b.textContent === "Lap")) return "laps={false} still shows Lap";
sm.querySelector(".ui-stopwatch-stop").click(); await wait();
