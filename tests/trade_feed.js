const live = $("#trade_feed-demo-live .ui-tfeed"), still = $("#trade_feed-demo-still .ui-tfeed");
if (!live || !still) return "the two feeds are missing";
const ids = () => [...live.querySelectorAll("tbody tr")].map((r) => Number(r.dataset.id));
const status = () => live.querySelector("[role=status]").textContent;
let a = ids();
if (a.length !== 12) return `limit={12} shows ${a.length} rows`;
if (a.some((v, i) => i > 0 && v !== a[i - 1] - 1)) return `not newest first: ${a}`;
const box = live.querySelector(".ui-tfeed-box");
if (box.getAttribute("role") !== "region" || box.getAttribute("aria-label") !== "BTC-USD trades") return "the list is not a named region";
for (const r of live.querySelectorAll("tbody tr")) {
    const sell = r.querySelector(".ui-sr").textContent.trim() === "sell";
    if (r.classList.contains("ui-tfeed-sell") !== sell) return "a row's colour does not say its side";
    if (!/^\d\d:\d\d:\d\d$/.test(r.cells[0].textContent)) return `time ${r.cells[0].textContent}`;
}
if (getComputedStyle(live.querySelector(".ui-tfeed-buy .ui-tfeed-price")).color === getComputedStyle(live.querySelector(".ui-tfeed-sell .ui-tfeed-price")).color) return "buys and sells share a colour";
await wait(1400);
let b = ids();
if (!(b[0] > a[0]) || b.length !== 12) return `no new trade came in (${a[0]} then ${b[0]})`;
const top = live.querySelector("tbody tr");
if (!top.classList.contains("ui-tfeed-new")) return "a new row does not flash";
if (!/^Last 12 of \d+$/.test(status())) return `status: ${status()}`;
const pause = live.querySelector(".ui-tfeed-pause");
pause.click(); await wait();
if (pause.getAttribute("aria-pressed") !== "true" || pause.textContent !== "Resume") return "Pause is not pressed";
const held = ids();
await wait(1400);
if (ids().join() !== held.join()) return "rows changed while paused";
if (!/^Paused · [1-9]\d* new$/.test(status())) return `while paused: ${status()}`;
pause.click(); await wait();
if (!(ids()[0] > held[0])) return "Resume did not show the trades that came";
$("#trade_feed-demo-toggle").click(); await wait();
const stopped = ids();
await wait(900);
if (ids().join() !== stopped.join()) return "the demo's feed did not stop";
const rows = [...still.querySelectorAll("tbody tr")];
if (rows.length !== 4 || rows[0].cells[2].textContent !== "25,000") return "the still feed";
if (!rows[0].classList.contains("ui-tfeed-large") || rows[1].classList.contains("ui-tfeed-large")) return "large={10000} does not pick out the big trade";
const ticks = rows.map((r) => r.querySelector(".ui-tfeed-tick").textContent);
if (ticks.join() !== ",▼,▲,") return `tick arrows: ${ticks}`;
if (rows.some((r) => r.classList.contains("ui-tfeed-new"))) return "trades the page starts with flash";
if (document.documentElement.scrollWidth > innerWidth) return "widens the page";
