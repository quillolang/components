const box = $("#infinite-scroll-demo-box");
const items = () => box.querySelectorAll("li").length;
const note = () => $(".demo-note").textContent;
const end = box.querySelector(".ui-infscroll-end");
if (!end || end.getAttribute("role") !== "status") return "no status sentinel";
if (items() !== 10) return `it starts with ${items()} items`;
const btn = end.querySelector(".ui-infscroll-btn");
if (!btn || btn.textContent !== "Load more") return "no Load more button";
box.scrollTop = box.scrollHeight; box.dispatchEvent(new Event("scroll")); await wait(500);
if (items() !== 20) return `scrolling to the end gave ${items()} items: ${note()}`;
if (!note().startsWith("20 of 40 entries, asked for more 1 time")) return `the note: ${note()}`;
box.scrollTop = box.scrollHeight; box.dispatchEvent(new Event("scroll")); await wait(500);
if (items() !== 30) return `the second scroll gave ${items()} items`;
box.scrollTop = 0; await wait(300);
end.querySelector(".ui-infscroll-btn").click(); await wait();
if (items() !== 40) return `the button gave ${items()} items`;
if (end.textContent.trim() !== "That's all" || end.querySelector("button")) return `done does not say so: ${end.textContent}`;
box.scrollTop = box.scrollHeight; box.dispatchEvent(new Event("scroll")); await wait(500);
if (!note().startsWith("40 of 40 entries, asked for more 3 times")) return `done still asks: ${note()}`;
