const row = $("[role=tablist].ui-filtertabs");
if (!row || row.getAttribute("aria-label") !== "Filter") return "it is not a labelled tablist";
const tabs = [...row.querySelectorAll("[role=tab]")];
if (tabs.length !== 4 || tabs[0].getAttribute("aria-selected") !== "true" || tabs[1].tabIndex !== -1) return "it does not start on All";
if (tabs[0].getAttribute("aria-controls") !== "filter-tabs-demo-list") return "the tabs do not say what they control";
const counts = tabs.map((t) => t.querySelector(".ui-filtertabs-count")?.firstChild.textContent);
if (counts.join() !== "6,3,3,0") return `the counts are ${counts}`;
if (!tabs[3].disabled) return "disabled: true does not disable the tab";
const hidden = row.querySelector("input[type=hidden][name=status]");
if (!hidden || hidden.value !== "all") return "the hidden input does not hold the key";
const list = () => document.getElementById("filter-tabs-demo-list").querySelectorAll("li").length;
const note = () => row.closest(".demo-stack").querySelector("p.demo-note").textContent;
if (list() !== 6) return "the list does not start with every item";
tabs[1].click(); await wait();
if (tabs[1].getAttribute("aria-selected") !== "true" || list() !== 3 || hidden.value !== "open" || !note().includes("3 of 6")) return `clicking Open did not filter: ${list()} shown, hidden ${hidden.value}`;
if (getComputedStyle(tabs[1]).backgroundColor === getComputedStyle(tabs[2]).backgroundColor) return "the selected tab does not look it";
key(tabs[1], "ArrowRight"); await wait();
if (tabs[2].getAttribute("aria-selected") !== "true" || document.activeElement !== tabs[2] || hidden.value !== "closed") return "ArrowRight did not select and focus Closed";
key(tabs[2], "ArrowRight"); await wait();
if (tabs[0].getAttribute("aria-selected") !== "true" || list() !== 6) return "ArrowRight from the last live tab did not wrap to All, skipping the disabled one";
key(tabs[0], "End"); await wait();
if (tabs[2].getAttribute("aria-selected") !== "true") return "End did not go to the last live tab";
const line = $$("[role=tablist].ui-filtertabs")[1];
if (!line.classList.contains("ui-filtertabs-line") || line.querySelector("[aria-selected=true]")?.textContent.trim().startsWith("Bugs") !== true) return "the line variant does not start on its selected key";
if (line.querySelector("input[type=hidden]")) return "without a name there should be no hidden input";
