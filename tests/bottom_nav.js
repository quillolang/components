const nav = $("#bottom-nav-demo");
if (!nav || nav.tagName !== "NAV" || nav.getAttribute("aria-label") !== "Main") return "the bar is not a labelled <nav>";
const items = [...nav.querySelectorAll("a.ui-bottomnav-item")];
if (items.length !== 4) return `expected 4 links, found ${items.length}`;
const cur = items.filter((a) => a.getAttribute("aria-current") === "page");
if (cur.length !== 1 || !cur[0].textContent.includes("Inbox")) return "the current page is not marked once";
if (cur[0].querySelector(".ui-bottomnav-badge")?.textContent !== "3" || !cur[0].textContent.includes("3 new")) return "the badge is not shown and told";
if (!items[0].querySelector(".ui-bottomnav-icon svg path")) return "an SVG path icon is not drawn";
const tops = items.map((a) => Math.round(a.getBoundingClientRect().top));
if (new Set(tops).size !== 1) return "the tabs are not in one row";
const ic = items[0].querySelector(".ui-bottomnav-icon").getBoundingClientRect(), tx = items[0].querySelector(".ui-bottomnav-text").getBoundingClientRect();
if (tx.top < ic.bottom - 1) return "the label is not under the icon";
if (getComputedStyle(nav).position === "fixed") return "fixed={false} still fixes it";
const live = $("#bottom-nav-demo-live");
const btns = [...live.querySelectorAll("button.ui-bottomnav-item")];
if (btns.length !== 3 || btns[0].getAttribute("aria-current") !== "true") return "the live bar does not start on Feed";
if (btns[1].title !== "Explore" || btns[1].querySelector(".ui-bottomnav-text").getBoundingClientRect().width > 1) return "without labels, the tooltip or the hidden text is wrong";
btns[2].click(); await wait();
if (!live.closest(".demo-stack").querySelector(".demo-note").textContent.includes("Saved") || btns[2].getAttribute("aria-current") !== "true") return "on_select did not reach the note";
