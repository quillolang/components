if (document.documentElement.scrollWidth > innerWidth) return "widens the page";
const charts = $$("figure.ui-bulletc");
if (charts.length !== 2) return `expected 2 bullet charts, found ${charts.length}`;
if (/NaN|Infinity|undefined/.test(charts.map((c) => c.innerHTML).join(""))) return "a chart has NaN, Infinity or undefined in it";
const [goals, times] = charts;
const tracks = [...goals.querySelectorAll(".ui-bulletc-track")];
if (tracks.length !== 5) return `5 items made ${tracks.length} rows`;
const t0 = tracks[0].getBoundingClientRect();
const bands = [...tracks[0].querySelectorAll(".ui-bulletc-band")].map((b) => b.getBoundingClientRect());
if (bands.length !== 3) return "three ranges did not make three bands";
if (Math.abs(bands[2].right - t0.right) > 0.6 || Math.abs(bands[0].width - t0.width * 150 / 300) > 0.6) return "the bands are not where the ranges end";
const shades = [...tracks[0].querySelectorAll(".ui-bulletc-band")].map((b) => getComputedStyle(b).backgroundColor);
if (new Set(shades).size !== 3) return "the bands are not three shades";
const bar = tracks[0].querySelector(".ui-bulletc-bar").getBoundingClientRect();
if (Math.abs(bar.width - t0.width * 270 / 300) > 0.6) return "the measure is not as long as its value";
if (!(bar.height < t0.height / 2)) return "the measure is not thinner than the bands";
const tg = tracks[0].querySelector(".ui-bulletc-target").getBoundingClientRect();
if (Math.abs((tg.left + tg.right) / 2 - (t0.left + t0.width * 250 / 300)) > 0.6) return "the target is not at 250 of 300";
const ticks = [...goals.querySelectorAll(".ui-bulletc-ticks")[0].querySelectorAll("span")].map((s) => s.textContent);
if (ticks[0] !== "0" || ticks[ticks.length - 1] !== "300") return `the ticks: ${ticks}`;
const name = goals.querySelector(".ui-bulletc-name");
if (name.querySelector("b").textContent !== "Revenue" || name.querySelector("small").textContent !== "US$, thousands") return "the label and its sub";
const tip = goals.querySelectorAll(".ui-bulletc-tip")[2];
if (getComputedStyle(tip).display !== "none") return "the tooltip shows before hover";
if (tip.textContent !== "Order sizeValue320Target550BandPoor") return `tooltip: ${tip.textContent}`;
if (goals.querySelectorAll("tbody tr")[0].textContent !== "Revenue (US$, thousands)270250Good") return `the table: ${goals.querySelectorAll("tbody tr")[0].textContent}`;

const tb = [...times.querySelectorAll(".ui-bulletc-track")[0].querySelectorAll(".ui-bulletc-band")].map((b) => getComputedStyle(b).backgroundColor);
if (tb[0] !== shades[2] || tb[2] !== shades[0]) return "lower_is_better does not shade the first band lightest";
const rows = [...times.querySelectorAll("tbody tr")].map((r) => r.lastElementChild.textContent);
if (rows.join() !== "Fast,Fair,Slow") return `lower_is_better bands: ${rows}`;
if (times.querySelectorAll("tbody td")[0].textContent !== "180 ms") return "shared ranges and suffix";
