const cards = $$(".ui-quick-view"), note = () => $(".demo-note").textContent;
if (cards.length !== 3) return `expected 3 cards, found ${cards.length}`;
const [first] = cards, btn = first.querySelector(".ui-quick-view-open"), dlg = first.querySelector("dialog.ui-quick-view-dialog");
if (!first.querySelector("strong") || first.querySelector("strong").textContent !== "Linen shirt") return "the card (children) is not shown";
if (btn.getAttribute("aria-label") !== "Quick view: Linen shirt" || btn.getAttribute("aria-haspopup") !== "dialog") return "the button is not named for its item";
if (getComputedStyle(btn).opacity !== "0") return "the button shows before hover or focus";
btn.focus(); await wait(250);
if (getComputedStyle(btn).opacity !== "1") return "focus does not show the button";
if (dlg.open || dlg.getAttribute("aria-label") !== "Linen shirt") return "the dialog is not named, closed";
btn.click(); await wait(250);
if (!dlg.open) return "the button does not open the preview";
const img = dlg.querySelector("img.ui-quick-view-img");
if (!img || img.alt !== "Linen shirt, a placeholder picture" || !img.getAttribute("src").startsWith("data:image/svg")) return "the image or its alt is missing";
if (dlg.querySelector("h2").textContent !== "Linen shirt" || dlg.querySelector(".ui-quick-view-meta").textContent !== "€49" || !dlg.querySelector(".ui-quick-view-text").textContent.includes("washed linen")) return "title, meta or text missing";
const link = dlg.querySelector("a.ui-quick-view-link");
if (!link || link.getAttribute("href") !== "#quick_view" || link.textContent !== "View details →") return "no details link";
const ir = img.getBoundingClientRect(), info = dlg.querySelector(".ui-quick-view-info").getBoundingClientRect();
if (info.left < ir.right - 1) return "the image and the info are not side by side";
dlg.querySelector(".ui-quick-view-act").click(); await wait();
if (dlg.open || note() !== "In the cart: Linen shirt.") return `the action does not run and close: ${note()}`;
const second = cards[1], d2 = second.querySelector("dialog");
second.querySelector(".ui-quick-view-open").click(); await wait(250);
if (!d2.open || d2.querySelector("h2").textContent !== "Wool scarf") return "the second card opens the wrong preview";
d2.querySelector(".ui-quick-view-x").click(); await wait();
if (d2.open) return "the close button does not close it";
second.querySelector(".ui-quick-view-open").click(); await wait(250);
d2.dispatchEvent(new MouseEvent("click", { bubbles: true })); await wait();
if (d2.open) return "a click outside does not close it";
if (note() !== "In the cart: Linen shirt.") return "closing ran the action";
