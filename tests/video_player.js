const [main, quiet] = $$(".ui-video-player");
if (!main || !quiet) return "expected two players";
if (main.getAttribute("role") !== "region" || main.getAttribute("aria-label") !== "A flower opening") return "the player is not a named region";
const v = main.querySelector("video");
if (!v || v.querySelectorAll("source").length !== 2 || !v.poster.startsWith("data:image/svg+xml")) return "the video, its sources or poster are missing";
main.scrollIntoView({ block: "center" });
const time = () => main.querySelector(".ui-video-player-time").textContent.trim();
for (let i = 0; i < 80 && time().endsWith("/ 0:00"); i++) await wait(150);
if (!/^0:00 \/ 0:\d\d$/.test(time())) return `before playing the time reads "${time()}" (the sample is from mdn.github.io)`;
const seek = main.querySelector(".ui-video-player-seek");
if (seek.getAttribute("aria-label") !== "Seek" || +seek.max < 5 || seek.disabled) return `the seek bar is not ready: max ${seek.max}`;
type(seek, "5"); await wait(400);
if (Math.abs(v.currentTime - 5) > 0.5) return `seeking to 5 put the video at ${v.currentTime}`;
if (!time().startsWith("0:05")) return `after seeking the time reads "${time()}"`;
if (!seek.getAttribute("aria-valuetext").startsWith("0:05 of")) return "the seek bar does not say the time";
const mute = main.querySelector('.ui-video-player-vol-box button');
if (mute.getAttribute("aria-label") !== "Mute") return `the mute button says ${mute.getAttribute("aria-label")}`;
mute.click(); await wait();
if (!v.muted || mute.getAttribute("aria-label") !== "Unmute" || mute.getAttribute("aria-pressed") !== "true") return "mute did not mute";
const vol = main.querySelector(".ui-video-player-vol");
if (vol.value !== "0") return `muted, the volume slider shows ${vol.value}`;
type(vol, "0.4"); await wait();
if (Math.abs(v.volume - 0.4) > 0.01 || v.muted) return `setting the volume gave ${v.volume}, muted ${v.muted}`;
// The sample is about 5 seconds long: ArrowLeft from 5 goes to 0, ArrowRight from 0 to 5.
key(main, "ArrowLeft"); await wait(300);
if (v.currentTime > 0.3) return `ArrowLeft from 5 seeks to ${v.currentTime}`;
key(main, "ArrowRight"); await wait(300);
if (Math.abs(v.currentTime - 5) > 0.3) return `ArrowRight from 0 seeks to ${v.currentTime}`;
key(main, "m"); await wait();
if (!v.muted) return "M does not mute";
if (!main.querySelector('[aria-label="Full screen"]')) return "there is no full screen button";
if (getComputedStyle(main.querySelector(".ui-video-player-big")).display === "none") return "the big play button is hidden before it starts";
// Playing: headless Chrome plays a muted video without a real click (not sound: the main one is not played here).
const qv = quiet.querySelector("video");
const note = () => $("#video-player-demo-events").textContent;
quiet.querySelector(".ui-video-player-big").click();
for (let i = 0; i < 40 && qv.paused; i++) await wait(150);
if (qv.paused) return "play did not start the muted video";
await wait(300);
if (quiet.querySelector(".ui-video-player-bar button").getAttribute("aria-label") !== "Pause") return "while playing the button does not say Pause";
if (getComputedStyle(quiet.querySelector(".ui-video-player-big")).display !== "none") return "the big play button stays once started";
quiet.querySelector(".ui-video-player-bar button").click(); await wait(300);
if (!qv.paused || note() !== "play, pause") return `pause: paused ${qv.paused}, events "${note()}"`;
key(quiet, " "); await wait(500);
if (qv.paused) return "Space does not play";
key(quiet, " "); await wait(300);
if (!qv.paused) return "Space does not pause";
