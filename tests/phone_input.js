const box = $("#phone-input-pi-demo-phone");
const host = box.closest(".ui-phone-input");
const select = host.querySelector("select");
const sent = () => [$("input[type=hidden][name=pi-demo-phone]").value, $("input[type=hidden][name=pi-demo-phone_country]").value].join(" ");
if (box.type !== "tel" || box.name) return "the box is not an unnamed tel input";
if (select.value !== "GB" || box.value !== "2079460958") return `+44 20 7946 0958 did not pick GB and the national digits: ${select.value} ${box.value}`;
if (sent() !== "+442079460958 GB") return `the form would send ${sent()}`;
if (host.querySelector(".ui-phone-input-code")?.textContent !== "+44") return "the dialling code is not shown";
if (select.getAttribute("aria-label") !== "Country" || !box.labels[0]?.textContent.includes("Phone")) return "the select and the box are not labelled";
if (![...select.options].some((o) => o.textContent.includes("Portugal") && o.textContent.includes("+351"))) return "the countries do not show names and codes";
type(select, "PT"); await wait();
if (host.querySelector(".ui-phone-input-code")?.textContent !== "+351" || sent() !== "+3512079460958 PT") return `changing the country: ${sent()}`;
type(box, "912 345 678"); await wait();
if (box.value !== "912 345 678" || sent() !== "+351912345678 PT") return `typing: "${box.value}" sends ${sent()}`;
type(box, "91a2#3"); await wait();
if (box.value !== "9123") return `letters got in: "${box.value}"`;
type(box, ""); await wait();
if (sent() !== " PT") return `emptied: ${sent()}`;
const live = $("#phone-input-pi-demo-mobile");
const lh = live.closest(".ui-phone-input");
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
if ([...lh.querySelector("select").options].map((o) => o.value).join() !== "PT,ES,FR,GB,US") return "countries={[...]} does not limit and order the list";
type(live, "912345678"); await wait();
if (note() !== "Will call +351912345678 (PT).") return `on_change: ${note()}`;
type(lh.querySelector("select"), "ES"); await wait();
if (note() !== "Will call +34912345678 (ES).") return `on_change after a country change: ${note()}`;
const bad = $("#phone-input-pi-demo-bad");
if (bad.getAttribute("aria-invalid") !== "true" || !bad.closest(".ui-phone-input").querySelector("[role=alert]")) return "error does not mark the box";
if (bad.value !== "555" || $("input[name=pi-demo-bad]").value !== "+1555") return "a value without + is not national digits";
if ($("#phone-input-pi-demo-sm").closest(".ui-phone-input").querySelector("select").value !== "JP") return "country=JP is not picked";
