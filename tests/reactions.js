const group = $("#reactions-demo-live-add").closest(".ui-reactions");
const chips = () => [...group.querySelectorAll(".ui-reactions-chip")];
const hidden = group.querySelector("input[type=hidden][name=reactions]");
const note = () => group.closest(".demo-stack").querySelector(".demo-note").textContent;
const add = $("#reactions-demo-live-add");
const menu = $("#reactions-demo-live-menu");
if (group.getAttribute("role") !== "group" || group.getAttribute("aria-label") !== "Reactions") return "the reactions are not a named group";
if (chips().length !== 3 || chips()[0].getAttribute("aria-pressed") !== "true" || chips()[0].getAttribute("aria-label") !== "thumbs up, 12, you reacted") return `the chips start as ${chips().map((c) => c.getAttribute("aria-label"))}`;
if (hidden.value !== "👍") return `the hidden input starts as "${hidden.value}"`;
if (!menu.hidden || add.getAttribute("aria-expanded") !== "false" || add.getAttribute("aria-controls") !== menu.id) return "the menu starts open or is not tied to the button";
chips()[1].click(); await wait();
if (chips()[1].getAttribute("aria-pressed") !== "true" || chips()[1].querySelector(".ui-reactions-count").textContent !== "4" || hidden.value !== "👍,❤️") return `reacting: ${chips()[1].textContent} / ${hidden.value}`;
if (note() !== "Last: ❤️ on.") return `on_change did not reach the note: ${note()}`;
chips()[0].click(); await wait();
if (chips()[0].getAttribute("aria-pressed") !== "false" || chips()[0].querySelector(".ui-reactions-count").textContent !== "11" || hidden.value !== "❤️") return "taking a reaction back did not count down";
if (note() !== "Last: 👍 off.") return `on_change(off): ${note()}`;
chips()[2].click(); await wait();
if (chips().length !== 3 || chips()[2].querySelector(".ui-reactions-count").textContent !== "2") return "reacting with the party emoji did not count up";
chips()[2].click(); await wait();
if (chips()[2].getAttribute("aria-pressed") !== "false" || chips()[2].querySelector(".ui-reactions-count").textContent !== "1") return "taking back the party did not count down";
add.click(); await wait();
if (menu.hidden || add.getAttribute("aria-expanded") !== "true") return "the add button did not open the menu";
const picks = [...menu.querySelectorAll(".ui-reactions-pick")];
if (picks.length !== 6 || picks[1].getAttribute("aria-pressed") !== "true") return "the menu does not show six emoji with the heart pressed";
picks[2].click(); await wait();
if (!menu.hidden || chips().length !== 4 || chips()[3].textContent.trim() !== "😂1" || hidden.value !== "❤️,😂") return `picking from the menu: ${chips().map((c) => c.textContent.trim())} / ${hidden.value}`;
if (note() !== "Last: 😂 on.") return `on_change from the menu: ${note()}`;
chips()[3].click(); await wait();
if (chips().length !== 3) return "a chip whose count reaches zero stays";
add.click(); await wait(); key(group, "Escape"); await wait();
if (!menu.hidden) return "Escape did not close the menu";
const empty = $("#reactions-demo-empty-add");
if (empty.getAttribute("aria-label") !== "React" || empty.closest(".ui-reactions").querySelectorAll(".ui-reactions-chip").length !== 0) return "an empty set is not just the add button";
if (!$("#reactions-demo-sm-add").closest(".ui-reactions").classList.contains("ui-reactions-sm")) return "size sm is not applied";
