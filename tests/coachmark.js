localStorage.removeItem("ui-coach:demo-share");
const near = (a, b, tol = 3) => Math.abs(a - b) <= tol;
const marks = $$(".ui-coach");
if (marks.length !== 2) return `expected 2 open coachmarks (one per step, and the share one), found ${marks.length}`;
const first = marks.find((m) => m.getAttribute("aria-label") === "Export is here now");
if (!first || first.getAttribute("role") !== "dialog") return "the first is not a dialog named by its title";
if (first.querySelector(".ui-coach-step")?.textContent !== "1 of 2" || first.querySelector(".ui-coach-btn")?.textContent !== "Next") return "step or done text";
const exp = $("#coachmark-demo-export");
if (!exp.classList.contains("ui-coach-target")) return "the target is not marked";
let r = first.getBoundingClientRect(), t = exp.getBoundingClientRect();
if (!near(r.top, t.bottom + 10) || !near((r.left + r.right) / 2, (t.left + t.right) / 2)) return `the callout is not under its target: ${JSON.stringify(r)} vs ${JSON.stringify(t)}`;
if (getComputedStyle(first).visibility !== "visible") return "the callout is hidden";
first.querySelector(".ui-coach-btn").click(); await wait();
if (!$(".demo-note").textContent.includes("step 2 of 2")) return `on_done did not move the tour on: ${$(".demo-note").textContent}`;
if (exp.classList.contains("ui-coach-target")) return "the first target stays marked";
const second = $$(".ui-coach").find((m) => m.getAttribute("aria-label") === "Filter the list");
if (!second) return "the second step did not open";
const fil = $("#coachmark-demo-filters");
r = second.getBoundingClientRect(); t = fil.getBoundingClientRect();
if (!near(r.left, t.right + 10) || !near((r.top + r.bottom) / 2, (t.top + t.bottom) / 2)) return `placement right is not beside the target: ${JSON.stringify(r)} vs ${JSON.stringify(t)}`;
if (!fil.classList.contains("ui-coach-target")) return "the second target is not marked";
window.scrollBy(0, 40); await wait(300);
const r2 = second.getBoundingClientRect(), t2 = fil.getBoundingClientRect();
if (!near(r2.left, t2.right + 10) || !near((r2.top + r2.bottom) / 2, (t2.top + t2.bottom) / 2)) return "it does not follow the target when the page scrolls";
window.scrollBy(0, -40); await wait(300);
second.querySelector(".ui-coach-btn").focus(); key(second.querySelector(".ui-coach-btn"), "Escape"); await wait();
if ($$(".ui-coach").length !== 1 || !$(".demo-note").textContent.includes("Tour done")) return "Escape did not finish the step";
const share = $(".ui-coach");
const sh = $("#coachmark-demo-share");
r = share.getBoundingClientRect(); t = sh.getBoundingClientRect();
if (!near(r.bottom, t.top - 10)) return "placement top is not above the target";
share.querySelector(".ui-coach-btn").click(); await wait();
if ($$(".ui-coach").length !== 0) return "Got it did not close it";
if (localStorage.getItem("ui-coach:demo-share") !== "1") return "remember did not keep the dismissal";
localStorage.removeItem("ui-coach:demo-share");
