const menu = $("#ctx-file");
const items = () => [...menu.querySelectorAll("[role=menuitem]")];
const note = () => $(".demo-note").textContent;
if (menu.getAttribute("role") !== "menu" || !menu.hasAttribute("popover")) return "the menu is not a popover with role=menu";
if (area.tabIndex !== 0 || !area.getAttribute("aria-describedby")) return "the area cannot be focused or does not tell about the menu";
area.scrollIntoView({ block: "center" });
const ar = area.getBoundingClientRect();
const x = ar.left + 40, y = ar.top + 20;
const ev = new MouseEvent("contextmenu", { clientX: x, clientY: y, bubbles: true, cancelable: true });
area.dispatchEvent(ev); await wait();
if (!ev.defaultPrevented) return "the browser's own menu is not held back";
if (!menu.matches(":popover-open")) return "right-click does not open the menu";
const m = menu.getBoundingClientRect();
if (Math.abs(m.left - x) > 2 || Math.abs(m.top - y) > 2) return `the menu is at ${m.left},${m.top}, not at the pointer ${x},${y}`;
if (document.activeElement !== items()[0]) return "the first item is not focused";
if (menu.querySelectorAll("[role=separator]").length !== 2) return "dividers are not separators";
if (items()[2].querySelector(".ui-ctx-key").textContent !== "Ctrl D" || items()[2].getAttribute("aria-keyshortcuts") !== "Ctrl+D") return "shortcuts are not shown";
key(document.activeElement, "ArrowDown"); await wait(100);
if (document.activeElement !== items()[1]) return "ArrowDown does not move to the next item";
key(document.activeElement, "ArrowUp"); key(document.activeElement, "ArrowUp"); await wait(100);
if (document.activeElement !== items().at(-1)) return "ArrowUp from the first does not wrap to the last";
key(document.activeElement, "Home"); await wait(100);
if (document.activeElement !== items()[0]) return "Home does not go to the first";
key(document.activeElement, "d"); await wait(100);
if (document.activeElement.textContent.trim() !== "DuplicateCtrl D") return `typing d goes to ${document.activeElement.textContent}`;
key(document.activeElement, "d"); await wait(100);
if (!document.activeElement.textContent.startsWith("Download")) return `typing d again goes to ${document.activeElement.textContent}`;
const share = items().find((i) => i.textContent.startsWith("Share"));
if (share.getAttribute("aria-disabled") !== "true") return "disabled is not marked";
share.click(); await wait();
if (!menu.matches(":popover-open") || note() !== "No action yet.") return "a disabled item does something";
items().find((i) => i.textContent.startsWith("Rename")).click(); await wait();
if (menu.matches(":popover-open")) return "choosing does not close the menu";
if (note() !== "Chose “Rename”.") return `on_select: ${note()}`;
if (document.activeElement !== area) return "focus does not go back to the area";
area.dispatchEvent(new KeyboardEvent("keydown", { key: "F10", shiftKey: true, bubbles: true, cancelable: true })); await wait();
if (!menu.matches(":popover-open")) return "Shift+F10 does not open the menu";
key(document.activeElement, "Escape"); await wait();
if (menu.matches(":popover-open") || document.activeElement !== area) return "Escape does not close the menu and go back to the area";
key(area, "ContextMenu"); await wait();
if (!menu.matches(":popover-open")) return "the Menu key does not open the menu";
menu.hidePopover();
const edge = new MouseEvent("contextmenu", { clientX: innerWidth - 5, clientY: innerHeight - 5, bubbles: true, cancelable: true });
area.dispatchEvent(edge); await wait();
const e2 = menu.getBoundingClientRect();
if (e2.right > innerWidth || e2.bottom > innerHeight) return "near the corner the menu goes off the screen";
menu.hidePopover();
area.dispatchEvent(new PointerEvent("pointerdown", { pointerType: "touch", clientX: x, clientY: y, bubbles: true })); await wait(800);
if (!menu.matches(":popover-open")) return "a long press does not open the menu";
area.dispatchEvent(new PointerEvent("pointerup", { pointerType: "touch", bubbles: true }));
menu.hidePopover();
