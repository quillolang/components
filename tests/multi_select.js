const box = $("#ms-demo-langs");
const sent = (n) => $$(`input[type=hidden][name=${n}]`).map((i) => i.value).join(",");
const pop = box.closest(".ui-multi-select").querySelector(".ui-multi-select-pop");
const opts = () => [...$("#ms-demo-langs-list").querySelectorAll("[role=option]")];
if (box.getAttribute("role") !== "combobox" || box.getAttribute("aria-controls") !== "ms-demo-langs-list") return "the search is not a combobox for its list";
if ($("#ms-demo-langs-list").getAttribute("aria-multiselectable") !== "true") return "the list is not multi-select";
if (sent("langs") !== "en,pt") return `starts sending: ${sent("langs")}`;
if (box.name) return "the search box would be sent";
const chips = () => [...box.closest(".ui-multi-select-box").querySelectorAll(".ui-multi-select-chip")].map((c) => c.textContent.trim());
if (chips().join() !== "English,Portuguese") return `chips: ${chips()}`;
if (!pop.hidden) return "the list starts open";
key(box, "ArrowDown"); await wait();
if (pop.hidden || box.getAttribute("aria-expanded") !== "true") return "ArrowDown did not open the list";
if (opts().length !== 16 || !opts()[0].textContent.includes("Select all")) return `expected Select all and 15 options, got ${opts().length}`;
if (opts().find((o) => o.textContent.includes("English")).getAttribute("aria-selected") !== "true") return "a chosen option is not aria-selected";
type(box, "an"); await wait();
const names = opts().map((o) => o.textContent.trim());
if (names.join() !== "Select all 5 shown,German,Italian,Japanese,Korean,Spanish") return `"an" shows: ${names}`;
if (box.getAttribute("aria-activedescendant") !== opts()[0].id) return "the first row is not active";
key(box, "ArrowDown"); key(box, "Enter"); await wait();
if (sent("langs") !== "en,de,pt") return `Enter did not tick German (in the options' order): ${sent("langs")}`;
key(box, "ArrowUp"); key(box, "Enter"); await wait();
if (sent("langs") !== "en,de,it,ja,ko,pt,es") return `Select all did not tick the shown ones: ${sent("langs")}`;
if (opts()[0].getAttribute("aria-selected") !== "true") return "Select all is not shown as selected";
key(box, "Enter"); await wait();
if (sent("langs") !== "en,pt") return `Select all again did not untick them: ${sent("langs")}`;
key(box, "Escape"); await wait();
if (!pop.hidden) return "Escape did not close the list";
key(box, "Escape"); await wait();
if (box.value !== "") return "Escape on a closed list did not clear the search";
key(box, "Backspace"); await wait();
if (sent("langs") !== "en") return `Backspace did not take the last chip off: ${sent("langs")}`;
box.closest(".ui-multi-select-box").querySelector('button[aria-label="Remove English"]').click(); await wait();
if (sent("langs") !== "" || chips().length !== 0) return "× did not remove English";
if (!box.closest(".ui-multi-select").querySelector("[aria-live]").textContent.includes("English removed")) return "removing is not announced";
if (document.getElementById("ms-demo-langs-count").textContent !== "None chosen") return "the count is not kept";
box.click(); await wait();
opts()[4].click(); await wait();
if (sent("langs") !== "en") return `clicking an option: ${sent("langs")}`;
box.dispatchEvent(new FocusEvent("focusout", { bubbles: true, relatedTarget: document.body })); await wait();
if (!pop.hidden) return "leaving did not close the list";
// max 2: a third cannot be added; on_change gets the list.
const rv = $("#ms-demo-reviewers");
rv.click(); await wait();
const ropts = () => [...$("#ms-demo-reviewers-list").querySelectorAll("[role=option]")];
if (ropts()[0].textContent.includes("Select all")) return "max still offers Select all";
ropts()[0].click(); ropts()[1].click(); await wait();
if (sent("reviewers") !== "Ada,Grace") return `max 2 did not hold: ${sent("reviewers")}`;
if (ropts()[1].getAttribute("aria-disabled") !== "true") return "options past max are not marked disabled";
const note = rv.closest(".demo-stack").querySelector(".demo-note").textContent;
if (note !== "Review by Ada and Grace.") return `on_change: ${note}`;
rv.dispatchEvent(new FocusEvent("focusout", { bubbles: true, relatedTarget: document.body }));
if ($("#ms-demo-days").getAttribute("aria-invalid") !== "true") return "error does not mark it";
