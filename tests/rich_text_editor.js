const area = $("#rich-text-editor-rte-demo-body");
const host = area.closest(".ui-rich-text-editor");
const hidden = $("input[type=hidden][name=rte-demo-body]");
const tool = (h, name) => h.querySelector(`button[aria-label^="${name}"]`);
if (area.getAttribute("contenteditable") !== "true" || area.getAttribute("role") !== "textbox" || area.getAttribute("aria-multiline") !== "true") return "the area is not an editable multiline textbox";
if (!document.getElementById(area.getAttribute("aria-labelledby"))?.textContent.includes("Description")) return "the area is not labelled";
if (area.querySelector("quillo-raw")) return "the starting HTML is still wrapped";
if (area.querySelector("b")?.textContent !== "bold" || area.querySelectorAll("li").length !== 2) return `the starting HTML is not shown: ${area.innerHTML}`;
if (!hidden.value.includes("<b>bold</b>")) return `the hidden input starts as: ${hidden.value}`;
if (host.querySelector("[role=toolbar]")?.querySelectorAll("button").length !== 10) return "the toolbar does not have every tool";
// Select "start" and make it italic.
area.focus();
const textNode = [...area.querySelector("p").childNodes].find((n) => n.nodeType === 3 && n.textContent.includes("start"));
const at = textNode.textContent.indexOf("start");
const sel = getSelection(); const r = document.createRange();
r.setStart(textNode, at); r.setEnd(textNode, at + 5); sel.removeAllRanges(); sel.addRange(r);
tool(host, "Italic").click(); await wait();
if (!/<i>start<\/i>|<em>start<\/em>/.test(area.innerHTML)) return `italic: ${area.innerHTML}`;
if (!/<i>start<\/i>|<em>start<\/em>/.test(hidden.value)) return "the hidden input does not follow";
if (tool(host, "Italic").getAttribute("aria-pressed") !== "true") return "the Italic button does not show it is on";
const live = $("#rich-text-editor-rte-demo-note");
const lh = live.closest(".ui-rich-text-editor");
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
if (lh.querySelector("[role=toolbar]").querySelectorAll("button").length !== 4) return "tools={[...]} is not kept";
live.focus();
document.execCommand("insertText", false, "hello world"); await wait();
if (note() !== "HTML: hello world") return `typing: ${note()}`;
const tn = live.firstChild; const r2 = document.createRange(); r2.setStart(tn, 0); r2.setEnd(tn, 5);
getSelection().removeAllRanges(); getSelection().addRange(r2);
live.dispatchEvent(new KeyboardEvent("keydown", { key: "b", ctrlKey: true, bubbles: true, cancelable: true })); await wait();
if (!note().includes("<b>hello</b>")) return `Ctrl+B: ${note()}`;
tool(lh, "Bulleted").click(); await wait();
if (!note().includes("<ul>")) return `list: ${note()}`;
