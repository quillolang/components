const [mail, sql, live] = $$(".ui-splitter");
if (!mail || !sql || !live) return "expected three splitters";
const bar = mail.querySelector("[role=separator]");
if (!bar || bar.tabIndex !== 0) return "the divider is not a focusable separator";
if (bar.getAttribute("aria-valuenow") !== "30" || bar.getAttribute("aria-valuemin") !== "20" || bar.getAttribute("aria-valuemax") !== "60") return `the divider's values are ${bar.getAttribute("aria-valuenow")} ${bar.getAttribute("aria-valuemin")}-${bar.getAttribute("aria-valuemax")}`;
if (bar.getAttribute("aria-orientation") !== "vertical" || bar.getAttribute("aria-label") !== "Resize the folder list") return "the side-by-side divider is not vertical or has no label";
const first = mail.querySelector(".ui-splitter-pane");
if (bar.getAttribute("aria-controls") !== first.id) return "the divider does not say which pane it controls";
const width = () => first.getBoundingClientRect().width / mail.getBoundingClientRect().width * 100;
if (Math.abs(width() - 30) > 2) return `the first pane takes ${width()}%, not 30%`;
bar.focus(); key(bar, "ArrowRight"); await wait();
if (bar.getAttribute("aria-valuenow") !== "35" || Math.abs(width() - 35) > 2) return `ArrowRight made it ${bar.getAttribute("aria-valuenow")} / ${width()}%`;
key(bar, "End"); await wait();
if (bar.getAttribute("aria-valuenow") !== "60") return "End did not go to max";
key(bar, "ArrowRight"); await wait();
if (bar.getAttribute("aria-valuenow") !== "60") return "it went past max";
key(bar, "Home"); await wait();
if (bar.getAttribute("aria-valuenow") !== "20") return "Home did not go to min";
key(bar, "Enter"); await wait();
if (bar.getAttribute("aria-valuenow") !== "0" || getComputedStyle(first).visibility !== "hidden" || width() > 2) return "Enter did not fold the collapsible pane";
key(bar, "Enter"); await wait();
if (bar.getAttribute("aria-valuenow") !== "20" || getComputedStyle(first).visibility === "hidden") return "Enter again did not bring it back";
// Drag with the pointer (a made-up pointer cannot be captured, so capturing does nothing here).
bar.setPointerCapture = () => {};
bar.scrollIntoView({ block: "center" });
const r = mail.getBoundingClientRect(), b = bar.getBoundingClientRect();
const pe = (t, x, y) => bar.dispatchEvent(new PointerEvent(t, { bubbles: true, cancelable: true, pointerId: 1, button: 0, isPrimary: true, clientX: x, clientY: y }));
const y = b.top + b.height / 2;
pe("pointerdown", b.left + b.width / 2, y);
pe("pointermove", r.left + r.width * 0.45, y); await wait(50);
pe("pointermove", r.left + r.width * 0.5, y);
pe("pointerup", r.left + r.width * 0.5, y); await wait();
if (Math.abs(+bar.getAttribute("aria-valuenow") - 50) > 1 || Math.abs(width() - 50) > 2) return `dragging to the middle made it ${bar.getAttribute("aria-valuenow")} / ${width()}%`;
pe("pointerdown", r.left + r.width * 0.5, y); pe("pointermove", r.left + r.width * 0.95, y); pe("pointerup", r.left + r.width * 0.95, y); await wait();
if (bar.getAttribute("aria-valuenow") !== "60") return "dragging went past max";
// Stacked.
const vb = sql.querySelector("[role=separator]");
if (vb.getAttribute("aria-orientation") !== "horizontal") return "the stacked divider is not horizontal";
const [top, bottom] = sql.querySelectorAll(".ui-splitter-pane");
if (bottom.getBoundingClientRect().top < top.getBoundingClientRect().bottom - 1) return "vertical panes are not one above the other";
if (Math.abs(sql.getBoundingClientRect().height - 300) > 1) return "height is not applied";
key(vb, "ArrowDown"); await wait();
if (vb.getAttribute("aria-valuenow") !== "45") return "ArrowDown did not move the stacked divider";
if (Math.abs(top.getBoundingClientRect().height / sql.getBoundingClientRect().height * 100 - 45) > 2) return "the top pane did not grow";
if (sql.querySelector("[role=separator]").getAttribute("aria-valuetext") !== "45%") return "aria-valuetext is not the percentage";
// on_change.
const lb = live.querySelector("[role=separator]");
key(lb, "ArrowLeft"); await wait();
const note = () => live.parentElement.querySelector(".demo-note").textContent;
if (!note().includes("30%")) return `on_change did not report: ${note()}`;
key(lb, "Enter"); await wait();
if (!note().includes("folded")) return `on_change did not report the fold: ${note()}`;
key(lb, "Enter"); await wait();
