const box = $("#scroll-tabs-demo-tab-0").closest(".ui-scrolltabs"), list = box.querySelector("[role=tablist]");
const tabs = [...list.querySelectorAll("[role=tab]")];
if (tabs.length !== 12 || list.getAttribute("aria-label") !== "Months") return "the tabs are not 12 in a labelled tablist";
if (tabs[0].getAttribute("aria-selected") !== "true" || tabs[1].tabIndex !== -1) return "it does not start on the first tab";
if (list.scrollWidth <= list.clientWidth + 1) return "the row does not overflow (the demo is too wide)";
const shown = (el) => getComputedStyle(el).display !== "none";
const left = box.querySelector(".ui-scrolltabs-left"), right = box.querySelector(".ui-scrolltabs-right");
if (shown(left) || !shown(right)) return "at the start only the right arrow should show";
const panel = () => box.querySelector("[role=tabpanel]").textContent;
right.click(); await wait(600);
if (list.scrollLeft < 50 || !shown(left)) return `the right arrow did not scroll the row: ${list.scrollLeft}`;
list.scrollTo({ left: list.scrollWidth, behavior: "instant" }); await wait(300);
if (shown(right) || !shown(left)) return "at the end only the left arrow should show";
tabs[11].click(); await wait();
if (tabs[11].getAttribute("aria-selected") !== "true" || !panel().includes("December")) return `clicking December did not select it: ${panel()}`;
key(tabs[11], "ArrowRight"); await wait(600);
if (!panel().includes("January") || document.activeElement !== tabs[0]) return "ArrowRight on the last tab did not wrap to the first and focus it";
const r = tabs[0].getBoundingClientRect(), lr = list.getBoundingClientRect();
if (r.left < lr.left - 1 || r.right > lr.right + 1) return "the selected tab was not scrolled into view";
key(tabs[0], "End"); await wait(600);
if (!panel().includes("December") || tabs[11].getBoundingClientRect().right > lr.right + 1) return "End did not go to December and show it";
if (box.querySelector("[role=tabpanel]").getAttribute("aria-labelledby") !== tabs[11].id) return "the panel is not named by the selected tab";
const pill = $("#scroll-tabs-demo-pill-tab-2");
if (!pill.closest(".ui-scrolltabs").classList.contains("ui-scrolltabs-pill") || pill.getAttribute("aria-selected") !== "true") return "the pill one does not start on its selected tab";
