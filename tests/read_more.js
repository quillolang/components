const text = $("#read-more-demo-three");
const box = text.closest(".ui-read-more");
const btn = () => box.querySelector("button.ui-read-more-btn");
if (!text || !btn()) return "the text or the button is missing";
const cs = (el) => getComputedStyle(el);
if (cs(text).webkitLineClamp !== "3" || text.scrollHeight <= text.clientHeight + 1) return "the text is not folded to three lines";
if (btn().getAttribute("aria-expanded") !== "false" || btn().getAttribute("aria-controls") !== "read-more-demo-three") return "the button is not wired to the text";
if (btn().textContent.trim() !== "Read more") return `the button says "${btn().textContent.trim()}"`;
const folded = text.getBoundingClientRect().height;
btn().click(); await wait();
if (text.classList.contains("ui-clamp") || text.scrollHeight > text.clientHeight + 1) return "Read more did not unfold the text";
if (!(text.getBoundingClientRect().height > folded * 1.5)) return "the unfolded text is not taller";
if (btn().getAttribute("aria-expanded") !== "true" || btn().textContent.trim() !== "Show less") return "the button does not say Show less";
if (!text.textContent.includes("A second paragraph")) return "the hidden paragraph is missing";
btn().click(); await wait();
if (cs(text).webkitLineClamp !== "3" || btn().textContent.trim() !== "Read more") return "Show less did not fold it again";
const live = $("#read-more-demo-live").closest(".ui-read-more");
const note = live.closest(".demo-stack").querySelector(".demo-note");
if (live.querySelector("button").textContent.trim() !== "See all") return "more= does not label the button";
live.querySelector("button").click(); await wait();
if (note.textContent !== "Unfolded." || live.querySelector("button").textContent.trim() !== "See fewer") return `on_toggle did not reach the note: ${note.textContent}`;
live.querySelector("button").click(); await wait();
if (note.textContent !== "Folded.") return "on_toggle(false) did not reach the note";
const short = $("#read-more-demo-short").closest(".ui-read-more");
if (short.querySelector("button")) return "a text that fits still has a button";
