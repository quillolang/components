const f = $("#activity-feed-demo-main");
if (!f || f.tagName !== "OL" || f.getAttribute("aria-label") !== "Recent activity") return "the feed is not a named <ol>";
const days = [...f.querySelectorAll(".ui-activity-day")].map((d) => d.textContent);
if (days.join() !== "Today,Yesterday") return `day headings: ${days}`;
const items = [...f.querySelectorAll(".ui-activity-item")];
if (items.length !== 5) return `expected 5 items, found ${items.length}`;
const line = items[0].querySelector(".ui-activity-line").textContent.replace(/\s+/g, " ").trim();
if (line !== "Ada Lovelace commented on Invoice #1041 2 h ago") return `the first line reads "${line}"`;
if (items[0].querySelector("a.ui-activity-target")?.getAttribute("href") !== "#inv-1041") return "the target is not a link";
if (items[0].querySelector("time").getAttribute("datetime") !== "2026-10-28T09:12:00Z") return "datetime";
if (!items[0].querySelector(".ui-activity-body")?.textContent.includes("accounts")) return "the quote is missing";
if (items[0].querySelector(".ui-activity-pic").textContent.trim() !== "AL") return "initials";
if (!items[0].querySelector(".ui-activity-icon").classList.contains("ui-activity-info")) return "the comment icon's tone";
if (!items[2].querySelector(".ui-activity-icon").classList.contains("ui-activity-danger") || !items[3].querySelector(".ui-activity-icon").classList.contains("ui-activity-success")) return "delete is not red or create green";
if (items[3].querySelector("a")) return "a target without href is a link";
if (getComputedStyle(items[0], "::before").display === "none") return "no line joins the items";
if (getComputedStyle(items[2], "::before").display !== "none") return "the line runs past the end of a day";
const c = $("#activity-feed-demo-compact");
if (!c.classList.contains("ui-activity-compact") || c.querySelector(".ui-activity-pic").textContent.trim() !== "") return "compact still shows initials";
if (!c.querySelectorAll(".ui-activity-item")[2].querySelector(".ui-activity-icon").classList.contains("ui-activity-accent")) return "tone given";
