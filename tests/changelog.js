const c = $("#changelog-demo");
const rels = [...c.querySelectorAll("article.ui-changelog-rel")];
if (rels.length !== 3) return `expected 3 releases, found ${rels.length}`;
if (rels[0].id !== "v1.8.0" || rels[0].getAttribute("aria-labelledby") !== "v1.8.0-h") return "the release's id";
const h = rels[0].querySelector("h4.ui-changelog-head");
if (!h || h.id !== "v1.8.0-h") return "level={4} does not make an h4";
if (h.textContent.replace(/\s+/g, " ").trim() !== "1.8.0 Autumn Latest") return `the heading reads "${h.textContent.trim()}"`;
const t = rels[0].querySelector("time");
if (t.getAttribute("datetime") !== "2026-10-28" || t.textContent !== "Oct 28, 2026") return `the date: ${t.textContent}`;
if (rels[0].querySelector(".ui-changelog-summary")?.textContent !== "Dark mode everywhere, and exports.") return "summary";
const kinds = (r) => [...r.querySelectorAll(".ui-changelog-kind")].map((k) => k.textContent).join();
if (kinds(rels[0]) !== "Added,Changed,Fixed") return `kinds are not in the usual order: ${kinds(rels[0])}`;
const added = rels[0].querySelector(".ui-changelog-group");
if (added.getAttribute("aria-label") !== "Added in 1.8.0" || added.querySelectorAll("li").length !== 2) return "the Added group";
if (!rels[0].querySelector(".ui-changelog-kind").classList.contains("ui-changelog-added")) return "the kind's class";
if (kinds(rels[1]) !== "Fixed,Security") return `a list of changes: ${kinds(rels[1])}`;
if (rels[1].querySelector("h4 a")?.getAttribute("href") !== "#v1.7.2") return "href links the version";
if (!rels[1].querySelector(".ui-changelog-tag").classList.contains("ui-changelog-tag-danger")) return "tag_tone";
if (kinds(rels[2]) !== "Deprecated,Removed,Docs") return `other kinds come last: ${kinds(rels[2])}`;
if (rels[2].querySelector(".ui-changelog-tag")) return "a release without tag has one";
