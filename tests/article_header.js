const h = $("#article-header-demo-main");
const clean = (el) => el.textContent.replace(/\s+/g, " ").trim();
if (!h || h.tagName !== "HEADER") return "the header is not a <header>";
const h1 = h.querySelector("h1.ui-arth-headline");
if (!h1 || h1.textContent !== "The river that ran out of water") return "the headline is not an <h1>";
if (h.querySelector(".ui-arth-label").textContent !== "Analysis" || !h.querySelector(".ui-arth-label").classList.contains("ui-arth-label-accent")) return "the label";
const k = h.querySelector("a.ui-arth-kicker");
if (!k || k.getAttribute("href") !== "#climate" || k.textContent !== "Climate") return "the kicker is not a link";
if (!h.querySelector(".ui-arth-dek").textContent.startsWith("Three summers")) return "the dek";
const lines = [...h.querySelectorAll(".ui-arth-byline")].map(clean);
if (lines[0] !== "By Inês Carvalho, Tom Reid and Maya Okafor") return `the byline reads "${lines[0]}"`;
if (lines[1] !== "Photographs by Luís Pinto" || lines[2] !== "With additional reporting by Sara Klein") return `the other lines: ${lines.slice(1)}`;
const links = [...h.querySelectorAll(".ui-arth-byline a[rel=author]")].map((a) => a.getAttribute("href"));
if (links.join() !== "#by-ines,#by-maya") return `author links: ${links}`;
if (h.querySelector(".ui-arth-byline b")?.textContent !== "Tom Reid") return "an author without href is not bold text";
const faces = [...h.querySelectorAll(".ui-arth-face")].map((f) => f.textContent);
if (faces.join() !== "IC,TR,MO" || h.querySelector(".ui-arth-faces").getAttribute("aria-hidden") !== "true") return `faces: ${faces}`;
const times = h.querySelectorAll(".ui-arth-times time");
if (times.length !== 2) return "published and updated";
if (times[0].getAttribute("datetime") !== "2026-10-29T08:00:00-04:00" || times[0].textContent !== "Oct 29, 2026, 8:00 AM ET") return `published reads "${times[0].textContent}"`;
if (times[1].textContent !== "Oct 30, 2026, 2:20 PM ET" || !times[1].closest(".ui-arth-updated")?.textContent.startsWith("Updated")) return `updated reads "${times[1].textContent}"`;
if (!clean(h.querySelector(".ui-arth-times")).endsWith("9 min read")) return "read time";
const size = parseFloat(getComputedStyle(h1).fontSize);
if (size < 28) return `the headline is only ${size}px`;
const live = $("#article-header-demo-live");
if (!live.querySelector("h2.ui-arth-headline") || live.querySelector("h1")) return "level={2} does not make an <h2>";
if (!live.classList.contains("ui-arth-center") || getComputedStyle(live).textAlign !== "center") return "align center";
if (!live.querySelector(".ui-arth-label").classList.contains("ui-arth-label-danger")) return "a Live label is not red";
if (live.querySelector(".ui-arth-kicker").tagName !== "SPAN") return "a kicker without href is a link";
if (live.querySelector("time").textContent !== "Started 19 minutes ago" || live.querySelector(".ui-arth-updated")) return "published_text, or an updated time that was not given";
if (live.querySelector(".ui-arth-times").textContent.trim() !== "Started 19 minutes ago") return `published_text is the whole line: "${live.querySelector(".ui-arth-times").textContent}"`;
