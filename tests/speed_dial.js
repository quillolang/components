if (main.getAttribute("aria-expanded") !== "true" || getComputedStyle(list).display === "none") return "clicking does not open the actions";
const items = [...list.querySelectorAll(".ui-speed-dial-item")];
if (items.length !== 4) return `expected 4 actions, found ${items.length}`;
if (items[0].tagName !== "A" || items[0].getAttribute("href") !== "#speed_dial") return "an item with an href is not a link";
if (items[0].getAttribute("aria-label") !== "New document" || list.querySelector(".ui-speed-dial-name").textContent !== "New document") return "an action has no name and label chip";
if (items[2].getAttribute("aria-disabled") !== "true") return "disabled is not aria-disabled";
