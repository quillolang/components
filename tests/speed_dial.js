key(host, "ArrowUp"); await wait(50);
if (document.activeElement !== items[1]) return "ArrowUp does not move to the next";
key(host, "ArrowUp"); await wait(50);
if (document.activeElement !== items[3]) return "ArrowUp skipped over the disabled one wrongly";
key(host, "ArrowDown"); await wait(50);
if (document.activeElement !== items[1]) return "ArrowDown does not move back";
items[2].click(); await wait();
if (main.getAttribute("aria-expanded") !== "true" || note() !== "Did: nothing yet") return "a disabled action did something";
items[3].click(); await wait();
if (main.getAttribute("aria-expanded") !== "false" || note() !== "Did: Call") return `choosing does not close and call on_select: ${note()}`;
if (document.activeElement !== main) return "focus does not go back to the main button";
