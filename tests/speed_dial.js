const note = () => $(".demo-note").textContent;
if (main.getAttribute("aria-expanded") !== "false" || main.getAttribute("aria-controls") !== list.id) return "the main button is not a closed disclosure for its list";
if (main.getAttribute("aria-label") !== "Create") return "the main button has no name";
if (getComputedStyle(list).display !== "none") return "the actions show while closed";
