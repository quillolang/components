const live = $("#world-clock-demo-now ul.ui-world-clock");
if (!live || live.getAttribute("aria-label") !== "World clock") return "the clock is not a labelled list";
const zones = [...live.querySelectorAll(".ui-world-clock-zone")];
if (zones.length !== 4) return `expected 4 zones, found ${zones.length}`;
const fmt = (tz) => new Intl.DateTimeFormat("en-GB", { timeZone: tz, hour: "2-digit", minute: "2-digit", hourCycle: "h23" }).format(new Date());
const shown = (z) => z.querySelector(".ui-world-clock-time").textContent.slice(0, 5);
if (shown(zones[0]) !== fmt("Europe/Lisbon") || shown(zones[3]) !== fmt("Asia/Tokyo")) return `Lisbon ${shown(zones[0])} (${fmt("Europe/Lisbon")}), Tokyo ${shown(zones[3])} (${fmt("Asia/Tokyo")})`;
const metas = zones.map((z) => z.querySelector(".ui-world-clock-meta").textContent);
if (!/^(Today|Tomorrow|Yesterday), −[45]h$/.test(metas[1]) || !/, \+[45]h 30m$/.test(metas[2])) return `the differences read ${metas}`;
if (!/^Lisbon: \d\d:\d\d:\d\d, \w+day$/.test(zones[0].getAttribute("aria-label"))) return `Lisbon is heard as ${zones[0].getAttribute("aria-label")}`;
const s0 = zones[0].querySelector(".ui-world-clock-time").textContent;
await wait(2100);
if (zones[0].querySelector(".ui-world-clock-time").textContent === s0) return "it does not tick";
const fixed = $("#world-clock-demo-fixed ul.ui-world-clock");
if (!fixed.classList.contains("ui-world-clock-list") || fixed.getAttribute("aria-label") !== "Team hours") return "variant list or the label is not applied";
const f = [...fixed.querySelectorAll(".ui-world-clock-zone")];
const read = f.map((z) => z.querySelector(".ui-world-clock-time").textContent + " " + z.querySelector(".ui-world-clock-meta").textContent);
if (read.join("|") !== "10:30PM Today|2:30PM Today, −8h|9:30AM Tomorrow, +11h|4:15AM Tomorrow, +5h 45m") return `the fixed moment reads ${read.join("|")}`;
if (f[0].querySelector(".ui-world-clock-note").textContent !== "Ana, Ben") return "the note is missing";
if (!f[0].classList.contains("ui-world-clock-night") || f[1].classList.contains("ui-world-clock-night")) return "night hours are not shaded";
if (f[1].querySelector("time").getAttribute("datetime") !== "2026-11-02T14:30:00-08:00") return `the machine time is ${f[1].querySelector("time").getAttribute("datetime")}`;
const t0 = f[0].querySelector(".ui-world-clock-time").textContent;
await wait(300);
if (f[0].querySelector(".ui-world-clock-time").textContent !== t0) return "a fixed moment changed";
