const btn = $("button.ui-mobilenav-btn");
const dlg = document.getElementById("mobile-nav-demo");
if (!btn || !dlg || dlg.tagName !== "DIALOG" || btn.getAttribute("aria-controls") !== "mobile-nav-demo") return "the button does not control a dialog";
if (btn.getAttribute("aria-label") !== "Menu" || btn.getAttribute("aria-expanded") !== "false" || dlg.open) return "it does not start closed with a named button";
const note = () => $(".demo-note").textContent;
btn.click(); await wait(300);
if (!dlg.open || !dlg.matches(":modal")) return "clicking does not open the dialog as a modal";
if (btn.getAttribute("aria-expanded") !== "true" || !note().includes("is open")) return "on_toggle(true) did not reach the note";
const r = dlg.getBoundingClientRect();
if (r.width < innerWidth - 1 || r.height < innerHeight - 1 || r.top > 1 || r.left > 1) return `the dialog does not cover the screen: ${r.width}x${r.height} at ${r.top},${r.left}`;
if (dlg.querySelector(".ui-mobilenav-brand")?.textContent !== "Acme") return "the brand is missing";
const nav = dlg.querySelector("nav");
if (!nav || nav.getAttribute("aria-label") !== "Menu") return "the links are not in a labelled <nav>";
const links = [...nav.querySelectorAll("a")];
if (links.length !== 8 || links[0].getAttribute("href") !== "#home") return `expected 8 links, found ${links.length}`;
const [la, lb] = links.map((a) => a.getBoundingClientRect());
if (lb.top <= la.bottom - 1) return "the links are not one under another";
const groups = [...nav.querySelectorAll("details")];
if (groups.length !== 2 || !groups[0].open || groups[1].open) return "the group holding the current page is not the only one open";
const cur = nav.querySelectorAll("[aria-current=page]");
if (cur.length !== 1 || cur[0].textContent.trim() !== "Components") return "the current page is not marked once";
if (!links[0].querySelector(".ui-mobilenav-icon svg") || [...links].find((a) => a.textContent.includes("Inbox"))?.querySelector(".ui-mobilenav-badge")?.textContent !== "4") return "icons or the badge are missing";
groups[1].querySelector("summary").click(); await wait();
if (!groups[1].open) return "a group does not open on click";
if (dlg.querySelectorAll(".ui-mobilenav-foot .ui-btn").length !== 2) return "children are not at the bottom";
dlg.querySelector('[aria-label="Close menu"]').click(); await wait(300);
if (dlg.open || btn.getAttribute("aria-expanded") !== "false" || !note().includes("Click the menu")) return "the close button does not close it and tell on_toggle";
btn.click(); await wait(300);
links[3].click(); await wait(300);
if (dlg.open) return "following a link does not close the menu";
