const thumbs = $$(".ui-lb-thumb");
const dlg = $("dialog.ui-lb");
if (thumbs.length !== 6) return `expected 6 thumbnails, got ${thumbs.length}`;
if (thumbs[0].querySelector("img").alt !== "Green hills under a blue sky") return "a thumbnail is not named by its alt";
if (getComputedStyle(thumbs[0]).aspectRatio.replace(/\s/g, "") !== "4/3") return `ratio is ${getComputedStyle(thumbs[0]).aspectRatio}`;
const img = () => dlg.querySelector(".ui-lb-stage img");
const count = () => dlg.querySelector(".ui-lb-count").textContent.trim();
const cap = () => dlg.querySelector(".ui-lb-cap").textContent.trim();
thumbs[2].focus(); thumbs[2].click(); await wait();
if (!dlg.open) return "clicking a thumbnail does not open the viewer";
if (count() !== "3 / 6" || cap() !== "Day 2: the moon over camp") return `opened at "${count()}" "${cap()}"`;
if (img().alt !== "Dark hills under a full moon" || !img().src.startsWith("data:image/svg+xml")) return "the image shown is not the third";
const r = dlg.getBoundingClientRect();
if (r.width < innerWidth - 2 || r.height < innerHeight - 2) return "the viewer does not fill the screen";
key(dlg, "ArrowRight"); await wait();
if (count() !== "4 / 6" || cap() !== "Day 3: snow overnight") return `ArrowRight shows ${count()}`;
dlg.querySelector(".ui-lb-prev").click(); dlg.querySelector(".ui-lb-prev").click(); await wait();
if (count() !== "2 / 6") return `Previous twice shows ${count()}`;
key(dlg, "End"); await wait();
if (count() !== "6 / 6") return `End shows ${count()}`;
dlg.querySelector(".ui-lb-next").click(); await wait();
if (count() !== "1 / 6") return `Next from the last does not loop: ${count()}`;
if (dlg.querySelector(".ui-lb-count").getAttribute("aria-live") !== "polite") return "the counter is not announced";
const stage = dlg.querySelector(".ui-lb-stage");
stage.dispatchEvent(new PointerEvent("pointerdown", { clientX: 400, bubbles: true }));
stage.dispatchEvent(new PointerEvent("pointerup", { clientX: 250, bubbles: true })); await wait();
if (count() !== "2 / 6") return `a swipe left does not go to the next: ${count()}`;
dlg.querySelector(".ui-lb-x").click(); await wait();
if (dlg.open) return "Close does not close the viewer";
if (document.activeElement !== thumbs[1]) return "focus does not go back to the thumbnail of the image last seen";
thumbs[4].click(); await wait();
stage.click(); await wait();
if (dlg.open) return "clicking beside the image does not close it";
