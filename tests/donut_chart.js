const charts = $$("figure.ui-dn");
if (charts.length !== 4) return `expected 4 donut charts, found ${charts.length}`;
if (/NaN|Infinity|undefined/.test(charts.map((c) => c.innerHTML).join(""))) return "a chart has NaN, Infinity or undefined in it";
const [traffic, budget, plans, storage] = charts;
const segs = [...traffic.querySelectorAll(".ui-dn-seg")];
if (segs.length !== 5) return `5 parts made ${segs.length} segments`;
const lens = segs.map((s) => Number(s.getAttribute("stroke-dasharray").split(" ")[0]));
const total = lens.reduce((a, b) => a + b, 0);
if (Math.abs(total + 5 * 0.6 - 100) > 0.01) return `the segments and gaps make ${total} of 100`;
const offs = segs.map((s) => -Number(s.getAttribute("stroke-dashoffset")));
if (Math.abs(offs[1] - (offs[0] + lens[0] + 0.6)) > 0.01) return "a segment does not start where the last one ended";
if (traffic.getAttribute("aria-label") !== "Traffic by source, total 8,660") return `aria-label: ${traffic.getAttribute("aria-label")}`;
if (traffic.querySelector(".ui-dn-total").textContent !== "8,660Total") return `the middle says ${traffic.querySelector(".ui-dn-total").textContent}`;
const item = traffic.querySelector(".ui-dn-legend li");
if (item.textContent !== "Search4,21048.6%") return `the legend reads ${item.textContent}`;
if (getComputedStyle(item.querySelector(".ui-dn-key")).backgroundColor !== getComputedStyle(segs[0]).stroke) return "the legend's key is not its segment's colour";
if (new Set(segs.map((s) => getComputedStyle(s).stroke)).size !== 5) return "parts share a colour";
if (getComputedStyle(traffic.querySelector(".ui-dn-c2")).visibility !== "hidden") return "a part's figure shows before hover";
if (segs[0].querySelector("title").textContent !== "Search: 4,210 (48.6%)") return "segments have no title";
if (budget.querySelector("figcaption")?.textContent !== "Budget this month") return "show_label";
if (!budget.querySelector(".ui-dn-total").textContent.startsWith("$65,925.50")) return `decimals={2}: ${budget.querySelector(".ui-dn-total").textContent}`;
if (budget.querySelectorAll(".ui-dn-val")[1].textContent !== "$6,350.50") return "the legend's money has no cents";
const ring = budget.querySelector(".ui-dn-ring").getBoundingClientRect();
if (Math.round(ring.width) !== 150) return `size={150} is ${ring.width}px`;
const mid = budget.querySelector(".ui-dn-total b").getBoundingClientRect();
if (mid.width > ring.width * 0.72) return "the total overflows the hole";
if (plans.querySelector(".ui-dn-center")) return "a pie has a middle";
if (plans.querySelector("svg").style.getPropertyValue("--w").trim() !== "50px" || plans.querySelector(".ui-dn-seg").getAttribute("r") !== "25") return "a pie is not filled";
const rows = [...storage.querySelectorAll(".ui-dn-legend li")];
if (rows.length !== 8 || rows[7].querySelector(".ui-dn-name").textContent !== "Other" || rows[7].querySelector(".ui-dn-val").textContent !== "0.6 GB")
    return `nine parts do not fold into Other: ${rows.map((r) => r.textContent)}`;
if (storage.querySelector(".ui-dn-total b").textContent !== "82%") return "center={...} is not in the middle";
