const t = $("#timer-demo-short-minutes").closest(".ui-timer");
const time = () => t.querySelector(".ui-timer-time").textContent;
const btn = (s) => [...t.querySelectorAll(".ui-timer-buttons button")].find((b) => b.textContent === s);
const alert = t.querySelector("[role=alert]");
const note = () => t.closest(".demo-stack").querySelector(".demo-note").textContent;
if (t.getAttribute("role") !== "group" || t.getAttribute("aria-label") !== "Tea") return "the timer is not a named group";
if (time() !== "00:02" || t.querySelector("[role=timer]").getAttribute("aria-label") !== "00:02 left") return `it starts at ${time()}`;
if (t.querySelector(".ui-timer-preset")) return "presets={[]} still shows presets";
if (!btn("Reset").disabled) return "Reset is on before it has run";
btn("Start").click(); await wait(700);
if (!btn("Pause") || time() !== "00:02") return `running for 0.7 s it reads ${time()}`;
if (!$("#timer-demo-short-minutes").disabled) return "the minutes can be changed while it runs";
btn("Pause").click(); await wait(400);
const paused = time();
if (!btn("Resume")) return "paused, it does not offer Resume";
await wait(400);
if (time() !== paused) return "it runs while paused";
btn("Resume").click(); await wait(2000);
if (time() !== "00:00" || alert.textContent !== "Tea is ready" || !t.classList.contains("ui-timer-done")) return `at zero: ${time()} / "${alert.textContent}"`;
if (!note().startsWith("on_end called 1 time.") || !note().includes("start · pause · start")) return `the callbacks: ${note()}`;
if (!btn("Start")) return "at zero it does not offer Start again";
btn("Reset").click(); await wait();
if (time() !== "00:02" || alert.textContent !== "" || t.classList.contains("ui-timer-done")) return "Reset did not set it back";
const minutes = $("#timer-demo-short-minutes");
type(minutes, "1.5"); await wait();
if (time() !== "01:30") return `1.5 minutes reads ${time()}`;
const p = $("#timer-demo-pomodoro-minutes").closest(".ui-timer");
if (p.querySelector(".ui-timer-time").textContent !== "25:00" || $("#timer-demo-pomodoro-minutes").value !== "25") return "minutes={25} does not show 25:00";
const presets = [...p.querySelectorAll(".ui-timer-preset")];
if (presets.map((b) => b.textContent).join() !== "1 min,5 min,10 min,25 min" || presets[3].getAttribute("aria-pressed") !== "true") return "the presets are wrong";
presets[1].click(); await wait();
if (p.querySelector(".ui-timer-time").textContent !== "05:00" || presets[1].getAttribute("aria-pressed") !== "true" || $("#timer-demo-pomodoro-minutes").value !== "5") return "a preset did not set the time";
const fill = p.querySelector(".ui-timer-fill");
if (fill.getAttribute("stroke-dashoffset") !== "0") return `a full timer's ring is at ${fill.getAttribute("stroke-dashoffset")}`;
