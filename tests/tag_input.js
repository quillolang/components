const box = $("#tag-input-topics");
const sent = (name) => $$(`input[type=hidden][name=${name}]`).map((i) => i.value).join(",");
if (sent("topics") !== "rust,web") return `the form would send: ${sent("topics")}`;
if (box.name) return "the text box itself would be sent";
type(box, "css"); key(box, "Enter"); await wait();
if (sent("topics") !== "rust,web,css" || box.value !== "") return `Enter did not add css: ${sent("topics")}, "${box.value}"`;
type(box, "Rust"); key(box, "Enter"); await wait();
if (sent("topics") !== "rust,web,css") return "a duplicate in another case was added";
type(box, "html, security,"); await wait();
if (sent("topics") !== "rust,web,css,html,security" || box.value !== "") return `a comma did not add: ${sent("topics")}`;
key(box, "Backspace"); await wait();
if (sent("topics") !== "rust,web,css,html") return `Backspace in the empty box did not remove the last: ${sent("topics")}`;
box.parentElement.querySelector('button[aria-label="Remove web"]').click(); await wait();
if (sent("topics") !== "rust,css,html") return `× did not remove web: ${sent("topics")}`;
if (document.activeElement !== box) return "removing a tag does not put the focus back in the box";
const offered = [...$("#tag-input-topics-list").options].map((o) => o.value);
if (offered.includes("rust") || !offered.includes("web")) return `suggestions should leave out the tags there: ${offered}`;
if (!box.closest(".ui-tag-input").querySelector("[aria-live]").textContent.includes("Removed web")) return "the change is not announced";
const labels = $("#tag-input-ti-labels");
type(labels, "a,b,c,d,"); await wait();
if (sent("ti-labels") !== "design,a,b,c") return `max 4 did not hold: ${sent("ti-labels")}`;
const note = labels.closest(".demo-stack").querySelector(".demo-note").textContent;
if (!note.includes("4 labels: design, a, b, c")) return `on_change did not update the note: ${note}`;
type(box, "draft"); box.blur(); box.dispatchEvent(new FocusEvent("blur")); await wait();
if (!sent("topics").endsWith(",draft")) return "leaving the box does not add what was typed";
