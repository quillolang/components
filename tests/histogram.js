if (document.documentElement.scrollWidth > innerWidth) return "widens the page";
const charts = $$("figure.ui-histc");
if (charts.length !== 3) return `expected 3 histograms, found ${charts.length}`;
if (/NaN|Infinity|undefined/.test(charts.map((c) => c.innerHTML).join(""))) return "a chart has NaN, Infinity or undefined in it";
const [times, totals, ages] = charts;
const vals = Array.from({ length: 240 }, (_, i) => 80 + (i * 37) % 61 + (i * 53) % 67 + (i * 11) % 29);
const lo = Math.min(...vals), hi = Math.max(...vals), w = (hi - lo) / 12;
const want = Array(12).fill(0);
for (const v of vals) want[Math.min(11, Math.floor((v - lo) / w + 1e-6))]++;
const bins = [...times.querySelectorAll(".ui-histc-bin")];
if (bins.length !== 12) return `bins={12} made ${bins.length} bins`;
const got = bins.map((b) => Number(b.querySelector(".ui-histc-bar")?.dataset.count ?? 0));
if (got.join() !== want.join()) return `the counts are ${got}, not ${want}`;
if (times.getAttribute("aria-label") !== "Response times, 240 values") return `aria-label: ${times.getAttribute("aria-label")}`;
const r = bins.map((b) => b.getBoundingClientRect());
if (r.some((b, i) => i > 0 && Math.abs(b.left - r[i - 1].right) > 0.6)) return "the bins do not touch";
const tall = bins.map((b) => b.querySelector(".ui-histc-bar")?.getBoundingClientRect().height ?? 0);
const k = got.indexOf(Math.max(...got));
const ticks = [...times.querySelectorAll(".ui-histc-y span")].map((s) => Number(s.textContent));
if (ticks.some((t) => !Number.isInteger(t))) return `count ticks are not whole: ${ticks}`;
if (Math.abs(tall[k] - 220 * got[k] / ticks[ticks.length - 1]) > 1) return "the tallest bar is not as tall as its count";
const tip = bins[0].querySelector(".ui-histc-tip");
if (getComputedStyle(tip).display !== "none") return "the tooltip shows before hover";
const fmt = (x) => `${Math.round(x * 100) / 100} ms`;
const wantTip = `${fmt(lo)} – ${fmt(lo + w)}Requests${want[0]}${Math.round(want[0] * 1000 / 240) / 10}%`;
if (tip.textContent !== wantTip) return `tooltip: ${tip.textContent}, not ${wantTip}`;
const mean = times.querySelector(".ui-histc-mean");
const m = vals.reduce((a, b) => a + b, 0) / 240;
if (!mean || Math.abs(parseFloat(mean.style.getPropertyValue("--x")) - (m - lo) * 100 / (hi - lo)) > 0.02) return "the mean line is not at the mean";
if (!mean.textContent.startsWith("Mean ")) return "the mean line has no label";
if (times.querySelectorAll("tbody tr").length !== 12) return "the table has no row per bin";

const tx = [...totals.querySelectorAll(".ui-histc-x span")].map((s) => s.textContent);
if (!tx.every((t) => /^\$\d+$/.test(t) && Number(t.slice(1)) % 25 === 0)) return `width={25} edges are not multiples of $25: ${tx}`;
if (totals.querySelector(".ui-histc-mean")) return "a mean line without show_mean";
const agesBins = [...ages.querySelectorAll(".ui-histc-bin")].map((b) => Number(b.querySelector(".ui-histc-bar")?.dataset.count ?? 0));
if (agesBins.join() !== "3,4,3,3") return `the ages fall in ${agesBins}`;
if (ages.querySelector("tbody tr").textContent !== "23 – 32.53") return `ages' first row: ${ages.querySelector("tbody tr").textContent}`;
