const fs = $("#signature-pad-sp-demo-sign");
const canvas = fs.querySelector("canvas");
const hidden = $("input[type=hidden][name=sp-demo-sign]");
if (!canvas || canvas.width !== 400 || canvas.height !== 160) return "the canvas is not 400 by 160";
if (canvas.getAttribute("role") !== "img" || !canvas.getAttribute("aria-label")?.includes("empty")) return "the canvas is not an image said to be empty";
if (!fs.querySelector("legend")?.textContent.includes("Sign here") || !fs.querySelector(".ui-signature-pad-req")) return "no legend with the required mark";
if (hidden.value !== "") return "the hidden input is not empty to start";
const clear = [...fs.querySelectorAll("button")].find((b) => b.textContent === "Clear");
if (!clear || !clear.disabled) return "Clear is not disabled while empty";
canvas.setPointerCapture = () => {};
const r = canvas.getBoundingClientRect();
const pe = (t, x, y) => canvas.dispatchEvent(new PointerEvent(t, { bubbles: true, cancelable: true, pointerId: 1, button: 0, isPrimary: true, clientX: r.left + x, clientY: r.top + y }));
pe("pointerdown", 40, 80); pe("pointermove", 120, 40); pe("pointermove", 200, 100); pe("pointerup", 200, 100); await wait();
if (!hidden.value.startsWith("data:image/png;base64,")) return `a stroke did not give a PNG: ${hidden.value.slice(0, 30)}`;
const ctx = canvas.getContext("2d");
const inked = () => { const d = ctx.getImageData(0, 0, canvas.width, canvas.height).data; let n = 0; for (let i = 3; i < d.length; i += 4) if (d[i] > 0) n++; return n; };
if (inked() < 50) return `the stroke drew ${inked()} pixels`;
if (!canvas.getAttribute("aria-label").includes("signed") || clear.disabled) return "after a stroke it is not said to be signed and Clear stays disabled";
const png1 = hidden.value;
clear.click(); await wait();
if (hidden.value !== "" || inked() !== 0 || !clear.disabled) return "Clear does not empty the pad and the value";
const toggle = [...fs.querySelectorAll("button")].find((b) => b.textContent === "Type it instead");
if (!toggle) return "typed={true} offers no Type it instead";
toggle.click(); await wait();
const box = fs.querySelector(".ui-signature-pad-typed");
if (!box || document.activeElement !== box) return "Type it instead does not show and focus a text box";
type(box, "Ada Lovelace"); await wait();
if (!hidden.value.startsWith("data:image/png;base64,") || inked() < 50) return "typing a name does not draw it";
if (hidden.value === png1) return "the typed name gives the same PNG as the stroke";
type(box, ""); await wait();
if (hidden.value !== "" || inked() !== 0) return "emptying the name does not clear the pad";
const live = $("#signature-pad-sp-demo-initials");
const lc = live.querySelector("canvas");
if (lc.width !== 240 || lc.height !== 100 || [...live.querySelectorAll("button")].some((b) => b.textContent.includes("instead"))) return "width, height and typed={false} are not honoured";
lc.setPointerCapture = () => {};
const lr = lc.getBoundingClientRect();
const lpe = (t, x, y) => lc.dispatchEvent(new PointerEvent(t, { bubbles: true, cancelable: true, pointerId: 1, button: 0, isPrimary: true, clientX: lr.left + x, clientY: lr.top + y }));
lpe("pointerdown", 20, 50); lpe("pointermove", 100, 30); lpe("pointerup", 100, 30); await wait();
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
if (!note().startsWith("Signed:")) return `on_change did not update the note: ${note()}`;
