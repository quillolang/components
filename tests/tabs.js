const radios = $$("input.ui-tabs-radio[name=tabs-demo-os]");
if (radios.length !== 3) return `expected 3 tabs, found ${radios.length}`;
const panel = (r) => r.nextElementSibling.nextElementSibling;
const visible = (el) => getComputedStyle(el).display !== "none";
const showing = (rs) => rs.filter((r) => visible(panel(r))).map((r) => r.nextElementSibling.textContent.trim());
if (showing(radios).join() !== "macOS") return `at first the panels showing are: ${showing(radios)}`;
if (radios.some((r) => r.form !== null)) return "the tab radios belong to a form, which would send them";
const label = radios[1].nextElementSibling;
if (label.tagName !== "LABEL" || label.htmlFor !== radios[1].id) return "a tab is not a label for its radio";
label.click(); await wait();
if (!radios[1].checked || showing(radios).join() !== "Linux") return `clicking Linux shows: ${showing(radios)}`;
if (!panel(radios[1]).textContent.includes("install.sh")) return "the Linux panel has the wrong content";
const lr = label.getBoundingClientRect(), pr = panel(radios[1]).getBoundingClientRect();
if (pr.top < lr.bottom - 1) return "the panel is not below the tabs";
if (radios[0].nextElementSibling.getBoundingClientRect().top !== radios[2].nextElementSibling.getBoundingClientRect().top) return "the tabs are not in one row";
radios[0].nextElementSibling.click(); await wait();
const pills = $$("input[name=tabs-demo-period]");
if (pills.some((r) => r.checked) || showing(pills).join() !== "This week") return "with none selected, the first panel does not show";
pills[2].nextElementSibling.click(); await wait();
if (showing(pills).join() !== "This year") return `clicking This year shows: ${showing(pills)}`;
if (getComputedStyle(pills[2].nextElementSibling).backgroundColor === getComputedStyle(pills[1].nextElementSibling).backgroundColor)
    return "the selected pill does not look selected";
const tabs = $$("[role=tab]");
if (tabs.length !== 3 || tabs[0].getAttribute("aria-selected") !== "true" || tabs[1].tabIndex !== -1) return "TabBar does not start on its first tab";
key(tabs[0], "ArrowRight"); await wait();
if (tabs[1].getAttribute("aria-selected") !== "true" || document.activeElement !== tabs[1]) return "ArrowRight did not select and focus the next tab";
const note = () => $("[role=tabpanel]").textContent;
if (!note().includes("style.css")) return `on_change did not update the panel: ${note()}`;
key(tabs[1], "End"); await wait();
if (!note().includes("README.md") || tabs[2].tabIndex !== 0) return "End did not move to the last tab";
key(tabs[2], "ArrowRight"); await wait();
if (!note().includes("main.qwe")) return "ArrowRight on the last tab did not wrap to the first";
tabs[1].click(); await wait();
if (!note().includes("style.css") || $("[role=tabpanel]").getAttribute("aria-labelledby") !== tabs[1].id) return "clicking a tab did not select it";
