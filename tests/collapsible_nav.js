localStorage.removeItem("ui-colnav-collapsible-nav-demo");
const nav = $("#collapsible-nav-demo");
if (!nav || nav.tagName !== "NAV" || nav.getAttribute("aria-label") !== "Navigation") return "it is not a labelled <nav>";
const groups = [...nav.querySelectorAll("details.ui-colnav-group")];
if (groups.length !== 3) return `expected 3 groups, found ${groups.length}`;
const titles = groups.map((g) => g.querySelector("summary span").textContent);
if (titles.join() !== "Getting started,Language,Deploying") return `the groups are ${titles}`;
if (!groups[0].open || !groups[1].open || groups[2].open) return "open: false and the defaults are not honoured";
const top = nav.querySelector(".ui-colnav-top a");
if (top?.getAttribute("href") !== "#overview") return "a link outside any group is missing";
const cur = nav.querySelectorAll("[aria-current=page]");
if (cur.length !== 1 || cur[0].textContent.trim() !== "Your first program") return "the current page is not marked once";
if ([...nav.querySelectorAll("a")].find((a) => a.textContent.includes("Components"))?.querySelector(".ui-colnav-badge")?.textContent !== "4") return "the badge is missing";
const note = () => nav.closest(".demo-row").querySelector(".demo-note").textContent;
groups[1].querySelector("summary").click(); await wait();
if (groups[1].open) return "clicking a title does not fold the group";
if (!note().includes("Language closed")) return `on_toggle did not reach the note: ${note()}`;
const saved = JSON.parse(localStorage.getItem("ui-colnav-collapsible-nav-demo") ?? "{}");
if (saved["Language"] !== false) return `the browser did not remember the fold: ${JSON.stringify(saved)}`;
groups[2].querySelector("summary").click(); await wait();
if (!groups[2].open || JSON.parse(localStorage.getItem("ui-colnav-collapsible-nav-demo"))["Deploying"] !== true || !note().includes("Deploying opened")) return "unfolding is not remembered or told";
const link = groups[2].querySelector("a");
if (link.getBoundingClientRect().height === 0) return "an unfolded group's links do not show";
groups[1].querySelector("summary").click(); groups[2].querySelector("summary").click(); await wait();
localStorage.removeItem("ui-colnav-collapsible-nav-demo");
