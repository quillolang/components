const btn = $("#week-picker-wp-demo-week");
const host = btn.closest(".ui-week-picker");
const pop = host.querySelector("[role=dialog]");
const hidden = $("input[type=hidden][name=wp-demo-week]");
const month = () => pop.querySelector("h2").textContent.trim();
const focused = () => document.activeElement?.getAttribute("aria-label");
if (hidden.value !== "2026-W45" || !btn.textContent.includes("Week 45, 2026") || !btn.textContent.includes("2 – 8 November 2026")) return `it starts as ${btn.textContent} / ${hidden.value}`;
if (btn.getAttribute("aria-haspopup") !== "dialog" || !pop.hidden) return "the button does not open a dialog, or it starts open";
btn.click(); await wait();
if (pop.hidden || month() !== "November 2026") return `it opened on ${month()}`;
if (focused() !== "Week 45, 2 – 8 November 2026" || document.activeElement.getAttribute("aria-selected") !== "true") return `the focus is on ${focused()}`;
const rows = [...pop.querySelectorAll("[role=option]")];
if (pop.querySelector("[role=listbox]") == null || rows.length !== 6 || rows[0].getAttribute("aria-label") !== "Week 44, 26 October – 1 November 2026") return `November 2026's weeks: ${rows.map((r) => r.getAttribute("aria-label"))}`;
if (rows[0].getAttribute("aria-current") !== "date") return "this week is not marked";
const k = async (name) => { key(document.activeElement, name); await wait(80); };
await k("ArrowDown"); if (focused() !== "Week 46, 9 – 15 November 2026") return `ArrowDown: ${focused()}`;
await k("End"); if (focused() !== "Week 49, 30 November – 6 December 2026" || month() !== "November 2026") return `End: ${focused()} in ${month()}`;
await k("ArrowDown"); if (focused() !== "Week 50, 7 – 13 December 2026" || month() !== "December 2026") return `ArrowDown into December: ${focused()} ${month()}`;
await k("PageDown"); if (!focused()?.includes("January 2027") || month() !== "January 2027") return `PageDown: ${focused()} ${month()}`;
await k("Home"); if (focused() !== "Week 53, 28 December 2026 – 3 January 2027") return `Home, across the year: ${focused()}`;
await k("Enter");
if (hidden.value !== "2026-W53" || !pop.hidden || document.activeElement !== btn) return `Enter picked ${hidden.value}`;
btn.click(); await wait();
pop.querySelector("[aria-label='Previous month']").click(); await wait();
if (month() !== "November 2026") return `Previous month: ${month()}`;
key(document.activeElement, "Escape"); await wait();
if (!pop.hidden || document.activeElement !== btn) return "Escape did not close and go back to the button";
const live = $("input[type=hidden][name=wp-demo-sprint]").closest(".ui-week-picker");
const note = () => live.closest(".demo-stack").querySelector(".demo-note").textContent;
if (live.querySelector(".ui-week-picker-trigger") || live.querySelector("[role=group]").hidden) return "inline={true} does not show the weeks";
if (!live.querySelector("h2").textContent.trim().endsWith("October 2026")) return "inline does not open on today's month";
live.querySelectorAll("[role=option]")[1].click(); await wait();
if (note() !== "2026-W41: 2026-10-05 to 2026-10-11.") return `on_change: ${note()}`;
if ($("#week-picker-wp-demo-sm").getAttribute("aria-invalid") !== "true") return "error does not mark the button";
