const user = $("#form-field-demo-user");
if (!user || user.labels.length !== 1 || !user.labels[0].textContent.includes("Username")) return "the label is not tied to the control";
const field = user.closest(".ui-form-field");
if (!field.querySelector(".ui-form-field-req")) return "required shows no mark";
const hint = document.getElementById("form-field-demo-user-hint");
if (!hint || !hint.textContent.includes("Letters") || !user.getAttribute("aria-describedby").includes(hint.id)) return "the hint is not there with the id the control points to";
const country = $("#form-field-demo-country");
const err = document.getElementById("form-field-demo-country-error");
if (!err || err.getAttribute("role") !== "alert" || !err.textContent.includes("Choose a country")) return "the error is not an alert with the control's id";
if (!country.closest(".ui-form-field").classList.contains("ui-form-field-invalid")) return "an error does not mark the field";
if (getComputedStyle(country).borderTopColor === getComputedStyle(user).borderTopColor) return "a control with an error is not drawn red";
if (!country.closest(".ui-form-field").querySelector(".ui-form-field-aside a")) return "aside is not shown beside the label";
const nick = $("#form-field-demo-nick");
const nf = nick.closest(".ui-form-field");
if (!nf.classList.contains("ui-form-field-inline") || !nf.querySelector(".ui-form-field-opt")?.textContent.includes("optional")) return "inline and optional are not shown";
const lr = nf.querySelector("label").getBoundingClientRect(), cr = nick.getBoundingClientRect();
if (cr.left <= lr.right) return "an inline label is not beside its control";
if (cr.width > 260) return `width=20ch did not cap the control: ${cr.width}px`;
if (user.getBoundingClientRect().height < 34) return "a plain input is not drawn as a field";
