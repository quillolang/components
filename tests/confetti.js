const canvases = $$("canvas.ui-confetti-canvas");
if (canvases.length !== 2) return `expected 2 canvases, found ${canvases.length}`;
const [mine, sides] = canvases;
if (!mine.hidden || mine.getAttribute("aria-hidden") !== "true") return "the canvas shows before firing, or is not hidden from screen readers";
const btn = $(".ui-confetti-btn");
if (!btn || btn.textContent !== "🎉 Celebrate") return "no trigger button";
const painted = (c) => { const d = c.getContext("2d").getImageData(0, 0, c.width, c.height).data; let n = 0; for (let i = 3; i < d.length; i += 64) if (d[i] > 0) n++; return n; };
btn.click(); await wait(300);
if (mine.hidden) return "firing did not show the canvas";
const cs = getComputedStyle(mine);
if (cs.position !== "fixed" || cs.pointerEvents !== "none" || Math.abs(mine.getBoundingClientRect().width - innerWidth) > 20) return "the canvas does not cover the window and let clicks through";
if (painted(mine) < 20) return `nothing drawn: ${painted(mine)}`;
if (!sides.hidden) return "the other Confetti fired too";
for (let i = 0; i < 50 && !mine.hidden; i++) await wait(100);
if (!mine.hidden) return "the burst does not end";
if ($(".demo-note").textContent !== "Bursts over: 1.") return `on_done: ${$(".demo-note").textContent}`;
$("#confetti-demo-fire").click(); await wait(300);
if (mine.hidden || sides.hidden) return "confetti_fire() did not fire them all";
if (painted(sides) < 20) return "the sides burst drew nothing";
for (let i = 0; i < 50 && !(mine.hidden && sides.hidden); i++) await wait(100);
if ($(".demo-note").textContent !== "Bursts over: 2.") return "on_done after confetti_fire()";
